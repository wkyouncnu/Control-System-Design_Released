%% 1. 상태궤환 — 출력이 아니라 상태를 되먹인다
% 지금까지 열두 주 동안 되먹인 것은 **출력 $y$ 하나**였습니다.
%
% $$u = C(s)\,(r - y)$$
%
% 상태궤환은 **상태 전부**를 되먹입니다.
%
% $$u = -Kx + K_r r, \qquad K = [k_1\;\;k_2\;\;\cdots\;\;k_n]$$
%
% 이것을 상태방정식에 넣으면
%
% $$\dot{x} = Ax + B(-Kx + K_r r) = (A - BK)\,x + BK_r\,r$$
%
% 즉 **$A$ 가 $A - BK$ 로 바뀝니다.**
% 우리가 $K$ 를 고르면 그 고유값을 정할 수 있다는 뜻입니다.
%
% ![상태궤환 : u = -Kx + Kr r](loop_statefb.png)
%
% **그림 파일** `loop_statefb.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_statefb')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('statefeedback', ...)` 로 부릅니다
% **직접 확인해 보려면** — `W13_04_run_simulink.m` 이 `W13_PolePlacement.slx` 에서
% 이 그림 그대로의 블록 배치를 돌립니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 되먹임 선이 **플랜트 안쪽**에서 나오는 것 | $y$ 가 아니라 $x$ 를 가져온다 | **오늘의 핵심 차이** |
% | 되먹임 상자 $K$ | 스칼라가 아니라 **행벡터** | 상태마다 계수가 따로 있다 |
% | 그 선이 여러 가닥인 것 | 상태 개수만큼 | 그래서 자유도가 $n$ 개다 |
% | 앞단의 $K_r$ | 지령을 곱해 주는 상수 | 6절에서 다룬다. **없으면 엉뚱한 데 멈춘다** |
% | 합산점의 부호 | $-Kx$ 를 더한다 | 빼는 것과 같다 |
% | 출력 $y$ 로 가는 선 | $C$ 를 거친다 | 오늘은 **$x$ 를 전부 안다고 가정**한다 |
%
% 마지막 줄이 오늘 내내 깔려 있는 가정입니다.
% **이 가정을 깨는 것이 14주차입니다.**
%% 2. $K$ 를 손으로 구하기 — 계수비교법
% 절차는 세 줄입니다.
%
% - **1단계** 원하는 극점으로 원하는 특성다항식을 만든다
%
% $$(s+8)(s+10)(s+12) = s^3 + 30 s^2 + 296 s + 960$$
%
% - **2단계** $A - BK$ 의 특성다항식을 $K$ 의 원소로 적는다
% - **3단계** 두 다항식의 **계수를 하나씩 맞춘다**
%
% 미지수 개수($K$ 의 원소 $n$ 개)와 방정식 개수(계수 $n$ 개)가 같으므로
% **답이 정확히 하나** 나옵니다. 이것이 극배치가 되는 이유입니다.
%
% 그리고 12주차의 조건이 여기서 나옵니다 — **가제어여야 합니다.**
% 가제어가 아니면 위 연립방정식이 풀리지 않습니다.
[Gp, p] = plant_dcmotor('position');
sys = ss(p.A, p.B, p.C, p.D);
p_des = [-8 -10 -12];
K = place(p.A, p.B, p_des);
fprintf('개루프 고유값 : %s\n', mat2str(round(eig(p.A).', 4)));
fprintf('원하는 특성다항식 계수 : %s\n', mat2str(round(poly(p_des), 4)));
fprintf('place 로 구한 K = %s\n', mat2str(round(K, 4)));
fprintf('검증 eig(A-BK) = %s\n', mat2str(round(sort(eig(p.A-p.B*K)).', 4)));
%% 2-1. 계수비교를 **직접** 해 본다 — 가장 작은 예
% 위에서는 절차만 말하고 `place` 에 맡겼습니다.
% 그러면 무슨 일이 일어나는지 안 보이므로, 상태가 둘뿐인 예로 손으로 풉니다.
%
% $$A = \left[\begin{array}{cc} 0 & 1 \\ -2 & -3 \end{array}\right], \qquad
%   B = \left[\begin{array}{c} 0 \\ 1 \end{array}\right], \qquad
%   K = \left[\begin{array}{cc} k_1 & k_2 \end{array}\right]$$
%
% **1단계** — 원하는 극점을 $-4$, $-5$ 로 두면
%
% $$(s+4)(s+5) = s^2 + 9s + 20$$
%
% **2단계** — $A - BK$ 를 만들고 특성다항식을 $k_1, k_2$ 로 적습니다.
%
% $$A - BK = \left[\begin{array}{cc} 0 & 1 \\
%   -2-k_1 & -3-k_2 \end{array}\right]$$
%
% $2\times2$ 행렬의 특성다항식은 $s^2 - (\text{대각합})s + (\text{행렬식})$ 이므로
%
% $$s^2 + (3+k_2)\,s + (2+k_1)$$
%
% **3단계** — 두 다항식의 계수를 하나씩 맞춥니다.
%
% | 차수 | 원하는 계수 | $K$ 로 적은 계수 | 풀면 |
% |---|---|---|---|
% | $s^1$ | $9$ | $3 + k_2$ | $k_2 = 6$ |
% | $s^0$ | $20$ | $2 + k_1$ | $k_1 = 18$ |
%
% 따라서 $K = \left[\begin{array}{cc} 18 & 6 \end{array}\right]$ 입니다.
% **미지수 두 개, 방정식 두 개.** 그래서 답이 딱 하나 나옵니다.
%
% 지금 한 일을 한 장으로 묶으면 이렇습니다.
%
% ![계수비교법 — 원하는 극점에서 K 까지](w13_coeff_match.png)
%
% **그림 파일** `w13_coeff_match.png` — `make_figures.m` 의 `fig_w13_coeff_match`
%   · 다시 만들려면 `make_figures('w13_coeff_match')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w13_coeff_match`
% **직접 확인해 보려면** — `W13_01_pole_placement.m` 의 **2절**이
% 같은 예제를 손계산과 `place` 로 나란히 풉니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | ① 파란 칸 | 원하는 극점 $-4$, $-5$ | **우리가 정하는 것.** 사양에서 온다 |
% | ② 파란 칸 | 그 극점을 근으로 갖는 다항식 | 극점을 계수로 바꾼 것 |
% | ③ 회색 칸 | $A - BK$ 의 특성다항식 | **시스템이 주는 것.** $K$ 가 미지수로 들어 있다 |
% | ④ 빨간 글씨 | 같은 차수끼리 등식을 세운 것 | 미지수 2 개, 방정식 2 개 |
% | ⑤ 초록 칸 | 연립방정식의 해 | 얻는 상태궤환 이득 |
% | ② 와 ③ 의 차수가 같은 것 | 둘 다 $n$ 차 | 그래서 방정식 개수가 미지수 개수와 같다 |
%
% ③ 에 $k_1$ 이나 $k_2$ 가 **아예 나타나지 않는 경우**가 있습니다.
% 그러면 ④ 를 풀 수 없습니다. 그것이 **가제어가 아닌 경우**입니다.
% 12주차의 판정이 여기서 쓰입니다.
A2 = [0 1; -2 -3];  B2 = [0; 1];
K2_hand  = [18 6];
K2_place = place(A2, B2, [-4 -5]);
fprintf('\n=== 계수비교법 손계산 확인 ===\n');
fprintf('  손으로 푼 K   : %s\n', mat2str(K2_hand));
fprintf('  place 가 준 K : %s\n', mat2str(round(K2_place, 4)));
fprintf('  A-BK 특성다항식 : %s   (원하는 것 : %s)\n', ...
        mat2str(round(poly(A2 - B2*K2_hand), 4)), mat2str(poly([-4 -5])));
fprintf('  eig(A-BK) = %s\n', mat2str(round(sort(eig(A2 - B2*K2_hand)).', 4)));
%% 2-2. 3차에서는 기호 계산으로 맡긴다
% 상태가 셋이 되면 손으로 전개하기가 번거롭습니다.
% 그래도 **원리는 똑같다**는 것을 확인하기 위해 기호로 풀어 봅니다.
%
% Symbolic Math Toolbox 의 `charpoly` 가 특성다항식을 $k_1,k_2,k_3$ 이
% 들어간 채로 만들어 주고, `solve` 가 계수를 맞춰 줍니다.
%
% 새로 나오는 명령 두 개
%
% - `charpoly(M, s)` — 행렬 `M` 의 특성다항식을 변수 `s` 로 돌려준다
% - `coeffs(expr, s, 'All')` — 다항식의 계수를 **높은 차수부터 전부** 뽑는다
%
% 우리 DC 모터의 $A - BK$ 특성다항식은 이렇게 나옵니다.
%
% $$s^3 + (2k_3 + 12)\,s^2 + \left(2k_2 + 20k_3 + \frac{1001}{50}\right)s + 2k_1$$
%
% 원하는 다항식 $s^3 + 30s^2 + 296s + 960$ 과 계수를 맞추면
% 미지수 세 개에 방정식 세 개이므로 답이 하나로 정해집니다.
%  [주의] 이 절만 Symbolic Math Toolbox 가 필요합니다.
%         없는 PC 에서도 강의노트가 끝까지 돌도록 확인하고 건너뜁니다.
hasSym = license('test','Symbolic_Toolbox') && ~isempty(which('syms'));

if hasSym
    syms k1 k2 k3 sv real
    Ksym = [k1 k2 k3];
    cpoly = expand(charpoly(sym(p.A) - sym(p.B)*Ksym, sv));
    wpoly = expand(poly2sym(poly(p_des), sv));
    sol   = solve(coeffs(cpoly - wpoly, sv, 'All') == 0, [k1 k2 k3]);
    K_hand3 = double([sol.k1 sol.k2 sol.k3]);

    fprintf('\n=== 3차도 같은 방법으로 ===\n');
    fprintf('  계수비교로 푼 K : %s\n', mat2str(round(K_hand3, 4)));
    fprintf('  place 가 준 K   : %s\n', mat2str(round(K, 4)));
    fprintf('  두 결과의 차이   : %.2e\n', max(abs(K_hand3 - K)));
else
    fprintf('\n=== 3차도 같은 방법으로 ===\n');
    fprintf('  Symbolic Math Toolbox 가 없어 기호 계산은 건너뜁니다.\n');
    fprintf('  계수만 대조해도 같은 확인이 됩니다.\n');
    fprintf('  원하는 특성다항식 : %s\n', mat2str(round(poly(p_des), 4)));
    fprintf('  A-BK 의 특성다항식 : %s\n', mat2str(round(poly(p.A - p.B*K), 4)));
end
