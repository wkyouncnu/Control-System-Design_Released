%% 7. $K_r$ 은 어떻게 구하는가
% 정상상태에서는 $\dot{x} = 0$ 이므로
%
% $$0 = (A - BK)\,x_{ss} + BK_r\,r
%   \qquad\Rightarrow\qquad
%   x_{ss} = -(A-BK)^{-1}BK_r\,r$$
%
% $$y_{ss} = C\,x_{ss} = -C(A-BK)^{-1}B\,K_r\,r$$
%
% 이것이 $r$ 과 같아지려면
%
% $$K_r = \frac{1}{-C(A-BK)^{-1}B}
%       = \frac{1}{\mathrm{dcgain}(A-BK,\,B,\,C,\,D)}$$
%
% MATLAB 에서는 한 줄입니다.
Kr = 1/dcgain(ss(p.A - p.B*K, p.B, p.C, p.D));
fprintf('Kr = %.2f\n', Kr);
fprintf('보정 후 직류이득 = %.6f\n', ...
        dcgain(ss(p.A - p.B*K, p.B*Kr, p.C, p.D)));
%% 8. $K_r$ 의 약점과 적분 상태
% $K_r$ 은 **모델을 믿고 미리 계산한 값**입니다.
% 1주차와 5주차에서 본 그 문제가 그대로 돌아옵니다.
%
% 그런데 **한 가지 예외가 있습니다.**
%
% - 플랜트 안에 **적분기가 이미 있으면** ($A$ 의 첫 열이 $0$)
%   $K_r$ 만으로도 계단 오차가 저절로 $0$ 이 됩니다
% - 없으면 $K_r$ 은 모델 오차만큼 그대로 어긋납니다
%
% 오늘 쓰는 DC 모터 **위치** 모델은 앞쪽입니다 (각도는 각속도의 적분).
% **속도** 모델은 뒤쪽입니다. `W13_02_reference_tracking.m` 의 3절에서
% 두 경우를 나란히 확인합니다.
%
% 확실히 없애려면 **적분 상태를 하나 더** 넣습니다.
%
% $$\dot{x}_i = r - y$$
%
% $$\left[\begin{array}{c}\dot{x}\\ \dot{x}_i\end{array}\right] =
%   \left[\begin{array}{cc}A & 0\\ -C & 0\end{array}\right]
%   \left[\begin{array}{c}x\\ x_i\end{array}\right] +
%   \left[\begin{array}{c}B\\ 0\end{array}\right] u +
%   \left[\begin{array}{c}0\\ 1\end{array}\right] r$$
%
% 이 확대 시스템에 극배치를 하면 상태가 $n+1$ 개인 제어기가 나옵니다.
