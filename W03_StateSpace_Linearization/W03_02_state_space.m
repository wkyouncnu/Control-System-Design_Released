%% 1. "상태"가 뭔가요
%
%  게임 세이브 파일을 생각해 봅시다.
%
%  게임을 저장하고 껐다가 내일 다시 켜서 이어서 하려면 무엇을 저장해야 할까요?
%  캐릭터 위치, 체력, 가진 아이템 정도면 됩니다.
%  지금까지 어떤 경로로 걸어왔는지는 저장할 필요가 없습니다.
%  현재 상황만 알면 이어서 할 수 있으니까요.
%
%  제어공학에서 "상태(state)"가 바로 이것입니다.
%
%      상태 = 지금부터의 미래를 계산하는 데 필요한 최소한의 정보
%
%  질량-스프링-댐퍼에서는 무엇을 저장해야 할까요?
%
%      위치만?   부족합니다. 같은 위치라도 날아가는 중인지 멈춰 있는지 다릅니다.
%      위치+속도? 충분합니다. 이 둘과 앞으로 들어올 힘만 알면 미래가 다 정해집니다.
%
%  그래서 이 시스템의 상태는 두 개입니다.
%
%      x1 = 위치
%      x2 = 속도
%
%  상태가 몇 개인지는 미분방정식의 차수와 같습니다. 2계 미분방정식이면 상태 2개입니다.
%  왜냐하면 2계 미분방정식을 풀려면 초기조건이 두 개 필요하기 때문입니다.

%% 2. 상태공간으로 적어 보기
%
%  운동방정식은 이것이었습니다.
%
%      m*x'' + b*x' + k*x = F
%
%  상태를 x1 = 위치, x2 = 속도 로 두면 x2 = x1' 입니다.
%  이제 규칙은 하나입니다. "모든 상태의 미분을, 상태와 입력만으로 표현한다."
%
%  첫 번째 상태의 미분:
%      x1' = x2                              (위치의 미분은 속도, 당연합니다)
%
%  두 번째 상태의 미분:
%      x2' = x'' = (F - b*x' - k*x)/m
%          = (F - b*x2 - k*x1)/m
%          = -(k/m)*x1 - (b/m)*x2 + (1/m)*F
%
%  이 둘을 행렬로 묶으면 끝입니다.
%
%      [x1']   [   0      1  ] [x1]   [ 0 ]
%      [   ] = [             ] [  ] + [   ] F
%      [x2']   [ -k/m  -b/m  ] [x2]   [1/m]
%       ----    --------------  ----   -----
%        x'    =       A         x   +   B    u
%
%  그리고 우리가 측정하는 값(출력)이 위치라면
%
%      y = [1  0] [x1; x2] + 0*F
%           -----
%             C                  D
%
%  이것이 상태공간 표현입니다. 항상 이 두 줄 형태입니다.
%
%      x' = A*x + B*u        (상태가 어떻게 변하는가)
%      y  = C*x + D*u        (그중 무엇을 내다보는가)

m = 1; b = 0.2; k = 1;

A = [   0     1  ;
     -k/m  -b/m ];
B = [0; 1/m];
C = [1 0];
D = 0;

sys_ss = ss(A, B, C, D);

fprintf('=== 상태공간 행렬 ===\n');
fprintf('A =\n'); disp(A);
fprintf('B =\n'); disp(B);
fprintf('C =\n'); disp(C);
fprintf('D = %g\n\n', D);

%% 3. A, B, C, D 는 각각 무슨 뜻인가
%
%  이름만 외우면 헷갈립니다. 역할로 기억하십시오.
%
%      A : 아무도 안 건드려도 시스템이 저 혼자 어떻게 움직이는가
%          (진자를 그냥 놓아두면 어떻게 흔들리는가)
%
%      B : 입력이 상태에 어떻게 들어가는가
%          (힘을 주면 어느 상태가 얼마나 밀리는가)
%
%      C : 여러 상태 중 우리가 실제로 볼 수 있는 것은 무엇인가
%          (센서가 위치만 잰다면 속도는 못 봅니다)
%
%      D : 입력이 출력에 곧바로 튀어나오는 몫
%          (대부분의 물리 시스템에서 0 입니다. 힘을 준다고 위치가
%           그 순간 순간이동하지는 않으니까요)
%
%  이 중 A 가 가장 중요합니다. 시스템의 성격을 A 가 혼자 다 정합니다.
%  실제로 A 의 고유값(eigenvalue)이 곧 전달함수의 극점입니다. 확인해 봅시다.

fprintf('=== A 의 고유값 vs 전달함수의 극점 ===\n');
fprintf('  A 의 고유값 : ');
ev = eig(A); fprintf('%+.3f%+.3fj   ', [real(ev).'; imag(ev).']); fprintf('\n');

G = 1/(m*s^2 + b*s + k);
fprintf('  G 의 극점   : ');
pl = pole(G); fprintf('%+.3f%+.3fj   ', [real(pl).'; imag(pl).']); fprintf('\n');
fprintf('  --> 정확히 같습니다.\n');
fprintf('      그래서 12주차에서 안정도를 볼 때 eig(A) 만 보면 됩니다.\n\n');

%% 4. 전달함수와 상태공간 사이를 오가기
%
%  둘은 같은 시스템의 다른 표현이므로 자유롭게 오갈 수 있습니다.
%  MATLAB 명령 두 개면 됩니다.

G_from_ss = tf(sys_ss);          % 상태공간 -> 전달함수
sys_from_G = ss(G);              % 전달함수 -> 상태공간

fprintf('=== 상태공간 -> 전달함수 ===\n');
G_from_ss

t = 0:0.01:40;
fprintf('원래 전달함수와 응답 차이 : %.2e\n\n', ...
        max(abs(step(G, t) - step(G_from_ss, t))));

%% 5. 주의 : 상태공간 표현은 하나가 아닙니다
%
%  전달함수는 시스템 하나당 딱 하나입니다.
%  그런데 상태공간은 무한히 많습니다.
%
%  왜 그럴까요? 상태를 무엇으로 고르느냐가 우리 마음이기 때문입니다.
%  위치와 속도로 골라도 되고, 위치와 운동량으로 골라도 되고,
%  둘을 섞어서 골라도 됩니다.
%
%  비유하자면 같은 도시의 위치를 "동경/북위"로 적을 수도 있고
%  "서울역에서 몇 km 동쪽, 몇 km 북쪽"으로 적을 수도 있는 것과 같습니다.
%  좌표계가 달라도 그 도시는 같은 도시입니다.
%
%  아래에서 MATLAB 이 자동으로 만든 상태공간과 우리가 손으로 만든 것을 비교해 보면
%  A 행렬 숫자가 다른데도 고유값은 같고 응답도 같은 것을 볼 수 있습니다.

fprintf('=== 우리가 만든 A vs MATLAB 이 만든 A ===\n');
fprintf('우리 것 A =\n'); disp(A);
fprintf('MATLAB 것 A =\n'); disp(sys_from_G.A);
fprintf('우리 것 고유값   : ');   ev1 = eig(A);
fprintf('%+.3f%+.3fj  ', [real(ev1).'; imag(ev1).']); fprintf('\n');
fprintf('MATLAB 것 고유값 : ');   ev2 = eig(sys_from_G.A);
fprintf('%+.3f%+.3fj  ', [real(ev2).'; imag(ev2).']); fprintf('\n');
fprintf('--> 행렬 숫자는 달라도 고유값이 같으니 같은 시스템입니다.\n\n');

%% 6. 상태공간의 진짜 이점 : 초기조건
%
%  2주차 마지막에 풀지 못했던 문제로 돌아갑시다.
%
%      "물체를 0.5 m 당겨 놓고 힘 없이 놓았다. 어떻게 되는가?"
%
%  전달함수는 "아무 일도 없다"고 답했습니다. 입력이 0 이니까요.
%  상태공간은 초기 상태를 직접 넣을 수 있으므로 제대로 답합니다.
%
%      initial(sys, x0, t)    <- 초기조건에서 출발한 응답
%
%  x0 = [0.5; 0] 은 "위치 0.5 m, 속도 0" 이라는 뜻입니다.

x0 = [0.5; 0];

figure('Name','초기조건 응답');
h1 = plot(t, initial(sys_ss, x0, t), 'LineWidth', 2); hold on;
h2 = plot(t, zeros(size(t)), 'k--', 'LineWidth', 2);
yline(0, 'k:'); grid on;
xlabel('시간 [s]'); ylabel('위치 [m]');
title('0.5 m 당겨 놓고 놓았을 때 (힘은 0)');
legend([h1 h2], {'상태공간이 주는 답', '전달함수가 주는 답 (항상 0)'}, ...
       'Location','northeast');

fprintf('=== 초기조건 응답 ===\n');
fprintf('  전달함수 : 입력이 0 이니 출력도 0. 틀린 답입니다.\n');
fprintf('  상태공간 : 0.5 m 에서 출발해 진동하며 0 으로 갑니다. 맞는 답입니다.\n\n');

%% 7. 상태를 전부 꺼내 보기
%
%  전달함수는 출력 하나만 알려 줍니다.
%  상태공간은 내부 상태를 전부 볼 수 있습니다. 위치뿐 아니라 속도까지요.
%
%  C 행렬을 단위행렬로 바꾸면 "모든 상태를 출력으로 내보내라"는 뜻이 됩니다.

sys_all = ss(A, B, eye(2), [0;0]);       % 상태 둘 다 출력
[y_all, ~] = initial(sys_all, x0, t);

figure('Name','내부 상태 관찰');
tiledlayout(2,1)

nexttile
plot(t, y_all(:,1), 'LineWidth', 2); grid on;
ylabel('위치 [m]'); title('내부 상태를 모두 꺼내 본 결과');

nexttile
plot(t, y_all(:,2), 'LineWidth', 2, 'Color', [0.85 0.33 0.10]); grid on;
xlabel('시간 [s]'); ylabel('속도 [m/s]');

fprintf('=== 내부 상태 관찰 ===\n');
fprintf('  위치가 최대일 때 속도는 0 이고, 위치가 0 을 지날 때 속도가 최대입니다.\n');
fprintf('  진자나 그네를 떠올리면 자연스러운 결과입니다.\n');
fprintf('  이렇게 내부를 들여다볼 수 있는 것이 상태공간의 힘입니다.\n\n');

%% 8. 정리
%
%  1) 상태 = 미래를 계산하는 데 필요한 최소한의 정보 (게임 세이브 파일)
%     질량-스프링-댐퍼는 위치와 속도, 두 개면 충분합니다.
%
%  2) 상태공간은 항상 이 두 줄입니다.
%
%         x' = A*x + B*u
%         y  = C*x + D*u
%
%  3) A 가 시스템의 성격을 정합니다. A 의 고유값 = 전달함수의 극점입니다.
%
%  4) 상태공간 표현은 여러 가지입니다. 좌표를 어떻게 잡느냐가 자유이기 때문입니다.
%     그래도 고유값은 항상 같습니다.
%
%  5) 상태공간은 초기조건을 다룰 수 있고, 내부 상태를 볼 수 있습니다.
%     입출력이 여러 개여도 형태가 그대로입니다.
%     이 장점 때문에 12~14주차 현대제어는 전부 상태공간을 씁니다.
%
%  다음 실습 : W03_03_pendulum_linearization.m
%              이번 학기 전반부에서 가장 중요한 개념인 "선형화"를 다룹니다.
%              세상의 거의 모든 시스템은 사실 비선형인데, 우리는 지금까지
%              선형 이론만 배웠습니다. 이 간극을 어떻게 메울까요?
