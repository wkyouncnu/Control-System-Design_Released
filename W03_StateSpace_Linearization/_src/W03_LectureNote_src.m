%% 9-1. 선형화의 근거 — 테일러 급수
% 앞 절까지는 "$\sin\theta$ 를 $\theta$ 로 바꾼다" 를 **그림으로만** 정당화했습니다.
% 이제 근거를 식으로 적습니다. 근거는 테일러 급수 하나뿐입니다.
%
% 어떤 함수 $f$ 를 점 $x_0$ 근처에서 다음과 같이 전개할 수 있습니다.
%
% $$f(x_0 + \Delta x) = f(x_0) + f'(x_0)\,\Delta x
%   + \frac{1}{2}f''(x_0)\,\Delta x^2
%   + \frac{1}{6}f'''(x_0)\,\Delta x^3 + \cdots$$
%
% 여기서 **1차 항까지만 남기고 나머지를 버리는 것**이 선형화입니다.
%
% $$f(x_0 + \Delta x) \;\approx\; f(x_0) + f'(x_0)\,\Delta x$$
%
% 오른쪽 식을 보십시오. $\Delta x$ 에 대해 **상수 더하기 상수 곱하기**입니다.
% 즉 직선입니다. 이것이 선형화의 전부입니다.
%
% $\sin\theta$ 를 $\theta_0 = 0$ 에서 전개하면 다음과 같습니다.
%
% $$\sin\theta = \theta - \frac{\theta^3}{6} + \frac{\theta^5}{120} - \cdots$$
%
% 1차 항만 남기면 $\sin\theta \approx \theta$ 가 됩니다.
% 9절에서 그림으로 확인한 그 근사가 여기서 나온 것입니다.
%
% **버린 항이 곧 오차입니다.** 그러므로 오차의 크기는 미리 알 수 있습니다.
%
% $$\left|\sin\theta - \theta\right| \;\approx\; \frac{|\theta|^3}{6}$$
%
% $\Delta x$ 가 절반이 되면 오차는 $1/8$ 로 줄어듭니다.
% "좁게 보면 된다" 는 말의 정량적 의미가 이것입니다.
%
% ![항을 하나씩 더하면 근사가 어디까지 따라오는가](w03_taylor.png)
%
% **그림 파일** `w03_taylor.png` — `make_figures.m` 의 `fig_w03_taylor`
%   · 다시 만들려면 `make_figures('w03_taylor')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w03_taylor`
% **직접 확인해 보려면** — 명령창에서 `taylor(sin(x), x, 'Order', 6)` 을 실행하면
% 위 급수를 MATLAB 이 직접 보여 줍니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 검은 굵은 곡선 | $\sin\theta$ 의 참값 | 우리가 근사하려는 대상 |
% | 왼쪽 파란 파선 | 1차까지 : $\theta$ | 원점 근처에서만 검은 곡선과 겹친다 |
% | 왼쪽 주황 일점쇄선 | 3차까지 : $\theta - \theta^3/6$ | $\pm 90^\circ$ 까지 따라온다 |
% | 왼쪽 초록 점선 | 5차까지 | $\pm 150^\circ$ 까지 따라온다 |
% | 세 근사가 모두 원점을 지나는 것 | 전개 중심이 $\theta_0 = 0$ | 근사는 **전개 중심에서 정확**하고 멀어질수록 나빠진다 |
% | 오른쪽 굵은 하늘색 곡선 | 1차 근사의 실제 오차 | 로그 눈금이므로 직선에 가깝다 |
% | 오른쪽 검은 점선 | 버린 첫 항 $\theta^3/6$ | 하늘색 위에 **정확히 포개진다** |
% | 두 선이 포개진다는 사실 | 오차 $\approx$ 버린 첫 항 | 오차를 **미리 예측할 수 있다**는 뜻 |
% | 오른쪽 주황 곡선 | 3차 근사의 오차 | 항을 하나 더 남기면 오차가 수백 배 줄어든다 |
%
% 여기서 중요한 결론이 하나 나옵니다.
% **항을 더 남기면 근사는 좋아지지만, 그 순간 식이 다시 비선형이 됩니다.**
% $\theta^3$ 항이 있으면 중첩원리가 성립하지 않습니다.
% 그러므로 이 과목에서는 **반드시 1차 항까지만** 남깁니다.
%% 9-2. 변수가 여럿일 때 — 편미분과 야코비안
% 진자의 상태는 두 개이고 입력도 있습니다. 변수가 여럿일 때는
% 미분 대신 **편미분**을 쓰고, 그 결과를 행렬로 모읍니다.
%
% 비선형 상태방정식을 다음과 같이 적습니다.
%
% $$\dot{x} = f(x, u)$$
%
% 여기서 $x$ 는 $n$ 차원 상태벡터, $u$ 는 입력입니다.
% $f$ 는 각 성분이 $f_1, f_2, \ldots, f_n$ 인 벡터함수입니다.
%
% 동작점 $(x_0, u_0)$ 근처에서 각 성분을 테일러 전개하고 1차 항만 남기면
%
% $$\dot{x}_i \;\approx\; f_i(x_0, u_0)
%   + \sum_{j=1}^{n}\left.\frac{\partial f_i}{\partial x_j}\right|_{0}\Delta x_j
%   + \left.\frac{\partial f_i}{\partial u}\right|_{0}\Delta u$$
%
% 이것을 행렬로 묶으면 우리가 아는 두 줄이 됩니다.
%
% $$\Delta\dot{x} = A\,\Delta x + B\,\Delta u$$
%
% $$a_{ij} = \left.\frac{\partial f_i}{\partial x_j}\right|_{(x_0,u_0)}, \qquad
%   b_{i} = \left.\frac{\partial f_i}{\partial u}\right|_{(x_0,u_0)}$$
%
% 이 두 행렬을 **야코비안**이라 부릅니다.
% 강의자료 `03_Modeling` 의 slide 40 $\sim$ 42 가 같은 유도입니다.
%
% 기하학적으로는 이렇습니다. 1변수에서 곡선을 접선으로 바꾸었다면,
% 2변수에서는 **곡면을 접평면으로** 바꿉니다.
%
% ![곡면을 한 점에서 접평면으로 바꾸는 것이 야코비안이다](w03_jacobian.png)
%
% **그림 파일** `w03_jacobian.png` — `make_figures.m` 의 `fig_w03_jacobian`
%   · 다시 만들려면 `make_figures('w03_jacobian')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w03_jacobian`
% **직접 확인해 보려면** — `W03_05_linearize_verify.m` 의 **2 $\sim$ 4절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 회색 곡면 | 각가속도의 참값 $f_2(\theta, \dot\theta)$ | $\sin$ 때문에 휘어 있다 |
% | 왼쪽 주황 격자 | 동작점에서의 접평면 | 야코비안이 정의하는 평면 |
% | 원점 부근 (검은 점 근처) | 곡면과 평면이 붙어 있다 | 이 영역에서는 선형 모델이 정확하다 |
% | $\theta$ 축 양끝 | 곡면과 평면이 크게 벌어진다 | 멀어지면 선형 모델을 쓸 수 없다 |
% | 곡면이 $\dot\theta$ 방향으로는 안 휘는 것 | 감쇠항 $-b\dot\theta/J$ 는 원래 선형 | 비선형은 $\theta$ 방향에만 있다 |
% | 오른쪽 검은 곡선 | $\dot\theta = 0$ 으로 자른 단면 | 왼쪽 그림의 한 방향 절단면 |
% | 오른쪽 주황 파선의 기울기 $-32.7$ | $a_{21} = -mgl\cos\theta_0 / J$ | **접선의 기울기가 곧 $A$ 의 성분**이다 |
% | 두 선이 $\pm 40^\circ$ 밖에서 갈라지는 것 | 근사의 한계 | 9절의 오차표와 같은 이야기 |
%
% 진자에 이 정의를 적용하면 다음과 같습니다.
%
% $$f(x,u) = \left[\begin{array}{c}
%   x_2 \\[2pt] \frac{u - b x_2 - mgl\sin x_1}{J}
%   \end{array}\right]$$
%
% $$A = \left[\begin{array}{cc}
%   0 & 1 \\[2pt] -\frac{mgl\cos\theta_0}{J} & -\frac{b}{J}
%   \end{array}\right], \qquad
%   B = \left[\begin{array}{c} 0 \\[2pt] \frac{1}{J} \end{array}\right]$$
%
% $A$ 의 $(2,1)$ 성분에 $\cos\theta_0$ 가 들어 있습니다.
% **동작점이 바뀌면 이 성분이 바뀌고, 부호까지 뒤집힐 수 있습니다.**
% 12절에서 이 한 성분이 시스템의 성격을 정반대로 만드는 것을 봅니다.
%% 9-3. 동작점을 먼저 정한다 — 평형점 조건
% 선형화 식에는 $(x_0, u_0)$ 가 들어 있습니다.
% **그 점을 먼저 정하지 않으면 선형화 자체를 시작할 수 없습니다.**
%
% 아무 점이나 쓸 수는 있지만, 그러면 $f(x_0,u_0) \ne 0$ 이므로
% 상수항이 남아 다음과 같이 됩니다.
%
% $$\Delta\dot{x} = A\,\Delta x + B\,\Delta u + f(x_0,u_0)$$
%
% 맨 오른쪽 $f(x_0,u_0)$ 가 상수항입니다.
%
% 상수항이 있으면 $\Delta x = 0$ 이어도 상태가 계속 움직이므로
% 표준형 $\dot{x} = Ax + Bu$ 가 되지 않습니다.
% 그래서 **평형점을 고릅니다.** 평형점의 정의는 한 줄입니다.
%
% $$f(x_0, u_0) = 0$$
%
% 진자에서 이 식을 풀면 두 조건이 나옵니다.
%
% $$\dot\theta_0 = 0, \qquad u_0 = mgl\sin\theta_0$$
%
% 첫 줄은 "정지해 있어야 한다", 둘째 줄은 "중력 토크를 정확히 상쇄하는 토크를
% 계속 넣고 있어야 한다" 는 뜻입니다.
% $u_0 = 0$ 으로 두면 $\sin\theta_0 = 0$ 이므로 $\theta_0 = 0$ 또는 $\theta_0 = \pi$ 입니다.
% **평형점이 두 개**이고, 이것이 12절의 출발점입니다.
%
% ![평형점은 알짜 토크가 0 이 되는 자리다](w03_equilibrium.png)
%
% **그림 파일** `w03_equilibrium.png` — `make_figures.m` 의 `fig_w03_equilibrium`
%   · 다시 만들려면 `make_figures('w03_equilibrium')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w03_equilibrium`
% **직접 확인해 보려면** — `W03_05_linearize_verify.m` 의 **1절**이
% `fzero` 로 두 평형점을 실제로 찾아 출력합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 검은 곡선 | 중력 토크 $mgl\sin\theta$ | $\theta$ 에 따라 사인 모양으로 변한다 |
% | 왼쪽 초록 원 ($0^\circ$, $360^\circ$) | 곡선이 $0$ 을 **위로 지나간다** | 벗어나면 되돌리는 방향 $\to$ 안정 |
% | 왼쪽 빨간 원 ($180^\circ$) | 곡선이 $0$ 을 **아래로 지나간다** | 벗어나면 더 밀어내는 방향 $\to$ 불안정 |
% | 영점 통과 방향이 다르다는 사실 | 곡선의 기울기 부호 | 그 기울기가 곧 $A$ 의 $(2,1)$ 성분이다 |
% | 오른쪽 파란 곡선 | 알짜 토크 $u_0 - mgl\sin\theta$ ($u_0 = 0.6$) | 곡선 전체가 위로 올라갔다 |
% | 오른쪽 회색 점선 | $u_0 = 0$ 인 경우 | 비교 기준 |
% | 오른쪽 파란 원 $24.1^\circ$ | 새 평형점 | **토크를 넣으면 평형점 자체가 옮겨 간다** |
% | 오른쪽 빨간 원 $155.9^\circ$ | 또 하나의 평형점 | 여기도 불안정하다 |
% | 두 원의 간격이 좁아진 것 | $u_0$ 가 커질수록 가까워진다 | $u_0 = mgl$ 에서 둘이 만나 사라진다 |
%
% 마지막 줄이 중요합니다. $u_0 > mgl$ 이면 평형점이 **하나도 없습니다.**
% 아무리 큰 토크를 넣어도 진자가 멈추지 못하고 계속 도는 상태입니다.
% 이런 경우에는 선형화할 자리 자체가 없습니다.
%% 9-4. 편차 변수 — 선형 모델의 원점은 평형점이다
% 선형 모델의 변수는 $x$ 가 아니라 $\Delta x = x - x_0$ 입니다.
% **이 구분을 놓치면 뒤에서 반드시 사고가 납니다.**
%
% 정리하면 이렇습니다.
%
% | 기호 | 뜻 | 예 (거꾸로 선 진자) |
% |---|---|---|
% | $x$ | 실제 상태 (절대값) | $\theta = 190^\circ$ |
% | $x_0$ | 동작점 | $\theta_0 = 180^\circ$ |
% | $\Delta x = x - x_0$ | 선형 모델이 다루는 값 | $\Delta\theta = 10^\circ$ |
% | $u$ | 실제 입력 | 실제로 모터가 내는 토크 |
% | $u_0$ | 동작점 유지에 필요한 입력 | $mgl\sin\theta_0$ |
% | $\Delta u = u - u_0$ | 선형 제어기가 계산하는 값 | 그 위에 얹는 보정 토크 |
%
% 그러므로 실제 시스템에 넣는 입력은 다음과 같습니다.
%
% $$u = u_0 + \Delta u = u_0 - K\,(x - x_0)$$
%
% **$u_0$ 를 빠뜨리면** 평형을 유지하는 힘이 없어 제어기가 아무리 잘 설계되어도
% 시스템이 동작점에서 벗어납니다.
% **$x_0$ 를 빼지 않으면** 제어기가 절대 각도를 오차로 착각해 반대로 밉니다.
%
% 13주차에서 거꾸로 선 진자를 세울 때 이 두 항이 그대로 다시 나옵니다.
% 그때 좌표를 혼동하면 결과가 전혀 다르게 나오므로 지금 확실히 해 두십시오.
%% 10. 진자에서 확인하기
% 줄 끝에 추가 달린 진자입니다. $\theta$ 는 아래쪽 수직에서 잰 각도이므로
% 가만히 매달려 있으면 $\theta = 0$ 입니다.
%
% 운동방정식은 이렇습니다.
%
% $$ml^2\ddot{\theta} = u - b\dot{\theta} - mgl\sin\theta$$
%
% 이 식이 어디서 나오는지는 자유물체도 한 장이면 끝납니다.
%
% ![중력을 두 방향으로 쪼개면 sin 이 나온다](pendulum_fbd.png)
%
% **그림 파일** `pendulum_fbd.png` — `common/dg_pendulum.m` 의 `dg_pendulum`
%   · 다시 만들려면 `make_figures('pendulum_fbd')`
%
% **만드는 곳** — `common/dg_pendulum.m` 을 `dg_pendulum('fbd')` 로 부릅니다
% (`make_figures('pendulum_fbd')`)
% **직접 확인해 보려면** — `W03_03_pendulum_linearization.m` 의 **4절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 맨 위 검은 점 | 회전축 | 여기를 중심으로 돈다. 토크를 여기 기준으로 센다 |
% | 검은 점선 | 연직 기준선 | $\theta$ 를 이 선에서 잰다. 매달려 있으면 $\theta=0$ |
% | 빨간 화살표 $mg$ | 항상 **똑바로 아래**를 향한다 | 중력은 각도와 상관없이 방향이 같다 |
% | 파란 화살표 $mg\sin\theta$ | 막대에 **수직**인 방향 | 회전에 실제로 기여하는 것은 이 성분뿐이다 |
% | 회색 점선 (막대 방향 성분) | 막대를 잡아당기기만 한다 | 회전에는 아무 기여도 없다. 그래서 식에 안 나온다 |
