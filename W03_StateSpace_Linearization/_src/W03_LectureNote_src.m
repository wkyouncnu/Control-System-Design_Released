%% 14-1. 왜 이 과목은 선형 모델을 기준으로 두는가
% 이 절이 3주차 전체의 결론입니다.
%
% 이 과목이 다루는 도구를 나열해 보면 이렇습니다.
%
% | 도구 | 다루는 주차 | 성립 조건 |
% |---|---|---|
% | 전달함수 $G(s)$ | 2주차 | 선형 · 시불변 · 초기조건 $0$ |
% | 극점과 시간응답의 대응 | 4주차 | 선형 |
% | 라우스 판별법 · 시스템 타입 | 5주차 | 선형 |
% | 근궤적 | 6 $\sim$ 7주차 | 선형 |
% | 보드 선도 · 나이퀴스트 · 안정여유 | 9 $\sim$ 11주차 | 선형 (정현입력에 정현출력) |
% | 상태궤환 극배치 · 관측기 | 12 $\sim$ 14주차 | 선형 |
%
% **오른쪽 칸이 전부 "선형" 입니다.** 예외가 하나도 없습니다.
%
% 그 이유는 두 가지입니다.
%
% - **중첩원리** — 입력을 나누어 넣고 답을 더할 수 있어야 전달함수가 정의된다.
%   비선형에서는 $G(s)$ 라는 개념 자체가 성립하지 않는다
% - **정현입력에 정현출력** — 주파수응답 전체가 이 성질 위에 서 있다.
%   비선형 시스템에 사인을 넣으면 없던 주파수 성분이 생겨 나온다
%
% 그러므로 이 과목에서 **기준 모델은 언제나 선형 모델**입니다.
% 비선형 모델은 두 곳에서만 등장합니다.
%
% - 선형 모델을 **만들어 내는 출발점**으로 (오늘 9 $\sim$ 13절)
% - 설계가 끝난 뒤 **최종 검증 대상**으로 (13주차, 14주차)
%
% 이 두 자리를 정확히 구분하는 것이 3주차의 목표입니다.
%
% 정리하면 설계의 전체 흐름은 다음과 같습니다.
%
% | 단계 | 쓰는 모델 | 이번 학기 어디에서 |
% |---|---|---|
% | 1. 물리 법칙으로 모델링 | 비선형 | 2 $\sim$ 3주차 |
% | 2. 평형점 찾기 | 비선형 | 오늘 9-3절 |
% | 3. 야코비안으로 선형화 | 비선형 $\to$ 선형 | 오늘 9-2절 |
% | 4. 유효 범위 확인 | 두 모델 비교 | 오늘 13-3절 |
% | 5. 제어기 설계 | **선형만** | 4 $\sim$ 14주차 전부 |
% | 6. 비선형 모델로 최종 검증 | 비선형 | 13주차, 14주차 |
%
% 5단계가 학기의 대부분을 차지하지만, 그것이 성립하려면
% **2 $\sim$ 4단계가 먼저 제대로 되어 있어야 합니다.**
%% 15. 오늘의 정리
