%% 1. 블록선도 — 외울 것은 세 줄뿐
% 실제 시스템은 제어기, 모터, 기계, 센서가 줄줄이 이어져 있습니다.
% 이걸 하나로 합치는 규칙은 딱 세 개입니다.
%
% - **직렬** — 곱한다. $G_1 G_2$
% - **병렬** — 더한다. $G_1 + G_2$
% - **되먹임** — $\frac{G}{1+GH}$
%
% 직렬이 곱셈인 이유는 환율 계산과 같습니다.
% 원 → 달러, 달러 → 유로로 갈 때 두 배율을 곱하는 것과 똑같습니다.
%
% 세 규칙을 한 장에 모으면 이렇게 됩니다. **이 그림 한 장이 오늘 1~3절 전부입니다.**
%
% ![블록선도에서 외울 것은 이 세 줄뿐](block_rules.png)
%
% **그림 파일** `block_rules.png` — `common/dg_block_rules.m` 의 `dg_block_rules`
%   · 다시 만들려면 `make_figures('block_rules')`
%
% **만드는 곳** — `common/dg_block_rules.m` (`make_figures('block_rules')` 로 다시 그립니다)
% **직접 확인해 보려면** — `W03_01_block_reduction.m` 의 **2·3·4절**을 차례로 실행하면
% 이 세 줄이 실제 숫자로 맞는지 하나씩 대조해 줍니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | ① 줄 — 상자 두 개가 나란히 | $u \to G_1 \to G_2 \to y$ | 신호가 두 상자를 **차례로** 지난다. 그래서 배율이 곱해진다 |
% | ① 줄 아래 식 | $y = G_2 G_1 u$ | 순서를 바꿔 써도 같다. 전달함수는 곱셈 순서가 상관없다 |
% | ② 줄 — 왼쪽에서 갈라지는 점 | 같은 $u$ 가 위아래로 **똑같이** 들어간다 | 갈라져도 신호는 약해지지 않는다 |
% | ② 줄 — 오른쪽 원(합산점) | $+$ 두 개 | 두 길로 간 결과를 **더한다** |
% | ② 줄 아래 식 | $y = (G_1 + G_2)u$ | 그래서 병렬은 덧셈이다 |
% | ③ 줄 — 왼쪽 원의 $+$ 와 $-$ | 목표에서 되돌아온 값을 **뺀다** | 이 뺄셈이 오차 $e$ 다 |
% | ③ 줄 — $G$ 뒤에서 아래로 갈라지는 선 | 출력이 $H$ 를 거쳐 돌아온다 | 이 한 바퀴가 분모의 $GH$ 다 |
% | ③ 줄 아래 식 | $y = Gu/(1+GH)$ | **분자는 앞으로 가는 길, 분모는 $1+$ 한 바퀴** |
%
% 셋 중 ③ 하나만 확실히 하십시오. ①과 ②는 상식이고, 이 과목이 학기 내내
% 들여다보는 것은 ③의 **분모**입니다.
%% 2. 되먹임 공식은 세 줄이면 유도됩니다
% 외우는 것보다 유도해 보는 게 빠릅니다.
%
% $$e = r - y, \qquad y = Ge$$
%
% 둘째 식에 첫째 식을 넣으면
%
% $$y = G(r-y) \;\Longrightarrow\; y(1+G) = Gr \;\Longrightarrow\;
%   \frac{y}{r} = \frac{G}{1+G}$$
%
% 기억할 형태는 이것입니다.
%
% $$\text{폐루프} = \frac{\text{앞으로 가는 길}}{1 + \text{한 바퀴 도는 길}}$$
%
% 분모의 "$1+$ 한 바퀴"가 앞으로 이 과목 내내 나옵니다.
% 6주차 근궤적도, 10주차 안정여유도 결국 이 식을 들여다보는 일입니다.
%% 3. 센서가 이상하면 출력도 이상해집니다
% 현실에서는 출력을 그대로 되돌리지 않고 센서로 재서 되돌립니다.
% 그래서 분모의 "한 바퀴"가 $GH$ 가 됩니다.
%
% ![센서 H(s) 가 있는 비단위 피드백 — 되돌아오는 값이 y 가 아니라 H y 다](loop_sensor.png)
%
% **그림 파일** `loop_sensor.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_sensor')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('sensor', ...)` 로 부릅니다
% (`make_figures('loop_sensor')`)
% **직접 확인해 보려면** — `W03_01_block_reduction.m` 의 **5절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 원으로 들어오는 두 화살표 | 위는 $r$, 아래는 $H$ 를 거쳐 온 값 | 제어기가 비교하는 것은 $r$ 과 **$Hy$** 다. $y$ 가 아니다 |
% | 아래쪽 $H$ 상자 | 센서 | 여기에 오차가 있으면 **제어기가 속는다** |
% | 오른쪽 $y$ 화살표 | 진짜 출력 | 우리가 원하는 것은 이것인데, 아무도 이걸 안 보고 있다 |
%
% 여기서 꼭 알아 둘 것이 있습니다.
%
% 체온계가 고장 나서 실제보다 3배로 표시된다고 합니다. 환자 체온이 12도인데
% 체온계는 36도라고 보여 줍니다. 의사는 "정상이네" 하고 넘어갑니다.
%
% **제어기도 똑같습니다.** 제어기는 센서가 보여 주는 값만 믿습니다.
% 센서 값이 목표와 같아지면 거기서 멈춥니다. 실제 출력은 어긋난 채로요.
%
% 아래에서 센서 이득이 3배인 경우를 확인해 봅니다.
G = 1/(s+1) * 20/(s+2);
H = 3/(0.2*s+1);
t = 0:0.01:10;
plot(t, step(feedback(G,1), t), 'LineWidth',2); hold on
plot(t, step(feedback(G,H), t), 'LineWidth',2)
yline(1,'k--','LineWidth',1.5); grid on
xlabel('시간 [s]'); ylabel('출력')
title('센서가 3배로 부풀려 읽으면 출력은 1/3 에서 멈춘다')
legend('센서 정상','센서 3배 오류','목표값','Location','southeast')
