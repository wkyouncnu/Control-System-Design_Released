%% 5. 상태공간은 항상 두 줄입니다
% 형태가 언제나 똑같습니다. 이것만 기억하면 됩니다.
%
% $$\dot{x} = Ax + Bu$$
%
% $$y = Cx + Du$$
%
% 네 행렬의 역할을 이름이 아니라 **뜻으로** 기억하십시오.
%
% - $A$ — 아무도 안 건드려도 시스템이 저 혼자 어떻게 움직이는가
% - $B$ — 입력이 어느 상태를 얼마나 밀어 주는가
% - $C$ — 여러 상태 중 우리가 실제로 볼 수 있는 것은 무엇인가
% - $D$ — 입력이 출력에 곧바로 튀어나오는 몫 (대개 $0$)
%
% 두 줄을 블록선도로 그리면 왜 이 네 글자뿐인지 한눈에 보입니다.
%
% ![상태공간 두 줄을 블록선도로 그리면 이렇게 된다](loop_statespace.png)
%
% **그림 파일** `loop_statespace.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_statespace')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('statespace', ...)` 로 부릅니다
% (`make_figures('loop_statespace')`)
% **직접 확인해 보려면** — `W03_02_state_space.m` 의 **3절**이 네 행렬의 뜻을
% 숫자로 하나씩 보여 줍니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 가운데 **적분** 상자 | 이 그림에서 유일하게 기억을 가진 부품 | 상태가 여기 들어 있다. **적분기 개수 $=$ 상태 개수** |
% | 적분기 왼쪽 신호 이름 | $dx/dt$ | 상태의 **변화율**. $\dot{x} = Ax + Bu$ 의 왼쪽 |
% | 적분기 오른쪽 신호 이름 | $x$ | 상태 그 자체 |
% | 왼쪽 $B$ 상자 | 입력 $u$ 가 들어오는 유일한 길 | **$B$ 는 입력이 어느 상태를 미는가** |
% | 아래쪽 $A$ 상자와 되돌아오는 선 | $x$ 가 자기 자신에게 되돌아온다 | **$A$ 는 아무도 안 건드려도 저 혼자 어떻게 움직이는가** |
% | 오른쪽 $C$ 상자 | $x$ 중 일부만 $y$ 로 나간다 | **$C$ 는 우리가 볼 수 있는 것** |
% | 합산점의 두 $+$ | $Bu$ 와 $Ax$ 를 더한다 | 이 덧셈이 $\dot{x}=Ax+Bu$ 의 오른쪽 그대로다 |
%
% $D$ 는 이 그림에 없습니다. $u$ 에서 $y$ 로 **적분기를 안 거치고 바로 가는 선**이
% $D$ 인데, 대개 $0$ 이라 아예 그리지 않습니다.
%
% 이 중 $A$ 가 가장 중요합니다. 시스템의 성격을 $A$ 가 혼자 다 정합니다.
% 실제로 **$A$ 의 고유값이 곧 전달함수의 극점**입니다. 확인해 봅니다.
[G_msd, p] = plant_msd();
disp('A 의 고유값:');    disp(eig(p.A))
disp('전달함수의 극점:'); disp(pole(G_msd))
%% 5-1. 미분방정식을 상태공간으로 — 손으로 해 봅니다
% 2주차에서 세운 식을 그대로 가져옵니다.
%
% $$m\,\ddot{x} + b\,\dot{x} + k\,x = F$$
%
% 절차는 **네 단계**입니다. 매번 똑같습니다.
%
% ![2주차에서 쓰던 그 장치 그대로다](msd_only.png)
%
% **그림 파일** `msd_only.png` — `common/dg_msd.m` 의 `dg_msd`
%   · 다시 만들려면 `make_figures('msd_only')`
%
% **만드는 곳** — `common/dg_msd.m` 을 `dg_msd('system')` 으로 부릅니다
% (`make_figures('msd_only')`)
% **직접 확인해 보려면** — `W03_02_state_space.m` 의 **2절**이 아래 네 단계를
% 그대로 코드로 밟습니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 빗금 벽 | 고정된 곳 | 위치 $x$ 를 재는 기준. 여기서 얼마나 떨어졌나가 $x$ 다 |
% | 스프링 $k$ | 늘어난 만큼 되당긴다 | 위치에 비례하는 힘 $\to$ $x$ 가 상태가 되는 이유 |
% | 댐퍼 $b$ | 빠를수록 세게 막는다 | 속도에 비례하는 힘 $\to$ $\dot{x}$ 가 상태가 되는 이유 |
% | 질량 $m$ 상자 | 힘을 받아 움직이는 몸통 | $F=ma$ 를 쓰는 대상이 이 하나뿐이다 |
% | 오른쪽 힘 화살표 $F$ | 우리가 넣는 입력 | 상태공간의 $u$ 가 이것이다 |
% | $x$ 를 재는 화살표 방향 | 오른쪽이 $+$ | **부호를 여기서 정한다.** 여기서 틀리면 끝까지 틀린다 |
%% 5-2. 1단계 — 상태를 고른다
% 규칙 하나면 됩니다.
%
% - **가장 높은 미분보다 한 단계 낮은 것까지** 를 상태로 잡는다
%
% 여기서는 가장 높은 미분이 $\ddot{x}$ (2계)이므로 $x$ 와 $\dot{x}$ 를 잡습니다.
%
% $$x_1 = x \quad (\text{위치}), \qquad x_2 = \dot{x} \quad (\text{속도})$$
%
% 왜 이렇게 잡는가 — **이 둘만 알면 앞으로 벌어질 일이 전부 정해지기** 때문입니다.
% 지금 어디에 있고 얼마나 빨리 가고 있는지를 알면, 그다음은 물리 법칙이 정해 줍니다.
% 게임 세이브 파일에 저장해야 할 것이 딱 이 둘입니다.
%
% **상태를 고르는 더 좋은 기준 — 에너지**
%
% 혼동될 때는 "**에너지를 저장하는 곳이 어디인가**" 를 물어보십시오.
% 저장된 에너지 하나가 상태 하나입니다.
%
% | 부품 | 저장 에너지 | 에너지를 정하는 변수 | 상태 여부 |
% |---|---|---|---|
% | 스프링 $k$ | 위치에너지 $\frac{1}{2}kx^2$ | 위치 $x$ | **예** |
% | 질량 $m$ | 운동에너지 $\frac{1}{2}m\dot{x}^2$ | 속도 $\dot{x}$ | **예** |
% | 댐퍼 $b$ | 없음 (열로 버린다) | — | 아니오 |
%
% 댐퍼는 에너지를 **버리기만** 하고 저장하지 않습니다. 그래서 상태가 아닙니다.
% 이 기준은 어느 시스템에나 통합니다.
%
% - RC 회로 — 커패시터가 에너지를 저장하니 상태 하나 (1차)
% - RLC 회로 — 커패시터와 인덕터, 상태 둘 (2차)
% - DC 모터 — 인덕터(전류)와 관성(각속도), 상태 둘
%% 5-3. 2단계 — 각 상태의 미분을 상태와 입력으로만 적는다
% **오른쪽에 $x_1$, $x_2$, $u$ 말고 다른 것이 남으면 안 됩니다.**
%
% 첫 줄은 정의에서 바로 나옵니다.
%
% $$\dot{x}_1 = \dot{x} = x_2$$
%
% 둘째 줄은 운동방정식을 $\ddot{x}$ 에 대해 풀면 됩니다.
%
% $$m\,\ddot{x} = F - b\,\dot{x} - k\,x$$
%
% $$\ddot{x} = \frac{1}{m}\left(F - b\,\dot{x} - k\,x\right)$$
%
% 여기에 $x = x_1$, $\dot{x} = x_2$, $F = u$ 를 넣으면
%
% $$\dot{x}_2 = -\frac{k}{m}\,x_1 - \frac{b}{m}\,x_2 + \frac{1}{m}\,u$$
%
% 오른쪽에 $x_1$, $x_2$, $u$ 만 남았습니다. 성공입니다.
%% 5-4. 3단계 — 행렬로 묶는다
% 두 줄을 그대로 세로로 세우고 계수만 뽑아 씁니다.
%
% $$\begin{array}{l}
%   \dot{x}_1 = 0\cdot x_1 + 1\cdot x_2 + 0\cdot u \\
%   \dot{x}_2 = -\frac{k}{m}\,x_1 - \frac{b}{m}\,x_2 + \frac{1}{m}\,u
%   \end{array}$$
%
% 계수를 그대로 옮겨 적으면 $A$ 와 $B$ 가 나옵니다.
%
% $$\left[\begin{array}{c}\dot{x}_1\\ \dot{x}_2\end{array}\right] =
%   \left[\begin{array}{cc} 0 & 1\\ -\frac{k}{m} & -\frac{b}{m}\end{array}\right]
%   \left[\begin{array}{c}x_1\\ x_2\end{array}\right] +
%   \left[\begin{array}{c}0\\ \frac{1}{m}\end{array}\right] u$$
%
% **첫 줄이 항상 $[0\;\;1]$ 인 것**을 눈여겨보십시오.
% "위치의 미분은 속도" 라는 정의에서 나온 것이라 어느 2차 시스템이든 똑같습니다.
%% 5-5. 4단계 — 출력을 고른다
% 우리가 재는 것이 위치라면
%
% $$y = x = x_1 = \left[\begin{array}{cc}1 & 0\end{array}\right]
%     \left[\begin{array}{c}x_1\\ x_2\end{array}\right] + 0\cdot u$$
%
% 이므로 $C = [1\;\;0]$, $D = 0$ 입니다.
%
% 속도를 잰다면 $C = [0\;\;1]$ 이 되고, 둘 다 잰다면 $C$ 가 $2\times 2$ 단위행렬이 됩니다.
% **$C$ 는 "무엇을 볼 수 있는가" 를 적는 자리**일 뿐입니다.
%
% 값을 넣어 확인해 봅니다.
fprintf('=== 손으로 만든 상태공간 ===\n');
fprintf('  m = %.1f, b = %.1f, k = %.1f\n\n', p.m, p.b, p.k);
A_hand = [0 1; -p.k/p.m, -p.b/p.m];
B_hand = [0; 1/p.m];
C_hand = [1 0];
D_hand = 0;
disp('A ='); disp(A_hand);
disp('B ='); disp(B_hand);
fprintf('C = %s ,  D = %g\n\n', mat2str(C_hand), D_hand);
%% 5-6. 정말 같은 시스템인가
% 상태공간에서 전달함수로 되돌아가는 공식이 있습니다.
%
% $$G(s) = C\,(sI - A)^{-1} B + D$$
%
% 이 식이 어디서 오는지도 두 줄이면 나옵니다.
% $\dot{x} = Ax + Bu$ 를 라플라스 변환하면 (초기조건 $0$)
%
% $$sX(s) = A\,X(s) + B\,U(s) \quad \Rightarrow \quad (sI - A)X(s) = B\,U(s)$$
%
% $$X(s) = (sI - A)^{-1} B\,U(s)$$
%
% 이것을 $Y = CX + DU$ 에 넣으면
%
% $$Y(s) = \left[\,C (sI-A)^{-1} B + D\,\right] U(s)$$
%
% MATLAB 에서는 `tf(ss(A,B,C,D))` 한 줄이면 됩니다. 2주차 결과와 비교해 봅니다.
sys_hand = ss(A_hand, B_hand, C_hand, D_hand);
G_from_ss = tf(sys_hand);
fprintf('=== 상태공간에서 되돌린 전달함수 ===\n');
G_from_ss
fprintf('  2주차에서 직접 구한 것과 극점 차이 : %.2e\n', ...
        max(abs(sort(pole(G_from_ss)) - sort(pole(G_msd)))));
fprintf('  --> 같은 시스템의 두 표현일 뿐입니다\n\n');
t_cmp = (0:0.02:30)';
plot(t_cmp, step(G_from_ss, t_cmp), 'LineWidth', 2.5); hold on;
plot(t_cmp, step(G_msd, t_cmp), '--', 'LineWidth', 1.8);
yline(1, 'k:'); grid on;
xlabel('시간 [s]'); ylabel('위치 [m]');
legend('상태공간에서 되돌린 것', '2주차 전달함수', '최종값', 'Location','southeast');
title('두 응답이 완전히 겹친다 — 같은 시스템이다');
