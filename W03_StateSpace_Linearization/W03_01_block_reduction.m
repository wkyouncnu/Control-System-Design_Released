%% W03_01_block_reduction.m
%  3주차 실습 (1) : 블록선도 합치기
%
%  실제 시스템은 전달함수 하나로 끝나지 않습니다.
%  제어기, 모터, 기계, 센서가 줄줄이 이어져 있습니다.
%  이걸 하나로 합치는 방법을 배웁니다.
%
%  결론부터 말하면 외울 것은 딱 세 개입니다.
%
%      직렬  ->  곱한다
%      병렬  ->  더한다
%      되먹임 ->  G / (1 + G*H)
%
%  이 셋이면 아무리 복잡한 그림도 하나로 정리됩니다.
%
%  대응하는 강의노트 : W03_LectureNote.mlx
%
%  제어시스템설계 3주차 | 충남대학교 자율운항시스템공학과

clc; clear all; close all;

%% 경로 자동 등록 — setup_path 를 아직 안 했어도 알아서 잡습니다
%  (이 블록은 실습 내용과 상관없습니다. 지우지 마십시오.)
if isempty(which('plant_msd'))
    p_ = pwd;
    if ~isempty(mfilename('fullpath')), p_ = fileparts(mfilename('fullpath')); end
    for k_ = 1:4
        if isfile(fullfile(p_,'setup_path.m')), run(fullfile(p_,'setup_path.m')); break; end
        p_ = fileparts(p_);
    end
    clear p_ k_
end
s = tf('s');

%% 1. 연습용 블록 세 개
%
%  설명을 위해 간단한 전달함수 세 개를 준비합니다.
%  숫자에 큰 의미는 없습니다. 규칙을 익히는 것이 목적입니다.

G1 = 1/(s+1);           % 제어기라고 생각합시다
G2 = 20/(s+2);          % 플랜트(모터 등)라고 생각합시다
H  = 3/(0.2*s+1);       % 센서라고 생각합시다 (실제보다 3배로 읽는 불량 센서)

t = 0:0.01:10;

fprintf('연습용 블록\n');
fprintf('  G1 = 1/(s+1)        제어기\n');
fprintf('  G2 = 20/(s+2)       플랜트     (천천히 넣으면 10배로 나옴)\n');
fprintf('  H  = 3/(0.2*s+1)    센서       (실제보다 3배로 읽음)\n\n');
fprintf('  참고: "천천히 넣었을 때 몇 배로 나오는가"를 DC 이득이라 하고\n');
fprintf('        MATLAB 에서는 dcgain 명령으로 구합니다.\n');
fprintf('        G2 의 DC 이득 = %.0f,  H 의 DC 이득 = %.0f\n\n', dcgain(G2), dcgain(H));

%% 2. 직렬 연결 : 곱한다
%
%      u --> [G1] --> [G2] --> y
%
%  일상 비유:
%      환율 계산과 같습니다.
%      원 -> 달러가 1/1300 배, 달러 -> 유로가 0.9 배라면
%      원 -> 유로는 그냥 두 배율을 곱하면 됩니다.
%
%  전달함수도 똑같습니다. 신호가 G1 을 지나며 G1 배가 되고,
%  이어서 G2 를 지나며 G2 배가 되니까 전체는 G1*G2 배입니다.

T_series = G1 * G2;

fprintf('=== 직렬 연결 ===\n');
T_series

%% 3. 병렬 연결 : 더한다
%
%           +--> [G1] --+
%      u ---+          (+)--> y
%           +--> [G2] --+
%
%  일상 비유:
%      같은 손님이 두 창구에서 각각 서비스를 받고, 결과를 합치는 것과 같습니다.
%      한 사람이 두 갈래로 갈라져 각자 처리된 뒤 더해집니다.
%
%  실제 예: PID 제어기가 바로 이 구조입니다.
%      같은 오차 신호가 P(비례), I(적분), D(미분) 세 갈래로 들어가
%      각각 계산된 뒤 더해져서 나옵니다.

T_parallel = G1 + G2;

fprintf('\n=== 병렬 연결 ===\n');
T_parallel

%% 4. 되먹임 연결 : 이번 절이 핵심
%
%      r --(+)--> [G] --+--> y
%           ^-          |
%           +-----------+
%
%  1주차에서 본 그 구조입니다. 유도는 아주 짧습니다.
%
%      오차는       e = r - y
%      출력은       y = G*e
%
%  두 번째 식에 첫 번째 식을 넣으면
%
%      y = G*(r - y)
%      y + G*y = G*r
%      y*(1 + G) = G*r
%      y/r = G/(1 + G)
%
%  이게 전부입니다. 종이에 직접 한 번 써 보십시오. 세 줄이면 끝납니다.
%
%  외울 형태는 이것입니다.
%
%      폐루프 = 앞으로 가는 길 / (1 + 한 바퀴 도는 길)
%
%  분모의 "1 + 한 바퀴" 가 앞으로 계속 나옵니다.
%  이 식이 0 이 되는 s 가 폐루프의 극점이고, 극점이 시스템의 성격을 정한다는 것은
%  2주차에서 배웠습니다.

G = G1 * G2;                    % 앞으로 가는 길
T_unity = feedback(G, 1);       % MATLAB 명령 (직접 나누기보다 이걸 쓰십시오)

fprintf('\n=== 되먹임 연결 (센서 없음) ===\n');
T_unity

%% 5. 센서가 붙으면
%
%      r --(+)--> [G] --+--> y
%           ^-          |
%           +---[H]-----+
%
%  현실에서는 출력을 그대로 되돌리지 않고 센서로 측정해서 되돌립니다.
%  같은 방법으로 유도하면 분모의 "한 바퀴 도는 길"이 G*H 가 됩니다.
%
%      y/r = G / (1 + G*H)
%
%  일상 비유 (여기가 중요합니다):
%      체온계가 고장 나서 실제보다 3배로 표시된다고 합시다.
%      환자 체온이 12도인데 체온계는 36도라고 보여 줍니다.
%      의사는 "정상이네" 하고 넘어갑니다.
%
%      제어기도 똑같습니다. 제어기는 센서가 보여 주는 값만 믿습니다.
%      그래서 센서 값이 목표와 같아지는 데서 멈춥니다.
%      실제 출력은 센서 이득만큼 어긋난 채로 끝납니다.
%
%  아래 그림에서 실제로 확인해 봅시다.

T_sensor = feedback(G, H);

fprintf('\n=== 센서가 있을 때 정상상태 ===\n');
fprintf('  센서 이득 H(0)     = %.1f  (실제보다 3배로 읽는 센서)\n', dcgain(H));
fprintf('  센서 없을 때 출력  = %.3f  (목표값 1 에 거의 도달)\n', dcgain(T_unity));
fprintf('  센서 있을 때 출력  = %.3f  (1/3 근처에서 멈춤)\n', dcgain(T_sensor));
fprintf('  --> 제어기는 센서가 보여 주는 값이 1 이 되면 만족하고 멈춥니다.\n');
fprintf('      센서가 3배로 부풀려 읽으니, 실제 출력이 1/3 일 때 이미\n');
fprintf('      센서는 1 이라고 보고합니다. 그래서 거기서 멈춰 버립니다.\n');
fprintf('      센서 보정이 왜 중요한지 보여 주는 예입니다.\n');

figure('Name','센서의 영향');
h1 = plot(t, step(T_unity,  t), 'LineWidth', 2); hold on;
h2 = plot(t, step(T_sensor, t), 'LineWidth', 2);
h3 = yline(1, 'k--', 'LineWidth', 1.5);
grid on; xlabel('시간 [s]'); ylabel('출력 y');
title('센서가 없을 때 vs 센서(이득 3)가 있을 때');
legend([h1 h2 h3], {'센서 없음', '센서 있음', '목표값'}, 'Location','southeast');

%% 6. 루프가 두 겹이면 : 안쪽부터 푼다
%
%      r --(+)--> [G1] --(+)--> [G2] --+--> y
%           ^-           ^-            |
%           |            +----[H1]-----+   <- 안쪽 루프
%           +--------------------------+   <- 바깥 루프
%
%  겁먹을 필요 없습니다. 양파 껍질 벗기듯 안쪽부터 하나씩 합치면 됩니다.
%
%  1단계 : 안쪽 루프를 하나의 블록으로 합친다
%  2단계 : 그 블록을 G1 과 직렬로 놓고 바깥 루프를 합친다
%
%  실제 예: 드론이나 자동차가 이런 구조입니다.
%      안쪽 루프는 모터 속도를 빠르게 잡고,
%      바깥 루프는 위치를 천천히 잡습니다.

H1 = 0.5;

T_inner = feedback(G2, H1);          % 1단계
T_total = feedback(G1*T_inner, 1);   % 2단계

fprintf('\n=== 이중 루프 ===\n');
fprintf('  1단계 : 안쪽 루프를 합침\n');
T_inner
fprintf('  2단계 : 바깥 루프까지 합침\n');
T_total

figure('Name','이중 루프');
h1 = plot(t, step(feedback(G1*G2,1), t), 'LineWidth', 2); hold on;
h2 = plot(t, step(T_total, t), 'LineWidth', 2);
h3 = yline(1, 'k--', 'LineWidth', 1.5);
grid on; xlabel('시간 [s]'); ylabel('출력 y');
title('안쪽 루프가 없을 때 vs 있을 때');
legend([h1 h2 h3], {'단일 루프', '이중 루프', '목표값'}, 'Location','southeast');

%% 7. 정리
%
%  오늘 외울 것은 세 줄입니다.
%
%      직렬   : G1 * G2
%      병렬   : G1 + G2
%      되먹임 : G / (1 + G*H)          <- MATLAB 에서는 feedback(G, H)
%
%  그리고 기억할 문장 하나.
%
%      폐루프 = 앞으로 가는 길 / (1 + 한 바퀴 도는 길)
%
%  분모의 "1 + 한 바퀴"는 앞으로 이 과목 내내 나옵니다.
%  6주차 근궤적도, 10주차 안정여유도 결국 이 식을 들여다보는 일입니다.
%
%  실무 팁 : 손으로 G/(1+G) 를 계산하지 말고 feedback(G,1) 을 쓰십시오.
%            손으로 하면 약분이 안 된 채로 남아서 결과가 지저분해집니다.
%
%  다음 실습 : W03_02_state_space.m
%              전달함수 말고 다른 방식으로 시스템을 적는 법을 배웁니다.
