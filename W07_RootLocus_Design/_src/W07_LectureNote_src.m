% | 오른쪽 빨간 곡선 ($z=3$) | 최종값 $0.783$ | 오차 $22\%$ |
% | 오른쪽 초록 곡선 ($z=6$) | 최종값 $0.915$ | 오차 $8.5\%$ — **가장 정확하다** |
% | 세 곡선의 $K$ | $3.6$, $4.8$, $7.2$ | 영점이 멀수록 같은 예산으로 $K$ 를 더 크게 쓸 수 있다 |
% | 세 곡선 모두 봉우리가 거의 없는 것 | 오버슈트가 작다 | PD 는 원래 오버슈트가 작다 |
%
% 왜 $z$ 가 크면 $K$ 를 크게 쓸 수 있는가 — 제어입력의 처음 크기가 대략
