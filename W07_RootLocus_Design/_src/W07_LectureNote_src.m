%
% 2단계에서 쓰는 두 공식은 4주차의 것입니다.
%
% $$\zeta_{min} = \frac{-\ln(\%OS/100)}{\sqrt{\pi^2 + \ln^2(\%OS/100)}}, \qquad \omega_{n,min} = \frac{4}{\zeta_{min}\, t_s}$$
%
% 6단계를 빠뜨리는 사람이 많습니다. 반드시 하십시오.
%
% - 5단계까지는 **근사식**입니다. 극점 두 개, 영점 없음을 가정한 공식이기 때문입니다
% - 진짜 답은 6단계의 `stepinfo` 실측에서 나옵니다
% - 그리고 제어입력을 안 본 설계는 절반만 한 설계입니다
%
% 3~5단계에서 **궤적이 사양 영역을 아예 안 지나면** 비례제어로는 끝입니다.
% 그때부터 오늘의 본론인 보상기 설계가 시작되고, 영점을 어디에 놓을지는
% **2-0절의 각도 부족**으로 계산합니다. 6주차 1-2절의 각도 조건을 뒤집어 쓰는 것입니다.
[zm, wm] = spec2pole(10, 2);
fprintf('사양 : 오버슈트 10 %%, 정착시간 2 s\n');
fprintf('  -> zeta >= %.4f ,  wn >= %.4f\n', zm, wm);
%% 1-2. 오늘 쓰는 새 도구 두 개
% 6주차에서 쓴 `rlocfind` 는 마우스로 궤적 위를 찍는 명령입니다.
% 감을 잡기에는 좋지만 두 가지가 불편합니다.
%
% - 손이 떨리면 값이 달라진다
% - 스크립트를 자동으로 돌릴 수 없다 (클릭을 기다리며 멈춘다)
%
% 그래서 같은 일을 숫자로 하는 함수 두 개를 `common` 폴더에 넣어 두었습니다.
%
% **(1) rl_scan — 근궤적 위를 훑어 성능표를 만든다**
%
% - **원리** — 이득 $K$ 를 촘촘히 바꿔 가며 매번 `feedback` 으로 폐루프를 닫고
%   `pole` · `stepinfo` · `dcgain` 으로 성능을 잰다. 전부 1, 4, 5 주차에서 배운 명령이다
% - **입력** — `rl_scan(C1, G, Kvec)`. 여기서 `C1` 은 **이득을 뺀** 제어기이고
%   개루프는 $L(s) = K\,C_1(s)\,G(s)$ 가 된다. P 제어면 `C1 = 1`, PD 면 `C1 = (s+z)`
% - **출력** — 표(table). 한 행이 이득 하나이고 열은
%   `K` `stable` `zeta` `wn` `OS` `ts` `Tp` `ess` `umax`
% - **주의** — 표의 `zeta` 는 지배극점의 감쇠비다. **영점이 가까이 있으면
%   감쇠비가 커도 오버슈트가 클 수 있다.** 오버슈트는 항상 `OS` 열을 믿을 것
%
% **(2) ctrl_input — 계단 지령에 대한 제어입력**
%
% - **원리** — 지령에서 제어입력까지의 전달함수는 아래와 같다. 여기에 계단 $1/s$ 를
%   곱해 역라플라스 변환하면 $u(t)$ 가 나온다
%
% $$\frac{U(s)}{R(s)} = \frac{C(s)}{1 + C(s)G(s)}$$
%
% - **입력** — `ctrl_input(C, G)`. 여기서 `C` 는 **이득까지 포함한** 제어기
% - **출력** — `[u, t, umax]`
% - **주의** — 이상적인 PD 는 계단 지령에서 $t=0$ 에 임펄스를 만든다.
%   이 함수는 그 임펄스를 뺀 값을 돌려준다 (5절에서 자세히)
%
% 실제로 한 번 써 봅니다.
G_demo = 1/(s*(s+2)*(s+5));
