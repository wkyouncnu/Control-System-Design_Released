%% 3. PI 제어 — 원점에 극점을 추가한다
% $$C(s) = K_p + \frac{K_i}{s} = \frac{K_p\left(s + K_i/K_p\right)}{s}$$
%
% **원점 극점 하나와 영점 하나**를 함께 추가합니다.
%
% - 원점 극점 — 시스템 타입을 하나 올린다 → 정상상태 오차 제거 (5주차)
% - 영점 — 그 극점이 만드는 나쁜 영향을 완화한다
%
% 5주차에서 배운 대로 원점 극점은 궤적을 오른쪽으로 밀어 불안정하게 만듭니다.
% 그래서 PI 는 **반드시 영점을 함께** 붙입니다.
% 영점이 없으면 순수 적분기가 되어 거의 항상 불안정해집니다.
%
% 영점 위치 지침
%
% - **원점에 아주 가깝게** 둔다. 보통 지배극점의 $1/10$ 정도
% - 이유 — 원점 극점과 영점이 거의 상쇄되어 궤적의 나머지는 거의 그대로 두면서
%   정상상태 오차만 없애기 위해서
%% 4. PD 와 PI 는 서로를 대신할 수 없다
% 선택 기준은 단순합니다. **무엇이 문제인가** 를 보면 됩니다.
%
% - 과도응답이 문제다 (느리다, 진동한다) → **PD**
% - 정상상태 오차가 문제다 → **PI**
% - 둘 다 문제다 → **PID** (11주차)
%
% 주의
%
% - **PD 는 정상상태 오차를 개선하지 못한다.** 영점은 타입을 바꾸지 않는다
% - **PI 는 과도응답을 나쁘게 만든다.** 극점을 추가하니 느려진다
%
% 실제로 확인해 보면 P 제어와 PD 제어의 타입은 둘 다 $1$ 로 같고,
% PI 를 붙여야 타입이 $2$ 가 됩니다.
%
% 타입 0 플랜트 $G = 1/((s+1)(s+4))$ 에 셋을 붙여 나란히 보겠습니다.
%
% ![PD 는 과도응답을, PI 는 정상상태를 고친다](w07_pd_vs_pi.png)
%
% **그림 파일** `w07_pd_vs_pi.png` — `make_figures.m` 의 `fig_w07_pd_vs_pi`
%   · 다시 만들려면 `make_figures('w07_pd_vs_pi')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w07_pd_vs_pi`
% **직접 바꿔 보려면** — `W07_02_pd_and_pi.m` 의 **4절**에서 제어기 이득을
% 바꿔 가며 같은 비교를 해 볼 수 있습니다
%
% 그림 해석 — **왼쪽은 오래, 오른쪽은 짧게 본 같은 응답입니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 회색 곡선 (P) | $0.833$ 에서 멈춘다 | 오차 $17\%$ 가 영구히 남는다 |
% | 왼쪽 빨간 곡선 (PD) | $0.857$ 에서 멈춘다 | **PD 도 오차가 남는다.** 조금 나아졌을 뿐 |
% | 빨간 곡선이 회색보다 아주 조금 높은 것 | $0.857$ 대 $0.833$ | 영점이 $K_p$ 를 조금 키웠을 뿐, 타입은 그대로 |
