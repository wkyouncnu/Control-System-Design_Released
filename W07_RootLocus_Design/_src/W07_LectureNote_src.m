% - 같은 제어입력 예산 안에서 오차를 결정하는 것은 $K_p = Kz/4$ 다
% - $z = 1$ 이면 $K_p = 0.92$, $z = 6$ 이면 $K_p = 10.92$ 로 $12$ 배 차이가 난다
% - 그래서 **영점을 왼쪽으로 옮길수록 같은 힘으로 더 정확해진다**
%
% ![같은 힘 예산에서 영점을 왼쪽에 둘수록 정확해진다](w07_zero_place.png)
%
% **그림 파일** `w07_zero_place.png` — `make_figures.m` 의 `fig_w07_zero_place`
%   · 다시 만들려면 `make_figures('w07_zero_place')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w07_zero_place`
