%% 10. 유사미분 — 사실 Lead 와 같은 것
% 미분항을 안전하게 쓰는 또 하나의 방법이 있습니다.
%
% $$\text{순수 미분} : K_d s \qquad\rightarrow\qquad
%   \text{유사미분} : \frac{K_d s}{\tau s + 1}$$
%
% 분모에 1차 필터를 붙인 것입니다. 고주파 이득이 $K_d/\tau$ 로 제한됩니다.
%
% 왜 이렇게까지 하는지, 잡음이 조금 섞인 신호를 실제로 미분해 보면 압니다.
%
% ![잡음 3 % 가 미분을 지나면 신호를 삼킨다](w07_pseudo_deriv.png)
%
% **그림 파일** `w07_pseudo_deriv.png` — `make_figures.m` 의 `fig_w07_pseudo_deriv`
%   · 다시 만들려면 `make_figures('w07_pseudo_deriv')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w07_pseudo_deriv`
% **직접 바꿔 보려면** — 함수 안의 `tau = 0.05` 를 `0.005` 로 줄이면
% 유사미분도 함께 지저분해집니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 굵은 곡선 | 진짜 신호 (진폭 $1$ 의 사인파) | 우리가 재고 싶은 것 |
% | 왼쪽 회색 선 | 잡음이 섞인 측정 신호 | 파란 선과 거의 구별이 안 된다 |
% | 왼쪽 그림 제목 | 잡음이 신호의 $3\%$ | **눈으로는 아무 문제 없어 보인다** |
% | 오른쪽 빨간 선 (순수 미분) | 위아래로 $\pm 100$ 까지 심하게 진동한다 | 최대 $103$. **참값의 $30$ 배** |
% | 오른쪽 빨간 선 속에서 참값이 안 보이는 것 | 신호가 잡음에 묻혔다 | 미분이 잡음만 키웠다 |
% | 오른쪽 검은 점선 | 참값 (진폭 약 $3.1$) | $2\pi \times 0.5 = 3.14$ |
% | 오른쪽 파란 곡선 (유사미분) | 검은 점선과 **거의 포개진다** | 최대 $4.2$. 참값에 가깝다 |
% | 두 미분의 최대값 비 | $103$ 대 $4.2$, 약 $25$ 배 | 필터 하나가 이만큼 막아 준다 |
%
% **왼쪽 그림에서는 문제가 안 보이는데 오른쪽에서 터집니다.**
% 그래서 미분항을 쓸 때는 반드시 제어입력을 그려 봐야 합니다.
%
% 그런데 유사미분을 쓴 PD 를 정리해 보면
%
% $$K_p + \frac{K_d s}{\tau s+1} = \frac{(K_p\tau + K_d)s + K_p}{\tau s + 1}$$
%
% 분자와 분모가 모두 1차인 전달함수, 즉 **Lead 입니다.**
% 이름만 다를 뿐 같은 것을 하고 있는 셈입니다.
%
% Simulink 의 `PID Controller` 블록도 내부적으로 이 방식을 씁니다.
% 블록을 열면 "Filter coefficient N" 이라는 값이 있는데 그것이 $\tau = 1/N$ 입니다.
% 11주차에서 다시 만납니다.
%% 11. 오늘의 정리
% **설계 절차**
%
% - **설계 6단계** : 사양 → $s$ 평면 → 궤적 → 영역 → 이득 → **검증**
% - 5단계까지는 근사식이다. 6단계의 `stepinfo` 실측이 진짜 답이다
% - `rl_scan` 으로 이득을 훑고 `ctrl_input` 으로 제어입력을 확인한다
%
% **비례제어로 안 되는 세 가지 경우**
%
% - 궤적이 사양 영역을 비껴간다 (6주차의 DC 모터)
% - 궤적이 실축을 벗어나지 않아 진동 사양 자체가 성립하지 않는다 (예제 B)
% - 오차 사양이 요구하는 이득이 안정 한계를 넘는다 (예제 C)
%
% **설계할 때 조심할 것**
%
% - **감쇠비만 보고 오버슈트를 판단하지 말 것.** 영점이 가까우면 어긋난다
% - 안정한 극점 상쇄는 써도 되지만 **불안정한 극점 상쇄는 절대 금지**
% - 제어입력을 사양에 넣으면 답이 좁아지고 고르는 기준이 생긴다
% - 손 공식 : 비례제어는 $u(0^+) = K$.
%   PD 는 **상대차수에 따라 갈린다** — $r=2$ 면 $K(z-Kb)$, $r\ge3$ 이면 $Kz$ (4-2-1절)
%
% **보상기**
%
% - 근궤적이 사양 영역을 비껴가면 **길 자체를 바꿔야** 한다
% - **PD** 는 영점을 추가해 궤적을 왼쪽으로 당긴다. 과도응답을 고친다
% - 영점 위치는 감이 아니라 **각도 부족**으로 계산한다 :
%   목표 극점에서 $-180^\circ$ 에 모자란 각 $\phi$ 를 재고
%   $z = \sigma_d + \omega_d/\tan\phi$ 에 놓는다 (2-0절)
% - 그렇게 해도 **오버슈트는 공식보다 커진다.** 영점이 더 키우기 때문이다.
%   목표를 보수적으로 잡고 되풀이한다
% - **PI** 는 원점 극점을 추가해 타입을 올린다. 정상상태 오차를 고친다
% - 둘은 서로 다른 문제를 풀며 **서로를 대신할 수 없다**
% - PD 는 부적절해서 **실제로 만들 수 없다.** MATLAB 도 거부한다
% - **Lead** 는 PD 에 극점을 붙여 고친 것. $p$ 를 $z$ 의 $5\sim20$ 배로
% - **Lag** 는 PI 의 원점 극점을 원점 근처로 옮겨 안전하게 만든 것
% - Lead 와 Lag 는 식이 같고 부등호만 다르다
% - $p$ 를 키우면 성능은 좋아지지만 제어입력이 커진다. **맞바꿈이다**
% - 잡음이 들어오면 PD 의 제어입력만 요동친다. **출력만 보면 놓친다**
