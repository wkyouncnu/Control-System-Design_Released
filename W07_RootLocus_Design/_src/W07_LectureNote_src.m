% | 첫째 칸 PD | 초록 $\circ$ 하나만 | 궤적을 왼쪽으로 당기기만 한다. **부작용이 없다** |
% | 둘째 칸 Lead | $\circ$ 옆에 $\times$ 가 **훨씬 왼쪽**에 | 당기는 힘은 그대로, 미는 힘은 멀리 두어 약하게 |
% | 둘째 칸에서 $\times$ 가 $-12$, $\circ$ 가 $-3$ | 약 $4$ 배 | 경험칙 "$p$ 를 $z$ 의 $5{\sim}20$ 배로" |
