%% 6. Lead 보상기 — PD 에 극점을 하나 붙인 것
% $$C(s) = K_c\,\frac{s+z}{s+p}, \qquad p > z$$
%
% PD 와 비교하면
%
% - **PD** — $K_d(s+z)$. 분모 없음. 고주파 이득이 무한대
% - **Lead** — $K_c(s+z)/(s+p)$. 분모 있음. 고주파 이득이 $K_c$ 로 제한
%
% 이름이 Lead(앞섬)인 이유는 위상을 앞서게 만들기 때문입니다.
% 위상 이야기는 9~10주차에서 제대로 다룹니다. 오늘은 근궤적 관점으로만 봅니다.
%
% 근궤적 관점
%
% - 영점 $s=-z$ — 궤적을 왼쪽으로 당긴다 (PD 와 같은 효과)
% - 극점 $s=-p$ — 궤적을 오른쪽으로 민다 (원하지 않는 부작용)
%
% 그래서 극점을 **영점보다 훨씬 왼쪽에** 둡니다.
% 그러면 극점의 나쁜 영향이 작아지고 영점의 좋은 효과만 남습니다.
%
% **경험칙** — $p$ 를 $z$ 의 $5\sim20$ 배로
%% 6-1. Lead 설계에는 맞바꿈이 있다
% 실습에서 $z=2$ 로 고정하고 $p$ 만 바꿔 본 결과입니다.
%
% - $p=15$ — $K_c = 265$, 최대입력 $265\,\mathrm{V}$, 오버슈트 $8.2\%$, 정착 $1.17\,\mathrm{s}$
% - $p=30$ — $K_c = 552$, 최대입력 $552\,\mathrm{V}$, 오버슈트 $4.1\%$, 정착 $1.04\,\mathrm{s}$
% - $p=60$ — $K_c = 1135$, 최대입력 $1135\,\mathrm{V}$, 오버슈트 $2.6\%$, 정착 $0.94\,\mathrm{s}$
%
% **$p$ 를 키우면 성능은 좋아지지만 제어입력이 커집니다.**
%
% ![p 를 키우면 성능도 전압도 함께 오른다](w07_lead_tradeoff.png)
%
% **그림 파일** `w07_lead_tradeoff.png` — `make_figures.m` 의 `fig_w07_lead_tradeoff`
%   · 다시 만들려면 `make_figures('w07_lead_tradeoff')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w07_lead_tradeoff`
% **직접 바꿔 보려면** — `W07_05_lead_and_lag.m` 의 **3절** 후보 표에서
% `p_cand` 에 $120$ 을 추가해 보십시오
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 곡선 ($p=15$) | 오버슈트 $8.2\%$, $t_s = 1.17$ s | 셋 중 오버슈트가 가장 크고 가장 느리다 |
% | 왼쪽 빨간 곡선 ($p=30$) | 오버슈트 $4.1\%$, $t_s = 1.04$ s | 나아졌다 |
% | 왼쪽 초록 곡선 ($p=60$) | 오버슈트 $2.6\%$, $t_s = 0.94$ s | **가장 좋다** |
% | 세 곡선의 최종값 | 셋 다 $1$ | 정상상태는 셋 다 같다. 과도응답만 다르다 |
% | 오른쪽 파란 곡선 ($p=15$) | 최대 $258$ V | |
% | 오른쪽 빨간 곡선 ($p=30$) | 최대 $522$ V | 두 배 |
% | 오른쪽 초록 곡선 ($p=60$) | 최대 $1011$ V | **또 두 배** |
% | 세 곡선의 $t=0$ 값 | $p$ 에 거의 비례 | $u(0) \approx K_c$ 이고 $K_c$ 가 $p$ 에 비례한다 |
% | 오른쪽 곡선들이 $t>0.2$ s 에서 음수로 내려가는 것 | 브레이크를 건다 | 미분 동작이 하는 일 |
%
% **왼쪽에서 초록을 고르고 싶어지지만, 오른쪽을 보면 $1011$ V 입니다.**
% $24$ V 짜리 드라이버로는 어느 것도 못 씁니다.
% 그래서 실제 설계는 "성능이 가장 좋은 것" 이 아니라
% **"구동기가 낼 수 있는 것 중 가장 좋은 것"** 을 고르는 일이 됩니다.
%
% 즉 "가장 좋은 성능" 을 고르면 안 됩니다.
% 구동기가 낼 수 있는 전압 안에서 골라야 합니다.
% 6주차의 교훈이 여기서도 그대로 적용됩니다.
%% 7. Lag 보상기 — PI 의 안전한 버전
% PI 의 문제는 원점 극점입니다.
%
% - 원점 극점은 궤적을 오른쪽으로 밀어 불안정하게 만든다 (5주차)
% - 적분기는 포화와 만나면 와인드업을 일으킨다 (11주차)
%
% Lag 는 극점을 원점이 아니라 **원점 아주 가까이**에 둡니다.
%
% $$C(s) = K_c\,\frac{s+z}{s+p}, \qquad p < z, \quad p \text{ 는 아주 작다}$$
%
% **Lead 와 식이 같고 부등호만 반대입니다.**
%
% - **Lead** — $p > z$ (극점이 영점보다 왼쪽) → 과도응답 개선
% - **Lag** — $p < z$ (극점이 영점보다 오른쪽) → 정상상태 오차 개선
%
% Lag 의 효과
%
% - 저주파 이득이 $z/p$ 배로 커진다 → 정상상태 오차가 그만큼 줄어든다
% - 극점이 원점은 아니므로 오차가 **완전히 $0$ 이 되지는 않는다**
% - 대신 불안정해질 위험이 훨씬 적다
%
% 즉 Lag 는 **오차를 완전히 없애지는 못하지만 안전하게 크게 줄이는** 타협입니다.
% 실습에서 $z=1$, $p=0.1$ 로 램프 오차가 $0.50$ 에서 $0.05$ 로 정확히 $10$ 배 줄었습니다.
%% 8. 네 가지 보상기 정리
% - **P** — $K_p$. 이득만 조절. 아무것도 고치지 못함
% - **PD** — $K_d(s+z)$. 과도응답 개선. **고주파 잡음 증폭, 만들 수 없음**
% - **Lead** — $K_c(s+z)/(s+p)$, $p>z$. 과도응답 개선. 실무용
% - **PI** — $K_p(s+z)/s$. 정상상태 오차 제거. 불안정, 와인드업
% - **Lag** — $K_c(s+z)/(s+p)$, $p<z$. 정상상태 오차 감소. 응답이 조금 느려짐
%
% 고르는 법
%
% - 과도응답이 문제 → **Lead**
% - 정상상태 오차가 문제 → **Lag**
% - 둘 다 문제 → **Lead-Lag** (둘을 직렬로)
% - 오차를 완전히 $0$ 으로 → **PI 또는 PID** (11주차)
%
% 혼동을 피하는 방법 — Lead 와 Lag 는 식이 같고 부등호만 다릅니다.
%
% - **Lead** : 극점이 영점보다 **왼쪽**
% - **Lag** : 극점이 영점보다 **오른쪽**
%% 8-1. 네 보상기의 극영점 배치를 한 그림에
% 표만 보면 혼동하기 쉽습니다. **어디에 무엇을 놓는가** 를 그림으로 보면 간단합니다.
%
% ![네 보상기가 극점과 영점을 어디에 놓는가](w07_pz_map.png)
%
% **그림 파일** `w07_pz_map.png` — `make_figures.m` 의 `fig_pz_map`
%   · 다시 만들려면 `make_figures('w07_pz_map')`
