TP0 = rl_scan(1, GE, linspace(0.2, 25, 300));
okP0 = TP0.stable & TP0.OS <= 20;
subP0 = TP0(okP0,:); [~, jP0] = min(subP0.ess);
tE = linspace(0, 8, 800)';
plot(tE, step(feedback(subP0.K(jP0)*GE,1), tE), 'LineWidth', 2); hold on;
plot(tE, step(TE, tE), 'LineWidth', 2);
