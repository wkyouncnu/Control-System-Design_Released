%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림 검은 $\times$ | 플랜트 극점 $-1$, $-4$ | 우리가 못 바꾸는 것 |
% | 왼쪽 그림 동그라미 셋 | 우리가 놓은 영점 $-1$, $-3$, $-6$ | 색이 그 영점의 궤적 색과 같다 |
% | 왼쪽 파란 궤적 ($z=1$) | 극점 $-1$ 과 겹쳐 **상쇄**된다. 남은 길이 짧다 | 안정한 극점을 지우는 기법 (2-2절) |
% | 왼쪽 빨간 궤적 ($z=3$) | 한 가지는 $-1$ 에서 영점 $-3$ 으로, 다른 가지는 $-4$ 에서 왼쪽 무한대로 | 실축을 못 벗어난다. **진동이 없다** |
% | 왼쪽 초록 궤적 ($z=6$) | 크게 **원을 그리며** 돈다 | 영점이 멀수록 궤적이 크게 부푼다 |
% | 세 궤적 모두 허수축을 안 넘는 것 | 좌반면 안에 머문다 | 영점 덕분에 셋 다 안정하다 |
% | 오른쪽 그림 | 같은 $\max|u| \le 10$ 예산으로 고른 응답 | **조건을 똑같이 맞춘 비교**다 |
