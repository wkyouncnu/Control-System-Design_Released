% - 위치를 일정한 값으로 유지하고 싶다 → 타입 1 이면 충분
% - 일정한 속도로 따라가고 싶다 (램프 추종) → 타입 2 가 필요
% - 예: 위성 안테나가 별을 추적하려면 타입 2 가 있어야 한다
%% 6-1. 표를 그림으로 — 아홉 칸을 한꺼번에
% 타입 0, 1, 2 에 계단 · 램프 · 포물선을 각각 넣어 봅니다.
% **파란 선이 지령, 빨간 선이 출력**이고 둘 사이 간격이 오차입니다.
%
% 한 칸씩 보지 말고 **대각선**을 보십시오.
% 왼쪽 위에서 오른쪽 아래로 갈수록 오차가 커집니다. 그것이 규칙 그대로입니다.
%
% ![적분기 하나가 입력 한 단계를 감당한다](w05_type_table.png)
%
% **그림 파일** `w05_type_table.png` — `make_figures.m` 의 `fig_type_table`
%   · 다시 만들려면 `make_figures('w05_type_table')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_type_table`
% **직접 바꿔 보려면** — 바로 아래 코드가 같은 그림을 그립니다.
% `Ls_type` 에 타입 3 을 하나 더 넣어 보십시오
%
% 그림 해석 — **왼쪽 위에서 오른쪽 아래로 대각선을 따라 읽으십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 모든 칸의 파란 선 | 지령 $r$ | 계단, 램프, 포물선 |
% | 모든 칸의 빨간 선 | 실제 출력 $y$ | 파란 선과의 간격이 오차다 |
% | 타입 0 · 계단 | 빨간 선이 $0.5$ 에서 멈춤. **오차 $0.50$ 로 일정** | 유한한 오차가 남는다 |
% | 타입 0 · 램프 | 오차가 $3.3 \to 6.3$ 으로 **커진다** | 자기 차수보다 높은 입력은 벌어진다 |
% | 타입 0 · 포물선 | 오차가 $10.7 \to 39.5$ | 더 심하게 벌어진다 |
% | 타입 1 · 계단 | 두 선이 **완전히 겹친다**. 오차 $0$ | 적분기 하나가 계단을 감당했다 |
% | 타입 1 · 램프 | 오차 $1.00$ 로 일정 | 한 단계 올라갔으니 램프에서 유한 오차 |
% | 타입 1 · 포물선 | 오차가 $5.2 \to 11.2$ | 여전히 벌어진다 |
% | 타입 2 · 계단 · 램프 | 둘 다 오차 $0$ | 적분기 둘이 두 단계를 감당했다 |
% | 타입 2 · 포물선 | 오차 $1.00$ 로 일정 | 여기서 멈춘다 |
% | 대각선 (타입 $=$ 입력 차수) | 전부 **"일정"** | 유한한 오차가 남는 자리 |
% | 대각선 위쪽 | 전부 **"오차 0"** | 완벽하게 따라간다 |
% | 대각선 아래쪽 | 전부 **"커짐"** | 벌어진다 |
% | 타입 2 · 계단 칸의 출렁임 | $1.5$ 까지 올라갔다 내려온다 | 적분기가 많으면 **진동이 심해진다.** 7절의 복선 |
Ls_type = { 'Type 0',  5/((s+1)*(s+5))
            'Type 1',  5/(s*(s+5))
            'Type 2',  5*(s+1)/(s^2*(s+5)) };
in_name = {'계단', '램프', '포물선'};
tt = (0:0.05:12)';
inputs = { ones(size(tt)), tt, 0.5*tt.^2 };
figure('Position',[60 60 1100 760]);
tiledlayout(3,3,'TileSpacing','compact','Padding','compact');
for a = 1:3
    for b = 1:3
        nexttile
        T = feedback(Ls_type{a,2}, 1);
        u = inputs{b};
        if all(real(pole(T)) < 0)
            y = lsim(T, u, tt);
        else
            y = nan(size(tt));
        end
        plot(tt, u, 'LineWidth', 2, 'Color', [0.15 0.35 0.75]); hold on;
        plot(tt, y, 'LineWidth', 2, 'Color', [0.85 0.20 0.15]);
        grid on; xlim([0 12]);
        ymax = max([u; y(~isnan(y))]);
        ylim([-0.1*ymax 1.15*ymax]);
        if a == 1, title(sprintf('%s 입력', in_name{b}), 'FontSize', 11); end
        if b == 1, ylabel(Ls_type{a,1}, 'FontWeight','bold'); end
        if a == 3, xlabel('시간 [s]'); end
        % 마지막 오차를 글자로.
        % "커진다" 는 판정은 크기가 아니라 절반 시점과 견주어 정한다.
        % 크기로만 보면 타입 0 + 계단(오차 0.50 으로 일정) 이 잘못 걸린다.
        e_end  = u(end) - y(end);
        e_half = u(round(end/2)) - y(round(end/2));
        if isnan(e_end)
            txt = '불안정';
        elseif abs(e_end) < 5e-3
            txt = '오차 0';
        elseif abs(e_end) > abs(e_half)*1.3 + 1e-6
            txt = sprintf('오차 커짐 (%.1f -> %.1f)', e_half, e_end);
        else
            txt = sprintf('오차 %.2f 로 일정', e_end);
        end
        text(0.05, 0.90, txt, 'Units','normalized', 'FontSize', 11, ...
             'FontWeight','bold', 'Color', [0.3 0.3 0.3]);
    end
end
