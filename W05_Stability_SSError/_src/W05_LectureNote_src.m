% | 빨간 화살표 $\tau = Ki$ | 전기 $\rightarrow$ 기계 | 전류가 흐르면 **토크**가 난다 |
% | 파란 화살표 $e = K\omega$ | 기계 $\rightarrow$ 전기 | 빨리 돌면 **역기전력**이 생겨 전류를 방해한다 |
% | 두 화살표가 **양방향**인 것 | 서로 물고 있다 | 그래서 식이 **두 줄**이고 전달함수가 2차가 된다 |
% | 두 식에 모두 나오는 $K$ | 같은 상수 | 모터 상수 하나가 양쪽을 잇는다 |
% | 초록 화살표 $b\omega$ | 마찰 토크 | 속도에 비례해 막는다. MSD 의 댐퍼와 같은 역할 |
% | 아래 두 줄 | 전기 쪽 식과 기계 쪽 식 | 이 둘을 연립해서 없애면 $G(s)$ 가 나온다 |
