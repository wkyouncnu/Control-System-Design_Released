% **타입이 올라갈수록 안정도가 나빠집니다.**
%
% ![적분기를 넣을수록 임계이득이 내려간다](w05_tradeoff.png)
%
% **그림 파일** `w05_tradeoff.png` — `make_figures.m` 의 `fig_w05_tradeoff`
%   · 다시 만들려면 `make_figures('w05_tradeoff')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w05_tradeoff`
% **직접 확인해 보려면** — `W05_01_stability.m` 의 **3절**이 같은 계산을
% 3차 안정 조건으로 손계산해 대조합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림 세로축 | 폐루프 극점 **실수부의 최댓값** | 가장 오른쪽 극점이 어디 있는가. 이것 하나로 안정 여부가 정해진다 |
% | 굵은 가로선 $0$ | 허수축 | **이 선 아래면 안정, 위면 불안정** |
% | 파란 곡선 (타입 0) | $K$ 를 $10^3$ 까지 키워도 계속 **아래**에 있다 | 2차 시스템은 항상 안정 |
% | 파란 곡선이 $K\approx 1$ 에서 꺾여 내려가는 것 | $-6$ 까지 떨어진다 | 이득을 키우면 **오히려 빨라진다** |
% | 빨간 곡선 (타입 1) | $K \approx 122$ 에서 $0$ 을 뚫는다 | 여기가 임계이득. 삼각형 표시가 그 자리 |
% | 빨간 곡선이 그 전에 $-1$ 까지 내려갔다 오는 것 | 중간에 가장 안정한 지점이 있다 | 이득은 **적당한 값**이 가장 좋다 |
% | 초록 곡선 (타입 2) | 왼쪽 끝부터 **이미 $0$ 위**에 있다 | 어떤 $K$ 로도 안정하지 않다 |
% | 오른쪽 표 세로 방향 | 아래로 갈수록 오차 칸은 좋아진다 | 타입이 올라가면 정상상태는 좋아진다 |
% | 오른쪽 표 마지막 열 | 아래로 갈수록 임계이득이 나빠진다 | **같은 방향으로 좋아지지 않는다** |
%
% 왜 그런가
