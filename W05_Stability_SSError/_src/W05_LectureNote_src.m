%
% 마지막 줄은 과장이 아닙니다. 특성방정식을 써 보면 $s$ 의 1차 항 계수가
% $0$ 이 되어, 계수가 전부 양수여야 한다는 **필요조건부터** 깨집니다.
% 비례이득 하나만으로는 손을 쓸 수가 없습니다. 이럴 때 쓰는 것이 7주차의
% 보상기와 11주차의 PID 입니다.
