% 같은 실험을 속도 모델로 하면 $K$ 를 아무리 키워도 안정합니다.
%
% 이유는 **차수**입니다.
%
% - 속도 모델은 **2차** — 특성방정식이 2차. 계수가 모두 양수면 항상 안정
% - 위치 모델은 **3차** — 3차부터는 계수가 양수여도 불안정할 수 있다
%
% 2차 시스템에서 $K$ 를 키우면 상수항만 커지므로 계수 부호가 바뀌지 않습니다.
%
% 즉 **적분기 하나가 추가되면서 시스템이 훨씬 까다로워진 것**입니다.
% 이것이 다음 이야기로 이어집니다.
%% 3. 정상상태 오차 — 왜 남는가
% 오차식을 세우기 전에 **오차 $e$ 가 그림의 어디인지** 확인합니다.
%
% ![오차 e 는 합산점 바로 뒤의 신호다](loop_closed.png)
%
% **그림 파일** `loop_closed.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_closed')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('closed', ...)` 로 부릅니다
%
% 그림 해석 — **유도에 쓸 기호를 그림에서 하나씩 짚습니다**
%
% | 관찰 위치 | 관찰 내용 | 유도에서의 역할 |
% |---|---|---|
% | 왼쪽으로 들어오는 화살표 | 목표값 $r$ | 우리가 넣는 것. 계단·램프·포물선 |
% | 원 안의 $+$ 와 $-$ | $r$ 에서 $y$ 를 뺀다 | **이 뺄셈의 결과가 $e$** 다 |
% | 원 바로 뒤의 화살표 | 오차 $e$ | 우리가 $0$ 으로 만들고 싶은 것 |
% | $C(s)$ 와 $G(s)$ 두 상자 | 앞으로 가는 길 | 둘을 곱한 것이 **개루프 $L = CG$** |
% | 오른쪽 끝 | 출력 $y$ | $L$ 을 지나 나온 것 |
% | 아래 되먹임 선 | $y$ 를 그대로 되돌린다 | **단위 되먹임** ($H=1$) |
%
% 이제 유도합니다. 그림에서 화살표를 따라가며 **두 줄**만 적으면 됩니다.
%
% $$e = r - y, \qquad y = L\,e$$
%
% 둘째 식을 첫째에 넣습니다.
%
% $$e = r - L\,e$$
%
% **$e$ 가 양변에 나왔으므로** 한쪽으로 모읍니다.
%
% $$e + L\,e = r \qquad\Rightarrow\qquad (1 + L)\,e = r$$
%
% 양변을 $(1+L)$ 로 나누면 오차식이 나옵니다.
%
% $$E(s) = \frac{R(s)}{1 + L(s)}$$
%
% **1주차에서 본 $(1+KG)$ 와 똑같은 자리**입니다.
% 그때는 $K$ 하나였고 지금은 제어기 전체 $L$ 이라는 차이뿐입니다.
%
% 이제 $t \to \infty$ 일 때의 값을 알고 싶습니다.
% 시간영역으로 역변환할 필요 없이 **최종값 정리**를 쓰면 됩니다.
%
% $$\lim_{t\to\infty} e(t) = \lim_{s\to 0} s\,E(s)$$
%
% 오차식을 넣으면
%
% $$e_{ss} = \lim_{s \to 0} \frac{s R(s)}{1 + L(s)}$$
%
% 핵심은 분모의 $L(0)$ 입니다.
%
% - $L(0)$ 이 **유한**하면 오차가 남는다
% - $L(0)$ 이 **무한대**면 오차가 $0$ 이 된다
%
% $L(0)$ 을 무한대로 만들려면 $L(s)$ 의 분모에 $s$ 가 있으면 됩니다.
% $s=0$ 에서 $0$ 으로 나누게 되기 때문입니다. 그 분모의 $s$ 가 바로 **적분기**입니다.
%% 3-1. 직관으로 보면
% - **비례제어**는 오차가 있어야만 힘을 낸다. 오차가 $0$ 이면 힘도 $0$
% - **적분제어**는 오차를 쌓아 둔다. 오차가 $0$ 이 되어도 쌓인 값이 남아
%   계속 힘을 낼 수 있다
%
% 그래서 적분제어는 오차를 $0$ 까지 밀어붙일 수 있습니다.
%
% 1주차에서 "오차가 제어기의 연료" 라고 했던 것을 떠올리십시오.
% 적분기는 **연료를 저장해 두는 탱크**인 셈입니다.
%
% 말로만 하면 잘 안 와닿으니 세 장을 나란히 놓고 보겠습니다.
% 특히 **세 번째 그림**을 보십시오. 여기가 핵심입니다.
%
% ![오차가 0 인데도 힘을 낼 수 있어야 오차가 0 으로 간다](w05_why_error.png)
%
% **그림 파일** `w05_why_error.png` — `make_figures.m` 의 `fig_w05_why_error`
%   · 다시 만들려면 `make_figures('w05_why_error')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w05_why_error`
% **직접 바꿔 보려면** — `W05_02_steady_state_error.m` 에서 $K_i$ 를 $0$ 으로
% 두고 실행하면 왼쪽 그림의 빨간 곡선만 남습니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림 빨간 곡선 | $0.80$ 에서 평평해진다 | 비례만 쓰면 목표 $1$ 에 **영원히 못 닿는다** |
% | 왼쪽 그림 파란 곡선 | $1.00$ 에 정확히 도달 | 적분기가 있으면 닿는다 |
% | 가운데 그림 빨간 곡선 | $0.20$ 에서 멈춘다 | 오차가 **남아 버틴다** |
% | 가운데 그림 파란 곡선 | $0$ 으로 내려간다 | 오차가 사라진다 |
% | 오른쪽 그림 검은 점선 | $u = 1$ | 목표 $1$ 을 유지하려면 **꼭 이만큼의 힘**이 필요하다 |
% | 오른쪽 그림 빨간 곡선 | $0.80$ 에서 멈춘다 | 비례제어가 낼 수 있는 힘은 $K_p \times e = 4 \times 0.2 = 0.8$ 뿐 |
% | 오른쪽 그림 파란 곡선 | $1.00$ 에 도달 | 적분기가 **모자란 $0.2$ 를 채워** 준다 |
%
% **오른쪽 그림이 오늘의 논리 전체입니다.**
%
% - 목표를 유지하려면 힘 $1$ 이 필요하다
% - 비례제어는 $u = K_p e$ 이므로 $e=0$ 이면 $u=0$ 이 된다. **모순**이다
% - 그래서 비례제어는 반드시 $e = 1/K_p \cdot 1 = 0.2$ 만큼 오차를 남겨야
%   힘 $0.8$ 을 낼 수 있다 (이 플랜트의 이득이 $1$ 이라 $0.8$ 이면 출력 $0.8$)
% - 적분기는 **오차와 무관하게 쌓아 둔 값**으로 힘을 내므로 이 모순이 없다
%%
% 같은 이야기를 **블록선도 위에서 신호를 따라가며** 확인하겠습니다.
% 위 그림들은 시간축이었고, 이번에는 **루프의 어느 자리**에서 벌어지는 일인지를 봅니다.
%
% ![정상상태에서 루프 각 지점의 값](w05_type_signal.png)
%
% **그림 파일** `w05_type_signal.png` — `make_figures.m` 의 `fig_w05_type_signal`
%   · 다시 만들려면 `make_figures('w05_type_signal')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w05_type_signal`
% **직접 확인해 보려면** — `W05_02_steady_state_error.m` 의 **1절**이
% 같은 두 경우의 정상상태 값을 계산해 출력합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 루프 합산점 뒤 | $e = 0.2$ | 오차가 **남아 있다** |
% | 위 루프 제어기 뒤 | $u = K_p e = 4 \times 0.2 = 0.8$ | $e$ 가 있어야만 $u$ 가 나온다 |
% | 위 루프 출력 | $y = 0.8$ | 목표 $1$ 에 못 닿는다 |
% | 위 루프에서 $e$ 를 $0$ 으로 두면 | $u$ 도 $0$ 이 된다 | 그러면 출력을 유지할 수 없다. **모순** |
% | 아래 루프 합산점 뒤 | $e = 0$ | 오차가 정확히 사라졌다 |
% | 아래 루프 제어기 뒤 | $u = 1$ | **$e=0$ 인데도 $u$ 가 나온다** |
% | 그것이 가능한 이유 | 적분기가 지나간 오차를 쌓아 두었다 | 지금의 $e$ 가 아니라 **과거의 누적**이 힘을 낸다 |
%
% 두 그림의 차이는 제어기 블록 하나뿐입니다.
% 그런데 그 하나가 $e$ 와 $u$ 의 관계를 바꿉니다.
%
% - 비례만 — $u$ 는 **지금의 $e$** 에 묶여 있다. $e=0$ 이면 $u=0$
% - 적분 포함 — $u$ 는 **$e$ 의 이력**에 묶여 있다. $e=0$ 이어도 $u$ 는 남는다
%
% 이 한 문장이 시스템 타입의 정의로 이어집니다.
%% 4. 시스템 타입
% 개루프 전달함수를 이렇게 씁니다.
%
% $$L(s) = \frac{K \cdot (\text{분자})}{s^N \cdot (\text{분모})}$$
%
% 단, 분자와 분모는 $s=0$ 에서 $0$ 이 아닙니다.
% 이 $N$ 을 **시스템 타입**이라 하며, 원점 극점(적분기)의 개수입니다.
%
% - 타입 0 — 적분기 없음. DC 모터 **속도** 모델
% - 타입 1 — 적분기 1개. DC 모터 **위치** 모델
% - 타입 2 — 적분기 2개
%
% 위치 모델이 타입 1 인 이유는 각도가 각속도의 적분이기 때문입니다.
% **물리적으로 적분기가 이미 들어 있는** 셈입니다.
%% 5. 오차상수 — $K_p$, $K_v$, $K_a$
% 입력 종류마다 오차를 계산하는 상수가 따로 있습니다.
% 전부 "$L(s)$ 에 $s$ 를 몇 개 곱하고 $s=0$ 대입" 입니다.
%
% $$K_p = \lim_{s\to 0} L(s), \qquad
%   K_v = \lim_{s\to 0} s L(s), \qquad
%   K_a = \lim_{s\to 0} s^2 L(s)$$
%
% 그리고 오차는
%
% $$e_{step} = \frac{1}{1+K_p}, \qquad
%   e_{ramp} = \frac{1}{K_v}, \qquad
%   e_{para} = \frac{1}{K_a}$$
%
% MATLAB 에서는 `dcgain` 으로 극한을 구합니다.
%
% - `Kp = dcgain(L)`
% - `Kv = dcgain(s*L)`
% - `Ka = dcgain(s^2*L)`
%
% **주의** — `dcgain` 은 극한이 무한대면 `Inf` 를 돌려줍니다.
% 오류가 아닙니다. `Inf` 는 **그 입력에 대해 오차가 $0$** 이라는 좋은 소식입니다.
%
% ![세 상수는 s 를 몇 개 곱하느냐만 다르다](w05_error_const.png)
%
% **그림 파일** `w05_error_const.png` — `make_figures.m` 의 `fig_w05_error_const`
%   · 다시 만들려면 `make_figures('w05_error_const')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w05_error_const`
% **직접 바꿔 보려면** — `W05_02_steady_state_error.m` 의 **3절**에서
% `dcgain(L)`, `dcgain(s*L)`, `dcgain(s^2*L)` 를 직접 찍어 보십시오
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림 가로축 | 주파수 $\omega$, 왼쪽 끝이 $\omega \to 0$ | $\omega \to 0$ 이 곧 $s \to 0$ 이다 |
% | 왼쪽 파란 곡선 (타입 0) | 왼쪽 끝에서 $1$ 로 **평평해진다** | $L(0)$ 이 유한하다 $\to$ $K_p$ 가 유한 $\to$ 오차가 남는다 |
% | 왼쪽 빨간 곡선 (타입 1) | 왼쪽으로 갈수록 계속 올라간다 ($10^2$ 를 넘음) | $L(0) = \infty$ $\to$ 계단 오차 $0$ |
% | 왼쪽 초록 곡선 (타입 2) | 더 가파르게 올라간다 ($10^4$) | 적분기가 둘이라 두 배로 가파르다 |
% | 세 곡선의 왼쪽 끝 기울기 | 평평 / $-20$ / $-40$ dB/dec | **기울기가 곧 타입 번호**다 |
% | 세 곡선의 오른쪽 | 결국 겹쳐서 내려간다 | 고주파에서는 타입이 무의미하다 |
% | 오른쪽 표 첫 줄 | $K_p$ 는 $s$ 를 **$0$ 개** 곱한다 | 계단 입력용 |
% | 오른쪽 표 둘째 줄 | $K_v$ 는 $s$ 를 **$1$ 개** | 램프 입력용 |
% | 오른쪽 표 셋째 줄 | $K_a$ 는 $s$ 를 **$2$ 개** | 포물선 입력용 |
% | 곱하는 $s$ 의 개수 | 입력 차수와 같다 | 외울 것은 이 한 줄뿐이다 |
K = 50;
Ls = {K*Gs, K*Gp, K*Gp/s};
nm = {'타입 0','타입 1','타입 2'};
for i=1:3
    fprintf('%s : Kp=%8.3f  Kv=%8.3f  Ka=%8.3f\n', nm{i}, ...
            dcgain(Ls{i}), dcgain(s*Ls{i}), dcgain(s^2*Ls{i}));
end
%% 6. 타입과 입력의 대응 — 규칙 하나
% 표를 외울 필요는 없습니다. 규칙 하나면 됩니다.
%
% **타입 $N$ 은 $N$ 차까지의 입력을 오차 없이 따라간다**
%
% - 타입 0 — 계단(0차)도 못 따라감. 오차가 유한하게 남는다
% - 타입 1 — 계단은 완벽. 램프(1차)는 오차가 유한하게 남는다
% - 타입 2 — 계단과 램프 완벽. 포물선(2차)은 오차가 유한하게 남는다
%
% 그리고 **자기 차수보다 높은 입력은 무한히 벌어집니다.**
%
% 실무에서 이것이 뜻하는 것
