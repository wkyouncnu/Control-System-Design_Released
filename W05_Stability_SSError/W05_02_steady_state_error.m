%  그때는 Kr 이라는 보정 상수로 억지로 맞췄습니다.
%  오늘은 오차가 남는 이유를 제대로 파고, 근본적으로 없애는 법을 배웁니다.
%
%  이 스크립트에서 답할 질문
%    Q1. 오차는 왜 남는가?                        -> 1절
%    Q2. 시스템 타입이란 무엇인가?                -> 2절
%    Q3. 오차상수 Kp, Kv, Ka 는 무엇인가?         -> 3절
%    Q4. 어떤 입력에 어떤 타입이 필요한가?        -> 4절
%    Q5. 적분기를 넣으면 정말 오차가 0 이 되는가? -> 5절
%    Q6. 그런데 공짜인가?                         -> 6절
%
%  대응하는 강의노트 : W05_LectureNote.mlx
%
%  제어시스템설계 5주차 | 충남대학교 자율운항시스템공학과

