end
s = tf('s');

%% 1. 오차는 왜 남는가 : 아주 단순한 이유
%
%  단위 되먹임 구조에서 오차는 이렇습니다.
%
%      E(s) = R(s) / (1 + L(s))        L(s) = 개루프 전달함수 (한 바퀴 도는 길)
%
%  최종값 정리를 쓰면 정상상태 오차가 나옵니다.
%
%      e_ss = lim_{s->0} s*E(s) = lim_{s->0} s*R(s) / (1 + L(s))
%
%  여기서 핵심은 분모의 L(0) 입니다.
%
%      L(0) 이 유한한 값이면  -> 오차가 남는다
%      L(0) 이 무한대면       -> 오차가 0 이 된다
%
%  그러면 L(0) 을 무한대로 만들려면 어떻게 해야 할까요?
%  L(s) 의 분모에 s 가 있으면 됩니다. s=0 에서 0 으로 나누게 되니까요.
%
%  분모의 s 가 바로 **적분기**입니다.
%
%  직관적으로 보면 이렇습니다.
%
%      비례제어는 "오차가 있어야만" 힘을 낸다. 오차가 0 이면 힘도 0.
%      적분제어는 "오차를 쌓아 둔다". 오차가 0 이 되어도 쌓인 값이 남아
%      계속 힘을 낼 수 있다. 그래서 오차가 0 이 될 수 있다.

%% 2. 시스템 타입 : 원점 극점을 몇 개 갖는가
%
%  개루프 전달함수 L(s) 를 이렇게 씁니다.
%
%      L(s) = K * (분자) / ( s^N * (분모) )     단, 분자와 분모는 s=0 에서 0 이 아님
%
%  이 N 을 **시스템 타입**이라고 합니다. 원점 극점(적분기)의 개수입니다.
%
%      타입 0 : 적분기 없음
%      타입 1 : 적분기 1개
%      타입 2 : 적분기 2개
%
%  DC 모터로 예를 들면
%
%      속도 모델 : 타입 0 (적분기 없음)
%      위치 모델 : 타입 1 (적분기 1개)
%
%  왜 위치 모델이 타입 1 인가: 각도는 각속도의 적분이기 때문입니다.
%  물리적으로 적분기가 이미 들어 있는 셈입니다.

[Gs, ~] = plant_dcmotor('speed');
[Gp, ~] = plant_dcmotor('position');

fprintf('=== 시스템 타입 판정 ===\n');
fprintf('  속도 모델 극점 : ');  fprintf('%+.3f ', pole(Gs)); fprintf('\n');
fprintf('  위치 모델 극점 : ');  fprintf('%+.3f ', pole(Gp)); fprintf('\n');
fprintf('  원점(0) 에 있는 극점의 개수가 타입입니다.\n');
fprintf('    속도 모델 -> 타입 0\n');
fprintf('    위치 모델 -> 타입 1\n\n');

%% 3. 오차상수 : Kp, Kv, Ka
%
%  입력 종류마다 오차를 계산하는 상수가 따로 있습니다.
%  전부 "L(s) 에 s 를 몇 개 곱하고 s=0 을 대입" 하는 것입니다.
%
%      위치오차상수  Kp = lim_{s->0}     L(s)      -> 계단입력용
%      속도오차상수  Kv = lim_{s->0}  s* L(s)      -> 램프입력용
%      가속도오차상수 Ka = lim_{s->0} s^2*L(s)     -> 포물선입력용
%
%  그리고 오차는 이렇게 나옵니다.
%
%      계단입력   : e_ss = 1/(1+Kp)
%      램프입력   : e_ss = 1/Kv
%      포물선입력 : e_ss = 1/Ka
%
%  MATLAB 에서는 dcgain 으로 극한을 구합니다.
%
%      Kp = dcgain(L)
%      Kv = dcgain(s*L)
%      Ka = dcgain(s^2*L)
%
%  주의 : dcgain 은 극한이 무한대면 Inf 를 돌려줍니다. 오류가 아닙니다.
%         Inf 가 나왔다면 그 입력에 대해 오차가 0 이라는 좋은 소식입니다.

K = 50;
L0 = K * Gs;      % 타입 0
L1 = K * Gp;      % 타입 1
L2 = K * Gp / s;  % 타입 2 (적분기를 하나 더 붙인 것)

Ls  = {L0, L1, L2};
nm  = {'타입 0 (속도 모델)', '타입 1 (위치 모델)', '타입 2 (적분기 추가)'};

fprintf('=== 오차상수 (K = %d) ===\n', K);
fprintf('  시스템                    Kp        Kv        Ka\n');
fprintf('  ----------------------  --------  --------  --------\n');
for i = 1:3
    Kp = dcgain(Ls{i});
    Kv = dcgain(s*Ls{i});
    Ka = dcgain(s^2*Ls{i});
    fprintf('  %-22s  %8.3f  %8.3f  %8.3f\n', nm{i}, Kp, Kv, Ka);
end
fprintf('\n');
fprintf('  읽는 법\n');
fprintf('    타입 0 : Kp 만 유한. Kv 와 Ka 는 0 -> 램프와 포물선은 오차 무한대\n');
fprintf('    타입 1 : Kp 가 무한 -> 계단 오차 0. Kv 가 유한 -> 램프 오차 유한\n');
fprintf('    타입 2 : Kp, Kv 무한 -> 계단과 램프 오차 0. Ka 가 유한\n\n');

%% 4. 타입과 입력의 대응표
%
%  이 표가 5주차의 핵심입니다. 외울 필요는 없고 규칙만 알면 됩니다.
%
%      규칙 : 타입 N 은 N 차까지의 입력을 오차 없이 따라간다
%
%             타입 0 -> 계단(0차)도 못 따라감 (오차 유한)
%             타입 1 -> 계단은 완벽, 램프(1차)는 오차 유한
%             타입 2 -> 계단과 램프 완벽, 포물선(2차)은 오차 유한
%
%  아래 표를 직접 계산해 확인합니다.

fprintf('=== 타입별 정상상태 오차 표 ===\n');
fprintf('                          계단입력    램프입력    포물선입력\n');
fprintf('  ----------------------  ---------  ---------  -----------\n');
for i = 1:3
    Kp = dcgain(Ls{i});
    Kv = dcgain(s*Ls{i});
    Ka = dcgain(s^2*Ls{i});
    e_step = 1/(1+Kp);
    e_ramp = 1/Kv;
    e_para = 1/Ka;
    fprintf('  %-22s  %9.4f  %9.4f  %11.4f\n', nm{i}, e_step, e_ramp, e_para);
end
fprintf('\n');
fprintf('  Inf 는 "따라가지 못하고 무한히 벌어진다" 는 뜻입니다.\n');
fprintf('  0 은 "완벽하게 따라간다" 는 뜻입니다.\n\n');
fprintf('  [매우 중요한 단서]\n');
fprintf('    이 표는 폐루프가 **안정할 때만** 의미가 있습니다.\n');
fprintf('    불안정한 시스템은 정상상태 자체가 없으므로 정상상태 오차도 없습니다.\n');
fprintf('    실제로 위 타입 2 는 K = %d 에서 이미 불안정합니다 (6절에서 확인).\n', K);
fprintf('    그러니 표를 쓰기 전에 반드시 안정한지부터 확인해야 합니다.\n\n');

%% 5. 정말 그런지 시뮬레이션으로 확인
%
%  표가 맞는지 실제 응답으로 확인합니다.
%  계단, 램프, 포물선 입력을 각각 만들어 lsim 으로 넣습니다.
%
%  입력 만드는 법
%      계단   : ones(size(t))
%      램프   : t
%      포물선 : 0.5*t.^2

%  안정한 두 경우(타입 0, 타입 1)만 시뮬레이션합니다.
%  타입 2 는 이 이득에서 불안정하므로 5-1 절에서 따로 봅니다.
%
%  충분히 기다려야 정상상태에 도달하므로 시간을 넉넉히 잡습니다.

t = (0:0.01:20)';
inputs = { ones(size(t)), '계단'
           t,             '램프'
           0.5*t.^2,      '포물선' };

figure('Name','타입별 추종 성능');
tiledlayout(2,3,'TileSpacing','compact');

fprintf('=== 시뮬레이션 확인 (t = %.0f s 에서의 오차) ===\n', t(end));
fprintf('  시스템                   계단      램프      포물선\n');
fprintf('  ---------------------  --------  --------  --------\n');
for i = 1:2
    T = feedback(Ls{i}, 1);          % 목표값 -> 출력
    fprintf('  %-21s', nm{i});
    for j = 1:3
        u = inputs{j,1};
        y = lsim(T, u, t);
        err = u(end) - y(end);
        fprintf('  %8.4f', err);

        nexttile((i-1)*3 + j)
        plot(t, u, 'k--', 'LineWidth', 1.5); hold on;
        plot(t, y, 'LineWidth', 2); grid on;
        if i == 1, title(inputs{j,2}); end
        if j == 1, ylabel(sprintf('타입 %d', i-1)); end
        if i == 2, xlabel('시간 [s]'); end
        ylim([0 1.2*max(u)]);
    end
    fprintf('\n');
end
fprintf('\n');
fprintf('  이론값과 비교\n');
fprintf('    타입 0 계단 : 이론 %.4f  <- 잘 맞습니다\n', 1/(1+dcgain(Ls{1})));
fprintf('    타입 1 계단 : 이론 0       <- 잘 맞습니다\n');
fprintf('    타입 1 램프 : 이론 %.4f  <- 잘 맞습니다\n', 1/dcgain(s*Ls{2}));
fprintf('    Inf 로 예측된 칸은 시간이 갈수록 계속 벌어집니다.\n\n');

%% 5-1. 타입 2 는 왜 시뮬레이션하지 않았는가
%
%  타입 2 시스템은 이 이득에서 이미 불안정합니다.
%  불안정한 시스템에는 정상상태가 없으므로 정상상태 오차를 말할 수 없습니다.
%
%  실제로 돌려 보면 응답이 발산합니다.

T2 = feedback(Ls{3}, 1);
fprintf('=== 타입 2 는 불안정합니다 ===\n');
fprintf('  폐루프 극점 : ');
p2 = pole(T2);
fprintf('%+.2f%+.2fj  ', [real(p2).'; imag(p2).']); fprintf('\n');
fprintf('  최대 실수부 = %+.3f  -> 우반면에 있으므로 발산합니다.\n\n', max(real(p2)));

t2s = (0:0.01:5)';
figure('Name','타입 2 는 발산한다');
plot(t2s, lsim(T2, ones(size(t2s)), t2s), 'LineWidth', 2); hold on;
plot(t2s, ones(size(t2s)), 'k--', 'LineWidth', 1.5);
grid on; xlabel('시간 [s]'); ylabel('출력');
title(sprintf('타입 2, K = %d : 정상상태가 아예 없다', K));
legend('출력 (발산)', '목표값', 'Location','northwest');

fprintf('  교훈\n');
fprintf('    정상상태 오차 공식을 쓰기 전에 반드시 안정한지 확인할 것.\n');
fprintf('    안정하지 않으면 공식이 주는 숫자는 아무 의미가 없습니다.\n\n');

%% 6. 적분기는 공짜가 아니다
%
%  "적분기를 넣으면 오차가 0 이 된다" 는 것을 배웠습니다.
%  그러면 적분기를 많이 넣으면 좋을까요?
%
%  아닙니다. W05_01 에서 이미 봤습니다.
%
%      속도 모델(타입 0) : K 를 아무리 키워도 안정
%      위치 모델(타입 1) : K = 120 을 넘으면 불안정
%
%  적분기를 하나 더 넣어 타입 2 로 만들면 어떻게 될까요?
%  아래에서 확인합니다.

fprintf('=== 타입이 올라갈수록 안정도는 ===\n');
for i = 1:3
    Li = Ls{i} / K;      % K 를 떼어낸 순수 플랜트
    [nu, de] = tfdata(Li, 'v');
    Kc = NaN;
    for Kx = logspace(-1, 4, 3000)
        coef = de + Kx*[zeros(1, numel(de)-numel(nu)) nu];
        if max(real(roots(coef))) > 0
            Kc = Kx; break
        end
    end
    if isnan(Kc)
        fprintf('  %-22s : 임계이득 없음 (아무리 키워도 안정)\n', nm{i});
    else
        fprintf('  %-22s : 임계이득 K_crit = %.1f\n', nm{i}, Kc);
    end
end
fprintf('\n');
fprintf('  읽는 법\n');
fprintf('    타입이 올라갈수록 안정도가 나빠집니다.\n');
fprintf('    타입 2 는 아주 작은 이득에서도 불안정해집니다.\n');
fprintf('    적분기는 원점에 극점을 하나 더 놓는 것이고,\n');
fprintf('    원점 극점은 위상을 90 도 늦춰 불안정에 가까워지게 만듭니다.\n');
fprintf('    (위상이라는 말은 9~10 주차에서 제대로 다룹니다)\n\n');

%% 7. 그래서 실무에서는
%
%  정상상태 오차와 안정도는 맞바꿈 관계입니다.
%
%      오차를 없애려면 적분기가 필요하다
%      적분기를 넣으면 불안정해지기 쉽다
%
%  이 둘을 동시에 잡는 것이 제어기 설계의 핵심입니다.
%  방법은 두 가지 방향이 있습니다.
%
%      (1) 적분기를 넣되 다른 것으로 안정도를 보완한다
%          -> PI 제어에 D 를 더한 PID (11주차)
%          -> 적분기 대신 원점 "근처"에 극점을 두는 지상보상기 (7주차)
%
%      (2) 애초에 적분기 없이 이득만 키운다
%          -> 오차는 남지만 안정하다
%          -> 오차가 허용 범위 안이면 이것으로 충분하다
%
%  어느 쪽을 고를지는 사양이 정합니다.
%  "정상상태 오차 0" 이 요구사항에 있으면 (1) 이고, 아니면 (2) 로 충분합니다.

%% 8. 1주차의 Kr 은 무엇이었나
%
%  1주차에서 폐루프에 Kr 을 곱해 오차를 없앴습니다.
%  그것과 적분기는 무엇이 다를까요?
%
%      Kr 방식  : 계산으로 미리 보정한다. 모델을 정확히 알아야 한다.
%                 모델이 틀리면 오차가 다시 생긴다.
%      적분기   : 오차를 보고 스스로 없앤다. 모델이 틀려도 오차가 0 이 된다.
%
%  즉 Kr 은 개루프식 보정이고, 적분기는 폐루프식 보정입니다.
%  1주차의 교훈 그대로, 모델이 틀리면 Kr 은 무너집니다.
%  아래에서 확인합니다.

K2 = 30;
Gp_design = Gp;                       % 설계에 쓴 모델
Gp_true   = Gp * 1.3;                 % 실제 플랜트가 30 % 더 강했다

% 방법 A : Kr 보정 (적분기 없음, 속도 모델 사용)
La_d = K2*Gs;
Kr = 1/dcgain(feedback(La_d,1));
y_Kr = dcgain(Kr*feedback(K2*Gs*1.3, 1));

% 방법 B : 적분기 (위치 모델은 이미 타입 1)
y_int = dcgain(feedback(K2*Gp_true, 1));

fprintf('=== 모델이 30 %% 틀렸을 때 (목표값 1) ===\n');
fprintf('  Kr 보정 방식 : 정상상태 %.4f  (오차 %.4f)\n', y_Kr, 1-y_Kr);
