%% 9. 이번 실습의 정리
%
%  1) 정상상태 오차는 e_ss = lim s*R(s)/(1+L(s)) 로 구한다.
%     분모의 L(0) 이 무한대면 오차가 0 이 된다.
%
%  2) L(0) 을 무한대로 만드는 것이 적분기(원점 극점)다.
%     원점 극점의 개수를 시스템 타입이라 한다.
%
%  3) 오차상수는 전부 "L 에 s 를 몇 개 곱하고 s=0 대입" 이다.
%       Kp = L(0),  Kv = lim s*L,  Ka = lim s^2*L
%       오차 = 1/(1+Kp), 1/Kv, 1/Ka
%
%  4) 규칙 하나 : 타입 N 은 N 차까지의 입력을 오차 없이 따라간다.
%
%  5) 적분기는 공짜가 아니다. 타입이 올라갈수록 불안정해지기 쉽다.
%     정상상태 오차와 안정도는 맞바꿈이다.
%
%  6) Kr 보정과 적분기는 다르다. Kr 은 모델이 틀리면 무너지지만
%     적분기는 오차를 보고 스스로 없애므로 모델이 틀려도 통한다.
%
%  다음 실습 : W05_03_run_simulink.m
%              Simulink 에서 적분기를 켜고 끄며 오차가 사라지는 것을 봅니다.
