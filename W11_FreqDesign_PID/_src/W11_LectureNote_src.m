%% 1. 설계 순서 — 다섯 단계
% 주파수영역 설계는 항상 이 순서입니다. **순서를 바꾸면 안 됩니다.**
%
% - **1단계** 정상상태 사양으로 이득 $K$ 를 먼저 정한다
% - **2단계** 그 $K$ 로 위상여유를 재 본다
% - **3단계** 모자란 위상을 계산한다
% - **4단계** 그만큼 채워 주는 보상기를 설계한다
% - **5단계** 검증한다 (`margin`, `step`, 그리고 **반드시 제어입력**)
%
% **왜 1단계가 먼저인가**
%
% - 정상상태 사양은 **저주파**가 정한다 (5주차의 오차상수)
% - 위상여유는 **교차주파수 근처**가 정한다
%
% 서로 다른 주파수 대역이라, 순서를 지키면 뒤 단계가 앞 단계를 망치지 않습니다.
% 이것이 주파수영역 설계가 편한 가장 큰 이유입니다.
%
% ![주파수영역 설계 다섯 단계](w11_design_steps.png)
%
% **그림 파일** `w11_design_steps.png` — `make_figures.m` 의 `fig_w11_design_steps`
%   · 다시 만들려면 `make_figures('w11_design_steps')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w11_design_steps`
% **직접 따라가 보려면** — `W11_01_lead_design.m` 이 1절부터 3절까지
% 이 다섯 단계를 순서대로 실행합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | ① 파란 칸 | 이득 $K$ 를 먼저 정한다 | **저주파**가 정하는 단계 |
% | ②③④ 주황 칸 | 여유를 재고 채운다 | **교차주파수 근처**가 정하는 단계 |
% | ⑤ 빨간 칸 | 검증 | 6주차와 같이 **가장 자주 빠뜨리는** 단계 |
% | ① 과 ②~④ 의 색이 다른 것 | 서로 다른 주파수 대역 | 그래서 순서를 지키면 안 겹친다 |
% | ⑤ 에 `u(t)` 가 적혀 있는 것 | 제어입력 확인 | Lead 는 제어입력을 $1/\alpha$ 배 키운다 |
%
% **6주차의 근궤적 여섯 단계와 나란히 놓고 보십시오.**
% 사양을 먼저 옮기고 → 도구로 그리고 → 읽고 → 검증하는 흐름이 똑같습니다.
% 도구가 근궤적에서 보드 선도로 바뀌었을 뿐입니다.
%% 1-1. 1단계 — 정상상태 사양으로 K 정하기
% 5주차에서 배운 오차상수를 그대로 씁니다.
%
% $$K_p = \lim_{s \to 0} L(s), \qquad
%   K_v = \lim_{s \to 0} s\,L(s), \qquad
%   K_a = \lim_{s \to 0} s^2 L(s)$$
%
% 예 — "단위 램프 입력에 대한 오차 $\le 0.01$" 이라면
%
% $$e_{ss} = \frac{1}{K_v} \le 0.01 \qquad \Rightarrow \qquad K_v \ge 100$$
%
% $G = 1/(s(s+1))$ 은 타입 1 이고 $K_v = K$ 이므로 $K \ge 100$ 입니다.
fprintf('=== 1단계 확인 ===\n');
fprintf('  Kv = lim s*K*G = %.2f\n', dcgain(s*K0*G0));
fprintf('  램프 오차 = 1/Kv = %.4f  (요구 0.01 이하)\n\n', 1/dcgain(s*K0*G0));
%% 2. Lead 보상기 — 위상을 끌어올린다
% $$D(s) = K\,\frac{Ts + 1}{\alpha T s + 1}, \qquad 0 < \alpha < 1$$
%
% **7주차의 PD 와 같은 물건**입니다. 다만 극점을 하나 붙여 두었습니다.
%
% 왜 극점을 붙이는가 — 이상적 PD 는 고주파에서 크기가 무한히 커져
% **잡음을 무한히 증폭**합니다. 극점이 그것을 $1/\alpha$ 배에서 멈춰 줍니다.
%% 2-1. Lead 의 성질 두 가지
% Lead 는 $\omega_m = \frac{1}{T\sqrt{\alpha}}$ 에서
%
% - 위상을 **가장 많이** 올린다. 그 최대치가 $\phi_{max}$ 이고
%
% $$\sin\phi_{max} = \frac{1-\alpha}{1+\alpha}
%   \qquad \Rightarrow \qquad
%   \alpha = \frac{1 - \sin\phi_{max}}{1 + \sin\phi_{max}}$$
%
% - 크기를 $\frac{1}{\sqrt{\alpha}}$ 배 (즉 $-10\log_{10}\alpha$ dB) 올린다
%
% 이 둘을 알면 설계가 기계적으로 끝납니다.
%
% ![위상을 올릴수록 고주파 이득이 급증한다](w11_lead_alpha.png)
%
% **그림 파일** `w11_lead_alpha.png` — `make_figures.m` 의 `fig_w11_lead_alpha`
%   · 다시 만들려면 `make_figures('w11_lead_alpha')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w11_lead_alpha`
% **직접 확인해 보려면** — 바로 아래 코드가 같은 표를 찍어 줍니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 빨간 곡선 | 올리려는 위상 대 고주파 이득 배율 $1/\alpha$ | 대가를 나타내는 곡선 |
% | 왼쪽 $\phi = 20^\circ$ 점 | $2.0$ 배 ($\alpha = 0.490$) | 싸다 |
% | 왼쪽 $\phi = 45^\circ$ 점 | $5.8$ 배 ($\alpha = 0.172$) | 아직 감당할 만하다 |
% | 왼쪽 $\phi = 60^\circ$ 점 | $13.9$ 배 ($\alpha = 0.072$) | **여기가 실용 한계** |
% | 왼쪽 $\phi = 70^\circ$ 점 | $32.2$ 배 ($\alpha = 0.031$) | 잡음이 $32$ 배로 증폭된다 |
% | 곡선이 $60^\circ$ 넘어서 급격히 증가하는 것 | 지수적으로 커진다 | 그래서 **한 단은 $60^\circ$ 까지**로 본다 |
% | 검은 세로 점선 | $60^\circ$ 선 | 실무 경계 |
% | 오른쪽 네 봉우리 | 각 $\alpha$ 로 만든 Lead 의 위상 | 봉우리의 **높이**가 곧 $\phi_{max}$ |
