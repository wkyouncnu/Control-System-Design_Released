%
% 그림 해석 — **네 칸을 왼쪽 아래 → 오른쪽 위 → 왼쪽 위 → 오른쪽 아래 순으로**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 아래 파란 곡선 | $t = 0.5 \sim 1.5$ s 동안 $15$ V 에 **평평하게 붙어 있다** | 구동기가 포화되어 그 이상 못 낸다 |
% | 그 평평한 구간의 길이 | 약 $1$ 초 | **여기서 문제가 자란다** |
% | 왼쪽 아래 빨간 곡선 | $t=0.8$ s 쯤 벌써 $15$ V 를 벗어난다 | anti-windup 이 일찍 빠져나오게 한다 |
% | 왼쪽 아래 파란 곡선의 $t=1.7$ s | $-4$ V 까지 **거꾸로** 내려간다 | 넘어간 것을 되돌리느라 반대로 민다 |
% | 오른쪽 위 파란 곡선 | 적분기에 쌓인 값이 $0.32$ 까지 오른다 | 포화 중에도 **오차를 계속 쌓았다** |
% | 오른쪽 위 빨간 곡선 | $0.03$ 근처에 머문다 | **쌓기를 멈췄다** |
% | 두 곡선의 최대값 비 | 약 $10$ 배 | 이 차이가 곧 와인드업의 크기 |
% | 왼쪽 위 파란 곡선 | $1.42$ 까지 넘어갔다가 $2$ s 넘어 돌아온다 | 쌓인 값을 다 빼내야 해서 늦다 |
% | 왼쪽 위 빨간 곡선 | $1.02$ 로 거의 안 넘고 $1$ s 에 안착 | anti-windup 의 효과 |
% | 오른쪽 아래 파란 곡선 | 오차가 $-0.42$ 까지 **음수로** 깊이 내려간다 | 목표를 지나쳐 버렸다는 뜻 |
% | 오른쪽 아래 빨간 곡선 | $0$ 근처에 머문다 | 지나치지 않았다 |
%
% **인과가 오른쪽 위에서 왼쪽 위로 흐릅니다.**
% 포화 중에 적분기가 쌓이고(오른쪽 위), 그 쌓인 값을 다 빼낼 때까지
% 출력이 목표를 넘어 있습니다(왼쪽 위). 처방은 **쌓기를 멈추는 것**입니다.
%% 6-1. 처방
% 아주 간단합니다. **포화 중에는 적분을 멈추면 됩니다.**
%
% - **clamping** — 포화되어 있고 오차가 포화를 더 키우는 방향이면 적분을 멈춘다
% - **back-calculation** — 포화로 잘려 나간 만큼을 적분기에서 빼 준다
%
% Simulink 의 `PID Controller` 블록은 이 두 가지를 옵션으로 제공합니다.
% `W11_PID_AntiWindup.slx` 에서 직접 켜고 끄며 비교합니다.
