%% 3. PI 와 Lag — 저주파 이득을 번다
% Lead 는 **위상**을 벌었습니다. PI 와 Lag 는 반대편을 봅니다.
%
% **PI 제어기**
%
% $$D(s) = K\left(1 + \frac{1}{T_i s}\right) = K\,\frac{T_i s + 1}{T_i s}$$
%
% 원점에 극점이 생기므로 **시스템 타입이 하나 올라갑니다.**
% 계단 오차가 $0$ 이 됩니다.
%
% **Lag 보상기**
%
% $$D(s) = K\,\frac{Ts + 1}{\beta T s + 1}, \qquad \beta > 1$$
%
% 극점을 원점 **가까이**에 두되 원점은 아닙니다.
% 저주파 이득은 $K$ 로 유한하고, 고주파 이득은 $K/\beta$ 로 줄어듭니다.
%% 3-1. Lag 는 저주파를 올리는 것이 아니다
% 흔한 오해입니다. **Lag 는 고주파를 내립니다.**
% 결과적으로 저주파가 상대적으로 높아 보일 뿐입니다.
%
% 그래서 이런 일이 일어납니다.
%
% - 크기 곡선이 고주파에서 내려간다
% - $0$ dB 를 지나는 곳이 **왼쪽**으로 옮겨간다
% - 그 자리의 플랜트 위상은 덜 떨어져 있다
% - 따라서 **위상여유가 저절로 늘어난다**
%
% Lag 자신이 위상을 올려 주는 것이 **아닙니다.** 오히려 깎습니다(최대 $-90^\circ$).
% 그래서 그 깎이는 구간이 새 교차주파수와 겹치지 않도록
% 영점을 **한 데케이드 아래**에 둡니다.
%
% ![Lag 는 고주파를 낮춰 교차주파수를 왼쪽으로 옮긴다](w11_lag_bode.png)
%
% **그림 파일** `w11_lag_bode.png` — `make_figures.m` 의 `fig_lag_bode`
%   · 다시 만들려면 `make_figures('w11_lag_bode')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_lag_bode`
% **직접 바꿔 보려면** — `W11_02_lag_and_pi.m` 에서 `PM_req` 를 바꿔 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 두 곡선의 **왼쪽 끝** | 둘 다 $40$ dB 로 겹친다 | **저주파 이득이 그대로**다. 정상상태는 안 나빠진다 |
% | 왼쪽 위 빨간 곡선의 오른쪽 | 파란 곡선보다 $20$ dB 아래 | 고주파만 낮췄다 |
% | 두 곡선이 $0$ dB 를 지나는 곳 | 파란 것은 오른쪽, 빨간 것은 왼쪽 | **교차주파수가 왼쪽으로 옮겨졌다** |
% | 빨간 세로 점선 | 새 교차주파수 | 여기서 위상여유를 읽는다 |
% | 왼쪽 아래 두 위상 곡선 | 오른쪽에서는 거의 겹친다 | **Lag 는 위상을 올리지 않는다** |
% | 왼쪽 아래 빨간 곡선이 저주파에서 아래로 처진 것 | 여기서는 오히려 깎는다 | 이름이 Lag(뒤처짐) 인 이유 |
% | 새 교차주파수 자리에서의 위상 | $-137^\circ$ | 원래 플랜트 위상이 여기서는 덜 처져 있다 |
% | 위상여유가 늘어난 이유 | 자리를 옮겼을 뿐 | **곡선을 올린 게 아니라 읽는 자리를 옮긴 것** |
% | 오른쪽 아래 곡선 | Lag 자신의 크기 | 고주파를 $20$ dB 낮춘다. $\beta = 10$ |
% | 오른쪽 위 파란 곡선 | 보상 전, 오버슈트 $63\%$ | PM $15^\circ$ |
% | 오른쪽 위 빨간 곡선 | Lag 적용 후, 잘 감쇠한다 | PM $43^\circ$ |
%
% **이것이 Lag 를 이해하는 열쇠입니다.** Lag 는 위상 곡선을 건드리지 않습니다.
% 크기 곡선을 낮춰 **위상을 읽는 자리를 왼쪽으로 옮길 뿐**입니다.
% 왼쪽은 아직 위상이 덜 처진 곳이라 여유가 저절로 늘어납니다.
%% 3-2. Lag 설계 절차
% - **1단계** 정상상태 사양으로 $K$ 를 정한다
