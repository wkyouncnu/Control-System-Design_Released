fprintf('   Lag 적용   %12.2f  %11.4f  %17.2f\n\n', ia.Overshoot, ia.RiseTime, bandwidth(feedback(D2*G2,1)));
%% 4. Lead 와 Lag 를 어떻게 고르는가
% 목적이 반대이므로 표로 정리해 두면 편합니다.
%
% | 항목 | Lead | Lag |
% |---|---|---|
% | 하는 일 | 위상을 올린다 | 고주파 크기를 낮춘다 |
% | 교차주파수 | 오른쪽 (빨라진다) | 왼쪽 (느려진다) |
% | 대역폭 | 넓어진다 | 좁아진다 |
% | 측정 잡음 | **취약해진다** | **강해진다** |
% | 제어입력 | 커진다 | 작아진다 |
% | 근궤적의 사촌 | PD | PI |
%
% 고르는 기준은 간단합니다.
%
% - 빠르게 하고 싶다 $\rightarrow$ **Lead**
% - 잡음이 심하거나 구동기가 약하다 $\rightarrow$ **Lag**
% - 둘 다 필요하다 $\rightarrow$ **Lead-Lag** (= PID)
%
% 같은 플랜트에 둘을 각각 붙여 나란히 놓으면 표가 그림이 됩니다.
%
% ![같은 위상여유를 얻는 두 가지 길](w11_lead_vs_lag.png)
%
% **그림 파일** `w11_lead_vs_lag.png` — `make_figures.m` 의 `fig_w11_lead_vs_lag`
%   · 다시 만들려면 `make_figures('w11_lead_vs_lag')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w11_lead_vs_lag`
% **직접 확인해 보려면** — `W11_01_lead_design.m` 과 `W11_02_lag_and_pi.m` 을
% 차례로 실행하면 같은 두 설계를 각각 자세히 볼 수 있습니다
%
% 그림 해석 — **왼쪽 동그라미 세 개의 가로 위치를 비교하십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 회색 동그라미 | 보상 전 교차주파수 $\omega_{cp} = 10.0$ | 출발점. PM $6^\circ$ 로 거의 없다 |
% | 왼쪽 빨간 동그라미 | Lead 후 $\omega_{cp} = 16.4$ | **오른쪽으로 갔다.** PM $53^\circ$ |
% | 왼쪽 파란 동그라미 | Lag 후 $\omega_{cp} = 0.7$ | **왼쪽으로 갔다.** PM $49^\circ$ |
% | 세 PM 값 | $6 \to 53$ 과 $6 \to 49$ | **두 길 모두 목표를 달성했다** |
% | 왼쪽 빨간 곡선의 오른쪽 끝 | 회색보다 위 | Lead 는 고주파를 **키운다** |
% | 왼쪽 파란 곡선의 오른쪽 끝 | 회색보다 아래 | Lag 는 고주파를 **낮춘다** |
% | 왼쪽 파란 곡선의 왼쪽 끝 | 회색보다 아래 | Lag 는 이 예에서 저주파도 조금 낮췄다 |
% | 오른쪽 회색 곡선 | $1.85$ 까지 초과하고 오래 진동한다 | 여유가 없는 원래 상태 |
% | 오른쪽 빨간 곡선 (Lead) | $0.2$ s 에 봉우리, $0.5$ s 에 안착 | **빠르다** |
% | 오른쪽 파란 곡선 (Lag) | $4$ s 에 봉우리, $8$ s 넘어 안착 | **아주 느리다** |
% | 두 곡선의 시간 차이 | 약 $16$ 배 | 교차주파수 비 $16.4/0.7 \approx 23$ 과 같은 이야기 |
%
% **같은 위상여유를 얻는 데 두 가지 길이 있고, 결과가 정반대입니다.**
% 구동기가 튼튼하고 잡음이 적으면 Lead, 반대면 Lag 를 고릅니다.
%% 5. PID 는 사실 Lead + Lag 다
% $$u(t) = K_p e + K_i \int e\,dt + K_d \frac{de}{dt}$$
%
% 각 항이 주파수영역에서 하는 일을 보면 이미 아는 것들입니다.
%
% | 항 | 역할 | 대응 |
% |---|---|---|
% | $I$ | 저주파 이득을 올린다 | **Lag** 계열 |
% | $D$ | 위상을 올린다 | **Lead** 계열 |
% | $P$ | 전체를 위아래로 옮긴다 | 비례이득 |
%
% 이 표를 주파수축 위에 그대로 올려 보면 왜 그런지 한눈에 보입니다.
%
% ![세 항이 주파수축을 나누어 맡는다](w11_pid_bands.png)
%
% **그림 파일** `w11_pid_bands.png` — `make_figures.m` 의 `fig_w11_pid_bands`
%   · 다시 만들려면 `make_figures('w11_pid_bands')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w11_pid_bands`
% **직접 바꿔 보려면** — `W11_03_pid_tuning.m` 의 **1절**에서 세 이득을
% 하나씩 $0$ 으로 두고 실행하면 해당 대역이 사라집니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 그림 파란 점선 | $K_i/s$ | 왼쪽으로 갈수록 커진다 |
% | 위 그림 회색 점선 | $K_p$ | 어디서나 일정 |
% | 위 그림 빨간 점선 | $K_d s$ | 오른쪽으로 갈수록 커진다 |
% | 위 그림 굵은 검은 곡선 | 세 항의 합 | **가장 큰 항을 따라간다** |
% | 파란 영역 | $\omega < K_i/K_p$ | I 가 이긴다. **Lag 가 하는 일** |
% | 흰 영역 | 그 사이 | P 가 이긴다. 곡선이 평평하다 |
% | 빨간 영역 | $\omega > K_p/K_d$ | D 가 이긴다. **Lead 가 하는 일** |
% | 아래 그림 왼쪽 끝 $-90^\circ$ | 적분기의 위상 | 저주파에서는 순수 적분처럼 보인다 |
% | 아래 그림 오른쪽 끝 $+90^\circ$ | 미분기의 위상 | 고주파에서는 순수 미분처럼 보인다 |
% | 아래 그림 가운데가 $0^\circ$ 를 지나는 것 | P 가 지배하는 구간 | 위상을 안 건드린다 |
%
% **꺾이는 두 주파수를 우리가 정합니다.**
%
% - $\omega = K_i/K_p$ — 여기 아래로 적분이 작동한다. 이 값을 올리면 오차는
%   빨리 없어지지만 위상을 더 많이 잃는다
% - $\omega = K_p/K_d$ — 여기 위로 미분이 작동한다. 이 값을 내리면 위상을
%   더 벌지만 잡음을 더 먹는다
%
% PID 튜닝이란 결국 **이 두 주파수를 어디에 놓을 것인가**입니다.
% 이름만 다를 뿐 앞 절의 Lead·Lag 설계와 같은 일을 하고 있습니다.
%
% ![P, PI, PID 를 나란히](w11_pid_compare.png)
%
% **그림 파일** `w11_pid_compare.png` — `make_figures.m` 의 `fig_pid_compare`
%   · 다시 만들려면 `make_figures('w11_pid_compare')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_pid_compare`
% **직접 바꿔 보려면** — `W11_03_pid_tuning.m` 의 **1절**에서 세 이득을
% 하나씩 $0$ 으로 두고 실행해 보십시오
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 곡선 (P) | $0.91$ 에서 멈춘다 | **오차가 $9\%$ 남는다.** 타입 0 플랜트라서 |
% | 왼쪽 빨간 곡선 (PI) | $1.30$ 까지 초과했다가 $1$ 로 | **$I$ 가 오차를 없앴다.** 대신 오버슈트가 커진다 |
% | 왼쪽 노란 곡선 (PID) | $1.05$ 까지만 초과하고 바로 안착 | **$D$ 가 진동을 잡았다** |
% | 세 곡선의 최종값 | P 만 $0.91$, 나머지는 $1.00$ | $I$ 항의 유무가 갈랐다 |
% | 빨간과 노란의 차이 | 봉우리 $1.30$ 대 $1.05$ | $D$ 항 하나가 만든 차이 |
% | 오른쪽 세 곡선의 $t=0$ 값 | 노란 것이 $1090$ 까지 급증한다 | **$D$ 항의 미분 킥** |
% | 오른쪽 곡선들이 $t>0.3$ s 에서 겹치는 것 | 정상 구간에서는 비슷 | 차이는 **초반에만** 난다 |
% | 오른쪽 세로축 범위 | $-200 \sim 1200$ V | 실제 드라이버는 $24$ V 정도다 |
%
% **왼쪽만 보면 PID 가 최고입니다. 오른쪽을 보십시오.**
% $t=0$ 의 $1090$ V 는 실물에서 즉시 포화됩니다.
% 이 스파이크를 없애는 것이 5-1 절의 미분 필터이고,
% 포화가 만드는 다음 문제가 6절의 와인드업입니다.
%% 5-1. 미분항에는 반드시 필터를 붙인다
% 이상적 미분기 $K_d s$ 는 두 가지 이유로 쓸 수 없습니다.
%
% - **부적절(improper)** 하다 — 분자 차수가 분모보다 높아 실제로 만들 수 없다
% - 고주파 이득이 무한대라 **잡음을 무한히 증폭**한다
%
% 그래서 필터를 붙입니다.
%
% $$K_d s \quad \rightarrow \quad \frac{K_d s}{\frac{s}{N} + 1}$$
%
% 실무에서 $N = 10 \sim 100$ 을 씁니다.
% 이것이 바로 **Lead 보상기와 같은 구조**입니다. 7주차의 유사미분과 같은 이야기입니다.
%
% ![N 을 키워도 응답은 안 좋아지고 고주파 이득만 커진다](w11_dfilter.png)
%
% **그림 파일** `w11_dfilter.png` — `make_figures.m` 의 `fig_w11_dfilter`
%   · 다시 만들려면 `make_figures('w11_dfilter')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w11_dfilter`
% **직접 바꿔 보려면** — 바로 아래 코드가 같은 표를 찍어 줍니다.
% `Ns` 에 $2$ 를 추가해 보면 너무 작아도 안 된다는 것을 알 수 있습니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 네 곡선의 왼쪽 끝 | 전부 겹친다 | **저주파에서는 $N$ 이 아무 영향이 없다** |
% | 왼쪽 곡선들이 갈라지는 곳 | $\omega \approx 10$ 부터 | 미분항이 일하기 시작하는 자리 |
% | 왼쪽 파란 곡선 ($N=5$) | $43.5$ dB 에서 평평 | 가장 낮게 막는다 |
% | 왼쪽 보라 곡선 ($N=1000$) | $77.1$ dB 까지 올라간다 | **파란 것보다 $34$ dB, 즉 $50$ 배 높다** |
% | 검은 세로 점선 | $\omega = 1000$ | 잡음이 있을 만한 주파수 |
% | 그 자리의 네 값 | $43.5 / 49.5 / 60.8 / 77.1$ dB | $N$ 이 커질수록 잡음을 더 키운다 |
% | 오른쪽 네 곡선 | 서로 거의 구별이 안 된다 | **성능은 거의 같다** |
% | 오른쪽 파란 곡선 ($N=5$) | 오버슈트가 오히려 조금 크다 | 너무 작으면 미분 효과가 약해진다 |
% | 오른쪽 나머지 셋 | $N=20$ 이후로는 차이가 없다 | **$N=20$ 이면 충분하다** |
% | 왼쪽 범례의 PM 값 | $40.7 \to 57.2 \to 84.8 \to 93.7$ 도 | 여유는 늘지만 잡음 대가가 크다 |
%
% **얻는 것은 $N=20$ 에서 이미 다 얻었고, 그 위로는 잡음만 커집니다.**
% 그래서 실무에서는 **필요한 만큼만 작은 $N$** 을 씁니다.
% Simulink `PID Controller` 블록의 "Filter coefficient N" 이 바로 이 값입니다.
Gm = plant_dcmotor('speed');
fprintf('=== 미분 필터 N 의 영향 ===\n');
fprintf('       N      w = 1000 에서 제어기 크기[dB]   위상여유[도]\n');
fprintf('   -------  -----------------------------  ------------\n');
for N = [5 20 100 1000]
    Cn = 100 + 200/s + 10*s/(s/N + 1);
    [~, pmn] = margin(Cn*Gm);
    fprintf('   %7.0f  %29.2f  %12.2f\n', N, 20*log10(abs(freqresp(Cn, 1000))), pmn);
end
fprintf('   --> 성능은 N = 20 이나 1000 이나 비슷한데 고주파 이득만 커집니다.\n');
fprintf('       **작은 N 을 쓰는 것이 이득**입니다.\n\n');
%% 5-2. `pidtune` — 자동 튜닝
% **오늘의 새 명령입니다.**
%
% 명령 정리
%
% - **원리** — 목표 교차주파수를 정하고, 그 자리에서 위상여유가 약 $60^\circ$ 가
%   되도록 $K_p$, $K_i$, $K_d$ 를 최적화한다. **즉 주파수영역 설계다**
% - **입력** — `pidtune(G, 'PIDF')` 또는 `pidtune(G, 'PIDF', wc)`
% - **출력** — `pid` 객체와 정보 구조체 (`CrossoverFrequency`, `PhaseMargin`)
%
% 주의 세 가지
%
% - 모델이 **정확해야** 한다. `pidtune` 은 모델을 그대로 믿는다
% - 기본 목표는 위상여유 $60^\circ$ 다
% - **구동기 한계는 모른다.** 결과를 반드시 검증해야 한다
[C_auto, ia_auto] = pidtune(Gm, 'PIDF');
fprintf('=== pidtune 결과 ===\n');
C_auto
fprintf('  교차주파수 %.3f rad s^-1, 위상여유 %.2f 도\n\n', ...
        ia_auto.CrossoverFrequency, ia_auto.PhaseMargin);
fprintf('  목표 교차주파수를 바꿔 가며\n');
fprintf('     wc 목표   정착시간[s]   최대 제어입력[V]\n');
fprintf('   ---------  -----------  ------------------\n');
tp = (0:0.002:3)';
for wc = [2 5 10 20]
    Ci = pidtune(Gm, 'PIDF', wc);
    ji = stepinfo(feedback(Ci*Gm, 1));
    ui = step(feedback(Ci, Gm), tp);
    fprintf('   %9.0f  %11.3f  %18.1f\n', wc, ji.SettlingTime, max(abs(ui)));
end
fprintf('   --> 두 배 빨라지려면 전압은 **네 배**가 필요합니다.\n');
fprintf('       빠르게 만드는 값은 선형이 아니라 제곱으로 비쌉니다.\n\n');
