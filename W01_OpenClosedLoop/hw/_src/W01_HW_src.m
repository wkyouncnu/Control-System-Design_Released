% 목표 $r$ 을 그대로 얻으려면 입력을 얼마로 주어야 하는가?
%
% $$y = G(0)\,u = r \qquad \Rightarrow \qquad u = \frac{r}{G(0)}$$
%
% 그래서 앞에 곱해 주는 상수를 이렇게 정합니다.
