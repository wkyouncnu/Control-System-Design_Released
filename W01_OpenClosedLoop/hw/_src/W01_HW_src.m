    plot(t_m, y1, 'LineWidth', 2); hold on;
    plot(t_m, y2, 'LineWidth', 2);
    yline(r_m, 'k--'); grid on;
    xlabel('시간 [s]'); ylabel('각속도 [rad s^{-1}]');
    legend('개루프', '폐루프 (K = 50)', '목표', 'Location', 'southeast');
    title('DC 모터 속도제어 — 개루프와 폐루프');
end

