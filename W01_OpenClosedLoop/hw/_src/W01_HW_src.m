    fprintf('폐루프 : T(0) = %.4f , Kr = %.3f\n', dcgain(T_m), Kr_m);
end

%% 2-3. 두 방법을 한 그림에
% 코드는 다 되어 있습니다. 위의 `TODO` 두 개를 채우면 그림이 나옵니다.

