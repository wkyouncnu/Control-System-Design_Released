%% 8. 두 장면을 하나로 묶는 것
% 여기서 재미있는 일이 벌어집니다.
%
% - 외란을 얼마나 잘 밀어내는지
% - 모델이 틀려도 얼마나 잘 버티는지
% - 둘 다 **똑같은 값 하나**로 결정된다
%
% $$S = \frac{1}{1 + KG}$$
%
% 왜 같은 값인가
%
% - 원리가 하나이기 때문
% - 무슨 이유로든 출력이 목표에서 벗어나면 오차가 생긴다
% - 제어기는 그 오차를 보고 힘을 더 낸다
% - 원인이 외란이든 모델 오차든 **제어기 입장에서는 똑같이 오차일 뿐**이다
%
% 말로만 하면 안 믿깁니다. **두 경우를 각각 계산해서 같은 식이 나오는지 봅니다.**
%% 8-A. 첫째 — 외란 쪽에서 $S$ 가 나오는 과정
% 6절에서 이미 얻었습니다. 외란에서 출력으로 가는 전달함수는
%
% $$\frac{y}{d} = \frac{G}{1+KG} = G \cdot \frac{1}{1+KG} = G \cdot S$$
%
% 개루프에서는 같은 자리가 $G$ 였습니다. 그러므로
%
% $$\frac{(\text{폐루프가 받는 외란})}{(\text{개루프가 받는 외란})}
%   = \frac{G S}{G} = S = \frac{1}{1+KG}$$
%
% **외란이 정확히 $S$ 배로 줄어듭니다.**
%% 8-B. 둘째 — 모델 오차 쪽. **먼저 숫자로 봅니다**
% 이쪽은 미분이 나옵니다. 식부터 보면 "왜 하필 이렇게 미분하지?" 싶으므로
% **먼저 숫자로 무슨 일이 일어나는지 보고** 그다음에 식을 세웁니다.
%
% 우리 플랜트는 $G(0) = 1$ 이고 $K = 9$ 입니다.
%
% 먼저 **부품의 오차가 $G$ 의 오차로 어떻게 넘어오는지** 확인하고 갑니다.
% MSD 의 직류이득은 $G(0) = 1/k$ 이므로 **스프링과 반대로 움직입니다.**
%
% | 스프링 | $k$ | $G(0) = 1/k$ | 방향 |
% |---|---|---|---|
% | 설계값 | $1.00$ | $1.000$ | 기준 |
% | 조금 무르다 | $0.99$ | $1.010$ | $k$ 가 작아지면 $G$ 는 **커진다** |
% | 조금 뻣뻣하다 | $1.01$ | $0.990$ | $k$ 가 커지면 $G$ 는 **작아진다** |
%
% 그러니 "스프링이 뻣뻣하다" 와 "$G$ 가 크다" 는 **같은 말이 아닙니다.**
% 헷갈리기 쉬운 자리이므로 여기서 한 번 짚고 갑니다.
%
% 아래에서는 스프링이 예상보다 **조금 물러서** $G$ 가 **$1\%$ 커졌다**고 두겠습니다.
%
% | | $G(0)$ | 그때의 출력 이득 | 변화율 |
% |---|---|---|---|
% | **개루프** $T = K_{ff}G$ | $1 \to 1.01$ | $1.000000 \to 1.010000$ | $1.00\%$ |
% | **폐루프** $T = \frac{KG}{1+KG}$ | $1 \to 1.01$ | $0.900000 \to 0.900892$ | $0.099\%$ |
%
% **개루프는 $1\%$ 틀리면 $1\%$ 틀립니다.** 그대로 옵니다.
% **폐루프는 $1\%$ 틀려도 $0.1\%$ 밖에 안 틀립니다.** 열 배 덜 틀립니다.
%
% 그리고 $\frac{1}{1+KG(0)} = \frac{1}{1+9} = 0.1$ 입니다. **$0.1$ 이 또 나왔습니다.**
% 우연이 아니라는 것을 이제 식으로 확인합니다.
%
% **반대 방향도 똑같습니다.** `W01_02_model_uncertainty.m` 은 스프링이
% $50\%$ **뻣뻣한** 경우를 다룹니다. 그때는 $G$ 가 작아지므로 출력도 작아지지만,
% 줄여 주는 비율은 여기와 같은 $S$ 입니다.
% 감도는 **방향이 아니라 비율**을 말하는 양이기 때문입니다.
%
% **다만 그 스크립트를 돌려 보면 $10$ 배가 아니라 $7$ 배가 나옵니다.**
% 틀린 것이 아니라, 감도가 **한 점 근처에서만 맞는 값**이기 때문입니다.
% 여기서 $1\%$ 라는 아주 작은 값을 쓴 것도 그래서입니다.
%
% | | 오차의 크기 | 줄어드는 배수 |
% |---|---|---|
% | 이 절 | $G$ 가 $1\%$ | $1 + K\,G_{\rm 설계} = 10$ 배 |
% | `W01_02` | $k$ 가 $50\%$ (즉 $G$ 가 $-33\%$) | $1 + K\,G_{\rm 실제} = 7$ 배 |
%
% 규칙은 하나입니다 — **분모의 $G$ 는 "지금 실제로 달려 있는" 플랜트의 값**입니다.
% 오차가 작으면 설계값과 실제값이 거의 같아 구별할 필요가 없고,
% 오차가 크면 갈립니다. 3주차의 "선형화는 동작점 근처에서만 맞다" 와 같은 이야기입니다.
%% 8-B-1. 왜 $G$ 로 미분하는가 — 미분의 뜻으로 돌아가기
% 여기서 막히는 사람이 많습니다. **왜 하필 $G$ 로 미분하는가?**
%
% 지금까지 미분은 대개 **시간 $t$ 로** 했습니다. "시간이 조금 지나면 값이 얼마나 변하나".
% 그런데 지금 우리가 묻는 것은 시간 이야기가 전혀 아닙니다.
%
% **"$G$ 가 조금 변하면 $T$ 가 얼마나 변하나?"**
%
% 이 문장을 그대로 기호로 옮기면 그것이 곧 $\frac{dT}{dG}$ 입니다.
% **"무엇이 조금 변할 때 무엇이 얼마나 변하나" 를 묻는 것이 미분**이고,
% 여기서는 그 "무엇" 이 시간이 아니라 $G$ 일 뿐입니다.
%
% 그래서 생각을 이렇게 바꿉니다.
%
% | 평소의 시각 | 지금의 시각 |
% |---|---|
% | $G$ 는 주어진 플랜트. 안 변한다 | $G$ 는 **우리가 정확히 모르는 값**. 조금 틀릴 수 있다 |
% | $T$ 는 $s$ 의 함수 | $T$ 를 **$G$ 의 함수**로 본다 |
% | $s$ 로 미분한다 | **$G$ 로 미분한다.** $K$ 는 우리가 정한 상수 |
%
% $T = \frac{KG}{1+KG}$ 를 보면 $K$ 는 우리가 다이얼로 맞춘 숫자이고
% $G$ 만 불확실합니다. 그러므로 **$K$ 는 상수로 두고 $G$ 만 변수로 봅니다.**
% 변수가 하나뿐이므로 사실 편미분이 아니라 그냥 미분입니다.
%
% 한 가지 더. 우리가 알고 싶은 것은 "$T$ 가 얼마나 변했나" 가 아니라
% **"몇 퍼센트 변했나"** 입니다. 절대량은 단위에 따라 달라져 비교가 안 되기 때문입니다.
% 그래서 **상대변화끼리의 비**를 정의하고 이것을 **상대감도**라 부릅니다.
%
% $$S^{T}_{G} \;=\; \frac{T \text{ 의 변화율}}{G \text{ 의 변화율}}
%   \;=\; \frac{\Delta T / T}{\Delta G / G}$$
%
% 이 식을 미분으로 바꾸는 다리가 한 줄 필요합니다.
% $\Delta G$ 가 아주 작으면 미분의 정의에 따라
%
% $$\Delta T \;\approx\; \frac{dT}{dG}\,\Delta G$$
%
% 이것을 위 정의에 넣고 정리합니다.
%
% $$S^{T}_{G} = \frac{\Delta T / T}{\Delta G / G}
%   = \frac{\Delta T}{T}\cdot\frac{G}{\Delta G}
%   = \frac{dT}{dG}\,\Delta G \cdot \frac{1}{T}\cdot\frac{G}{\Delta G}
%   = \frac{dT}{dG}\cdot\frac{G}{T}$$
%
% $\Delta G$ 가 위아래에서 지워집니다. 그래서 남는 것이 이 꼴입니다.
%
% $$S^{T}_{G} = \frac{dT}{dG}\cdot\frac{G}{T}$$
%
% **읽는 법** — 앞의 $\frac{dT}{dG}$ 는 "절대량이 얼마나 변하나",
% 뒤의 $\frac{G}{T}$ 는 그것을 **퍼센트로 바꿔 주는 환산 인수**입니다.
%% 8-B-2. 이제 실제로 미분한다
% **폐루프**부터 계산합니다. $T = \frac{KG}{1+KG}$ 를 $G$ 로 미분합니다.
%
% 분수이므로 **몫의 미분법**을 씁니다.
%
% $$\left(\frac{f}{g}\right)' = \frac{f'g - fg'}{g^2}$$
%
% 여기서 $f = KG$, $g = 1+KG$ 이고, **$K$ 는 상수**이므로
%
% $$f' = \frac{d}{dG}(KG) = K, \qquad
%   g' = \frac{d}{dG}(1+KG) = K$$
%
% 넣으면
%
% $$\frac{dT}{dG} = \frac{K(1+KG) - KG\cdot K}{(1+KG)^2}
%   = \frac{K + K^2G - K^2G}{(1+KG)^2} = \frac{K}{(1+KG)^2}$$
%
% 분자에서 $K^2G$ 가 **서로 지워지는 것**이 핵심입니다. 이제 정의에 넣습니다.
%
% $$S^{T}_{G} = \frac{K}{(1+KG)^2}\cdot\frac{G}{\frac{KG}{1+KG}}
%   = \frac{K}{(1+KG)^2}\cdot\frac{G\,(1+KG)}{KG}
%   = \frac{1}{1+KG}$$
%
% **$K$ 도 $G$ 도 전부 지워지고 $\frac{1}{1+KG}$ 만 남습니다.**
% 외란에서 나온 것과 **글자 하나까지 같은 식**입니다.
%
% **개루프**도 같은 방법으로 해 봅니다. $T_{\rm open} = G K_{ff}$ 이므로
%
% $$\frac{dT_{\rm open}}{dG} = K_{ff}
%   \qquad\Rightarrow\qquad
%   S^{T}_{G} = K_{ff}\cdot\frac{G}{G K_{ff}} = 1$$
%
% **정확히 $1$ 입니다.** 플랜트가 $1\%$ 틀리면 출력도 $1\%$ 틀린다는 뜻입니다.
% 줄여 주는 것이 하나도 없습니다.
%
% | | 상대감도 $S^T_G$ | 뜻 |
% |---|---|---|
% | 개루프 | $1$ | 모델 오차가 **그대로** 나온다 |
% | 폐루프 | $\frac{1}{1+KG}$ | $(1+KG)$ 배로 **줄어든다** |
%
% 이제 왜 두 문제의 답이 같은지 식으로도 보입니다.
% 되먹임을 닫는 순간 $(1+KG)$ 라는 항이 **분모에 한 번** 생기고,
% 외란이든 모델 오차든 그 항 하나가 똑같이 나눠 주기 때문입니다.
%
% 수치로도 확인합니다. 미분을 손으로 하지 않고 $G$ 를 아주 조금 바꿔
% 실제로 $T$ 가 몇 $\%$ 변하는지 재 봅니다.
dG_rel = 1e-6;                                  % G 를 0.0001 % 만 키운다
G_pert = tf(G_design.num{1}*(1+dG_rel), G_design.den{1});
T_now  = dcgain(feedback(K*G_design, 1));
T_new  = dcgain(feedback(K*G_pert,   1));
S_num  = ((T_new - T_now)/T_now) / dG_rel;

Kff_s  = 1/dcgain(G_design);
To_now = dcgain(Kff_s*G_design);
To_new = dcgain(Kff_s*G_pert);
So_num = ((To_new - To_now)/To_now) / dG_rel;

fprintf('=== 상대감도를 수치로 확인 ===\n');
fprintf('  폐루프 : 수치 %.6f   이론 1/(1+KG(0)) = %.6f\n', ...
        S_num, 1/(1+K*dcgain(G_design)));
fprintf('  개루프 : 수치 %.6f   이론 1\n', So_num);
fprintf('  --> G 가 1 %% 틀리면 폐루프 출력은 %.1f %% 만 틀립니다.\n', 100*S_num*0.01);
%
% 앞으로의 연결
%
% - 이 $S$ 를 **감도**(sensitivity)라 한다
% - 11주차 주파수영역 설계에서 주인공으로 다시 만난다
% - 오늘은 $\frac{1}{1+\text{루프이득}}$ 이라는 형태만 기억할 것
L0 = K*dcgain(G_design);
fprintf('루프이득 K*G(0) = %.1f\n', L0);
fprintf('감도 S = 1/(1+L) = %.3f\n', 1/(1+L0));
fprintf('즉 외란도 모델 오차도 약 %.0f 배 줄어듭니다.\n', 1+L0);

