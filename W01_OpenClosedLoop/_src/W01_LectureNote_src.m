% - `dcgain(G)` — $G(0)$. 충분히 기다렸을 때의 값
% - `feedback(G, H)` — $\frac{G}{1+GH}$. 손으로 나누지 말 것
% - `stepinfo(G)` — 오버슈트 · 정착시간을 숫자로
% - `lsim(G, u, t)` — 임의 입력에 대한 응답
%
% 앞으로 추가되는 명령
%
% - 6주차 — `rlocus`, `sgrid`
