%% 2-1. 제어 문제의 구조
% 제어 문제는 언제나 같은 모양입니다.
%
% - **제어 대상** (plant) — 우리가 마음대로 바꿀 수 없는 물리 시스템
% - **입력** $u$ — 우리가 넣을 수 있는 것. 힘, 전압, 조타각
% - **목표값** $r$ — 우리가 원하는 값
% - **출력** $y$ — 실제로 나온 값
%
% 제어기 설계란 "$r$ 을 보고 $u$ 를 어떻게 만들 것인가"를 정하는 일이고,
% 여기서 갈림길이 생깁니다.
%
% - **개루프** — $u$ 를 만들 때 $r$ 만 본다. $y$ 는 쳐다보지 않는다
% - **폐루프** — $u$ 를 만들 때 $r$ 과 $y$ 를 같이 본다. 되먹임이 있다
%
% 신호가 지나가는 길이 열려 있느냐 닫혀 있느냐에서 나온 이름입니다.
%% 2-2. 오늘의 제어 대상 — 질량-스프링-댐퍼
% 벽에 스프링과 댐퍼로 매달린 물체를 힘으로 밀어 원하는 위치에 세우는 문제입니다.
% 먼저 그림으로 봅니다. 오른쪽이 자유물체도이고, 거기서 아래 식이 나옵니다.
% ![질량-스프링-댐퍼 : 장치 그림과 자유물체도](msd_both.png)
%
% **그림 파일** `msd_both.png` — `common/dg_msd.m` 의 `dg_msd`
%   · 다시 만들려면 `make_figures('msd_both')`
%
% **만드는 곳** — `common/dg_msd.m` (`make_figures('msd_both')`)
% **직접 확인해 보려면** — `W01_01_open_vs_closed.m` 의 첫 절이
% 이 식에서 전달함수를 만듭니다
%
% 그림 해석 — **왼쪽에서 부호를 정하고 오른쪽에서 식을 세웁니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 빗금 벽 | 고정된 곳 | 위치 $x$ 를 재는 기준 |
% | 왼쪽 스프링 $k$ | 늘어난 만큼 되당긴다 | 위치에 비례하는 힘 |
% | 왼쪽 댐퍼 $b$ | 빠를수록 세게 막는다 | 속도에 비례하는 힘 |
% | 왼쪽 위 $x(t)$ 화살표 | 오른쪽이 $+$ | **여기서 부호를 정한다.** 틀리면 끝까지 틀린다 |
% | 왼쪽 빨간 $F(t)$ | 우리가 넣는 힘 | 제어입력 |
% | 오른쪽 파란 화살표 $kx$ | **왼쪽**을 향한다 | 오른쪽으로 밀리면 되당긴다. 그래서 $-kx$ |
% | 오른쪽 초록 화살표 $b\,dx/dt$ | 역시 왼쪽 | 속도를 막는다. 그래서 $-b\dot{x}$ |
% | 오른쪽 빨간 화살표 $F(t)$ | 오른쪽 | 우리가 미는 힘. 그래서 $+F$ |
% | 오른쪽 위 식 | $ma = F - kx - b\,dx/dt$ | **화살표 방향을 그대로 옮겨 적은 것** |
% | 오른쪽 회색 글씨 | 오른쪽을 $+$ 로 잡았다 | 왼쪽 그림의 약속과 같다 |
%
% **자유물체도를 먼저 그리는 이유**가 여기 있습니다.
% 화살표 방향만 정하면 식은 그대로 옮겨 적으면 됩니다.
% 그림 없이 식부터 쓰면 부호를 반드시 한 번은 틀립니다.
%% 2-2-1. 그림에서 나온 식
%
% $$m\ddot{x} + b\dot{x} + kx = F$$
%
% 라플라스 변환하면
%
% $$G(s) = \frac{X(s)}{F(s)} = \frac{1}{ms^2+bs+k}$$
%
% 왜 이 시스템인가
%
% - **세상에서 가장 흔한 2차 시스템**이다
% - 자동차 서스펜션, 건물의 흔들림, 로봇 관절의 탄성이 모두 이 꼴
%
% 표준형과의 대응
%
% - $\omega_n = \sqrt{k/m}$
% - $\zeta = \frac{b}{2\sqrt{mk}}$
%
% `plant_msd` 는 이 과목에서 준비해 둔 함수로, 전달함수와 파라미터 구조체를 돌려줍니다.
[G, p] = plant_msd();
G
fprintf('고유진동수 = %.2f rad/s,  감쇠비 = %.2f,  DC 이득 = %.2f\n', ...
        p.wn, p.zeta, dcgain(G));
