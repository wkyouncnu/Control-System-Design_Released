%% 3. 개루프 제어 — 미리 계산해서 넣기
% 아이디어는 단순합니다 — **출력이 얼마가 될지 아니까 역으로 계산해서 넣자.**
%
% 정상상태에서 $y = G(0)u$ 이므로 $y=r$ 이 되게 하려면
%
% $$u = \frac{r}{G(0)} = K_{ff}\,r$$
%
% - 이 $K_{ff}$ 를 **피드포워드 이득**이라 한다
% - 앞에서 배운 `dcgain` 이 여기서 쓰인다
%
% 여기서 꼭 짚을 점
%
% - 이 계산은 **$G(0)$ 를 정확히 안다는 가정** 위에 서 있다
% - 그 가정이 깨지는 순간 개루프는 무너진다
% - 7절에서 실제로 무너뜨려 본다
%
% 미리 한 장으로 보면 이렇습니다.
%
% ![모델이 맞으면 완벽하고, 틀리면 그만큼 그대로 틀린다](w01_ol_fail.png)
%
% **그림 파일** `w01_ol_fail.png` — `make_figures.m` 의 `fig_w01_openloop_fail`
%   · 다시 만들려면 `make_figures('w01_ol_fail')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w01_openloop_fail`
% **직접 바꿔 보려면** — `W01_02_model_uncertainty.m` 에서 실제 $k$ 의 배수를
% $1.3$, $1.6$ 말고 다른 값으로 바꿔 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림 파란 곡선의 최종값 | 정확히 $1$ | **모델이 맞으면 개루프도 완벽하다** |
% | 왼쪽 그림 제목의 $K_r = 1.00$ | 미리 계산한 보정 상수 | $1/\mathrm{dcgain}(G)$ 로 구한 것 |
% | 왼쪽 곡선이 크게 출렁이는 것 | 오버슈트 $73\%$ | 이 플랜트가 원래 감쇠가 약하다 |
% | 오른쪽 파란 곡선 | 모델이 맞을 때, 최종값 $1$ | 왼쪽과 같은 것 |
% | 오른쪽 빨간 곡선 | 실제 $k$ 가 $1.3$ 배, 최종값 약 $0.77$ | **$30\%$ 틀리면 $23\%$ 어긋난다** |
% | 오른쪽 노란 곡선 | 실제 $k$ 가 $1.6$ 배, 최종값 약 $0.63$ | 더 틀리면 더 어긋난다 |
% | 세 곡선이 끝까지 **안 만나는** 것 | 오차가 영구히 남는다 | 개루프는 **스스로 고칠 방법이 없다** |
% | 어긋난 정도와 모델 오차의 관계 | 거의 그대로 비례 | 개루프의 오차 $=$ 모델 오차 |
%
% **오른쪽 그림이 개루프의 한계입니다.** 계산은 맞았는데 세상이 달랐습니다.
% 그리고 개루프는 그 사실을 **알 방법조차 없습니다.** 출력을 보지 않기 때문입니다.
%
% 왼쪽은 모델이 정확할 때입니다. **개루프인데도 목표값에 정확히 닿습니다.**
% 개루프가 늘 나쁜 것이 아니라는 점을 여기서 분명히 해 두겠습니다.
%
% 오른쪽이 문제입니다. 스프링 상수 $k$ 가 예상보다 $1.3$ 배, $1.6$ 배 뻣뻣했다면
% 출력이 정확히 그 비율만큼 모자랍니다. **오차를 볼 방법이 없으니 고칠 수도 없습니다.**
%
% $$k \rightarrow 1.5\,k \quad\Rightarrow\quad G(0) = \frac{1}{k} \rightarrow \frac{1}{1.5k}
%   \quad\Rightarrow\quad y_{ss} = K_{ff}\,G_{real}(0) = \frac{1}{1.5} \approx 0.667$$
r   = 1;
Kff = 1 / dcgain(G);
y_open = step(r*Kff*G, t);
plot(t, y_open, 'LineWidth', 2); hold on
yline(r, 'k--', 'LineWidth', 1.5); grid on
xlabel('시간 [s]'); ylabel('변위 x [m]')
title(sprintf('개루프 제어 (Kff = %.2f): 정상상태 %.4f m', Kff, y_open(end)))
legend('개루프 출력', '목표값 r', 'Location','southeast'); ylim([0 2])
%% 3-1. 여기서 놀라야 합니다
% - 개루프인데 **목표값에 정확히 도달**했다
% - 즉 "피드백이 없으면 오차가 난다"는 말은 **사실이 아니다**
% - 모델이 정확하고 외란이 없다면 개루프로도 완벽하게 제어할 수 있다
%
% 우리 주변의 개루프 제어
%
% - 전자레인지 타이머
% - 신호등
% - 세탁기 급수 시간
%
% 결과를 재지 않고 "이만큼 하면 되겠지" 하고 정해 둔 대로 실행합니다.
