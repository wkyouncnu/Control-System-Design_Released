%% 4. 폐루프 비례제어
% 매 순간 출력을 재서 오차를 계산하고, 그 오차에 비례하는 힘을 넣습니다.
%
% $$e(t) = r - y(t), \qquad u(t) = K\,e(t)$$
%
% 폐루프 전달함수는 `feedback(K*G, 1)` 로 구합니다.
%
% $$T(s) = \frac{KG(s)}{1+KG(s)}, \qquad T(0) = \frac{K}{1+K}$$
%
% - $K$ 가 클수록 $1$ 에 가까워진다
% - 그러나 **절대로 $1$ 이 되지는 못한다**
%
% 왜 오차가 남는가
%
% - 비례제어는 **오차가 있어야만 힘을 낸다**
% - 오차가 $0$ 이면 힘도 $0$
% - 그런데 이 플랜트는 스프링이 있어서 힘이 $0$ 이면 원점으로 되돌아간다
% - 즉 스프링을 버틸 힘을 내려면 오차가 조금은 남아 있어야 한다
% - **오차가 제어기의 연료인 셈이다**
%
% ![이득을 키우면 정확해지지만 흔들린다](w01_gain_sweep.png)
%
% **그림 파일** `w01_gain_sweep.png` — `make_figures.m` 의 `fig_gain_sweep`
%   · 다시 만들려면 `make_figures('w01_gain_sweep')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_gain_sweep`
% **직접 바꿔 보려면** — `W01_01_open_vs_closed.m` 에서 `K` 목록을 바꿔 실행
%
% 그림 해석 — **오른쪽 그림의 두 세로축 색을 보십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 곡선 ($K=1$) | $0.5$ 근처에서 멈춘다 | 오차가 $50\%$ 나 남는다 |
% | 왼쪽 빨간 곡선 ($K=5$) | $0.85$ 근처 | 나아졌다 |
% | 왼쪽 노란 곡선 ($K=20$) | $1$ 에 가깝다 | **이득을 키우니 정확해졌다** |
% | 왼쪽 노란 곡선의 첫 봉우리 | $1.85$ 까지 초과한다 | 그런데 **많이 진동한다** |
% | 왼쪽 세 곡선의 진동 횟수 | $K$ 가 클수록 많다 | 이득이 클수록 오래 진동한다 |
% | 오른쪽 **파란** 곡선과 왼쪽 세로축 | 정상상태 오차, $67\%$ 에서 $3\%$ 로 | 이득을 키우면 **좋아진다** |
% | 오른쪽 **주황** 곡선과 오른쪽 세로축 | 오버슈트, $77\%$ 에서 $95\%$ 로 | 이득을 키우면 **나빠진다** |
% | 두 곡선이 서로 **반대 방향**인 것 | 하나가 내려가면 하나가 올라간다 | **이것이 첫 맞바꿈이다** |
% | 파란 곡선이 $K>20$ 에서 거의 평평한 것 | 더 키워도 얻는 게 적다 | 이득을 무한히 키울 이유가 없다 |
%
% **오른쪽 그림 하나가 이 과목 전체의 축소판입니다.**
% 하나를 얻으려면 하나를 내줘야 합니다.
% 4주차에서 이 맞바꿈을 숫자로 적는 법을 배우고,
% 6주차부터는 그 숫자를 보고 $K$ 를 고릅니다.
for K = [1 3 9]
    T = feedback(K*G, 1);
    plot(t, step(r*T, t), 'LineWidth', 2); hold on
    fprintf('K = %d : 정상상태 %.4f (이론 %.4f), 오차 %.1f %%\n', ...
            K, dcgain(r*T), K/(1+K), 100*(1 - K/(1+K)));
end
yline(r, 'k--', 'LineWidth', 1.5); grid on
xlabel('시간 [s]'); ylabel('변위 x [m]')
title('비례제어: K 를 키우면 오차는 줄지만 진동이 심해진다')
legend('K = 1','K = 3','K = 9','목표값 r', 'Location','southeast'); ylim([0 2])
%% 4-1. 이대로면 개루프의 완승입니다
% - 개루프는 오차가 $0$
% - 폐루프는 $10\sim50\%$ 나 틀리고 진동까지 심함
% - 이 그림만 보면 피드백을 쓸 이유가 없어 보인다
%
% 그런데 **이 비교는 불공정했습니다**
%
% - 개루프에는 $K_{ff}$ 라는 보정 상수를 붙여 줬다
% - 폐루프에는 아무것도 안 붙였다
% - 조건을 맞춰 줍시다
%% 5. 공정하게 — 폐루프에도 보정 상수를 붙이자
% 폐루프에도 상수를 하나 곱해 정상상태를 맞춥니다.
%
% $$K_r = \frac{1}{T(0)} = \frac{1+K}{K}$$
%
% - 여기서도 `dcgain` 이 쓰인다
% - 폐루프 전달함수의 DC 이득의 역수를 취하면 된다
% - 이 아이디어는 **13주차 상태궤환 제어**에서 똑같은 $K_r$ 이라는 이름으로 다시 등장한다
K  = 9;
T  = feedback(K*G, 1);
Kr = 1 / dcgain(T);
y_close = step(r*Kr*T, t);
plot(t, y_open, 'LineWidth', 2); hold on
plot(t, y_close, 'LineWidth', 2)
yline(r, 'k--', 'LineWidth', 1.5); grid on
xlabel('시간 [s]'); ylabel('변위 x [m]')
title('조건을 맞추면 정상상태는 개루프나 폐루프나 똑같다')
legend('개루프', sprintf('폐루프 (K=%d, Kr=%.2f)', K, Kr), '목표값 r', ...
       'Location','southeast'); ylim([0 2])
%% 6. 결정적 장면 하나 — 외란
% 무승부 상태에서 현실을 한 스푼 넣어 봅니다.
%
% - 바람, 마찰, 누가 툭 미는 힘
% - 이것을 **외란** $d$ 라 하고 플랜트 입력단에 더해진다
% - 즉 플랜트가 실제로 받는 힘은 $u+d$
%
% 식을 세우기 전에 **$u$ 와 $d$ 가 어디서 만나는지** 그림으로 확인합니다.
% 이 자리를 잘못 잡으면 뒤의 유도가 통째로 틀립니다.
%
% ![개루프 — 외란이 들어온 줄도 모른다](loop_dist_open.png)
%
% **그림 파일** `loop_dist_open.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_dist_open')`
%
% ![폐루프 — 같은 자리에 같은 외란이 들어온다](loop_dist_closed.png)
%
% **그림 파일** `loop_dist_closed.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_dist_closed')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('dist_open', ...)` 과
% `dg_loop('dist_closed', ...)` 로 부릅니다
% **직접 확인해 보려면** — `W01_01_open_vs_closed.m` 의 외란 실험 절
%
% 그림 해석 — **두 그림을 위아래로 놓고 같은 자리를 짚어 가며 읽으십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 두 그림의 빨간 점선 화살표 | 외란 $d$ | 두 구조 모두 **플랜트 바로 앞**으로 들어온다 |
% | 그 화살표가 꽂히는 동그라미 | 합산점 | **여기가 $u$ 와 $d$ 가 만나는 자리**다 |
% | 그 동그라미의 두 부호 | 둘 다 $+$ | 외란은 빼는 것이 아니라 **더해진다** |
% | 동그라미와 $G(s)$ 사이의 이름 | $u+d$ | **플랜트가 실제로 받는 힘**이다. $u$ 가 아니다 |
% | 첫 그림에 되먹임 선이 없는 것 | 개루프 | $y$ 를 안 보니 $d$ 가 들어온 줄 모른다 |
% | 둘째 그림의 아래쪽 되먹임 선 | 폐루프 | $y$ 가 바뀌면 $e$ 가 바뀌고 $u$ 가 따라 바뀐다 |
% | 둘째 그림에만 있는 $K$ 상자 | 비례제어기 | 이 상자가 오차를 보고 힘을 더 낸다 |
% | 첫 그림의 $K_{ff}$ 와 둘째의 $K_r$ | 둘 다 지령 보정 상수 | 두 방식을 **같은 조건**으로 견주려고 둔 것 |
% | 두 그림에서 $G(s)$ 는 같은 것 | 플랜트는 안 바뀐다 | **바뀐 것은 연결뿐**이다 |
%
% **첫 그림에서 $d$ 가 들어온 뒤 $y$ 까지 가는 길에 아무 장치도 없습니다.**
% 그래서 외란이 $G$ 를 그대로 통과합니다. 둘째 그림에는 되먹임 선이 있어
% $d$ 가 만든 변화가 다시 $e$ 로 돌아와 $u$ 를 바꿉니다. 이 차이가 전부입니다.
%
% 이제 각각의 출력이 어떻게 나오는지 **한 줄씩 따라가 봅니다.**
% 외우지 말고 **그림의 신호를 따라가면** 됩니다. 방법은 언제나 같습니다.
%
% - 출력 $y$ 에서 시작해 **거슬러 올라가며** 식을 적는다
% - $y$ 가 양변에 나오면 **한쪽으로 모은다**
% - $y$ 로 묶어 나눈다
%
% **개루프** — 제어기가 출력을 보지 않으므로 거슬러 올라갈 것이 없습니다.
%
% $$u = K_{ff}\,r$$
%
% 플랜트가 실제로 받는 힘은 $u + d$ 이므로
%
% $$y_{\rm open} = G\,(u + d) = G\,(K_{ff}\,r + d)
%   = G K_{ff}\,r
%   + G\,d$$
%
% **한 줄로 끝났습니다.** $y$ 가 오른쪽에 다시 나오지 않기 때문입니다.
%
% **폐루프** — 여기서는 $y$ 가 되돌아오므로 이야기가 달라집니다.
% 신호를 따라가면 세 줄입니다.
%
% $$e = K_r\,r - y, \qquad u = K\,e, \qquad y = G\,(u + d)$$
%
% 마지막 식에 앞의 둘을 차례로 넣습니다.
%
% $$y = G\left(K(K_r r - y) + d\right) = G K K_r\,r - G K\,y + G\,d$$
%
% **여기서 $y$ 가 양변에 나옵니다.** 왼쪽으로 모읍니다.
%
% $$y + G K\,y = G K K_r\,r + G\,d
%   \qquad\Rightarrow\qquad
%   (1 + KG)\,y = G K K_r\,r + G\,d$$
%
% 양변을 $(1+KG)$ 로 나누면 끝입니다.
%
% $$y_{\rm closed} = \frac{KG}{1+KG}\,K_r\,r + \frac{G}{1+KG}\,d
%   = K_r T\,r + \frac{G}{1+KG}\,d$$
%
% 여기서 $T = \frac{KG}{1+KG}$ 는 1-6절에서 `feedback` 이 계산해 준 그것입니다.
%
% **$(1+KG)$ 가 어디서 나왔는지 보십시오.** $y$ 를 한쪽으로 모으는 그 한 걸음에서
% 나왔습니다. 되먹임 선이 없으면 이 항이 생기지 않습니다.
% 오늘 이후 학기 내내 나오는 $1+KG$ 는 전부 이 자리에서 온 것입니다.
%
% 두 식을 나란히 놓으면 이렇습니다.
%
% | | 지령이 만든 항 | **외란이 만든 항** |
% |---|---|---|
% | 개루프 | $G K_{ff}\,r$ | $G\,d$ |
% | 폐루프 | $K_r T\,r$ | $\frac{G}{1+KG}\,d$ |
%
% 외란이 붙은 항을 보십시오.
%
% - **개루프** — $Gd$ 가 그대로 살아 있다
% - **폐루프** — 분모에 $(1+KG)$ 가 붙어 그만큼 줄어든다
%
% 개루프가 외란을 못 잡는 이유는 허무할 정도로 단순합니다.
%
% - **출력을 보지 않으니 외란이 들어온 줄도 모른다**
%
% 계산 방법
%
% - `lsim` 으로 목표값 신호와 외란 신호를 각각 넣고 두 응답을 더한다
% - 더해도 되는 이유는 선형 시스템이기 때문이며, 이를 **중첩의 원리**라 한다
%
% ![같은 외란인데 폐루프는 훨씬 작게 받는다](w01_disturbance.png)
%
% **그림 파일** `w01_disturbance.png` — `make_figures.m` 의 `fig_disturbance`
%   · 다시 만들려면 `make_figures('w01_disturbance')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_disturbance`
% **직접 바꿔 보려면** — `W01_01_open_vs_closed.m` 의 외란 실험 절에서
% $K$ 를 바꾸면 두 곡선의 간격이 달라집니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 검은 세로 점선 | $t = 10$ s | 여기서 외란이 들어온다 |
% | $t < 10$ s 구간 | 두 곡선이 모두 $0$ | 외란이 없으니 아무 일도 없다 |
% | 파란 곡선 (개루프) | $0.87$ 까지 급증한다 | **외란을 그대로 받는다** |
% | 파란 곡선이 계속 출렁이는 것 | $30$ s 까지도 $0.45$ | 스스로 못 없앤다 |
% | 빨간 곡선 (폐루프) | $0.10$ 을 넘지 않는다 | **약 $9$ 배 작다** |
% | 빨간 곡선이 빠르게 감쇠하는 것 | 진폭이 계속 준다 | 되먹임이 밀어내고 있다 |
% | 두 곡선의 봉우리 비 | $0.87 : 0.10$, 즉 약 $9$ 배 | 이 그림은 $K = 9$ 로 그린 것이다 |
%
% **$9$ 라는 숫자가 어디서 왔는지** 확인해 봅니다.
%
% 정상상태에서 외란이 출력에 얼마나 나오는지는 이렇게 됩니다.
%
% $$\text{개루프} : \; \frac{y}{d} = G(0)
%   \qquad\qquad
%   \text{폐루프} : \; \frac{y}{d} = \frac{G(0)}{1 + K\,G(0)}$$
%
% 두 값의 비가 $1 + KG(0)$ 입니다. 이 플랜트는 $G(0) = 1$ 이고 그림은
% $K = 9$ 로 그렸으므로 **정확히 $10$ 배**가 나와야 합니다.
%
% 그림에 $9$ 배로 적힌 것은 **정상상태가 아니라 봉우리끼리 견준 값**이라
% 그렇습니다. 과도응답 중에는 조금 다르게 나옵니다.
% 정상상태로 재면 정확히 $10$ 입니다. 다음 절에서 그 식을 유도합니다.
d = 0.5; t_d = 40;
u_ref = r*ones(size(t));
u_dis = d*(t >= t_d);
y_open_d  = lsim(Kff*G, u_ref, t) + lsim(G, u_dis, t);
y_close_d = lsim(Kr*T, u_ref, t) + lsim(feedback(G,K), u_dis, t);
plot(t, y_open_d, 'LineWidth', 2); hold on
plot(t, y_close_d, 'LineWidth', 2)
yline(r, 'k--', 'LineWidth', 1.5); xline(t_d, 'r:', 'LineWidth', 2); grid on
xlabel('시간 [s]'); ylabel('변위 x [m]')
title(sprintf('t = %d s 에 외란 %.1f N 이 들어왔을 때', t_d, d))
legend('개루프', '폐루프', '목표값 r', '외란 유입', 'Location','southeast'); ylim([0 2])
%% 6-1. 숫자로 확인
% - 외란 억제비의 이론값은 $\frac{1}{1+KG(0)}$
% - $K=9$, $G(0)=1$ 이므로 $\frac{1}{10}$
% - 즉 오차가 **10분의 1** 로 줄어야 한다
fprintf('개루프 최종 오차 : %+.4f m\n', r - y_open_d(end));
fprintf('폐루프 최종 오차 : %+.4f m\n', r - y_close_d(end));
fprintf('줄어든 비율      : %.1f 배   (이론값 %.0f)\n', ...
        abs((r-y_open_d(end))/(r-y_close_d(end))), 1+K*dcgain(G));
