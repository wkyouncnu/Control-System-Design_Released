% 읽는 법 — PM $60.6^\circ$, GM $24.0$ dB 입니다. **이상적인 플랜트에서는
% 사양 2·3번을 넉넉히 통과합니다.**
%
% 그런데 아직 두 가지를 안 봤습니다. 수송지연과 제어입력입니다.
% 여기서 끝냈다면 실물에서 실패합니다.
%% 8-5. 5단계 — 실제 플랜트로 검증한다 : 수송지연
% 왜 필요한가 — 센서가 값을 주기까지 $0.02$ 초가 걸립니다. 엔코더를 읽고
% 통신으로 보내고 제어기가 받기까지의 시간입니다. 이것을 **수송지연**
% (transport delay) 이라고 합니다.
%
% $$y_{측정}(t) = y(t - T_d), \qquad T_d = 0.02 \text{ s}$$
%
% 라플라스 변환하면 $e^{-s T_d}$ 가 곱해집니다. 이것이 왜 문제인가 —
% 크기와 위상을 따로 보면 바로 보입니다.
%
% $$|e^{-j\omega T_d}| = 1, \qquad \angle e^{-j\omega T_d} = -\omega T_d \text{ [rad]}$$
%
% **크기는 하나도 안 바뀌고 위상만 깎입니다.** 그리고 깎이는 양이
% $\omega$ 에 **비례**합니다. 고주파로 갈수록 끝없이 깎입니다.
%
% 손계산 — 8-4절에서 얻은 $\omega_c = 8.588$ rad/s 에서 깎이는 위상은
%
% $$-\omega_c T_d = -8.588 \times 0.02 = -0.1718 \text{ rad} = -9.84^\circ$$
%
% 라디안을 도로 바꾸는 것만 조심하면 됩니다 ($\times 180/\pi$).
% 즉 PM $60.6^\circ$ 가 $50.7^\circ$ 쯤으로 떨어질 것으로 예상됩니다.
% 사양 $50^\circ$ 를 **간신히 지킵니다.**
%
% ![수송지연은 크기를 안 건드리고 위상만 깎는다](w11b_delay.png)
%
% **그림 파일** `w11b_delay.png` — `make_figures.m` 의 `fig_w11b_delay`
%   · 다시 만들려면 `make_figures('w11b_delay')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 그림 | 지연이 있을 때와 없을 때의 크기 | **완전히 겹친다.** 교차주파수가 안 변한다 |
% | 아래 그림 | 두 위상 곡선 | 저주파에서는 같고 고주파에서 벌어진다 |
% | 벌어지는 양 | $-\omega T_d$ | 로그축이라 직선이 아니라 **휘어진다** |
% | 세로 점선 | $\omega_c$ | 그 자리의 두 곡선 간격이 **잃는 PM** |
% | 오른쪽 끝 | 위상이 끝없이 내려간다 | 그래서 $\omega_c$ 를 함부로 높이면 안 된다 |
%
% MATLAB 검산 — 지연을 `pade` 로 유리함수로 바꿔 넣습니다. 앱은 지연을
% 못 받지만 `margin` 은 `pade` 근사를 쓰면 받습니다.
%
% 명령 정리 — `pade`
%
% - **원리** — $e^{-sT_d}$ 를 같은 차수의 유리함수로 근사한다. 1차는
%   $\frac{1 - sT_d/2}{1 + sT_d/2}$, 차수를 올리면 더 넓은 주파수대에서 맞는다
% - **입력** — `[num, den] = pade(Td, n)`. $T_d$ 는 지연 시간, $n$ 은 차수
% - **출력** — 분자·분모 계수. `tf(num, den)` 으로 전달함수로 만든다
% - **주의** — 분자에 **불안정 영점**(우반면)이 생깁니다. 그것이 지연의 성질을
%   흉내 내는 방법입니다. 차수가 낮으면 고주파에서 틀립니다. $n = 3$ 이면
%   $\omega T_d < 2$ 쯤까지 믿을 수 있습니다
Td_cap = 0.02;
[nd, dd] = pade(Td_cap, 3);
G_real = G_m*tf(nd, dd);
[g_r, p_r, ~, wc_r] = margin(C_cap*G_real);
T_r = feedback(C_cap*G_real, 1);
s_r = stepinfo(T_r);
nm10 = {'이상 플랜트'; '지연 0.02 s 포함'};
table(nm10, [p_cap; p_r], [20*log10(g_cap); 20*log10(g_r)], [wc_cap; wc_r], ...
    [s_cl.Overshoot; s_r.Overshoot], [s_cl.SettlingTime; s_r.SettlingTime], ...
    'VariableNames', {'플랜트', 'PM_deg', 'GM_dB', 'wc', 'OS_퍼센트', 'ts'})
%%
% 읽는 법 — 예측대로입니다.
%
% - 교차주파수가 **똑같습니다** ($8.588$). 지연이 크기를 안 건드렸으니까
% - PM 이 $60.6^\circ \to 50.7^\circ$ 로 $9.84^\circ$ 떨어졌습니다.
%   **손계산 $-9.84^\circ$ 와 소수 둘째 자리까지 같습니다**
% - GM 도 $24.0 \to 13.5$ dB 로 크게 떨어졌습니다
% - 오버슈트가 $14.5\% \to 20.5\%$ 로 늘었습니다
%
% **PM $50.7^\circ$, GM $13.5$ dB — 사양 2·3번을 간신히 통과합니다.**
% 간신히라는 것이 중요합니다. 지연이 조금만 더 길어지면 깨집니다.
%
% 왜 중요한가 — 앱 안에서 본 $60.6^\circ$ 는 **실제 여유가 아니었습니다.**
% 앱은 유리함수만 다루므로 지연을 모릅니다.
% **지연이 있는 시스템은 반드시 Simulink 로 따로 확인해야 합니다** (9절).
%% 8-6. 마지막 확인 — 제어입력
% 왜 필요한가 — 사양 4번이 남았습니다. 그런데 앱의 기본 화면에는 $u$ 가
% 없습니다. 재 봅니다.
%
% 지령에서 제어입력까지의 전달함수를 유도합니다. 1-2절 그림에서
%
% $$u = Ce = C(r - y), \qquad y = Gu$$
%
% 둘째 식을 첫째에 넣으면 $u = C(r - Gu)$, $u$ 를 모으면 $(1 + CG)u = Cr$,
% 따라서
%
% $$\frac{u}{r} = \frac{C}{1 + CG}$$
%
% $s \to \infty$ 에서 이 값은 $C(\infty)$ 로 갑니다 ($G(\infty) = 0$ 이므로).
% 우리 제어기는 $C(\infty) = K/\alpha^2$ 입니다.
%
% 손계산 — $200/0.0994^2 = 20237$ 입니다. 계단 지령을 주면 첫 순간에
% **$20237$ V** 가 필요하다는 뜻입니다. 모터는 $12$ V 입니다.
Gu_cap = minreal(C_cap/(1 + C_cap*G_real));
t_cap = (0:1e-4:4)';
u_step = lsim(Gu_cap, ones(size(t_cap)), t_cap);
table(Kpick2/al_cap^2, max(abs(u_step)), ...
    'VariableNames', {'공식_K_over_alpha2', '실측_umax_계단'})
%%
% 읽는 법 — 공식과 실측이 같습니다. **계단 지령은 이 설계로 불가능합니다.**
%
% 그런데 사양 1번은 **램프** 지령이었습니다. 램프는 첫 순간의 점프가 없으니
% 다릅니다. 게다가 실제 장비는 지령을 갑자기 꺾지 않고 **매끄럽게** 올립니다.
% 그 지령으로 다시 재 봅니다.
A_cap = 0.2; tau_cap = 0.3;
r_cap = A_cap*(t_cap - tau_cap*(1 - exp(-t_cap/tau_cap)));   % 출발이 매끄러운 램프
u_cap = lsim(Gu_cap, r_cap, t_cap);
y_cap = lsim(feedback(C_cap*G_real,1), r_cap, t_cap);
table(max(abs(u_cap)), 12, r_cap(end) - y_cap(end), 0.01, ...
    'VariableNames', {'umax_V', '한계_V', '정상상태오차', '사양'})
%%
% 읽는 법 — **$4.2$ V 로 한계 $12$ V 안에 들어옵니다.** 정상상태오차도
% $0.0100$ rad 으로 사양을 지킵니다. **네 사양 전부 통과입니다.**
%
% 그림으로 확인합니다.
tiledlayout(2, 1, 'TileSpacing', 'compact');
nexttile; hold on; grid on;
plot(t_cap, r_cap, '--', 'LineWidth', 2);
plot(t_cap, y_cap, 'LineWidth', 2.2);
xlabel('시간 [s]'); ylabel('위치 [rad]');
legend('지령 (매끄러운 램프)', '출력', 'Location', 'northwest');
title('사양 1 — 간격이 0.01 rad');
nexttile; hold on; grid on;
plot(t_cap, u_cap, 'LineWidth', 2.2);
yline(12, 'r--', 'LineWidth', 1.5); yline(-12, 'r--', 'LineWidth', 1.5);
xlabel('시간 [s]'); ylabel('제어전압 [V]'); ylim([-14 14]);
legend('u', '한계 \pm12 V', 'Location', 'northeast');
title('사양 4 — 한계 안에 들어온다');
