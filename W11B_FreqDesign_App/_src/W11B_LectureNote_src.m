%% 1-2. 무엇을 편집하는가 — $C$ 를 고른다
% 왜 필요한가 — 앱 안에는 블록이 여러 개 있습니다 ($C$, $G$, $H$, $F$).
% 아무것도 고르지 않고 끌면 엉뚱한 블록이 바뀝니다.
%
