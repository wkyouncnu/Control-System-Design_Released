%% 3-3. PD 의 대가 — 고주파가 끝없이 올라간다
% 왜 문제인가 — 세 가지가 동시에 일어납니다.
%
% | 문제 | 왜 | 11A주차 어디 |
% |---|---|---|
% | **센서 잡음이 증폭된다** | $n \to u$ 전달함수에 $|C|$ 가 그대로 들어간다 | 6절 |
% | **제어입력이 터진다** | 계단 지령의 첫 순간 $u(0^+) = $ $C$ 의 고주파 이득 | 8-6절에서 다시 |
% | **모르는 동특성을 깨운다** | 모델에 없는 고주파 극점이 그 자리에 있을 수 있다 | 4절 |
%
% 둘째 문제를 숫자로 확인합니다. 그런데 **진짜 계단으로는 계산 자체가 안 됩니다.**
% 이유를 먼저 보겠습니다. 지령에서 제어입력까지의 전달함수는
%
% $$\frac{u}{r} = \frac{C}{1 + CG}$$
%
% 이고 $s \to \infty$ 를 넣어 보면
%
% $$C(s) = K(1 + T_d s) \to \infty, \qquad C(s)G(s) = \frac{K(1+T_d s)}{s(s+1)} \to 0$$
%
% 이므로 $u/r \to C \to \infty$ 입니다. 분자 차수가 분모보다 높은 것(비적정,
% improper)이고, `lsim` 은 이런 시스템을 아예 거부합니다.
% **수학이 "계단은 무리입니다" 라고 말해 주는 것입니다.**
%
% 그러니 현실처럼 지령을 조금 부드럽게 만들어 넣습니다. 시간상수 $\tau = 0.05$ 초의
% 1차 필터를 통과시킨 계단입니다 — 0.05 초 만에 올라가는, 충분히 급한 지령입니다.
tau = 0.05;
Rsmooth = tf(1, [tau 1]);                  % 부드럽게 올라가는 지령
tt2 = (0:1e-4:1)';
umax_pd = zeros(n1, 1);
for k = 1:n1
    Ck = 100*(1 + Tdv(k)*s);
    Gu = minreal(Ck/(1 + Ck*G1));          % r -> u
    uu = lsim(minreal(Gu*Rsmooth), ones(size(tt2)), tt2);
    umax_pd(k) = max(abs(uu));
end
table(Tdv, 100*Tdv/tau, umax_pd, ...
    'VariableNames', {'Td', '공식_K_Td_over_tau', 'umax_실측'})
%%
% 읽는 법 — 둘째 열과 셋째 열이 **정확히 같습니다**. 제어기의 미분항이
% 지령의 기울기를 그대로 받기 때문입니다. 지령이 $\tau$ 초 만에 $1$ 만큼
% 올라가면 기울기가 $1/\tau$ 이고, $C$ 의 미분항이 그것에 $K T_d$ 를 곱합니다.
%
% $$u_{max} = \frac{K T_d}{\tau}$$
%
% 그리고 이 식이 곧 "계단은 안 된다" 는 말입니다. 진짜 계단은 $\tau \to 0$ 이고
% 그러면 $u_{max} \to \infty$ 입니다. 지령을 두 배 급하게 만들면 필요한
% 전압이 두 배가 됩니다.
%
% **PD 는 순수한 형태로는 쓸 수 없습니다.** $T_d = 1$ 은 PM $90^\circ$ 를 주지만
% 제어입력이 $2000$ 이 필요합니다. 모터가 $12$ V 짜리면 그냥 포화됩니다.
% 가장 작은 $T_d = 0.05$ 조차 $100$ 이 필요합니다.
%
% 왜 중요한가 — 그래서 **고주파에서 멈추는 PD** 가 필요합니다.
% 그것이 Lead 입니다.
%% 4. Lead — PD 의 현실판
% 왜 필요한가 — PD 의 크기가 끝없이 올라가는 것은 분모가 $1$ 이기 때문입니다.
% **분모에 극점을 하나 넣어 어느 주파수부터 다시 평평해지게** 만들면 됩니다.
%
% $$C(s) = K \frac{1 + Ts}{1 + \alpha T s}, \qquad 0 < \alpha < 1$$
%
% 기호의 뜻
%
% | 기호 | 뜻 | 보드 선도에서 |
% |---|---|---|
% | $1/T$ | 영점 위치 | 여기서 $+20$ dB/dec 로 **올라가기 시작** |
% | $1/(\alpha T)$ | 극점 위치 | 여기서 다시 **평평해진다** |
% | $\alpha$ | 두 꺾이는 자리의 **비율** | $\alpha$ 가 작을수록 멀리 떨어진다 |
% | $1/\alpha$ | 고주파 이득의 배수 | $\alpha = 0.1$ 이면 10배 ($20$ dB) |
%
% $\alpha < 1$ 이므로 $1/(\alpha T) > 1/T$ 입니다. 즉 **영점이 극점보다 왼쪽**입니다.
% 이것이 Lead 의 정의입니다. 반대로 놓으면 Lag 가 됩니다 (6절, 7-3절).
%
% 가장 작은 예 — $\alpha = 0.1$, $T = 1$ 로 두면 영점이 $1$, 극점이 $10$ 입니다.
% 저주파 이득은 $K$, 고주파 이득은 $K/\alpha = 10K$ 입니다. 그 사이 한 데케이드
% 동안 $20$ dB 올라가고 **거기서 멈춥니다.**
Clead0 = (1 + s)/(1 + 0.1*s);
wl = [0.01; 1; 3.162; 10; 1000];
table(wl, 20*log10(squeeze(abs(freqresp(Clead0, wl)))), ...
    squeeze(angle(freqresp(Clead0, wl)))*180/pi, ...
    'VariableNames', {'w_rad_s', '크기_dB', '위상_deg'})
%%
% 읽는 법 — $\omega = 0.01$ 에서 $0$ dB, $\omega = 1000$ 에서 $20$ dB 로
% **멈춰 있습니다.** 그리고 위상이 가장 높은 곳은 $\omega = 3.162$ 입니다.
% 이 값은 $\sqrt{1 \times 10} = 3.162$, 즉 **두 꺾이는 자리의 기하평균**입니다.
% 다음 절에서 이것을 유도합니다.
%% 4-1. 최대 위상과 $\alpha$ — 유도
% 왜 필요한가 — 설계할 때 우리가 원하는 것은 "이 주파수에서 위상을 $50^\circ$
% 올려 달라" 입니다. 그러려면 $\alpha$ 와 $T$ 를 그 요구에서 거꾸로 계산해야 합니다.
%
% **1단계 위상 식을 쓴다.**
%
% $$\angle C(j\omega) = \arctan(\omega T) - \arctan(\alpha \omega T)$$
%
% 영점이 $+\arctan$, 극점이 $-\arctan$ 을 줍니다. $\alpha < 1$ 이므로 앞의 항이
% 항상 크고, 따라서 **위상이 항상 $+$** 입니다.
%
% **2단계 최대가 되는 곳을 찾는다.** tan 의 덧셈정리를 씁니다.
% $x = \omega T$ 로 두면
%
% $$\tan \phi = \frac{x - \alpha x}{1 + \alpha x^2} = \frac{(1-\alpha)x}{1 + \alpha x^2}$$
%
% 이것을 $x$ 로 미분해 $0$ 으로 둡니다. 분자의 미분이 $0$ 이면 되므로
%
% $$(1-\alpha)(1 + \alpha x^2) - (1-\alpha)x \cdot 2\alpha x = 0$$
%
% $(1-\alpha)$ 로 나누면 $1 + \alpha x^2 - 2\alpha x^2 = 0$, 즉
% $1 = \alpha x^2$ 입니다. 따라서
%
% $$x = \omega T = \frac{1}{\sqrt{\alpha}} \quad \Rightarrow \quad \omega_{max} = \frac{1}{T\sqrt{\alpha}} = \sqrt{\frac{1}{T} \cdot \frac{1}{\alpha T}}$$
%
% **두 꺾이는 자리의 기하평균**입니다. 로그축에서는 정확히 **가운데**입니다.
%
% **3단계 그 자리의 위상을 구한다.** $x = 1/\sqrt{\alpha}$ 를 넣습니다.
%
% $$\tan \phi_{max} = \frac{(1-\alpha)/\sqrt{\alpha}}{1 + \alpha \cdot (1/\alpha)} = \frac{1-\alpha}{2\sqrt{\alpha}}$$
%
% $\tan$ 을 $\sin$ 으로 바꾸면 ($1 + \tan^2$ 을 쓰면 분모가 $\frac{1+\alpha}{2\sqrt{\alpha}}$ 가 됩니다)
%
% $$\sin \phi_{max} = \frac{1-\alpha}{1+\alpha} \quad \Rightarrow \quad \alpha = \frac{1 - \sin\phi_{max}}{1 + \sin\phi_{max}}$$
%
% **4단계 그 자리의 크기도 구한다.** 같은 $x$ 를 크기식에 넣으면
%
% $$|C(j\omega_{max})| = K \frac{\sqrt{1 + 1/\alpha}}{\sqrt{1 + \alpha}} = \frac{K}{\sqrt{\alpha}}$$
%
% dB 로는 $20\log_{10}(K) - 10\log_{10}(\alpha)$ 입니다. 즉 **$\omega_{max}$ 에서
% 크기가 $-10\log_{10}\alpha$ dB 만큼 올라가 있습니다.** 이것이 설계에서 중요한
% 이유는 7절에서 봅니다 — 크기가 올라가면 교차주파수가 오른쪽으로 밀립니다.
%
% 손계산 — $\phi_{max} = 50^\circ$ 를 넣어 봅니다. $\sin 50^\circ = 0.766$ 이므로
%
% $$\alpha = \frac{1 - 0.766}{1 + 0.766} = \frac{0.234}{1.766} = 0.1325$$
%
% 그리고 $-10\log_{10}(0.1325) = 8.78$ dB 입니다.
%
% MATLAB 검산 — 네 각도에 대해 공식과 실측을 맞대 봅니다.
phiv = [20; 35; 50; 65];
n2 = numel(phiv);
alv = (1 - sind(phiv))./(1 + sind(phiv));
ph_meas = zeros(n2,1); mg_meas = zeros(n2,1); wmax_meas = zeros(n2,1);
wsc = logspace(-2, 2, 20001);
for k = 1:n2
    Ck = (1 + s)/(1 + alv(k)*s);            % T = 1 로 두면 wmax = 1/sqrt(alpha)
    fr = squeeze(freqresp(Ck, wsc));
    [ph_meas(k), i_] = max(angle(fr)*180/pi);
    wmax_meas(k) = wsc(i_);
    mg_meas(k) = 20*log10(abs(fr(i_)));
end
table(phiv, alv, ph_meas, 1./sqrt(alv), wmax_meas, -10*log10(alv), mg_meas, ...
    'VariableNames', {'phi_목표', 'alpha', 'phi_실측', 'wmax_공식', 'wmax_실측', ...
                      '크기_공식_dB', '크기_실측_dB'})
%%
% 읽는 법 — 네 줄 모두 공식과 실측이 일치합니다. 그리고 표에서 **중요한 경고**가
% 하나 읽힙니다.
%
% - $\phi_{max} = 65^\circ$ 는 $\alpha = 0.0545$ 입니다. 고주파 이득이 $18$ 배입니다
% - $\phi_{max} = 70^\circ$ 를 넣으면 $\alpha = 0.0311$, $32$ 배가 됩니다
% - $\phi_{max} \to 90^\circ$ 면 $\alpha \to 0$, 즉 **PD 로 되돌아갑니다**
%
% 그래서 실무 규칙은 이렇습니다 — **한 단으로 $55^\circ$ 를 넘기지 않는다.**
% 더 필요하면 두 단으로 나눕니다 (4-5절).
%% 4-2. Lead 설계 다섯 단계
% 지금까지의 식을 **절차**로 정리합니다. 손으로 할 때도, 앱으로 할 때도 같습니다.
%
% | 단계 | 하는 일 | 쓰는 식 |
% |---|---|---|
% | 1 | $K$ 를 정상상태오차에서 정한다 | $K_v = \lim s L$ (2-1절) |
% | 2 | 그 $K$ 로 현재 PM 을 잰다 | `margin` |
% | 3 | **필요한 위상** $\phi = PM_{목표} - PM_{현재} + \epsilon$ | $\epsilon = 5 \sim 10^\circ$ 여유 |
% | 4 | $\alpha$ 와 $T$ 를 계산한다 | $\alpha = \frac{1-\sin\phi}{1+\sin\phi}$, $T = \frac{1}{\omega_{max}\sqrt\alpha}$ |
% | 5 | 결과를 **다시 재서** 확인하고 모자라면 3번으로 | `margin`, `stepinfo` |
%
% 3단계에 **$\epsilon$ 을 더하는 이유**가 중요합니다. Lead 를 넣으면 크기가
% $-10\log_{10}\alpha$ dB 올라가므로 **교차주파수가 오른쪽으로 밀립니다.**
% 밀려간 자리에서는 플랜트의 위상이 더 깎여 있으니, 계산한 것보다 PM 이
% 덜 나옵니다. 그 손실을 미리 보태 두는 것입니다.
%
% $\omega_{max}$ 는 어디에 놓는가 — **새 교차주파수가 될 자리**에 놓습니다.
% 실무 절차는 이렇습니다.
%
% - $|KG(j\omega)| = 10\log_{10}\alpha$ dB (즉 Lead 가 올릴 양만큼 **아래**) 인
%   주파수를 찾아 거기를 $\omega_{max}$ 로 둔다
% - 또는 그냥 현재 $\omega_c$ 의 $1.5 \sim 2$ 배에 놓고 5단계에서 조정한다
%
% 수업에서는 두 번째, **놓고 재고 고치는** 방법을 씁니다. 앱이 있으면 그것이
% 훨씬 빠릅니다.
%% 4-3. 예제 — $\phi_{max} = 50^\circ$ 로 설계한다
% 2-3절에서 막힌 자리입니다. $G = 1/(s(s+1))$, $K = 100$, 현재 PM $5.7^\circ$.
% 목표는 **PM $50^\circ$ 정도**로 둡니다 (오버슈트 $20\%$ 쯤).
%
% 3단계 — 필요한 위상은 $50 - 5.7 = 44.3^\circ$ 입니다. 여유를 보태
% $\phi_{max} = 50^\circ$ 로 둡니다.
%
% 4단계 — 손계산입니다.
%
% $$\alpha = \frac{1 - \sin 50^\circ}{1 + \sin 50^\circ} = 0.1325, \qquad -10\log_{10}\alpha = 8.78 \text{ dB}$$
%
% $\omega_{max}$ 는 $|100 G(j\omega)| = -8.78$ dB 인 자리로 잡습니다.
% 수업 코드에서는 그 값이 $\omega_{max} = 16.7$ rad/s 로 나왔습니다. 확인합니다.
phi_max = 50;
alpha_l = (1 - sind(phi_max))/(1 + sind(phi_max));
boost = -10*log10(alpha_l);
wgrid = logspace(0, 2, 4001);
magKG = 20*log10(squeeze(abs(freqresp(100*G1, wgrid))));
[~, iw] = min(abs(magKG + boost));          % |KG| = -boost 인 자리
table(alpha_l, boost, wgrid(iw), ...
    'VariableNames', {'alpha', '올라가는_dB', 'wmax_찾은값'})
%%
% 읽는 법 — $\omega_{max} = 16.7$ rad/s 가 나옵니다. 수업 코드의 그 숫자입니다.
% 여기에 $8.78$ dB 를 보태면 그 자리가 정확히 $0$ dB, 즉 **새 교차주파수**가
% 됩니다. 그리고 그 자리에서 Lead 가 위상을 $50^\circ$ 올려 줍니다.
%
% 이제 $T$ 를 구해 제어기를 만듭니다.
%
% $$T = \frac{1}{\omega_{max}\sqrt{\alpha}} = \frac{1}{16.7 \times 0.364} = 0.1645$$
w_max = 16.7;
T_l = 1/(w_max*sqrt(alpha_l));
C_lead = 100*(T_l*s + 1)/(alpha_l*T_l*s + 1);
[gm_l, pm_l, ~, wc_l] = margin(C_lead*G1);
Tl = feedback(C_lead*G1, 1);
sl = stepinfo(Tl);
table(T_l, 1/T_l, 1/(alpha_l*T_l), pm_l, 20*log10(gm_l), wc_l, sl.Overshoot, sl.SettlingTime, ...
    'VariableNames', {'T', '영점', '극점', 'PM_deg', 'GM_dB', 'wc', 'OS_퍼센트', 'ts'})
%%
% 읽는 법 — PM 이 $53.5^\circ$ 로 올라갔습니다. 목표 $50^\circ$ 를 넘겼으니
% 5단계 합격입니다. 정착시간은 $7.6$ 초에서 $0.44$ 초로 줄었습니다.
%
% 오버슈트가 $22.5\%$ 인 것에 주의하십시오. 11A주차 3-4절의 어림셈으로는
% $\zeta \approx 0.535$ 이고 그 오버슈트는 $13.3\%$ 입니다. **실측이 더 큽니다.**
% 이유는 11A주차 3-4절의 "(나) 폐루프 영점" 과 같습니다 — Lead 가 넣은 영점
% $s = -6.08$ 이 폐루프에 그대로 남아 있습니다.
%
% PD 와 Lead 를 나란히 놓고 봅니다.
%
% ![PD 와 Lead — 위상은 비슷하게 주고 고주파에서 갈린다](w11b_pd_vs_lead.png)
%
% **그림 파일** `w11b_pd_vs_lead.png` — `make_figures.m` 의 `fig_w11b_pd_vs_lead`
%   · 다시 만들려면 `make_figures('w11b_pd_vs_lead')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 그림 왼쪽 끝 | 둘 다 같은 높이 | 저주파 이득은 똑같이 $K$ |
% | 위 그림 오른쪽 끝 | PD 는 계속 올라가고 Lead 는 멈춘다 | **Lead 의 전부가 이 차이**다 |
% | 아래 그림의 봉우리 | Lead 의 위상이 봉우리를 만든다 | 그 꼭대기가 $\phi_{max}$, 자리가 $\omega_{max}$ |
% | 아래 그림 오른쪽 | PD 는 $90^\circ$ 에 머물고 Lead 는 $0$ 으로 | Lead 는 고주파에서 **아무 일도 안 한다** |
% | 봉우리의 위치 | 로그축에서 두 꺾임의 가운데 | 4-1절의 기하평균 |
%
% 왜 중요한가 — **Lead 는 필요한 곳에만 위상을 주고 빠집니다.** 그래서 실물에
% 쓸 수 있습니다. PD 는 안 됩니다.
%% 4-4. 앱의 숫자와 손의 숫자가 같은 것임을 확인한다
% 왜 필요한가 — 앱에서 설계하고 Export 하면 손으로 쓴 꼴과 **다르게 생긴 식**이
% 나옵니다. 처음 보면 설계가 틀린 줄 알고 당황합니다.
%
% 손으로 쓴 꼴 ($\alpha$, $T$ 꼴) 과 앱이 보여 주는 꼴 (영점·극점 꼴) 을
% 서로 바꾸는 식입니다.
%
% $$C(s) = K \frac{1 + Ts}{1 + \alpha T s} = K \frac{T\left(s + \frac{1}{T}\right)}{\alpha T \left(s + \frac{1}{\alpha T}\right)} = \frac{K}{\alpha} \cdot \frac{s + 1/T}{s + 1/(\alpha T)}$$
%
% 유도 — 분자와 분모에서 $s$ 의 계수를 각각 묶어냈을 뿐입니다. 묶어낸 $T$ 와
% $\alpha T$ 가 약분되어 $1/\alpha$ 만 남습니다.
%
% 그래서 세 숫자의 대응은 이렇습니다.
%
% | 손으로 쓴 꼴 | 앱이 보여 주는 꼴 |
% |---|---|
% | 이득 $K$ | 이득 $K/\alpha$ |
% | $1/T$ | 영점 위치 |
% | $1/(\alpha T)$ | 극점 위치 |
%
% 손계산 — 4-3절의 설계를 바꿔 봅니다. $K = 100$, $\alpha = 0.1325$,
% $T = 0.1645$ 이므로
%
% - 이득 : $100/0.1325 = 754.9$
% - 영점 : $1/0.1645 = 6.078$
% - 극점 : $1/(0.1325 \times 0.1645) = 45.88$
%
% 즉 **$C = 754.86 \frac{s + 6.078}{s + 45.88}$** 입니다. 수업 코드의 `D2` 가
% 바로 이 숫자입니다. 두 꼴이 같은 제어기인지 MATLAB 으로 확인합니다.
D_hand = 100*(T_l*s + 1)/(alpha_l*T_l*s + 1);        % 손으로 쓴 꼴
D_app  = 754.86*(s + 6.078)/(s + 45.88);             % 앱이 보여 주는 꼴
w_cmp = [0.1; 1; 16.7; 100; 1000];
table(w_cmp, 20*log10(squeeze(abs(freqresp(D_hand, w_cmp)))), ...
    20*log10(squeeze(abs(freqresp(D_app, w_cmp)))), ...
    squeeze(angle(freqresp(D_hand, w_cmp)))*180/pi, ...
    squeeze(angle(freqresp(D_app, w_cmp)))*180/pi, ...
    'VariableNames', {'w_rad_s', '손_크기_dB', '앱_크기_dB', '손_위상', '앱_위상'})
%%
% 읽는 법 — 다섯 주파수에서 소수 둘째 자리까지 같습니다. **같은 제어기입니다.**
% 앱에서 `Edit Compensator` 창의 아래쪽에 있는 표시 형식 선택에서
% **Time constant** 와 **Zero/pole/gain** 을 서로 바꿔 볼 수 있습니다.
%
% 왜 중요한가 — 시험에서 "앱으로 설계한 결과를 손계산과 비교하라" 는 문제가
% 나오면 이 변환식이 답입니다. 그리고 실무에서는 **앱 결과를 코드로 옮길 때**
% 반드시 이 확인을 합니다.
%% 4-5. 한 단으로 안 되면 두 단
% 왜 필요한가 — 4-1절에서 한 단 Lead 가 줄 수 있는 위상에 한계가 있다고
% 했습니다. 실제로 막히는 예를 봅니다. 교수님 수업의 Example 7-3 입니다.
%
% $$G(s) = \frac{10}{s(s+1)(s/5+1)}$$
%
% 극점이 $0$, $-1$, $-5$ 세 개입니다. 적분기 하나에 극점 두 개가 더 있으니
% 위상이 $-270^\circ$ 까지 내려갑니다.
Gc = 10/(s*(s+1)*(s/5+1));
[gm_c, pm_c, wg_c, wc_c] = margin(Gc);
table(pm_c, 20*log10(gm_c), wc_c, wg_c, ...
    'VariableNames', {'PM_deg', 'GM_dB', 'wc', 'w_at_180deg'})
%%
% 읽는 법 — **PM 이 음수**이고 GM 도 음수입니다. 이 루프는 닫으면 발산합니다.
% 위상여유를 $0$ 에서 $40^\circ$ 까지 올려야 하니 **$50^\circ$ 이상**이 필요합니다.
%
% 1단 Lead 를 넣어 봅니다. 수업 코드의 값 $T = 0.67$, $\alpha = 0.1$ 입니다.
C1s = (0.67*s + 1)/(0.067*s + 1);
C2s = C1s*(0.27*s + 1)/(0.3*0.27*s + 1);
nmc = {'맨몸'; '1단 Lead'; '2단 Lead'};
Lc = {Gc, C1s*Gc, C2s*Gc};
pmc = zeros(3,1); gmc = zeros(3,1); wcc = zeros(3,1); osc = zeros(3,1);
for k = 1:3
    [g_, p_, ~, w_] = margin(Lc{k});
    pmc(k) = p_; gmc(k) = 20*log10(g_); wcc(k) = w_;
    if p_ > 0, osc(k) = stepinfo(feedback(Lc{k},1)).Overshoot; else, osc(k) = NaN; end
end
table(nmc, pmc, gmc, wcc, osc, ...
    'VariableNames', {'제어기', 'PM_deg', 'GM_dB', 'wc', 'OS_퍼센트'})
%%
% 읽는 법 — 이것이 오늘 가장 중요한 표입니다.
%
% - **1단으로는 PM $23.3^\circ$ 까지밖에 못 온다.** 안정은 되었지만 사양 미달
% - **2단을 넣으면 $40.9^\circ$.** 합격
% - 교차주파수도 $2.86 \to 4.75 \to 6.72$ 로 계속 오른쪽으로 밀린다
%
% 왜 1단으로 안 되는가 — Lead 를 넣으면 크기가 올라가 $\omega_c$ 가 오른쪽으로
% 갑니다. 이 플랜트는 오른쪽으로 갈수록 위상이 **빠르게** 떨어지므로
% (극점이 세 개라서) Lead 가 올려 준 위상을 플랜트가 바로 되먹습니다.
% **쫓아가기 경쟁**이 되는 것입니다.
%
% 두 단의 설계값은 어떻게 고르는가 — 한 단씩 **다른 주파수에** 놓습니다.
nm2 = {'1단'; '2단'};
Ts2 = [0.67; 0.27]; al2 = [0.1; 0.3];
table(nm2, Ts2, al2, 1./Ts2, 1./(al2.*Ts2), asind((1-al2)./(1+al2)), -10*log10(al2), ...
    'VariableNames', {'단', 'T', 'alpha', '영점', '극점', 'phi_max_deg', '올리는_dB'})
%%
% 읽는 법 — 1단은 $\omega_{max} = 1/(T\sqrt\alpha) = 4.72$ 에서 $54.9^\circ$ 를,
% 2단은 $\omega_{max} = 6.76$ 에서 $32.6^\circ$ 를 줍니다. 두 봉우리를
% **조금 떨어뜨려 놓아** 넓은 주파수대에서 위상을 받쳐 주는 것입니다.
%
% 앱에서는 **Add lead** 를 두 번 누르면 됩니다. 그러면 영점 두 개, 극점 두 개가
% 생기고 각각 따로 끌 수 있습니다.
%
% 왜 중요한가 — 8절의 종합 설계에서 똑같은 상황이 나옵니다.
% 그때는 **두 단을 쓰는 것이 유일한 답**입니다.
%% 5. PI — 정상상태오차를 $0$ 으로
% 왜 필요한가 — 지금까지는 플랜트에 적분기가 있어서 ($G = 1/(s(s+1))$)
% 계단오차가 알아서 $0$ 이었습니다. 적분기가 없으면 어떻게 되는지 봅니다.
%
% 이제 플랜트를 바꿉니다. 교수님 수업 Example 7-4 의 플랜트입니다.
%
% $$G(s) = \frac{1}{(s+1)(s/5+1)}$$
%
% 극점이 $-1$ 과 $-5$ 두 개이고 **적분기가 없습니다.** 형 0 입니다.
G2 = 1/((s+1)*(s/5+1));
Kv2 = [1; 10; 100];
n3 = numel(Kv2);
ess2 = zeros(n3,1); pm2 = zeros(n3,1); wc2 = zeros(n3,1); os2 = zeros(n3,1);
for k = 1:n3
    L = Kv2(k)*G2;
    ess2(k) = 1/(1 + dcgain(L));
    T = feedback(L,1);
    [~, p_, ~, w_] = margin(L);
    pm2(k) = p_; wc2(k) = w_; os2(k) = stepinfo(T).Overshoot;
end
table(Kv2, dcgain(G2)*Kv2, ess2, 100*ess2, pm2, wc2, os2, ...
    'VariableNames', {'K', 'Kp', '계단오차', '오차_퍼센트', 'PM_deg', 'wc', 'OS_퍼센트'})
%%
% 읽는 법 — 맞바꿈이 아주 선명합니다.
%
% - $K = 10$ : 위상여유 $48^\circ$ 로 **좋지만** 오차가 $9.1\%$ 남는다
% - $K = 100$ : 오차가 $0.99\%$ 로 **좋지만** 위상여유가 $15.4^\circ$ 다
%
% $K = 1$ 줄의 PM 이 $-180^\circ$ 로 나온 것은 **계산이 틀린 것이 아닙니다.**
% $|L(0)| = 1$ 이라 $0$ dB 선에 딱 접하는 특이한 경우여서 `margin` 이 교차점을
% 못 찾은 것입니다. $K = 1$ 은 이 플랜트에서 쓰지 않습니다.
%
% 어느 쪽도 쓸 수 없습니다. **오차를 $0$ 으로 만드는 다른 길**이 필요합니다.
%
% 비유 — 저울의 영점 조절 나사입니다. 아무리 조심해서 재도 조금씩 어긋나면,
% 어긋난 양을 **계속 쌓아서** 그만큼 미리 보정해 주는 것입니다. 적분이 하는 일이
% 바로 그것입니다.
%% 5-1. PI 의 보드 모양 — 유도
% 제어기를 이렇게 둡니다. 교수님 수업의 표기입니다.
%
% $$C(s) = K \left( 1 + \frac{1}{T_i s} \right) = K \frac{T_i s + 1}{T_i s}$$
%
% 기호의 뜻
%
% | 기호 | 뜻 | 보드 선도에서 |
% |---|---|---|
% | $K$ | 비례이득. 고주파 이득 | 오른쪽 평평한 높이 |
% | $T_i$ | **적분시간** | 길수록 적분이 천천히 |
% | $1/T_i$ | 보드 선도에서 **꺾이는 자리** | 여기서 왼쪽으로 올라가기 시작 |
% | $K/T_i$ | 적분이득 $K_i$ | $C = K + K_i/s$ 로 쓸 때의 $K_i$ |
%
% **왜 저주파가 올라가는가** — $s \to 0$ 에서
%
% $$C(s) = K \frac{T_i s + 1}{T_i s} \to K \cdot \frac{1}{T_i s} \to \infty$$
%
% 분모의 $s$ 때문입니다. 즉 **PI 는 루프에 적분기를 하나 더 넣는 것**이고,
% 따라서 2-1절의 표에서 **시스템 형을 하나 올립니다.** 형 0 이 형 1 이 되므로
% 계단오차가 $0$ 이 됩니다.
%
% **고주파에서는 어떤가** — $s \to \infty$ 에서
%
% $$C(s) = K \frac{T_i s + 1}{T_i s} \to K \frac{T_i s}{T_i s} = K$$
%
% 즉 **고주파 이득은 그냥 $K$** 입니다. PD 와 정반대입니다. PD 는 고주파가
% 터지고 PI 는 **저주파가 터집니다.**
%
% 위상은 이렇습니다.
%
% $$\angle C(j\omega) = \arctan(\omega T_i) - 90^\circ$$
%
% 분모의 $j\omega$ 가 $-90^\circ$ 를 주고 분자의 영점이 $+\arctan$ 을 줍니다.
% 그래서 위상이 **항상 음수**입니다. 즉 PI 는 **위상여유를 깎습니다.**
%
% 손계산 — $K = 10$, $T_i = 1/0.6 = 1.667$ 이라고 둡니다. 꺾이는 자리는
% $1/T_i = 0.6$ rad/s 입니다. $\omega = 6$ (꺾이는 자리의 10배) 에서
%
% $$\angle C = \arctan(6 \times 1.667) - 90^\circ = \arctan(10) - 90^\circ = 84.3^\circ - 90^\circ = -5.7^\circ$$
%
% 즉 꺾이는 자리에서 **한 데케이드 오른쪽으로 가면 위상 손실이 $5.7^\circ$ 뿐**입니다.
% 그래서 실무 규칙이 나옵니다.
%
% **$1/T_i$ 를 교차주파수의 $1/10$ 쯤에 놓는다.**
%
% 그러면 저주파 이득은 무한으로 올리면서 교차주파수의 위상은 거의 안 건드립니다.
%
% MATLAB 검산 — 위 손계산을 확인하고, 꺾이는 자리에서 얼마나 떨어뜨리면 손실이
% 얼마인지 표로 만듭니다.
Ti = 1/0.6;
Cpi = 10*(Ti*s + 1)/(Ti*s);
ratio = [1; 2; 5; 10; 20];                 % 꺾이는 자리의 몇 배인가
w_pi = ratio/Ti;
table(w_pi, ratio, atand(w_pi*Ti) - 90, ...
    squeeze(angle(freqresp(Cpi, w_pi)))*180/pi, ...
    20*log10(squeeze(abs(freqresp(Cpi, w_pi)))), ...
    'VariableNames', {'w_rad_s', '꺾임의_몇배', '위상_공식', '위상_실측', '크기_dB'})
%%
% 읽는 법 — 꺾이는 자리에서 **10배 떨어지면 손실이 $5.7^\circ$**, 20배면
% $2.9^\circ$ 입니다. 반대로 꺾이는 자리 바로 위($1$배)에서는 $-45^\circ$ 를
% 잃습니다. 그래서 꺾이는 자리를 $\omega_c$ 근처에 놓으면 안 됩니다.
%
% 앱에서 PI 는 — **Add real pole** 로 $s = 0$ 에 극점을 하나 놓고,
% **Add real zero** 로 그 왼쪽 적당한 곳에 영점을 하나 놓습니다. 두 동작입니다.
%% 5-2. 예제 — 꺾이는 자리를 두 곳에 놓아 본다
% 교수님 수업 Example 7-4 를 그대로 합니다. $G = 1/((s+1)(s/5+1))$,
% $K = 10$ 고정, $1/T_i$ 를 $0.6$ 과 $3$ 두 가지로 둡니다.
%
% $K = 10$ 일 때 교차주파수가 $6.2$ rad/s 였으므로 ($5$절 표)
% 실무 규칙 "$\omega_c/10$" 는 $0.62$ 입니다. 즉 **$0.6$ 이 규칙에 맞는 값**이고
% $3$ 은 규칙을 어긴 값입니다.
av = [0.6; 3];
n4 = numel(av);
pm4 = zeros(n4,1); wc4 = zeros(n4,1); os4 = zeros(n4,1); ts4 = zeros(n4,1); e4 = zeros(n4,1);
for k = 1:n4
    Ck = 10*(1 + av(k)/s);
    Lk = Ck*G2;  Tk = feedback(Lk, 1);
    [~, p_, ~, w_] = margin(Lk);
    sk = stepinfo(Tk);
    pm4(k) = p_; wc4(k) = w_; os4(k) = sk.Overshoot; ts4(k) = sk.SettlingTime;
    e4(k) = 1 - dcgain(Tk);
end
table(av, 10*av, pm4, wc4, os4, ts4, e4, ...
    'VariableNames', {'꺾이는자리', 'Ki', 'PM_deg', 'wc', 'OS_퍼센트', 'ts', '계단오차'})
%%
% 읽는 법 — 둘 다 **계단오차가 정확히 $0$** 입니다. 그것이 PI 의 목적입니다.
% 차이는 나머지에서 납니다.
%
% - $1/T_i = 0.6$ : PM $42.4^\circ$, 오버슈트 $24\%$. $K=10$ 의 $48^\circ$ 에서
%   $5.6^\circ$ 만 잃었다 — **규칙대로 한 결과**
% - $1/T_i = 3$ : PM $21.4^\circ$, 오버슈트 $58\%$, 정착 $2.9$ 초.
%   $26.7^\circ$ 를 잃었다 — **꺾임을 $\omega_c$ 쪽으로 너무 당긴 결과**
%
% 교차주파수는 $6.20 \to 6.22 \to 6.58$ 로 거의 안 움직였습니다. PI 는
% **고주파를 건드리지 않으므로** 교차주파수를 거의 그대로 둡니다.
% 이것이 PD/Lead 와의 결정적 차이입니다.
%
% 그림으로 봅니다.
tiledlayout(1, 2, 'TileSpacing', 'compact');
nexttile; hold on; grid on;
tt3 = (0:0.002:5)';
plot(tt3, step(feedback(10*G2,1), tt3), '--', 'LineWidth', 2);
for k = 1:2
    plot(tt3, step(feedback(10*(1+av(k)/s)*G2,1), tt3), 'LineWidth', 2.2);
end
yline(1, 'k:');
xlabel('시간 [s]'); ylabel('출력'); ylim([0 2]);
legend('K = 10 만', '1/Ti = 0.6', '1/Ti = 3', 'Location', 'southeast');
title('둘 다 1 에 정확히 닿는다');
nexttile; hold on; grid on;
wb2 = logspace(-2, 2, 400);
semilogx(wb2, 20*log10(squeeze(abs(freqresp(10*G2, wb2)))), '--', 'LineWidth', 2);
for k = 1:2
    semilogx(wb2, 20*log10(squeeze(abs(freqresp(10*(1+av(k)/s)*G2, wb2)))), 'LineWidth', 2.2);
end
set(gca, 'XScale', 'log'); yline(0, 'k:');
xlabel('주파수 [rad/s]'); ylabel('|L| [dB]');
legend('K = 10 만', '1/Ti = 0.6', '1/Ti = 3', 'Location', 'southwest');
title('왼쪽만 올라갔다 — 0 dB 자리는 그대로');
