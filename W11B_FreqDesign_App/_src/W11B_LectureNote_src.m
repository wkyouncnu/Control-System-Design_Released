% 오른쪽 그림이 **PI 의 전부**입니다. 저주파가 올라갔고 $0$ dB 를 지나는 자리는
% 그대로입니다. 11A주차 4절의 "주파수 띠 세 개" 에서 **왼쪽 띠만 손본 것**입니다.
%% 6. Lag — PI 의 현실판
% 왜 필요한가 — PI 는 저주파 이득을 무한으로 만듭니다. 그런데 그것이 늘 좋은
% 것은 아닙니다. 두 가지 문제가 있습니다.
%
% | 문제 | 설명 | 어디서 배우나 |
% |---|---|---|
% | **적분 포화** | $u$ 가 한계에 걸린 동안 적분기가 계속 쌓인다 | 11주차 (PID) |
% | 꼭 $0$ 이 필요하지 않을 때 | 오차 $1\%$ 면 충분한데 적분기를 쓸 이유가 없다 | 지금 |
%
% 그래서 **저주파를 유한하게만 올리는** 제어기가 Lag 입니다. 꼴은 Lead 와
% 완전히 같고 $\alpha$ 의 범위만 반대입니다.
%
% $$C(s) = K \frac{1 + Ts}{1 + \alpha T s}, \qquad \alpha > 1$$
%
% $\alpha > 1$ 이므로 $1/(\alpha T) < 1/T$ 입니다. 즉 **극점이 영점보다 왼쪽**
% 입니다. 왼쪽 꺾임이 극점이면 거기서부터 크기가 올라가기 시작하고,
% 오른쪽 꺾임(영점)에서 멈춥니다.
%
% | | Lead | Lag |
% |---|---|---|
% | $\alpha$ | $< 1$ | $> 1$ |
% | 왼쪽 꺾임 | 영점 $1/T$ | 극점 $1/(\alpha T)$ |
% | 저주파 이득 | $K$ | $K$ |
% | 고주파 이득 | $K/\alpha$ (크다) | $K/\alpha$ (작다) |
% | 위상 | $+$ 봉우리 | $-$ 골 |
% | 쓰는 목적 | 위상을 올린다 | **저주파를 상대적으로 올린다** |
%
% 마지막 줄의 "상대적으로" 가 핵심입니다. Lag 는 저주파를 올리는 것이 아니라
% **고주파를 내립니다.** 그런데 $K$ 를 그만큼 미리 올려 두면 결과가 같습니다.
%
% 비유 — 사진의 노출을 전체적으로 올리면 밝은 곳이 날아갑니다. 밝은 곳만
% 눌러 놓고 전체를 올리면 어두운 곳만 밝아집니다. Lag 가 그것입니다.
%% 6-1. Lag 설계 — 필요한 dB 에서 $\alpha$ 를 구한다
% 설계 순서가 Lead 와 다릅니다. Lead 는 **위상**에서 $\alpha$ 를 구했지만
% Lag 는 **크기**에서 구합니다.
%
% 왜 그런가 — Lag 가 주는 위상은 쓸모가 없습니다 (음수니까). 쓰는 것은
% 고주파를 $1/\alpha$ 로 내린다는 사실뿐입니다. 그래서 설계는 이렇게 합니다.
%
% | 단계 | 하는 일 | 쓰는 식 |
% |---|---|---|
% | 1 | 정상상태오차 사양에서 $K$ 를 정한다 | $K_p = \lim L$ |
% | 2 | 원하는 PM 이 나오는 **새 교차주파수** $\omega_{new}$ 를 찾는다 | 플랜트 위상 곡선에서 |
% | 3 | 그 자리의 $|KG|$ 가 몇 dB 인지 잰다. **그만큼 내려야 한다** | `freqresp` |
% | 4 | $\alpha = 10^{(\text{내릴 dB})/20}$ | 크기 비율 |
% | 5 | 영점을 $\omega_{new}$ 의 $1/10$ 에 놓는다 : $1/T = \omega_{new}/10$ | 위상 손실 최소화 |
%
% 5단계의 근거는 5-1절과 같습니다 — 꺾이는 자리에서 한 데케이드 떨어지면
% 위상 손실이 $5.7^\circ$ 밖에 안 됩니다.
%
% 4단계의 식을 유도합니다. $\omega \gg 1/T$ 에서 $|C| \to K/\alpha$ 이므로
% 저주파 대비 고주파가 $1/\alpha$ 배, dB 로는
%
% $$-20\log_{10}\alpha \text{ dB} \quad \Rightarrow \quad \alpha = 10^{(\text{내릴 dB})/20}$$
%
% 손계산 — 수업 코드 Example 7-5 의 값입니다. 내려야 하는 양이 $18.8$ dB 라면
%
% $$\alpha = 10^{18.8/20} = 10^{0.94} = 8.71$$
%
% 그리고 $\omega_{new} = 6.75$ rad/s 이므로 $1/T = 0.675$, 즉 $T = 1.4815$ 입니다.
% 확인합니다.
dB_drop = 18.8;
alpha_g = 10^(dB_drop/20);
w_new = 6.75;
T_g = 10/w_new;
table(dB_drop, alpha_g, w_new, T_g, 1/T_g, 1/(alpha_g*T_g), ...
    'VariableNames', {'내릴_dB', 'alpha', 'w_new', 'T', '영점', '극점'})
%%
% 읽는 법 — 영점이 $0.675$, 극점이 $0.0775$ 입니다. 극점이 영점보다 **왼쪽**이니
% Lag 가 맞습니다. 두 꺾임 사이에서 크기가 $18.8$ dB 떨어집니다.
%% 6-2. 예제 — $K = 100$ 의 정확도를 $K = 10$ 의 여유로
% 5절의 맞바꿈 표로 돌아갑니다. $K = 100$ 은 오차가 좋고 $K = 10$ 은 여유가
% 좋았습니다. Lag 로 **둘을 동시에** 얻습니다.
C_lag = 100*(T_g*s + 1)/(alpha_g*T_g*s + 1);
nmg = {'K = 10 만'; 'K = 100 만'; 'K = 100 + Lag'};
Lg = {10*G2, 100*G2, C_lag*G2};
pmg = zeros(3,1); gmg = zeros(3,1); wcg = zeros(3,1); osg = zeros(3,1); eg = zeros(3,1);
for k = 1:3
    [g_, p_, ~, w_] = margin(Lg{k});
    Tk = feedback(Lg{k}, 1);
    pmg(k) = p_; gmg(k) = 20*log10(g_); wcg(k) = w_;
    osg(k) = stepinfo(Tk).Overshoot;
    eg(k) = 1 - dcgain(Tk);
end
table(nmg, pmg, wcg, osg, eg, 100*eg, ...
    'VariableNames', {'설계', 'PM_deg', 'wc', 'OS_퍼센트', '계단오차', '오차_퍼센트'})
%%
% 읽는 법 — 이 표가 Lag 의 존재 이유입니다.
%
% - $K = 10$ : PM $48.1^\circ$ 좋다, 오차 $9.09\%$ 나쁘다
% - $K = 100$ : PM $15.4^\circ$ 나쁘다, 오차 $0.99\%$ 좋다
% - **$K = 100$ + Lag : PM $39.8^\circ$ 쓸 만하다, 오차 $0.99\%$ 좋다**
%
% 즉 $K = 100$ 의 정확도를 거의 그대로 유지하면서 위상여유를 $15^\circ$ 에서
% $40^\circ$ 로 올렸습니다. 교차주파수도 $22.1 \to 6.78$ 로 내려와
% $K = 10$ 의 $6.20$ 과 비슷합니다.
%
% **대가는 느려지는 것**입니다. 교차주파수가 $22.1$ 에서 $6.78$ 로 내려갔으니
% 응답이 세 배 느려집니다. 11A주차 3-1절에서 $\omega_c$ 가 속도의 척도라고
% 한 그것입니다.
%
% PI 와 Lag 를 나란히 놓고 봅니다.
%
% ![PI 와 Lag — 저주파를 무한히 올리는가 유한하게 올리는가](w11b_pi_vs_lag.png)
%
% **그림 파일** `w11b_pi_vs_lag.png` — `make_figures.m` 의 `fig_w11b_pi_vs_lag`
%   · 다시 만들려면 `make_figures('w11b_pi_vs_lag')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 그림 왼쪽 끝 | PI 는 계속 올라가고 Lag 는 멈춘다 | PI 는 오차 $0$, Lag 는 오차 유한 |
% | 위 그림 오른쪽 끝 | 둘 다 평평하다 | 둘 다 고주파를 건드리지 않는다 |
% | 아래 그림 왼쪽 | PI 는 $-90^\circ$ 에 머문다 | 적분기 하나의 위상 |
% | 아래 그림의 골 | Lag 의 위상이 골을 만든다 | 그 깊이가 손실. 설계로 **피해야** 하는 것 |
% | 두 곡선이 겹치는 구간 | $\omega_c$ 근처 | 그래서 PM 에 미치는 영향이 비슷하다 |
%
% 왜 중요한가 — 둘의 선택 기준은 하나뿐입니다.
% **오차가 정확히 $0$ 이어야 하면 PI, $1\%$ 면 충분하면 Lag.**
% 적분 포화가 걱정되면 Lag 를 고릅니다.
%% 6-3. 네 제어기를 한 표로
% 여기까지가 오늘의 연장통입니다. 한 표에 모읍니다.
%
% | 제어기 | 식 | 앱 메뉴 | 저주파 | 고주파 | 위상 | 쓰는 목적 |
% |---|---|---|---|---|---|---|
% | **P** | $K$ | 이득 드래그 | $K$ | $K$ | $0^\circ$ | 전체를 올린다 |
% | **PD** | $K(1+T_d s)$ | Add real zero | $K$ | $\infty$ | $0 \to +90^\circ$ | 위상을 올린다 (실물 불가) |
% | **Lead** | $K\frac{1+Ts}{1+\alpha Ts}$, $\alpha<1$ | Add lead | $K$ | $K/\alpha$ | $+$ 봉우리 | 위상을 올린다 |
% | **PI** | $K(1+\frac{1}{T_i s})$ | Add pole at 0 $+$ zero | $\infty$ | $K$ | $-90^\circ \to 0^\circ$ | 오차를 $0$ 으로 |
% | **Lag** | $K\frac{1+Ts}{1+\alpha Ts}$, $\alpha>1$ | Add lag | $K$ | $K/\alpha$ | $-$ 골 | 오차를 줄인다 (유한) |
%
% 외우는 법 두 줄입니다.
%
% - **오른쪽(고주파)을 올리는 것이 위상을 올린다** — PD, Lead
% - **왼쪽(저주파)을 올리는 것이 오차를 줄인다** — PI, Lag
%
% 그리고 **PD 와 PI 는 끝없이 올라가고, Lead 와 Lag 는 멈춥니다.**
% 멈추는 쪽이 실물에서 쓰는 것입니다.
%
% 7주차와의 연결 — 7주차에서 근궤적으로 PD 를 설계했습니다. 같은 제어기를
% 이번에는 보드 선도에서 설계했습니다. 두 평면의 대응입니다.
%
% | 근궤적 평면 (7주차) | 보드 선도 (오늘) |
% |---|---|
% | 영점을 왼쪽에 놓아 궤적을 왼쪽으로 당긴다 | 영점을 놓아 $\omega_c$ 에서 위상을 올린다 |
% | 목표 극점의 각도 부족 $\phi$ 를 채운다 | 목표 PM 에서 부족한 위상 $\phi$ 를 채운다 |
% | 크기 조건으로 $K$ 를 구한다 | $0$ dB 교차 조건으로 $K$ 를 구한다 |
% | 결과 : 시간영역 사양 (오버슈트, 정착시간) | 결과 : 주파수영역 사양 (PM, $\omega_c$) |
%
% **같은 $\phi$ 라는 글자가 두 평면에서 각각 다른 뜻으로 쓰이는 것**에 주의하십시오.
% 근궤적에서는 목표 극점에서 본 각도이고, 보드에서는 위상여유의 부족분입니다.
%% 7. 앱에서 손으로 끌어 보기
% 왜 필요한가 — 지금까지는 숫자를 먼저 계산하고 코드로 확인했습니다.
% 실무와 시험에서는 **앱에서 끌면서** 합니다. 끌었을 때 무엇이 어떻게
% 변하는지 미리 알아 두면 훨씬 빠릅니다.
%
% 이 절의 내용은 `W11B_04_app_hands_on.m` 에서 전부 숫자로 확인할 수 있습니다.
% **앱을 열어 직접 끌어 보면서** 이 절을 읽으십시오.
%
%   >> G = tf(1, [1 1 0]);  controlSystemDesigner(G)
%% 7-1. $K$ 는 위상을 바꾸지 않는다
% 왜 중요한가 — 앱에서 가장 많이 하는 조작이 이득 드래그입니다. 그런데
% 위상 곡선은 **아무리 끌어도 움직이지 않습니다.** 처음 보면 고장난 줄 압니다.
%
% 유도 — $C = K$ 이면 $L = KG$ 이고 $K$ 가 실수 양수이므로
%
% $$\angle L(j\omega) = \angle K + \angle G(j\omega) = 0 + \angle G(j\omega)$$
%
% 즉 위상은 플랜트가 전부 정합니다. $K$ 는 **크기만** 올립니다.
%
% 그러면 왜 PM 이 바뀌는가 — 위상 곡선은 그대로지만 **그 곡선을 읽는 자리가
% 바뀌기 때문**입니다. $K$ 를 올리면 $0$ dB 교차점이 오른쪽으로 가고,
% 거기서 위상을 다시 읽습니다.
Kv7 = [25; 100; 400];
n7 = numel(Kv7);
wc7 = zeros(n7,1); ph7 = zeros(n7,1); pm7 = zeros(n7,1);
for k = 1:n7
    [~, p_, ~, w_] = margin(Kv7(k)*G1);
    wc7(k) = w_; pm7(k) = p_;
    ph7(k) = angle(evalfr(G1, 1i*w_))*180/pi;        % 플랜트만의 위상
end
table(Kv7, wc7, ph7, 180 + ph7, pm7, ...
    'VariableNames', {'K', 'wc', 'G의_위상_deg', '180_더하기', 'PM_deg'})
%%
% 읽는 법 — 셋째 열이 **플랜트 $G$ 하나만의 위상**입니다. $K$ 가 들어가지
% 않았는데도 PM(다섯째 열)과 넷째 열이 완전히 같습니다.
% 즉 **PM 은 플랜트의 위상 곡선 위의 한 점을 읽은 것**뿐입니다.
%
% 앱에서 끌어 보기 — 크기 곡선을 위아래로 끌면서 아래쪽 위상 곡선을
% 보십시오. 꼼짝도 하지 않습니다. 움직이는 것은 **위상 곡선 위의 표시점**입니다.
%% 7-2. 동그라미를 왼쪽으로 끌면 PM 이 올라간다
% 왜 그런가 — 영점을 왼쪽으로 옮기면 그 영점의 위상 기여가 **더 일찍** 올라옵니다.
% $\arctan(\omega/z)$ 에서 $z$ 가 작아지면 같은 $\omega$ 에서 각이 커집니다.
%
% 4-4절의 Lead 제어기 $C = 754.86(s+z)/(s+45.88)$ 에서 영점 $z$ 만 끌어 봅니다.
zv = [20; 10; 6; 3; 1.5];
n8 = numel(zv);
pm8 = zeros(n8,1); wc8 = zeros(n8,1); os8 = zeros(n8,1); dc8 = zeros(n8,1);
for k = 1:n8
    Ck = 754.86*(s + zv(k))/(s + 45.88);
    Lk = Ck*G1;
    [~, p_, ~, w_] = margin(Lk);
    pm8(k) = p_; wc8(k) = w_;
    os8(k) = stepinfo(feedback(Lk,1)).Overshoot;
    dc8(k) = dcgain(s*Lk);                        % Kv
end
table(zv, pm8, wc8, os8, dc8, 1./dc8, ...
    'VariableNames', {'영점위치', 'PM_deg', 'wc', 'OS_퍼센트', 'Kv', '램프오차'})
%%
% 읽는 법 — 영점을 $20$ 에서 $1.5$ 까지 왼쪽으로 끌면
%
% - PM 이 $24.5^\circ \to 69.4^\circ$ 로 **계속 올라간다**
% - 오버슈트가 $57.6\% \to 3.5\%$ 로 계속 줄어든다
% - 교차주파수는 $20.8 \to 15.6$ 으로 조금 내려간다
% - **그런데 $K_v$ 가 $329 \to 24.7$ 로 떨어진다** — 램프오차가 $0.003 \to 0.041$
%
% 마지막 줄이 함정입니다. 영점을 왼쪽으로 너무 많이 끌면 **저주파 이득이 깎여
% 정상상태오차 사양이 깨집니다.** $K_v = \lim s L$ 안에 영점 위치가 들어가기
% 때문입니다 ($K/\alpha \cdot z/p$ 꼴).
%
% 그래서 앱에서 끌 때는 **계단응답 창만 보지 말고 램프오차도 같이 봐야 합니다.**
% 7-4절의 "요구사항 그리기" 가 그래서 필요합니다.
%
% 극점은 반대입니다 — 극점($\times$)을 **오른쪽**으로 끌면 Lead 가 더 넓은
% 주파수대를 덮어 위상을 더 주지만, 고주파 이득 $K/\alpha$ 가 커집니다.
% 3-3절의 문제가 커지는 것입니다.
%% 7-3. 영점과 극점의 순서를 바꾸면 Lead $\leftrightarrow$ Lag
% 왜 알아야 하나 — 앱에서 끌다가 **영점이 극점을 지나쳐 버리는 일**이 자주
% 생깁니다. 그 순간 제어기의 성질이 완전히 뒤집힙니다. 그런데 화면의 모양은
% 비슷해 보여서 눈치채지 못합니다.
pr = {'영점 6.08 · 극점 45.9  (Lead)'; '영점 45.9 · 극점 6.08  (Lag)'};
zz = [6.078; 45.88]; pp = [45.88; 6.078];
ph9 = zeros(2,1); dc9 = zeros(2,1); hf9 = zeros(2,1);
wsc2 = logspace(-1, 3, 4001);
for k = 1:2
    Ck = (s + zz(k))/(s + pp(k));
    fr = squeeze(angle(freqresp(Ck, wsc2)))*180/pi;
    if k == 1, ph9(k) = max(fr); else, ph9(k) = min(fr); end
    dc9(k) = dcgain(Ck);
    hf9(k) = abs(evalfr(Ck, 1e5i));
end
table(pr, ph9, dc9, hf9, dc9./hf9, ...
    'VariableNames', {'배치', '위상_극값_deg', 'DC이득', '고주파이득', '비율_alpha'})
