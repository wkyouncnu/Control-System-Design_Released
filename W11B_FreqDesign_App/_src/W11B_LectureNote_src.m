% **앞먹임 블록 $F$** 가 하나 더 있습니다.
dg_loop('controller');
%%
% 그림 해석
%
% | 기호 | 그림의 어디 | 앱에서 | 오늘 |
% |---|---|---|---|
% | $r$ | 맨 왼쪽 화살표 | 지령 입력 | 계단과 램프를 준다 |
% | $e$ | 합산점 바로 뒤 | 오차 | $e = r - y$ (단위 되먹임) |
% | $C$ | 왼쪽 네모 | **우리가 편집하는 블록** | 오늘 설계하는 것 |
% | $u$ | $C$ 뒤 화살표 | 제어입력 | 8-6절에서 한계를 확인한다 |
% | $G$ | 오른쪽 네모 | 플랜트. **건드리지 않는다** | 주어진 것 |
% | $y$ | 맨 오른쪽 | 출력 | 사양을 재는 대상 |
% | $H$ | 되먹임 선의 네모 | 센서. 오늘은 $H = 1$ | 11A주차 1절 참고 |
%
% 하는 법 — 앱의 **Controllers and Fixed Blocks** 패널에서 `C` 를 클릭합니다.
% 그러면 아래 편집창에 $C$ 의 영점·극점·이득 목록이 나오고, 거기서
% **Add Pole/Zero** 로 모양을 추가합니다. 끌기도 그때부터 $C$ 에만 먹습니다.
%
% 오늘 쓰는 추가 항목은 이 네 개뿐입니다.
%
% | 앱 메뉴 | 수식 | 이 노트의 절 |
% |---|---|---|
% | 이득 드래그 (곡선 자체를 위아래로) | $K$ | 2절 |
% | **Add real zero** | $(1 + T_d s)$ | 3절 (PD) |
% | **Add lead** | $\frac{1+Ts}{1+\alpha Ts}$, $\alpha < 1$ | 4절 |
% | **Add lag** | $\frac{1+Ts}{1+\alpha Ts}$, $\alpha > 1$ | 6절 |
%
% 적분기 하나만 더하고 싶으면 **Add real pole** 로 $s = 0$ 에 극점을 놓습니다.
% 그것이 5절의 PI 입니다.
%% 2. 설계의 1단계는 항상 $K$ — 정상상태오차부터 맞춘다
% 왜 필요한가 — 설계 순서를 거꾸로 하면 일을 두 번 합니다. 위상여유를 먼저
% 맞춰 놓고 나중에 $K$ 를 올리면, 올린 만큼 교차주파수가 오른쪽으로 가서
% **위상여유가 다시 무너집니다** (0-1절에서 본 그것입니다).
%
% 그래서 순서는 언제나 이렇습니다.
%
% | 단계 | 무엇을 맞추나 | 연장 | 왜 이 순서인가 |
% |---|---|---|---|
% | 1 | **정상상태오차** | $K$ | $K$ 는 나중에 바꾸면 모든 것이 틀어진다 |
% | 2 | **위상여유 · 속도** | Lead 또는 PD | $K$ 가 고정된 뒤에야 의미가 있다 |
% | 3 | 저주파를 더 올려야 하면 | Lag 또는 PI | 교차주파수를 거의 안 건드리므로 마지막에 |
% | 4 | **검증** | Simulink, 제어입력 | 앱이 못 보는 것 (9절) |
%
% 그런데 1단계를 하려면 **정상상태오차와 $K$ 의 관계**를 알아야 합니다.
% 5주차에서 배운 것을 여기서 다시 꺼냅니다.
%% 2-1. 시스템 형과 오차상수 — 손으로 $K_p$, $K_v$, $K_a$
% 비유 — 달리는 버스를 쫓아가는 사람입니다. 버스가 서 있으면(계단) 언젠가는
% 잡습니다. 일정한 속도로 가면(램프) 일정한 거리만큼 뒤쳐집니다. 가속하면
% (포물선) 점점 멀어집니다. **지령이 빠를수록 오차가 커지는 것**이 핵심입니다.
%
% 가장 작은 예 — 루프이득이 $L = K/s$ 라고 해 봅시다. 램프 지령 $r = t$ 에 대한
% 오차는 최종값 정리로 구합니다.
%
% $$e_{ss} = \lim_{s \to 0} s \cdot E(s) = \lim_{s \to 0} s \cdot \frac{1}{1+L(s)} \cdot \frac{1}{s^2}$$
%
% 유도 — 램프의 라플라스 변환이 $1/s^2$ 이고, 오차는 $E = S \cdot R = R/(1+L)$ 입니다.
% $L = K/s$ 를 넣으면
%
% $$e_{ss} = \lim_{s \to 0} \frac{1}{s} \cdot \frac{1}{1 + K/s} = \lim_{s \to 0} \frac{1}{s + K} = \frac{1}{K}$$
%
% 손계산 — $K = 100$ 이면 $e_{ss} = 0.01$ 입니다. 0-1절 표의 둘째 열이 바로 이것입니다.
%
% 일반화 — 지령의 종류와 플랜트의 적분기 개수를 **표로 정리**합니다.
% 적분기 개수를 **시스템 형**(type) 이라고 부릅니다.
%
% | 오차상수 | 정의 | 어떤 지령에 | 그 지령의 오차 |
% |---|---|---|---|
% | $K_p$ (위치) | $\lim_{s\to 0} L(s)$ | 계단 | $e_{ss} = \frac{1}{1+K_p}$ |
% | $K_v$ (속도) | $\lim_{s\to 0} s L(s)$ | 램프 | $e_{ss} = \frac{1}{K_v}$ |
% | $K_a$ (가속) | $\lim_{s\to 0} s^2 L(s)$ | 포물선 | $e_{ss} = \frac{1}{K_a}$ |
%
% | 형 | 적분기 개수 | 계단 오차 | 램프 오차 | 포물선 오차 |
% |---|---|---|---|---|
% | 0 | 없다 | $\frac{1}{1+K_p}$ (유한) | $\infty$ | $\infty$ |
% | 1 | 하나 | $0$ | $\frac{1}{K_v}$ (유한) | $\infty$ |
% | 2 | 둘 | $0$ | $0$ | $\frac{1}{K_a}$ (유한) |
%
% 외우는 법 — **대각선으로 유한한 값이 하나씩 내려갑니다.** 형이 하나 올라가면
% 오차가 $0$ 이 되는 지령이 하나 늘어납니다.
%
% 보드 선도에서는 이것이 **저주파 기울기**로 보입니다.
%
% | 형 | 저주파 기울기 | 저주파 크기 |
% |---|---|---|
% | 0 | $0$ dB/dec (수평) | $K_p$ 에서 평평하다 |
% | 1 | $-20$ dB/dec | 끝없이 올라간다 |
% | 2 | $-40$ dB/dec | 더 급하게 올라간다 |
%
% 그래서 **앱의 보드 선도 왼쪽 끝 기울기만 보면 시스템 형을 알 수 있습니다.**
% 이것이 설계할 때 가장 먼저 보는 것입니다.
%
% MATLAB 검산 — 위 세 식을 `dcgain` 으로 그대로 확인합니다.
G1 = 1/(s*(s+1));                     % 형 1
G0 = 1/((s+1)*(s/5+1));               % 형 0 (5절에서 쓸 플랜트)
nm = {'형 1 : 1/(s(s+1))'; '형 0 : 1/((s+1)(s/5+1))'};
Kp_ = [dcgain(100*G1); dcgain(100*G0)];
Kv_ = [dcgain(s*100*G1); dcgain(s*100*G0)];
table(nm, Kp_, Kv_, 1./(1+Kp_), 1./Kv_, ...
    'VariableNames', {'플랜트', 'Kp', 'Kv', '계단오차', '램프오차'})
%%
% 읽는 법 — 형 1 은 $K_p$ 가 무한이라 계단오차가 $0$ 이고, $K_v = 100$ 이라
% 램프오차가 $0.01$ 입니다. 형 0 은 $K_p = 100$ 이라 계단오차가 $1/101 = 0.0099$,
% $K_v = 0$ 이라 램프오차가 무한입니다.
%
% 왜 중요한가 — 사양이 "램프 오차 $0.01$ 이하" 로 주어지면 이 표만으로
% **$K$ 가 바로 정해집니다.** 그것이 2-2절입니다.
%% 2-2. 예제 — 램프 오차 $0.01$ 을 맞추려면 $K = 100$
% 사양 — $G = 1/(s(s+1))$ 에 비례제어기를 걸어 **기울기 1 의 램프를 쫓을 때
% 정상상태오차를 $0.01$ 이하**로 만든다.
%
% 손계산 — $L = KG = K/(s(s+1))$ 이므로
%
% $$K_v = \lim_{s \to 0} s L(s) = \lim_{s \to 0} \frac{K}{s+1} = K$$
%
% 즉 $e_{ss} = 1/K \le 0.01$ 이려면 $K \ge 100$ 입니다. **딱 $K = 100$ 을 씁니다.**
%
% ![램프를 쫓는 모습과 그때의 오차](w11b_type_ramp.png)
%
% **그림 파일** `w11b_type_ramp.png` — `make_figures.m` 의 `fig_w11b_type_ramp`
%   · 다시 만들려면 `make_figures('w11b_type_ramp')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 그림의 두 직선 | 지령 램프와 출력 | 나란히 가면 오차가 **일정하다** |
% | 위 그림의 세로 간격 | 그 일정한 간격 | 바로 $e_{ss} = 1/K_v$ |
% | 아래 그림 | 오차 $r - y$ | 흔들리다 **수평선으로 수렴**한다 |
% | 아래 그림의 수평선 높이 | $K=10$ 은 $0.1$, $K=100$ 은 $0.01$ | $K$ 를 10배 하면 10배 줄어든다 |
% | 아래 그림 초반의 흔들림 | 과도응답 | $K$ 가 클수록 심하다. **2-3절의 문제** |
%
% MATLAB 검산 — 교수님 수업 코드와 같은 방식으로 `lsim` 에 램프를 넣습니다.
Kpick = 100;
Lp = Kpick*G1;
Tp = feedback(Lp, 1);
tr = (0:0.01:20)';
rr = tr;                                    % 기울기 1 의 램프
yr = lsim(Tp, rr, tr);
er = rr - yr;
y10 = lsim(feedback(10*G1, 1), rr, tr);     % K=10 도 같은 방법으로 한 번 더
e10 = rr - y10;
table([10; 100], [1/10; 1/100], [e10(end); er(end)], ...
    'VariableNames', {'K', '공식_1_over_Kv', '실측_마지막오차'})
%%
% 읽는 법 — 공식과 실측이 소수 넷째 자리까지 같습니다. 램프는 20 초면 충분히
% 정상상태에 듭니다.
%
% 그림으로도 확인합니다.
tiledlayout(2, 1, 'TileSpacing', 'compact');
nexttile; hold on; grid on;
plot(tr, rr, '--', 'LineWidth', 2);
plot(tr, yr, 'LineWidth', 2.2);
xlabel('시간 [s]'); ylabel('위치');
legend('지령 램프', 'K = 100 의 출력', 'Location', 'northwest');
title('나란히 간다 — 간격이 정상상태오차');
nexttile; hold on; grid on;
plot(tr, er, 'LineWidth', 2.2);
yline(0.01, 'r--', 'LineWidth', 1.5);
xlabel('시간 [s]'); ylabel('오차 r - y'); ylim([-0.1 0.3]);
legend('오차', '사양 0.01', 'Location', 'northeast');
title('0.01 로 수렴한다');
%% 2-3. 그런데 $K$ 만으로는 끝나지 않는다
% $K = 100$ 으로 사양 하나는 지켰습니다. 나머지를 재 봅니다.
L100 = 100*G1;
[gm1, pm1, ~, wc1] = margin(L100);
T100 = feedback(L100, 1);
si1 = stepinfo(T100);
table(pm1, 20*log10(gm1), wc1, si1.Overshoot, si1.SettlingTime, bandwidth(T100), ...
    'VariableNames', {'PM_deg', 'GM_dB', 'wc', 'OS_퍼센트', 'ts', 'wb'})
%%
% 읽는 법 — 위상여유가 $5.7^\circ$ 입니다. 11A주차 3-4절의 어림셈
% $\zeta \approx PM/100$ 으로 보면 감쇠비가 $0.057$ 입니다. 거의 감쇠가 없습니다.
% 오버슈트 $85\%$ 는 실물에서는 쓸 수 없는 값입니다.
%
% 왜 이렇게 되었는가 — 보드 선도로 보면 분명합니다. $G$ 의 위상은 $\omega$ 가
% 커지면 $-90^\circ$ 에서 $-180^\circ$ 로 내려갑니다. 그런데 $K$ 를 100 으로
% 올려 교차주파수를 $\omega_c = 9.98$ 까지 밀어 놓았습니다. 그 자리에서 $G$ 의
% 위상은 이미 $-174.3^\circ$ 입니다.
w_check = [1 5 10 20]';
table(w_check, squeeze(angle(freqresp(G1, w_check)))*180/pi, ...
    180 + squeeze(angle(freqresp(G1, w_check)))*180/pi, ...
    'VariableNames', {'w_rad_s', 'G_위상_deg', '그자리의_PM_deg'})
%%
% 읽는 법 — 마지막 열이 **"교차주파수가 여기라면 PM 이 얼마겠는가"** 입니다.
% $\omega = 10$ 에서는 $5.7^\circ$ 밖에 안 됩니다.
%
% 여기서 **두 가지 길**이 있습니다.
%
% | 길 | 하는 일 | 대가 | 절 |
% |---|---|---|---|
% | (가) **위상을 올린다** | 교차주파수 근처에서 위상을 $+$ 쪽으로 | 고주파 이득이 커진다 | 3~4절 |
% | (나) **교차주파수를 낮춘다** | 저주파만 올려 $K_v$ 를 벌고 $\omega_c$ 는 그대로 | 느려진다 | 5~6절 |
%
% (가) 가 이 예제의 답입니다. 사양이 $K_v \ge 100$ 을 요구하므로 $K$ 를 내릴 수
% 없고, 그렇다면 그 자리에서 위상을 끌어올리는 수밖에 없습니다.
%% 3. PD — 위상을 끌어올린다
% 비유 — 7주차의 그 비유입니다. 운전할 때 **앞을 보고 미리 핸들을 돌리는 것**
% 입니다. 지금의 오차만 보지 않고 오차가 **어느 쪽으로 변하고 있는지**를 봅니다.
%
% 가장 작은 예 — 제어기를 이렇게 둡니다.
%
% $$C(s) = K(1 + T_d s)$$
%
% 기호의 뜻
%
% | 기호 | 뜻 | 단위 |
% |---|---|---|
% | $K$ | 비례이득 | 없음 |
% | $T_d$ | **미분시간**. 몇 초 뒤를 내다보는가 | 초 |
% | $1/T_d$ | 보드 선도에서 **꺾이는 자리** | rad/s |
%
% 왜 이것이 위상을 올리는가 — $s = j\omega$ 를 넣어 봅니다.
%
% $$C(j\omega) = K(1 + j\omega T_d)$$
%
% 이것은 실수부가 $K$, 허수부가 $K\omega T_d$ 인 복소수입니다. 허수부가
% **항상 양수**이므로 위상이 항상 $+$ 입니다.
%
% $$\angle C(j\omega) = \arctan(\omega T_d)$$
%
% 손계산 — $T_d = 0.1$ 이라고 두면
%
% - $\omega = 1$ : $\arctan(0.1) = 5.7^\circ$ — 거의 안 올라간다
% - $\omega = 10 = 1/T_d$ : $\arctan(1) = 45^\circ$ — **꺾이는 자리에서 정확히 절반**
% - $\omega = 100$ : $\arctan(10) = 84.3^\circ$ — 거의 $90^\circ$
%
% 크기는 이렇습니다.
%
% $$|C(j\omega)| = K\sqrt{1 + (\omega T_d)^2}$$
%
% - $\omega \ll 1/T_d$ : $|C| \approx K$ — 평평하다
% - $\omega \gg 1/T_d$ : $|C| \approx K \omega T_d$ — $+20$ dB/dec 로 **끝없이 올라간다**
%
% MATLAB 검산 — 세 주파수에서 공식과 `freqresp` 를 맞대 봅니다.
Td = 0.1;
Cpd = 1 + Td*s;
wpd = [1; 10; 100];
table(wpd, atand(wpd*Td), squeeze(angle(freqresp(Cpd, wpd)))*180/pi, ...
    20*log10(sqrt(1 + (wpd*Td).^2)), 20*log10(squeeze(abs(freqresp(Cpd, wpd)))), ...
    'VariableNames', {'w_rad_s', '위상_공식', '위상_실측', '크기_공식_dB', '크기_실측_dB'})
%%
% 읽는 법 — 공식과 실측이 완전히 같습니다. 꺾이는 자리 $\omega = 1/T_d = 10$ 에서
% 위상이 정확히 $45^\circ$, 크기가 $3.01$ dB 인 것을 확인하십시오.
% **$3$ dB 와 $45^\circ$ 는 꺾이는 자리의 표시**입니다 (9주차에서 배운 그것).
%
% 왜 중요한가 — 위상을 올리고 싶은 주파수가 $\omega_c$ 라면, $1/T_d$ 를 그
% 근처나 그보다 **왼쪽**에 놓으면 됩니다. 그러면 $\omega_c$ 에서 이미 위상이
% 충분히 올라와 있습니다.
%% 3-1. 앱에서 PD 는 "Add real zero" 다
% 앱의 메뉴 이름이 PD 가 아닙니다. 왜 같은 것인지 확인합니다.
%
% $$C(s) = K(1 + T_d s) = K T_d \left( s + \frac{1}{T_d} \right)$$
%
% 즉 **$s = -1/T_d$ 에 실영점 하나를 더하고 이득을 $K T_d$ 로 바꾼 것**과
% 완전히 같습니다. 그래서 앱 메뉴가 **Add real zero** 입니다.
%
% | 수식의 말 | 앱의 말 | 끌면 어떻게 되나 |
% |---|---|---|
% | $T_d$ 를 키운다 | 영점을 **왼쪽**으로 끈다 | 위상이 더 일찍 올라온다 |
% | $T_d$ 를 줄인다 | 영점을 **오른쪽**으로 끈다 | 위상 기여가 줄어든다 |
% | $K$ 를 키운다 | 크기 곡선을 **위로** 끈다 | 위상은 그대로, $\omega_c$ 만 오른쪽 |
%
% 그래서 앱에서 PD 설계는 두 동작뿐입니다 — **동그라미를 하나 놓고 왼쪽으로 끈다.**
%% 3-2. 예제 — $T_d$ 를 바꿔 본다
% 2-3절에서 막힌 자리로 돌아갑니다. $G = 1/(s(s+1))$, $K = 100$ 고정,
% $T_d$ 만 바꿉니다. 교수님 수업의 Example 7-1 과 같은 설정입니다.
Tdv = [0.05; 0.1; 0.2; 1];
n1 = numel(Tdv);
pm_pd = zeros(n1,1); wc_pd = zeros(n1,1); os_pd = zeros(n1,1);
ts_pd = zeros(n1,1); hf_pd = zeros(n1,1);
for k = 1:n1
    Ck = 100*(1 + Tdv(k)*s);
    Lk = Ck*G1;
    [~, pm_pd(k), ~, wc_pd(k)] = margin(Lk);
    sk = stepinfo(feedback(Lk,1));
    os_pd(k) = sk.Overshoot;  ts_pd(k) = sk.SettlingTime;
    hf_pd(k) = 20*log10(abs(evalfr(Ck, 1000i)));    % w=1000 에서의 제어기 크기
end
table(Tdv, 1./Tdv, pm_pd, wc_pd, os_pd, ts_pd, hf_pd, ...
    'VariableNames', {'Td', '꺾이는자리', 'PM_deg', 'wc', 'OS_퍼센트', 'ts', 'C크기_w1000_dB'})
