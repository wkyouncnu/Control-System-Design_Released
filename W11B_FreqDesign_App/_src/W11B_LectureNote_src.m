% 봅니다. 제어입력에 대해서는 **아무 말도 해 주지 않습니다.**
% 7주차에서 `ctrl_input` 으로 이것을 보았고, 11A주차 6절에서 센서 잡음으로
% 또 보았습니다. 오늘 지령의 모양으로 다시 봅니다.
%
% 고치는 길 세 가지
%
% | 길 | 하는 일 | 대가 |
% |---|---|---|
% | (가) 지령을 매끄럽게 | 위에서 한 것. $\tau = 0.3$ s 로 완만하게 | 조금 느려진다 |
% | (나) $\omega_c$ 를 낮춘다 | $\omega_{max}$ 를 작게 | 사양 1번이 깨질 수 있다 |
% | (다) 모터를 바꾼다 | 더 센 모터 | 돈 |
%
% 실무에서는 (가) 를 먼저 합니다. 지령의 모양을 정하는 것도 설계의 일부입니다.
%% 9. Simulink 교차 검증 — 앱이 못 보는 두 가지
% 왜 필요한가 — 8절에서 두 가지를 발견했습니다. 지연과 제어입력 한계입니다.
% 둘 다 **앱 안에서는 볼 수 없습니다.** Simulink 에서 확인합니다.
%
% 모델은 `W11B_FreqDesign.slx` 입니다. 블록 구성입니다.
%
% | 블록 이름 | 기능 | 모델에서의 역할 |
% |---|---|---|
% | 지령 $r$ | Step | 설계한 제어기가 사양을 지키는지 볼 입력 |
% | 오차 계산 | Sum (+ −) | 앱에서 본 그 $e$ 다 |
% | 설계한 제어기 $C$ | Transfer Fcn. 앱에서 뽑아 온 계수 | $K$ · 앞선보상 · 뒤진보상을 곱해 하나로 합친 것 |
% | 구동기 한계 | Saturation | 켜고 끄며 $u$ 가 한계를 넘는지 본다. 넘으면 설계를 낮춘다 |
% | 플랜트 $G$ | Transfer Fcn | 앱에서 쓴 것과 **같은 모델**이어야 숫자가 맞는다 |
% | 수송지연 | Transport Delay | 앱은 유리함수만 다룬다. **지연은 여기서만** 확인된다 |
% | To Workspace | 작업공간으로 | `y_sim`(출력)과 `u_sim`(제어입력) |
% | Scope 두 개 | 그래프 | 위는 출력과 사양선, 아래는 제어입력과 한계선 |
%
% 같은 표가 `.slx` 안에도 주석으로 붙어 있습니다. 원본은 한 곳
% (`common/model_blocks.m`) 이고, `W11B_06_run_simulink.m` 의 0 절에서
% `model_blocks(model, 'print')` 로 다시 찍어 봅니다.
%%
% 블록 하나씩 — **처음 나오는 블록**만 설명합니다.
%
% **`Transport Delay`**
%
% - **하는 일** — 들어온 신호를 정해진 시간만큼 늦춰 그대로 내보낸다.
%   전달함수로는 $e^{-sT_d}$
% - **파라미터** — `Time delay` (늦추는 시간), `Initial output` (지연 동안
%   내보낼 값), `Buffer size` (과거 값을 저장할 개수)
% - **내부적으로 어떻게 계산하는가** — 과거 입력을 버퍼에 쌓아 두고 보간해
%   꺼냅니다. 그래서 **가변 스텝 솔버와 궁합이 중요**합니다. 스텝이 지연보다
%   커지면 보간 오차가 생기므로 `MaxStep` 을 지연의 $1/10$ 이하로 둡니다
% - **왜 이 블록인가** — 앱도 `margin` 도 유리함수만 다룹니다. 진짜 지연을
%   넣어 볼 수 있는 곳은 Simulink 뿐입니다
% - **대체품** — `Variable Transport Delay` (지연 시간이 변할 때),
%   또는 `pade` 로 만든 전달함수 (해석용)
%
% **`Saturation`** — 7주차와 13주차에서 썼습니다. 여기서는 $\pm 12$ V 로 두고
% **켜고 끄며** 비교합니다. 꺼 두면 앱의 결과와 정확히 같아야 하고,
% 켜면 8-6절의 문제가 보입니다.
%
% 실행과 대조는 `W11B_06_run_simulink.m` 이 합니다. 그 파일이 확인하는 것은
% 세 가지입니다.
%
% | # | 무엇을 대조하나 | 맞아야 하는 값 |
% |---|---|---|
% | 1 | 포화·지연을 모두 끈 계단응답 | MATLAB `step(feedback(C*G,1))` 과 같다 |
% | 2 | 지연만 켠 계단응답의 오버슈트 | 8-5절의 $20.5\%$ 와 비슷하다 |
% | 3 | 포화를 켠 매끄러운 램프의 $u$ | 8-6절의 $4.2$ V 와 같고 한계를 안 넘는다 |
%
% 2번에서 "비슷하다" 라고 한 것은 Simulink 가 **진짜 지연**을 쓰고
% 8-5절은 `pade` 3차 근사를 썼기 때문입니다. 그 차이를 눈으로 보는 것이
% 이 검증의 목적입니다.
%% 10. 오늘의 정리 — 모양을 외운다
% 교수님이 수업 마지막에 한 말입니다.
%
% **"유도는 다 잊어도 됩니다. 보드 선도의 모양 네 개만 외우십시오."**
%
% 이유는 이렇습니다. 설계는 **그림을 겹치는 일**입니다. 플랜트 곡선을 보고
% "여기가 모자라네" 하고 네 모양 중 하나를 고르는 것입니다.
% 그 판단은 공식이 아니라 그림으로 합니다.
%
% 외울 네 모양
%
% | 모양 | 크기 | 위상 | 고르는 때 |
% |---|---|---|---|
% | **P** | 전체가 평행이동 | 변화 없음 | 언제나 1단계 |
% | **Lead** | 오른쪽이 올라가다 멈춘다 | $+$ 봉우리 | 흔들린다 ($PM$ 부족) |
% | **Lag** | 왼쪽이 올라가다 멈춘다 | $-$ 골 | 오차가 크다 (유한해도 됨) |
% | **PI** | 왼쪽이 끝없이 올라간다 | $-90^\circ \to 0^\circ$ | 오차가 정확히 $0$ 이어야 한다 |
%
% 설계 순서 (2절)
%
% - **1단계** $K$ — 정상상태오차. 나중에 바꾸면 다 틀어진다
% - **2단계** Lead 또는 PD — 위상여유
% - **3단계** Lag 또는 PI — 남은 저주파
% - **4단계** 검증 — Simulink, 지연, 제어입력
%
% 꼭 기억할 숫자
%
% | 숫자 | 뜻 | 어디서 |
% |---|---|---|
% | $\alpha = \frac{1-\sin\phi}{1+\sin\phi}$ | 필요한 위상에서 Lead 의 $\alpha$ | 4-1절 |
% | $\omega_{max} = \frac{1}{T\sqrt\alpha}$ | 봉우리 자리 = 두 꺾임의 기하평균 | 4-1절 |
% | $-10\log_{10}\alpha$ | $\omega_{max}$ 에서 올라가는 dB | 4-1절 |
% | 한 단에 $55^\circ$ 까지 | 그 이상은 두 단으로 | 4-1, 4-5절 |
% | 꺾임을 $\omega_c/10$ 에 | PI·Lag 의 위상 손실을 $5.7^\circ$ 로 | 5-1, 6-1절 |
% | $K/\alpha$, $1/T$, $1/(\alpha T)$ | 손 꼴 $\to$ 앱 꼴 변환 | 4-4절 |
% | $-\omega T_d$ | 지연이 깎는 위상 | 8-5절 |
%
% 앱에서 꼭 할 것
%
% - 그리드 켜고 축 고정하고 **자동 스케일 끈다** (1-1절)
% - **$r \to u$ 창을 띄운다** (7-4절). 안 띄우면 8-6절의 함정에 빠진다
% - 설계 요구사항을 그려 놓고 끈다 (7-4절)
% - 마음에 드는 설계는 **Store** 로 저장한다 (7-4절)
%% 11. 다음 시간 예고
% 오늘은 제어기의 **모양**을 보드 선도에서 골랐습니다. 그런데 산업 현장에서
% 압도적으로 많이 쓰는 제어기는 이름이 따로 있습니다. **PID** 입니다.
%
% - 오늘의 PI 와 PD 를 **합친 것**이 PID 입니다
% - 그런데 그냥 합치면 안 됩니다. 미분항이 잡음을 증폭하고(3-3절),
%   적분항이 포화 때 쌓입니다(6절)
% - 그 두 문제를 고치는 것이 다음 주의 주제입니다 — **미분 필터**와
%   **적분 포화 방지**(anti-windup)
% - 그리고 사양 없이 **자동으로** 튜닝하는 방법도 봅니다 (`pidtune`)
%
% 숙제 안내 — `hw/W11B_HW.mlx` 에 문제가 세 개 있습니다.
% 1번은 몸풀기(수업 중), 2번이 기본, 3번은 선택입니다.
% 2번은 **오늘 배운 다섯 단계를 혼자 한 번 걸어 보는 것**입니다.
