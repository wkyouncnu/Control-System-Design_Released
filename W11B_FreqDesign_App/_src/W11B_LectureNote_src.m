%% 0. 오늘 한 장 요약
% 오늘 배우는 것을 한 문장으로 적으면 이렇습니다.
%
% **제어기를 설계한다는 것은 보드 선도에 더해 줄 모양 네 개 중에서 고르고,
% 그 모양을 어느 주파수에 놓을지 정하는 일이다.**
%
% ![제어기 네 개의 보드 모양 — 이 네 장을 외운다](w11b_shapes.png)
%
% **그림 파일** `w11b_shapes.png` — `make_figures.m` 의 `fig_w11b_shapes`
%   · 다시 만들려면 `make_figures('w11b_shapes')`
%
% **직접 확인해 보려면** — `W11B_02_pd_lead.m` 의 **1절**과
% `W11B_03_pi_lag.m` 의 **1절**이 같은 네 모양을 숫자와 함께 다시 그립니다.
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 줄 (크기) | 네 제어기의 $|C|$ 를 dB 로 | 더해 줄 **크기 모양** |
% | 아래 줄 (위상) | 네 제어기의 $\angle C$ 를 도로 | 더해 줄 **위상 모양** |
% | PD | 크기가 오른쪽으로 끝없이 올라간다 | 위상을 $+90^\circ$ 까지 주지만 고주파를 증폭한다 |
% | Lead | 크기가 올라가다 **멈춘다** | 위상을 일부만 주는 대신 증폭이 유한하다 |
% | PI | 크기가 왼쪽으로 끝없이 올라간다 | 저주파 이득이 무한. 정상상태오차가 $0$ 이 된다 |
% | Lag | 크기가 왼쪽에서 올라가다 **멈춘다** | 저주파를 유한하게 올린다. 위상은 거의 주지 않는다 |
%
% 보드 선도는 **곱이 덧셈이 되는 자리**입니다. $L = GC$ 이므로 dB 로는
% $|L|_{dB} = |G|_{dB} + |C|_{dB}$ 이고 위상도 그냥 더해집니다. 그러니 설계란
% 플랜트 곡선에 **위 네 장 중 하나를 겹쳐 그리는 일**입니다.
%
% 오늘의 계단
%
% - **1절** `controlSystemDesigner` — 설계를 손으로 하는 창
% - **2절** 1단계는 항상 $K$ — 정상상태오차부터 맞춘다
% - **3~4절** PD 와 Lead — 위상을 끌어올린다
% - **5~6절** PI 와 Lag — 저주파 이득을 올린다
% - **7절** 앱에서 손으로 끌어 보기
% - **8절** 종합 설계 — 모터 위치제어를 끝까지
% - **9절** Simulink 교차 검증 — 앱이 못 보는 두 가지
%% 0-1. 가장 작은 예 — 이득만 올려 보면 어떻게 되는가
% 비유 — 볼륨 손잡이 하나만 있는 라디오입니다. 소리가 작으면 돌리면 됩니다.
% 그런데 어느 지점을 넘으면 **삐 소리가 나기 시작**합니다. 그것이 발산입니다.
%
% 손잡이가 하나뿐일 때 무슨 일이 생기는지 숫자로 봅니다. 플랜트는 오늘 내내 쓸
% 가장 간단한 것으로 둡니다.
%
% $$G(s) = \frac{1}{s(s+1)}$$
%
% 극점이 $s = 0$ 과 $s = -1$ 두 개뿐이고 영점이 없습니다. 분모에 $s$ 가 하나
% 있으므로 **적분기가 하나 있는 플랜트**입니다 (2절에서 "형 1" 이라고 부릅니다).
G = 1/(s*(s+1));
Kv = [1 10 100]';
n0 = numel(Kv);
pm0 = zeros(n0,1); wc0 = zeros(n0,1); os0 = zeros(n0,1); ess0 = zeros(n0,1);
for k = 1:n0
    L = Kv(k)*G;
    [~, pm0(k), ~, wc0(k)] = margin(L);
    os0(k) = stepinfo(feedback(L,1)).Overshoot;
    ess0(k) = 1/Kv(k);                       % 램프 지령의 정상상태오차 (2-1절에서 유도)
end
table(Kv, ess0, pm0, wc0, os0, ...
    'VariableNames', {'K', '램프오차', 'PM_deg', 'wc', 'OS_퍼센트'})
%%
% 표를 읽는 법입니다.
%
% - $K$ 를 10배 올리면 **램프오차가 10배 줄어든다** — 좋다
% - 그런데 **위상여유가 같이 줄어든다** — $51.8^\circ \to 18.0^\circ \to 5.7^\circ$
% - 오버슈트는 $16\% \to 60\% \to 85\%$ 로 커진다 — 쓸 수 없다
%
% 왜 이렇게 되는가 — $K$ 는 크기 곡선을 **위로 평행이동**만 시킵니다. 위상은
% 전혀 건드리지 않습니다 (7-1절에서 다시 확인합니다). 그러니 곡선이 위로 올라가면
% 0 dB 선을 지나는 자리가 **오른쪽으로 밀려가고**, 플랜트의 위상은 오른쪽으로
% 갈수록 더 깎여 있으므로 위상여유가 그만큼 줄어드는 것입니다.
%
% 왜 중요한가 — 손잡이가 하나로는 부족하다는 결론입니다. **정확도를 올리면서
% 안정성을 지키려면 위상을 따로 올려 줄 연장이 필요합니다.** 그것이 3절의 PD 와
% 4절의 Lead 입니다.
%% 1. `controlSystemDesigner` — 설계를 손으로 하는 창
% 왜 필요한가 — 위 표를 만들려고 우리는 `margin` 과 `stepinfo` 를 세 번씩
% 불렀습니다. 설계는 보통 이것을 **수십 번** 되풀이합니다. 영점을 조금 왼쪽으로
% 옮기고 다시, 극점을 오른쪽으로 옮기고 다시 — 그때마다 코드를 고쳐 돌리면
% 하루가 갑니다.
%
% `controlSystemDesigner` 는 그 되풀이를 **마우스로** 하게 해 줍니다.
% 보드 선도 위의 꺾이는 점을 끌면 그 즉시 PM, GM, 계단응답이 전부 다시 그려집니다.
%
% ![앱 화면의 구성 — 네 영역만 알면 된다](w11b_app_tour.png)
%
% **그림 파일** `w11b_app_tour.png` — `make_figures.m` 의 `fig_w11b_app_tour`
%   · 다시 만들려면 `make_figures('w11b_app_tour')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 | 개루프 보드 선도 $L = GC$ | **설계하는 곳.** 여기의 점을 끈다 |
% | 왼쪽 아래 | 폐루프 계단응답 | **검사하는 곳.** 사양을 지키는지 본다 |
% | 선도 위의 동그라미 | 제어기의 영점 | 왼쪽으로 끌면 위상이 올라간다 (7-2절) |
% | 선도 위의 $\times$ | 제어기의 극점 | 오른쪽으로 끌면 고주파 증폭이 줄어든다 |
% | 선도의 글자 상자 | PM, GM 과 그 주파수 | 끌면서 **실시간으로** 바뀐다 |
% | 위쪽 리본 | Edit Architecture / Multimodel / Store | 구조 바꾸기 · 세션 저장 |
%
% 명령 정리
%
% - **원리** — 플랜트 $G$ 를 받아 $C$ 를 조작 대상으로 놓고, $L = GC$ 와
%   $T = L/(1+L)$ 을 **마우스 조작마다 다시 계산**해 그린다
% - **입력** — `controlSystemDesigner(G)` 로 플랜트를 주거나, 인자 없이 불러
%   앱 안에서 불러온다. 근궤적으로 시작하려면 `controlSystemDesigner('rlocus', G)`
% - **출력** — 화면. 설계가 끝나면 `Export` 로 $C$ 를 작업공간에 내보낸다
% - **주의 1** — 앱은 **유리함수만** 다룹니다. 수송지연 $e^{-sT_d}$ 는 넣을 수
%   없습니다. 9절에서 Simulink 로 따로 확인해야 합니다
% - **주의 2** — 앱은 **제어입력 $u$ 를 기본 화면에 보여 주지 않습니다.**
%   8-6절에서 꼭 따로 재야 합니다
%
% 예제 — 아래 한 줄을 명령창에 치면 앱이 열립니다. 강의노트에서는 창을 띄우지
% 않고 같은 계산을 코드로 합니다.
%
%   >> G = tf(1, [1 1 0]);  controlSystemDesigner(G)
%
% 7주차에서 쓴 `controlSystemDesigner` 와 **같은 앱**입니다. 그때는 근궤적 평면에서
% 극점을 끌었고, 오늘은 보드 선도에서 꺾이는 점을 끕니다. 창의 왼쪽 위에서
% 보기를 바꾸는 것뿐입니다.
%% 1-1. 처음에 해 둘 세 가지
% 왜 필요한가 — 앱을 켜고 바로 끌기 시작하면 그림이 계속 자동으로 스케일을
% 바꿔서 **무엇이 좋아지고 무엇이 나빠지는지 비교가 안 됩니다.** 끌 때마다 축이
% 움직이면 눈이 속습니다.
%
% 그래서 끌기 전에 세 가지를 해 둡니다. 수업 영상에서 교수가 매번 먼저 하는 것입니다.
%
% | # | 할 일 | 어디서 | 왜 |
% |---|---|---|---|
% | 1 | **그리드 켜기** | 그림에서 오른쪽 클릭 $\to$ Grid | dB 와 도를 눈으로 읽으려면 격자가 필요하다 |
% | 2 | **축 범위 고정** | 오른쪽 클릭 $\to$ Properties $\to$ Limits | 계단응답은 시간 $0 \sim 10$, 출력 $0 \sim 1.5$ 로 |
% | 3 | **자동 스케일 끄기** | 같은 창의 Auto-Scale 체크 해제 | 끄지 않으면 2번이 무용지물이 된다 |
%
% 세 번째가 가장 중요합니다. 2번만 하고 3번을 빼먹으면 다음 조작에서 축이 다시
