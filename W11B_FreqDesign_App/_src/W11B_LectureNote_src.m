%% 7-4. 요구사항을 그려 놓고 끈다 · 세션을 저장해 비교한다
% 왜 필요한가 — 7-2절에서 보았듯이 한 사양을 좋게 하면 다른 사양이 나빠집니다.
% 끌면서 **여러 사양을 동시에** 봐야 합니다. 그 방법이 두 가지 있습니다.
%
% **(1) 설계 요구사항 그리기** (Design Requirements)
%
% | 어디에 | 무엇을 그리나 | 어떻게 |
% |---|---|---|
% | 계단응답 창 | 오버슈트 한계, 정착시간 한계 | 오른쪽 클릭 $\to$ Design Requirements $\to$ New |
% | 보드 크기 창 | 저주파 이득 하한, 고주파 이득 상한 | 같은 메뉴 (11A주차 4절의 띠) |
% | 보드 위상 창 | 위상여유 하한 | 같은 메뉴 |
%
% 그려 놓으면 **합격 구역이 색으로 칠해집니다.** 끌면서 곡선이 색칠한 구역을
% 건드리는지만 보면 됩니다. 11A주차 4절에서 사양을 주파수축의 띠로 번역한 것이
% 여기서 화면에 그려지는 것입니다.
%
% **(2) 세션 저장과 비교** (Store / Compare)
%
% - 마음에 드는 설계가 나오면 **Store** 를 눌러 이름을 붙여 둔다
% - 다른 설계를 해 보고 **Compare** 로 두 설계의 곡선을 겹쳐 본다
% - 설계를 망쳤으면 저장해 둔 것으로 돌아간다
%
% 교수님 수업에서 쓴 방법이 이것입니다. $K$ 만 쓴 것, Lead 를 넣은 것,
% Lead 를 두 단 넣은 것을 각각 저장해 두고 마지막에 겹쳐서 비교합니다.
%
% **(3) 폐루프와 제어입력 창 띄우기**
%
% 앱의 기본 화면에는 개루프 보드와 폐루프 계단응답만 있습니다. 두 개를 더
% 띄워야 합니다.
%
% | 추가할 창 | 메뉴 | 왜 |
% |---|---|---|
% | 폐루프 보드 ($r \to y$) | New Plot $\to$ Bode $\to$ Closed loop $r$ to $y$ | 대역폭 $\omega_b$ 와 공명첨두를 본다 (11A 3-3절) |
% | 제어입력 ($r \to u$) | New Plot $\to$ Step $\to$ $r$ to $u$ | 8-6절의 그 문제. **반드시 띄워야 한다** |
% | 나이퀴스트 | New Plot $\to$ Nyquist | 루프 전달함수를 **직접 골라야** 그려진다 (10주차) |
%
% 나이퀴스트 창은 그냥 열면 비어 있습니다. 창의 설정에서 보여 줄 대상으로
% **Open loop $L$** 을 골라 줘야 합니다. 10주차에서 쓴 그 선도입니다.
%% 8. 종합 설계 — 모터 위치제어를 다섯 단계로
% 이제 처음부터 끝까지 한 번 해 봅니다. 5주차부터 쓴 학기 플랜트,
% **DC 모터의 위치제어**입니다.
G_m = plant_dcmotor('position');
G_m
