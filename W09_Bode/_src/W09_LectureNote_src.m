%% 6. 2차 항의 봉우리
% 점근선만 그리면 놓치는 것이 하나 있습니다. **2차 항의 봉우리**입니다.
%
% 2차 표준형에 $s = j\omega_n$ 을 넣어 보면 실수부가 서로 상쇄되고
% 허수부만 남습니다.
%
% $$T(j\omega_n) = \frac{\omega_n^2}
%   {(j\omega_n)^2 + 2\zeta\omega_n(j\omega_n) + \omega_n^2}
%   = \frac{\omega_n^2}{2j\zeta\omega_n^2} = \frac{1}{2j\zeta}$$
%
% 즉 $|T(j\omega_n)| = \frac{1}{2\zeta}$ 입니다.
% **감쇠비가 작을수록 이 값이 커집니다.** 그것이 봉우리입니다.
%
% ![감쇠비가 작을수록 봉우리가 높고, 시간영역에서는 오버슈트가 크다](w09_resonance.png)
%
% **그림 파일** `w09_resonance.png` — `make_figures.m` 의 `fig_resonance`
%   · 다시 만들려면 `make_figures('w09_resonance')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_resonance`
% **직접 바꿔 보려면** — `W09_02_bode_asymptotes.m` 의 마지막 절에서
% `zeta` 목록을 바꿔 실행
%
% 그림 해석 — **왼쪽 곡선과 오른쪽 곡선을 색으로 짝지어 읽으십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 곡선 ($\zeta=0.1$) | $\omega \approx 1$ 에서 $+14$ dB | 그 주파수의 사인을 넣으면 **$5$ 배로 커져서** 나온다 |
% | 왼쪽 빨간 곡선 ($\zeta=0.2$) | $+8$ dB | 봉우리가 낮아졌다 |
% | 왼쪽 노란 곡선 ($\zeta=0.4$) | $+2$ dB | 거의 없다 |
% | 왼쪽 보라 곡선 ($\zeta=0.707$) | 봉우리가 **사라졌다** | **$\zeta = 0.707$ 이 봉우리가 없어지는 경계** |
% | 왼쪽 초록 곡선 ($\zeta=1$) | 처음부터 계속 내려간다 | 공진이 전혀 없다 |
% | 다섯 곡선의 오른쪽 끝 | 모두 $-40$ dB/dec 로 겹친다 | 고주파에서는 $\zeta$ 가 무의미하다 |
% | 오른쪽 파란 곡선 | 첫 봉우리 $1.73$, 오래 진동한다 | 왼쪽 봉우리가 높았던 그 곡선 |
% | 오른쪽 보라 곡선 | 살짝 넘고 바로 감쇠한다 | 왼쪽에서 봉우리가 없던 그 곡선 |
% | 오른쪽 곡선들의 진동 주기 | 약 $3.1$ s | $2\pi/1 = 6.28$ 의 절반. 왼쪽 봉우리 위치 $\omega=1$ 과 같은 이야기 |
% | 좌우 곡선의 색 순서 | 완전히 같다 | **봉우리 높이 순서 = 오버슈트 순서** |
%
% 왼쪽과 오른쪽은 **같은 사실을 두 언어로 적은 것**입니다.
% 주파수영역의 "봉우리" 가 시간영역의 "오버슈트" 입니다.
% 10주차에서 이 대응을 $\zeta \approx \mathrm{PM}/100$ 이라는 공식으로 만듭니다.
%% 6-1. 봉우리와 오버슈트는 같은 이야기다
% 4주차에서 배운 것과 연결됩니다.
%
% - 시간영역 : $\zeta$ 가 작으면 **오버슈트**가 크다
% - 주파수영역 : $\zeta$ 가 작으면 **봉우리**가 크다
%
% 같은 성질을 두 각도에서 보는 것뿐입니다.
%
% 정확한 봉우리 값과 그 위치는 이렇습니다 ($\zeta < 0.707$ 일 때만 존재).
%
% $$M_r = \frac{1}{2\zeta\sqrt{1-\zeta^2}}, \qquad
%   \omega_r = \omega_n\sqrt{1 - 2\zeta^2}$$
%
% $\zeta \ge 0.707$ 이면 봉우리가 아예 없습니다.
% 이 값이 실무에서 자주 쓰이는 이유입니다.
fprintf('=== 감쇠비, 봉우리, 오버슈트 ===\n');
fprintf('     zeta    봉우리 Mr[dB]   오버슈트[%%]\n');
fprintf('    ------  --------------  ------------\n');
for z = [0.1 0.2 0.3 0.5 0.707 1.0]
    Tz = 1/(s^2 + 2*z*s + 1);
    ii = stepinfo(Tz);
    if z < 1/sqrt(2) - 1e-3
        Mr = 1/(2*z*sqrt(1-z^2));
        fprintf('    %6.3f  %14.2f  %12.2f\n', z, 20*log10(Mr), ii.Overshoot);
    else
        fprintf('    %6.3f  %14s  %12.2f\n', z, '없음', ii.Overshoot);
    end
end
fprintf('\n');
%% 7. 필터 — 주파수로 신호를 골라내기
% 지금까지는 시스템을 "제어 대상" 으로만 봤습니다.
% 그런데 같은 전달함수를 **신호를 골라내는 도구**로 쓸 수도 있습니다. 그것이 필터입니다.
%
% 왜 지금 필터를 다루는가 — 세 가지가 오늘 배운 것과 그대로 이어집니다.
%
% - 필터는 **주파수마다 다르게 통과시키는 것**이다. 곧 크기 응답 그 자체다
% - 무엇을 통과시키고 무엇을 막을지는 **보드 선도로 정한다**
% - 그리고 **공짜가 아니다.** 막는 대신 위상이 늦는다
%
% 마지막 항목이 이 과목에서 가장 중요합니다.
% 7주차에서 미분항의 잡음을 잡으려고 필터를 붙였고,
% 11주차에서 Lead 와 Lag 를 쓸 때 같은 맞바꿈을 다시 만납니다.
%% 7-1. 저역통과 필터 — 느린 것은 통과, 빠른 것은 차단
% 가장 많이 쓰는 필터입니다. 1차 저역통과는 이렇게 생겼습니다.
%
% $$G(s) = \frac{1}{\tau s + 1} = \frac{\omega_0}{s + \omega_0},
%   \qquad \omega_0 = \frac{1}{\tau}$$
%
% 기호를 정리해 두겠습니다.
%
% | 기호 | 뜻 | 단위 |
% |---|---|---|
% | $\tau$ | 시정수. 클수록 느리고 매끄럽다 | s |
% | $\omega_0 = 1/\tau$ | 차단주파수. 여기서 크기가 $-3$ dB | rad/s |
% | $f_0 = \omega_0/2\pi$ | 같은 것을 Hz 로 | Hz |
%
% 세 가지가 **같은 하나**를 다르게 부르는 것입니다. 하나를 정하면 나머지가 정해집니다.
%% 7-2. 실제로 어떻게 되는가 — 네 칸으로 함께 보기
% 왼쪽 두 칸은 **주파수영역**, 오른쪽 두 칸은 **시간영역**입니다.
% 같은 필터를 두 눈으로 보는 것입니다.
%
% ![저역통과 : 왼쪽은 주파수, 오른쪽은 시간](w09_lpf.png)
%
% **그림 파일** `w09_lpf.png` — `make_figures.m` 의 `fig_lpf`
%   · 다시 만들려면 `make_figures('w09_lpf')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_lpf`
% **직접 바꿔 보려면** — 함수 안의 차단주파수 $2$ Hz 를 $0.8$ 이나 $5$ 로
% 바꾸면 네 칸이 함께 움직입니다
%
% 그림 해석 — **왼쪽 두 칸이 주파수 이야기, 오른쪽 두 칸이 시간 이야기입니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 빨간 세로 점선 | 차단주파수 $2$ Hz | 여기를 경계로 통과와 차단이 갈린다 |
% | 왼쪽 위 빨간 가로 점선 | $-3$ dB | 차단주파수의 정의. 크기가 $0.707$ 배 되는 곳 |
% | 왼쪽 위 초록 동그라미 | 참 신호 $0.5$ Hz, 이득 약 $0$ dB | **거의 그대로 통과한다** |
% | 왼쪽 위 빨간 동그라미 | 잡음 $20$ Hz, 이득 $-20$ dB | **$1/10$ 로 줄어든다** |
% | 두 동그라미의 높이 차 | 약 $20$ dB | 이 차이가 필터가 하는 일 전부다 |
% | 왼쪽 아래 곡선 | 위상 | 통과시키는 대가로 **늦어진다** |
% | 왼쪽 아래 차단주파수에서의 값 | $-45^\circ$ | 1차 필터는 차단주파수에서 항상 $-45^\circ$ |
% | 오른쪽 위 회색 신호 | 센서가 준 값 | 잔털처럼 잡음이 붙어 있다 |
% | 오른쪽 위 초록 굵은 곡선 | 알고 싶은 참 신호 | $0.5$ Hz 의 매끈한 사인 |
% | 오른쪽 아래 파란 곡선 | 필터를 통과한 값 | **잔털이 사라졌다** |
% | 오른쪽 아래 초록 점선 | 참 신호 (비교용) | |
% | 파란 곡선이 초록 점선보다 오른쪽에 있는 것 | $78$ ms 늦다 | $0.5$ Hz 에서의 위상 $-14^\circ$ 를 시간으로 바꾼 값 |
%
% **공짜가 아닙니다.** 잡음을 없앤 대가로 신호가 $78$ ms 늦어졌습니다.
% 제어 루프 안에 필터를 넣으면 이 지연이 **위상여유를 깎습니다** (10주차).
% 그래서 필터는 세게 걸수록 좋은 것이 아닙니다.
%
% 왼쪽 위에서 읽을 것
%
% - 참 신호 $0.5$ Hz 는 차단주파수($2$ Hz)보다 **아래**라 거의 그대로 지나간다 (초록 동그라미)
% - 잡음 $20$ Hz 는 차단주파수보다 **위**라 $-20$ dB, 즉 **십분의 일**로 줄어든다 (빨간 동그라미)
%
% 오른쪽에서 읽을 것
%
% - 통과 전에는 참 신호가 잡음에 덮여 있다
% - 통과 후에는 잡음이 사라지고 참 신호가 드러난다
% - **다만 조금 늦다.** 이것이 왼쪽 아래 위상 그림이 말해 주던 것이다
%
% 늦는 양은 계산할 수 있습니다. $0.5$ Hz 에서 위상이 $-14^\circ$ 이므로
%
% $$\text{지연} = \frac{14^\circ}{360^\circ} \times \frac{1}{0.5\,\mathrm{Hz}}
%   \approx 78\ \mathrm{ms}$$
%% 7-3. 강의자료의 예제를 그대로
