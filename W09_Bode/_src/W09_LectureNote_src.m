%   · 다시 만들려면 `make_figures('w09_lpf_prof')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_lpf_prof`
% **직접 바꿔 보려면** — 함수 안의 `a = 0.99` 를 `0.9` 나 `0.999` 로 바꾸면
% 세 칸이 함께 움직입니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 칸 회색 가는 선 | 센서가 준 값 (참값 $+$ 잡음) | 실제로 손에 들어오는 것 |
% | 위 칸 보라 굵은 점선 | 참값 | 알고 싶은 것 |
% | 위 칸 빨간 굵은 선 | 필터를 통과한 값 | **잡음이 사라졌다** |
% | 빨간 선이 보라 점선보다 조금 오른쪽인 것 | 약간 늦다 | 필터의 지연. 공짜가 아니다 |
% | 아래 왼쪽 빨간 실선 | 이산 필터 $y_k = a y_{k-1} + (1-a)u_k$ | 코드로 짜는 형태 |
% | 아래 왼쪽 파란 점선 | 연속 필터 $1/(0.0995s+1)$ | 우리가 배운 전달함수 형태 |
% | 두 선이 **완전히 겹친 것** | 같은 것이다 | **계수 $a$ 는 시정수를 정하는 것일 뿐** |
% | 아래 오른쪽 빨간 세로 점선 | $\omega_0 = 10.1$ rad/s | $a=0.99$ 가 만드는 차단주파수 |
% | 아래 오른쪽 검은 가로 점선 | $-3.01$ dB | 차단주파수의 정의선 |
% | 세로 점선과 가로 점선이 곡선 위에서 만나는 것 | 정의대로다 | **$a$ 하나로 차단주파수가 정해진다** |
%
% 실무에서 마이크로컨트롤러에 필터를 넣을 때 쓰는 것이 아래 왼쪽의
% **한 줄짜리 이산 필터**입니다. 이 강의에서 배운 $1/(\tau s + 1)$ 과
% 정확히 같은 것이라는 점을 확인해 두십시오.
%
% 위 칸이 강의자료의 그림입니다. `Raw signal`, `True value`, `Filtered signal` 세 개가
% 그대로 나옵니다. 아래 두 칸은 **오늘 배운 것과 잇기 위해** 덧붙인 것입니다.
%
% - 왼쪽 아래 : 이 이산 필터가 사실 $1/(\tau s + 1)$ 과 **같은 것**임을 보인다
% - 오른쪽 아래 : 그 필터의 보드 선도. 계수 $a$ 가 곧 차단주파수를 정한다
%
% 이산 계수 $a$ 와 시정수의 관계는 이렇습니다.
%
% $$\tau = \frac{-\Delta t}{\ln a}$$
fprintf('=== 강의자료의 이산 필터와 연속 필터 ===\n');
dt_f = 0.001;
fprintf('     a       tau[s]    w0[rad s^-1]   f0[Hz]\n');
fprintf('   ------  ---------  -------------  --------\n');
for a_f = [0.90 0.95 0.99 0.999]
    tau_f = -dt_f/log(a_f);
    fprintf('   %6.3f  %9.5f  %13.2f  %8.3f\n', ...
            a_f, tau_f, 1/tau_f, 1/(2*pi*tau_f));
end
fprintf('\n');
fprintf('  읽는 법\n');
fprintf('    a 를 1 에 가깝게 할수록 시정수가 커집니다 = 더 매끄럽고 더 늦습니다.\n');
fprintf('    a = 0.99 는 차단주파수 1.6 Hz 짜리 필터입니다.\n');
fprintf('    같은 a 라도 **샘플 주기가 다르면 다른 필터**가 됩니다. 반드시 dt 와 함께 적으십시오.\n\n');
