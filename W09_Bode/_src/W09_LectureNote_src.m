%% 8. Simulink 로 직접 재 보기
% 오늘의 마지막은 **실험**입니다.
% 전달함수를 모른다고 치고, 사인을 넣어 보드 선도를 만들어 봅니다.
%
% ![측정 대상은 열린 시스템이다](loop_open.png)
%
% **그림 파일** `loop_open.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_open')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('open', ...)` 로 부릅니다
% **직접 해 보려면** — `W09_03_run_simulink.m` 을 실행하면
% `W09_SineSweep.slx` 로 이 측정을 자동으로 반복합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 되먹임 선이 **없는 것** | 루프가 닫혀 있지 않다 | 주파수응답은 **열린 시스템**의 성질이다 |
% | 왼쪽 입력 $u$ | 우리가 넣는 사인 | 주파수를 하나씩 바꿔 가며 넣는다 |
% | 가운데 상자 $G(s)$ | 재려는 대상 | **식을 몰라도 된다.** 실물이어도 된다 |
% | 오른쪽 출력 $y$ | 나오는 사인 | 진폭과 위상만 재면 끝 |
%
% 이 그림이 단순한 것이 핵심입니다. **모델이 없어도 잴 수 있다**는
% 주파수응답의 장점이 여기서 나옵니다. 실물 장비에 사인을 넣고
% 출력을 오실로스코프로 보면 그대로 보드 선도가 됩니다.
%
% 절차는 이렇습니다.
%
% - 주파수를 하나 정해 사인을 넣는다
% - 과도응답이 사라질 때까지 **충분히 기다린다**
% - 마지막 몇 주기만 잘라 진폭비와 위상차를 계산한다
% - 주파수를 바꿔 반복한다
%
% 모델을 열기 전에, 오늘 처음 보는 블록 하나를 먼저 봅니다.
%
% `Sine Wave` — 사인파를 만드는 블록
%
% - 하는 일 — $u(t) = A\sin(\omega t + \phi) + b$ 를 매 시각 계산해 내보낸다
% - `Amplitude` — 진폭 $A$. 오늘은 $1$ 로 둔다.
%   선형 시스템이므로 진폭은 결과에 영향을 주지 않는다 (비율만 보기 때문)
% - `Frequency` — 각주파수 $\omega$. 단위가 **Hz 가 아니라 rad/s** 다.
%   보드 선도의 가로축과 같은 단위이므로 그대로 넣으면 된다
% - `Phase` — 시작 위상 $\phi$. 오늘은 $0$ 으로 둔다
% - `Bias` — 더해지는 상수 $b$. 오늘은 $0$
% - `Sample time` — $0$ 으로 두면 연속시간 신호가 된다
%
% 오늘 바꾸는 것은 `Frequency` **하나뿐입니다.** 스크립트가 이 값을
% `logspace` 로 만든 목록에서 하나씩 꺼내 넣고, 그때마다 `sim` 을 부릅니다.
% 사람이 손으로 주파수 손잡이를 돌려 가며 재는 것과 정확히 같은 일입니다.
%
% 실습 스크립트에서 확인할 것
%
% - `W09_01_sine_to_bode.m` — 손으로 재는 두 가지 방법과 이론값 대조
% - `W09_02_bode_asymptotes.m` — 점근선 손작도
% - `W09_03_run_simulink.m` — `W09_SineSweep.slx` 로 주파수를 훑어 측정
