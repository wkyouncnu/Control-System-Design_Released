% 10주차의 안정여유는 이 **아래 그림**에서 나옵니다.
%% 3-1. `bode` — 주파수응답을 그리는 명령
% **오늘의 새 명령입니다.**
%
% 명령 정리
%
% - **원리** — 주파수 $\omega$ 를 훑으며 $G(j\omega)$ 를 계산해 크기와 위상을 그린다
% - **입력** — 전달함수. 주파수 벡터를 두 번째 인자로 줄 수도 있다
% - **출력** — 출력을 받지 않고 부르면 그림. 출력을 받으면 `[mag, phase, w]` 숫자
%
% 주의 세 가지
%
% - 출력으로 받은 `mag` 는 **dB 가 아니라 배율**이다. dB 로 보려면
%   `20*log10(mag)` 를 직접 해야 한다
% - `mag` 와 `phase` 는 3차원 배열로 나온다. `squeeze` 로 눌러야 그릴 수 있다
% - 위상은 $\pm 180^\circ$ 를 넘나들며 튈 수 있다. 필요하면 `unwrap` 을 쓴다
G1 = 10/(s*(s+1));
[mg, pg, wg] = bode(G1);
mg = squeeze(mg);  pg = squeeze(pg);
fprintf('=== bode 의 출력 ===\n');
fprintf('  주파수 점 %d 개\n', numel(wg));
fprintf('     w[rad s^-1]    mag(배율)    dB       위상[도]\n');
fprintf('    ------------  -----------  -------  ---------\n');
for i = round(linspace(1, numel(wg), 6))
    fprintf('    %12.4f  %11.4f  %7.2f  %9.2f\n', ...
            wg(i), mg(i), 20*log10(mg(i)), pg(i));
end
fprintf('\n');
bode(G1); grid on;
title('bode 로 그린 주파수응답');
%% 4. 왜 dB 이고 왜 로그축인가
% 두 가지 이유가 있고, 둘 다 실용적인 이유입니다.
%
% **이유 하나 — 곱셈이 덧셈이 된다**
%
% $$20\log_{10}|G_1 G_2| = 20\log_{10}|G_1| + 20\log_{10}|G_2|$$
%
% 전달함수는 대개 인수들의 곱입니다. 로그를 취하면 합이 되므로
% **조각마다 따로 그린 뒤 세로로 더하면** 전체가 됩니다.
% 5절의 손작도가 가능한 것이 순전히 이 성질 덕분입니다.
%
% **이유 둘 — 넓은 범위를 한 그림에**
%
% 크기가 $1000$ 배 차이 나도 dB 로는 $60$ 차이일 뿐입니다.
% 주파수도 마찬가지라서 로그축을 씁니다.
fprintf('=== 외워 두면 편한 dB 값 ===\n');
tbl = {0.01,'백분의 일'; 0.1,'십분의 일'; 0.5,'절반'; ...
       1/sqrt(2),'1/sqrt(2)'; 1,'그대로'; 2,'두 배'; 10,'열 배'; 100,'백 배'};
fprintf('     배율        dB      설명\n');
fprintf('    --------  --------  ----------\n');
for i = 1:size(tbl,1)
    fprintf('    %8.4f  %8.2f  %s\n', tbl{i,1}, 20*log10(tbl{i,1}), tbl{i,2});
end
fprintf('\n');
%% 4-1. 기울기의 단위 — dB per decade
% 데케이드(decade)는 **주파수가 10 배가 되는 구간**입니다.
%
% - 적분기 $1/s$ : 주파수가 10 배가 되면 크기가 $1/10$ 이 되므로 $-20$ dB
%   $\rightarrow$ **-20 dB per decade**
% - 극점이 두 개면 $-40$, 세 개면 $-60$
%
% 즉 **기울기를 보면 극점이 몇 개인지 알 수 있습니다.**
% 이것이 실험 데이터에서 모델을 읽어 내는 첫 단계입니다.
%% 5. 손으로 그리기 — 조각은 네 가지뿐
% 실계수 다항식은 반드시 1차식과 2차식의 곱으로 인수분해됩니다.
% 그래서 어떤 전달함수든 아래 **네 조각의 곱**입니다.
%
% - **상수** $K$
% - **원점의 극점 또는 영점** $s^{\pm n}$ (적분기, 미분기)
% - **1차** $(Ts + 1)$
% - **2차** $\left(\frac{s}{\omega_n}\right)^2 + 2\zeta\frac{s}{\omega_n} + 1$
%
% 조각마다 점근선이 어떻게 생겼는지만 알면 됩니다.
%
% | 조각 | 크기 점근선 | 위상 |
% |---|---|---|
% | 상수 $K > 0$ | $20\log_{10}K$ 수평선 | $0^\circ$ |
% | 적분기 $1/s$ | $-20$ dB per dec | $-90^\circ$ (항상) |
% | 1차 극점 | 꺾임 전 $0$, 후 $-20$ dB per dec | $0^\circ \rightarrow -90^\circ$ |
% | 1차 영점 | 꺾임 전 $0$, 후 $+20$ dB per dec | $0^\circ \rightarrow +90^\circ$ |
% | 2차 극점 | 꺾임 전 $0$, 후 $-40$ dB per dec | $0^\circ \rightarrow -180^\circ$ |
%% 5-1. 가장 흔한 실수 — 시정수 꼴로 정리하지 않는 것
% $(s+1)$ 과 $(0.1s+1)$ 은 같은 꼴이지만 $(s+10)$ 은 **아닙니다.**
% 점근선을 그리려면 상수항이 $1$ 이 되도록 먼저 정리해야 합니다.
%
% $$s + 10 = 10\,(0.1\,s + 1)$$
%
% 이때 튀어나온 $10$ 은 **상수 조각으로 넘어갑니다.**
% 이것을 빠뜨리면 그림 전체가 위아래로 어긋납니다.
%
% 정리해 보면
fprintf('=== 시정수 꼴로 정리하기 ===\n');
Gx = 50/((s+10)*(s+2));
fprintf('  원래   : 50 / ((s+10)(s+2))\n');
fprintf('  정리   : 50/(10*2) * 1/((0.1s+1)(0.5s+1))\n');
fprintf('         = %.3f * 1/((0.1s+1)(0.5s+1))\n', 50/20);
fprintf('  저주파 크기 (w -> 0) : %.4f = %.2f dB\n', dcgain(Gx), 20*log10(dcgain(Gx)));
fprintf('  꺾임주파수 : %.1f 과 %.1f rad s^-1\n\n', 2, 10);
%% 5-2. 조각을 더하면 전체가 된다
% 아래는 $L(s) = \frac{10}{s(s+1)(0.1s+1)}$ 을 네 조각으로 나눠 그린 뒤
% 세로로 더한 결과입니다.
%
% ![조각마다 그린 뒤 더하면 실제 곡선이 나온다](w09_asymptote.png)
%
% **그림 파일** `w09_asymptote.png` — `make_figures.m` 의 `fig_bode_asymptote`
%   · 다시 만들려면 `make_figures('w09_asymptote')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_bode_asymptote`
% **직접 해 보려면** — `W09_02_bode_asymptotes.m` 을 절 단위로 실행하면
% 조각을 하나씩 얹는 과정을 볼 수 있습니다
%
% 그림 해석 — **위 칸에서 조각을 세고, 아래 칸에서 합계를 확인합니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 칸 하늘색 가로선 | 상수 $10$ | $20\log_{10}10 = 20$ dB. **주파수와 무관하게 평평** |
% | 위 칸 주황 사선 | 적분기 $1/s$ | $-20$ dB/dec 로 **처음부터 끝까지** 내려간다 |
% | 주황 사선이 $0$ dB 를 지나는 곳 | $\omega = 1$ | $1/s$ 는 $\omega=1$ 에서 이득 $1$ |
% | 위 칸 노란 선 | 극점 $s+1$ | $\omega < 1$ 은 평평, $\omega > 1$ 부터 $-20$ dB/dec |
% | 노란 선이 꺾이는 곳 | $\omega = 1$ | **극점 위치가 꺾이는 자리**다 |
% | 위 칸 보라 선 | 극점 $0.1s+1$ | $\omega = 10$ 에서 꺾인다 |
% | 보라 선이 늦게 꺾이는 것 | $0.1s+1 = 0$ 이 $s=-10$ | 시정수 $0.1$ $\to$ 꺾임 $10$ rad/s |
% | 아래 칸 빨간 점선 | 위 네 조각을 **단순히 더한 것** | 손으로 그릴 수 있는 선 |
% | 아래 칸 파란 실선 | `bode` 의 진짜 곡선 | 컴퓨터가 계산한 것 |
% | 두 선이 거의 포개진 것 | 차이가 거의 없다 | **더하기만 하면 된다** |
% | 꺾이는 자리에서만 벌어지는 것 | 최대 $3$ dB | 유일한 오차. 그 외에는 정확하다 |
% | 아래 칸 전체 기울기 변화 | $-20 \to -40 \to -60$ dB/dec | 극점을 지날 때마다 $20$ 씩 가팔라진다 |
%
% **곱셈이 덧셈이 되는 것**이 로그를 쓰는 이유입니다.
% $G_1 G_2$ 의 dB 값은 $G_1$ 의 dB 와 $G_2$ 의 dB 를 더한 것입니다.
%
% 읽을 것
%
% - 꺾임주파수 **밖에서는 점근선이 거의 정확**하다
% - 꺾임주파수 **에서만 약 $3$ dB 어긋난다**
% - 그 이유는 1차 극점이 꺾임주파수에서 정확히 $-3.01$ dB 이기 때문이다
%   ($|1/(j1+1)| = 1/\sqrt{2}$)
L = 10/(s*(s+1)*(0.1*s+1));
w = logspace(-2, 3, 600);
a_sum = 20*log10(10) - 20*log10(w) ...
        - 20*log10(max(w/1,1)) - 20*log10(max(w/10,1));
m_real = 20*log10(squeeze(abs(freqresp(L, w))));
semilogx(w, a_sum, '--', 'LineWidth', 2.5); hold on; grid on;
semilogx(w, m_real, 'LineWidth', 2);
xline(1, ':'); xline(10, ':');
xlabel('주파수 [rad s^{-1}]'); ylabel('크기 [dB]'); ylim([-120 40]);
legend('점근선의 합', '실제 곡선', 'Location','southwest');
title('점근선을 더하면 실제와 거의 같다');
fprintf('=== 점근선과 실제의 차이 ===\n');
fprintf('     w[rad s^-1]   점근선[dB]   실제[dB]   차이[dB]\n');
fprintf('    ------------  -----------  ---------  ---------\n');
for wq = [0.1 1 2 10 100]
    fprintf('    %12.2f  %11.2f  %9.2f  %9.2f\n', wq, ...
            interp1(log(w), a_sum, log(wq)), ...
            interp1(log(w), m_real, log(wq)), ...
            interp1(log(w), m_real, log(wq)) - interp1(log(w), a_sum, log(wq)));
end
fprintf('\n');
%% 5-3. 위상도 점근선으로 그린다
% 앞 절에서는 **크기**만 점근선으로 그렸습니다.
% 그런데 10주차와 11주차에서 실제로 필요한 것은 **위상**입니다.
% 위상여유가 거기서 나오기 때문입니다. 위상 점근선 규칙을 세웁니다.
%
% 크기는 꺾임주파수에서 딱 꺾이지만, **위상은 그렇게 급하게 안 변합니다.**
% 그래서 규칙이 조금 다릅니다.
%
% | 조각 | 위상 점근선 |
% |---|---|
% | 상수 $K > 0$ | 항상 $0^\circ$ |
% | 적분기 $1/s$ | 항상 $-90^\circ$ (주파수와 무관) |
% | 미분기 $s$ | 항상 $+90^\circ$ |
% | 1차 극점 (꺾임 $\omega_c$) | $\omega < \omega_c/10$ 은 $0^\circ$, $\omega > 10\omega_c$ 는 $-90^\circ$, 그 사이는 **$-45^\circ$/dec 직선** |
% | 1차 영점 (꺾임 $\omega_c$) | 부호만 반대. $0^\circ \to +90^\circ$ |
%
% **외울 것은 두 가지뿐입니다.**
%
% - 변화는 꺾임주파수의 **$1/10$ 에서 시작해 $10$ 배에서 끝난다** (두 데케이드)
% - 꺾임주파수 **바로 그 자리에서 정확히 절반**, 즉 $-45^\circ$
%
% 왜 두 데케이드인가 — 1차 극점의 위상은 $-\arctan(\omega/\omega_c)$ 이고,
% $\omega = 0.1\omega_c$ 에서 $-5.7^\circ$, $\omega = 10\omega_c$ 에서 $-84.3^\circ$ 입니다.
% 양 끝에서 $0^\circ$ 와 $-90^\circ$ 에 충분히 가까워지므로 그 구간만 직선으로 잇습니다.
%
% 앞 절과 같은 $L(s) = \frac{10}{s(s+1)(0.1s+1)}$ 로 그려 봅니다.
%
% ![위상도 조각을 더하면 실제와 거의 같다](w09_phase_asym.png)
%
% **그림 파일** `w09_phase_asym.png` — `make_figures.m` 의 `fig_w09_phase_asym`
%   · 다시 만들려면 `make_figures('w09_phase_asym')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w09_phase_asym`
% **직접 확인해 보려면** — 아래 코드가 같은 표를 숫자로 찍어 줍니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 칸 하늘색 수평선 | 상수 $10$ | 위상에 기여하지 않는다. 항상 $0^\circ$ |
% | 위 칸 주황 수평선 | 적분기 $1/s$ | **주파수와 무관하게 $-90^\circ$**. 기울어지지 않는다 |
% | 위 칸 노란 사선 | 극점 $s+1$ | 꺾임이 $1$ 이므로 $0.1$ 에서 시작해 $10$ 에서 끝난다 |
% | 노란 사선이 $\omega=1$ 에서 지나는 값 | $-45^\circ$ | **꺾임주파수에서 정확히 절반** |
% | 위 칸 보라 사선 | 극점 $0.1s+1$ | 꺾임이 $10$ 이므로 $1$ 에서 시작해 $100$ 에서 끝난다 |
% | 두 사선의 기울기가 같은 것 | 둘 다 $-45^\circ$/dec | 1차 극점은 전부 같은 기울기 |
% | 두 사선이 $1 \sim 10$ 구간에서 **겹치는 것** | 둘이 동시에 내려간다 | 그 구간에서 합의 기울기가 $-90^\circ$/dec |
% | 아래 칸 빨간 점선 | 세 조각을 더한 것 | 손으로 그릴 수 있는 선 |
% | 아래 칸 파란 실선 | `bode` 의 실제 위상 | 컴퓨터가 계산한 것 |
% | 두 선의 어긋남 | 최대 $6.3^\circ$ | 크기 점근선의 $3$ dB 에 해당하는 오차 |
% | 어긋남의 부호가 번갈아 바뀌는 것 | $-6.3, +3.1, -5.7, 0, +5.7, \ldots$ | 꺾임점을 기준으로 **대칭**이라 평균적으로는 맞는다 |
%
% 아래 표에서 어긋남을 숫자로 확인하십시오.
L5 = 10/(s*(s+1)*(0.1*s+1));
fprintf('=== 위상 점근선과 실제 ===\n');
fprintf('  %-10s %-10s %-10s %-10s %s\n', 'w', '적분기', '두 극점', '점근선 합', '실제[도]');
for wq = [0.1 0.316 1 3.162 10 31.6 100]
    pa1 = -45*min(max(log10(wq/0.1), 0), 2);      % 극점 s+1  (꺾임 1)
    pa2 = -45*min(max(log10(wq/1  ), 0), 2);      % 극점 0.1s+1 (꺾임 10)
    pas = -90 + pa1 + pa2;
    [~, pt] = bode(L5, wq);
    fprintf('  %-10.3f %-10.0f %-10.1f %-10.2f %.2f   (차이 %+.2f)\n', ...
            wq, -90, pa1+pa2, pas, squeeze(pt), squeeze(pt) - pas);
end
fprintf('  --> 어긋남이 최대 6.3 도. 설계 초안에는 충분합니다.\n\n');
%% 5-4. 점근선만으로 교차주파수와 위상여유를 읽는다
% **이 절이 손작도를 배우는 이유입니다.**
% 지금까지 그린 두 점근선만 있으면 다음 두 숫자를 컴퓨터 없이 얻습니다.
%
% - **교차주파수** $\omega_c$ — 크기 점근선이 $0$ dB 를 지나는 곳
% - **위상여유** $PM$ — 그 자리에서 위상을 읽고 $180^\circ$ 를 더한 값
