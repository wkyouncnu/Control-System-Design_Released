%
% ![시정수가 클수록 느리다 (강의자료 17쪽)](w09_tau_time.png)
%
% **그림 파일** `w09_tau_time.png` — `make_figures.m` 의 `fig_tau_time`
%   · 다시 만들려면 `make_figures('w09_tau_time')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_tau_time`
% **직접 바꿔 보려면** — 함수 안의 `taus` 목록에 $2.0$ 을 추가해 보십시오
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 검은 가로 점선 | 최종값의 $63.21\%$ | $1 - e^{-1} = 0.6321$ |
% | 왼쪽 가장 왼쪽 곡선 ($\tau=0.1$) | 그 선을 $t=0.1$ s 에 지난다 | $t = \tau$ 에서 지난다 |
% | 왼쪽 가장 오른쪽 곡선 ($\tau=1.5$) | 그 선을 $t=1.5$ s 에 지난다 | 역시 $t = \tau$ |
% | 일곱 곡선의 모양 | 전부 같은 모양이고 **가로로 늘어났을 뿐** | $\tau$ 는 시간축의 배율일 뿐이다 |
% | 왼쪽 곡선들의 최종값 | 전부 $10$ | $\tau$ 는 **속도만** 바꾸고 크기는 안 바꾼다 |
% | 오른쪽 그림 가로축 | 시정수 $\tau$ | |
% | 오른쪽 그림 세로축 | $63.21\%$ 에 닿는 시각 | |
% | 오른쪽 점들이 **기울기 1 의 직선** 위에 있는 것 | 두 값이 항상 같다 | **이것이 $\tau$ 의 정의 그 자체** |
% | 오른쪽 그림 글씨 | 정착시간은 대략 $4\tau$ | 4주차에서 배운 어림 |
%
% 실험 데이터에서 $\tau$ 를 읽는 법이 여기 있습니다.
% **최종값의 $63\%$ 에 닿는 시각을 자로 재면 그것이 $\tau$ 입니다.**
% 모델을 몰라도 됩니다.
%
% $\tau$ 의 정의는 이것입니다.
%
% **최종값의 $63.21\%$ 에 닿는 시각.**
%
% 왜 하필 $63.21\%$ 인가 — 1차 계단응답이 $y(t) = y_c(1 - e^{-t/\tau})$ 이므로
% $t = \tau$ 를 넣으면
%
% $$y(\tau) = y_c\left(1 - e^{-1}\right) = 0.6321\,y_c$$
%
% 4주차에서 배운 것과 같은 이야기입니다. 정착시간은 대략 $4\tau$ 입니다.
%% 7-5. 같은 것을 주파수로 보면
% 강의자료 19쪽의 그림입니다. 같은 $\tau$ 들을 주파수영역에서 본 것입니다.
%
% ![시정수별 주파수응답 (강의자료 19쪽)](w09_tau_freq.png)
%
% **그림 파일** `w09_tau_freq.png` — `make_figures.m` 의 `fig_tau_freq`
%   · 다시 만들려면 `make_figures('w09_tau_freq')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_tau_freq`
% **직접 바꿔 보려면** — 앞 그림 `fig_tau_time` 과 같은 `taus` 를 쓰므로
% 둘을 함께 바꿔 보면 대응이 분명해집니다
%
% 그림 해석 — **같은 내용을 선형 눈금과 로그 눈금으로 두 번 그린 것입니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 검은 가로 점선 | $0.707$ | 차단주파수의 정의 (크기가 $1/\sqrt{2}$) |
% | 왼쪽 파란 곡선 ($\tau=0.1$) | 그 선을 $\omega = 10$ 에서 지난다 | $\omega_0 = 1/\tau = 10$ |
% | 왼쪽 보라 곡선 ($\tau=1.0$) | 그 선을 $\omega = 1$ 에서 지난다 | $\omega_0 = 1$ |
% | 왼쪽 그림 전체 | **$\tau$ 가 작을수록 넓게 통과시킨다** | 빠른 시스템 $=$ 넓은 대역폭 |
% | 오른쪽 검은 가로 점선 | $-3.01$ dB | $0.707$ 을 dB 로 적은 것. **같은 선** |
% | 오른쪽 네 곡선의 왼쪽 끝 | 전부 $0$ dB 에서 평평 | 느린 신호는 다 통과 |
% | 오른쪽 곡선들이 꺾이는 자리 | $\omega = 1/\tau$ | **로그 눈금에서는 꺾임이 또렷하다** |
% | 오른쪽 곡선들의 오른쪽 기울기 | 전부 $-20$ dB/dec | 1차 필터는 다 같은 기울기 |
% | 왼쪽과 오른쪽의 곡선 모양 차이 | 왼쪽은 뭉개지고 오른쪽은 또렷하다 | **왜 로그 눈금을 쓰는지**를 보여 준다 |
%
% 앞 그림(시간)과 이 그림(주파수)은 **같은 $\tau$ 를 두 방향에서 본 것**입니다.
% $\tau$ 가 작으면 시간영역에서는 빨리 오르고, 주파수영역에서는 넓게 통과시킵니다.
%
% 왼쪽은 선형 눈금이라 $0.707$ 선을, 오른쪽은 로그 눈금이라 $-3.01$ dB 선을 그었습니다.
% **같은 선입니다.**
%
% $$20\log_{10} \frac{1}{\sqrt{2}} = 20\log_{10} 0.7071 = -3.01\ \mathrm{dB}$$
%
% 그리고 그 선을 지나는 자리가 $\omega_0 = 1/\tau$ 입니다.
%
% **시간영역의 $\tau$ 와 주파수영역의 $\omega_0$ 는 같은 숫자의 앞뒷면입니다.**
% $\tau$ 를 두 배로 하면 $\omega_0$ 가 절반이 되고, 응답은 두 배 느려집니다.
fprintf('=== 시정수와 차단주파수는 같은 것의 앞뒷면 ===\n');
s_f = tf('s');
fprintf('     tau[s]   w0=1/tau   4*tau(정착)   실제 정착시간[s]   실제 대역폭\n');
fprintf('   --------  ---------  -----------  ----------------  -----------\n');
for tau_f = [0.1 0.2 0.5 1.0]
    Gf = 1/(tau_f*s_f + 1);
    ii = stepinfo(Gf);
    fprintf('   %8.1f  %9.1f  %11.1f  %16.2f  %11.2f\n', ...
            tau_f, 1/tau_f, 4*tau_f, ii.SettlingTime, bandwidth(Gf));
end
fprintf('   --> 4*tau 어림과 실제 정착시간이 잘 맞습니다.\n');
fprintf('       대역폭도 1/tau 와 거의 같습니다 (1차 시스템이므로).\n\n');
%% 7-6. 차단주파수를 어디에 둘 것인가 — 맞바꿈
% 이것이 필터 설계의 전부입니다. **낮추면 조용하지만 느리고, 높이면 빠르지만 시끄럽습니다.**
%
% ![차단주파수를 바꿔 가며 같은 신호를 걸러 본 것](w09_cutoff.png)
%
% **그림 파일** `w09_cutoff.png` — `make_figures.m` 의 `fig_cutoff_tradeoff`
%   · 다시 만들려면 `make_figures('w09_cutoff')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_cutoff_tradeoff`
% **직접 바꿔 보려면** — 함수 안의 차단주파수 목록 `[0.6 2 8 40]` 을
% 바꿔 실행
%
% 그림 해석 — **네 칸의 제목에 있는 두 숫자를 함께 보십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 네 칸의 회색 배경 신호 | 원래 측정값 (잡음 포함) | 네 칸 모두 **같은 입력**이다 |
% | 네 칸의 초록 점선 | 참 신호 $0.5$ Hz | 목표 |
% | 네 칸의 파란 곡선 | 필터를 통과한 값 | 비교 대상 |
% | 왼쪽 위 ($0.6$ Hz) | 아주 매끈하지만 파란 곡선이 초록보다 **한참 오른쪽** | 위상지연 $40^\circ$. 너무 늦다 |
% | 왼쪽 위 진폭 | 초록보다 **작다** ($0.8$ 정도) | 차단주파수가 신호에 너무 가까워 신호까지 깎았다 |
% | 오른쪽 위 ($2$ Hz) | 매끈하고 지연도 작다 | 지연 $14^\circ$, RMS 오차 $0.165$ |
% | 왼쪽 아래 ($8$ Hz) | 잔털이 조금 보이지만 지연 $4^\circ$ | RMS 오차 $0.102$ 로 **가장 작다** |
% | 오른쪽 아래 ($40$ Hz) | 잡음이 거의 그대로 남았다 | 지연은 $1^\circ$ 지만 RMS 오차 $0.226$ 으로 **가장 나쁘다** |
% | 네 칸의 RMS 값 | $0.423 \to 0.165 \to 0.102 \to 0.226$ | **가운데가 최소.** 양 끝이 다 나쁘다 |
%
% **양 끝이 다 나쁘고 가운데가 좋다** — 이것이 맞바꿈입니다.
% 낮게 잡으면 신호까지 깎이고 늦어지며, 높게 잡으면 잡음이 그대로 들어옵니다.
% "필터를 세게 걸면 좋다" 는 흔한 오해를 이 그림이 정면으로 반박합니다.
%
% 네 칸의 숫자를 보면 최적이 가운데 어딘가에 있습니다.
%
% - 차단 $0.6$ Hz — 아주 매끄럽지만 참값과의 오차가 가장 크다. **너무 늦어서** 그렇다
% - 차단 $8$ Hz — 이 네 개 중에서는 오차가 가장 작다
% - 차단 $40$ Hz — 잡음이 거의 그대로 통과해 오차가 다시 커진다
%
% **그림의 네 개만 보고 고르면 안 됩니다.** 아래 표처럼 촘촘히 훑어 보면
% 실제 최적은 그 사이($4$ Hz 근처)에 있습니다. 필터 설계도 6~7주차의 이득 선정과
% 똑같이 **훑어서 고르는 일**입니다.
%
% **고르는 원칙 하나** — 참 신호의 최고 주파수보다는 위에, 잡음의 최저 주파수보다는 아래에.
% 둘이 겹치면 필터로는 분리할 수 없습니다. 그때는 센서를 바꾸거나
% 다른 정보를 함께 써야 합니다 (칼만 필터가 그 이야기입니다).
fprintf('=== 차단주파수와 오차 ===\n');
t_f2 = (0:0.001:4)';
clean_f = sin(2*pi*0.5*t_f2);
rng(11);
noisy_f = clean_f + 0.35*sin(2*pi*20*t_f2) + 0.12*randn(size(t_f2));
fprintf('     차단[Hz]   참값과의 RMS 오차   0.5 Hz 에서의 지연[도]\n');
fprintf('   ---------  ------------------  ----------------------\n');
best_e = inf; best_f = NaN;
for fc_f = [0.3 0.6 1 2 4 8 16 40]
    Gf = (2*pi*fc_f)/(s_f + 2*pi*fc_f);
    yf = lsim(Gf, noisy_f, t_f2);
    e  = sqrt(mean((yf - clean_f).^2));
    if e < best_e, best_e = e; best_f = fc_f; end
    fprintf('   %9.1f  %18.4f  %22.1f\n', ...
            fc_f, e, -rad2deg(angle(freqresp(Gf, 2*pi*0.5))));
end
fprintf('   --> 이 신호에서는 차단 %.0f Hz 근처가 가장 좋습니다 (RMS %.4f).\n\n', ...
        best_f, best_e);
%% 7-7. 고역통과 필터 — 반대로 하면
