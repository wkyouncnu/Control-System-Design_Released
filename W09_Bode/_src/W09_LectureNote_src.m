%% 1. 왜 사인인가
% 계단이나 임펄스가 아니라 왜 하필 사인인가.
%
% 이유는 하나입니다. **선형 시불변 시스템에서 사인만이 모양을 유지합니다.**
%
% - 계단을 넣으면 출력은 계단이 아니다 (지수함수가 섞인 곡선이 나온다)
% - 임펄스를 넣으면 출력은 임펄스가 아니다
% - **사인을 넣으면 출력도 사인이다.** 크기와 위상만 달라진다
%
% 모양이 유지되므로 "무엇이 달라졌는가" 를 숫자 **두 개**로 요약할 수 있습니다.
% 그 두 숫자가 크기비와 위상차입니다.
%
% 그리고 푸리에가 알려 준 대로 어떤 신호든 사인의 합으로 쓸 수 있으므로,
% 사인 하나에 대한 답을 알면 **모든 신호에 대한 답을 아는 것**입니다.
%% 2. 정말 사인이 나오는가 — 유도
% 말로만 하지 말고 식으로 확인합니다.
%
% 입력이 $u(t) = \sin(\omega t)$ 이면 라플라스 변환은
%
% $$U(s) = \frac{\omega}{s^2 + \omega^2} = \frac{\omega}{(s-j\omega)(s+j\omega)}$$
%
% 출력은 $Y(s) = G(s)U(s)$ 이므로 부분분수로 쪼개면 이렇게 됩니다.
%
% $$Y(s) = \frac{A}{s - j\omega} + \frac{\bar{A}}{s + j\omega}
%          + (\text{G 의 극점에서 오는 항들})$$
%
% 오른쪽 괄호의 항들은 $G$ 의 극점이 좌반면에 있으면 **시간이 지나면 사라집니다.**
% 남는 것은 앞의 두 항뿐이고, 이것이 정상상태 응답입니다.
%
% 계수 $A$ 를 구하면
%
% $$A = \left. (s - j\omega)\,\frac{G(s)\,\omega}{(s-j\omega)(s+j\omega)}
%     \right|_{s = j\omega} = \frac{G(j\omega)}{2j}$$
%
% 이것을 되돌리면 결국
%
% $$y_{ss}(t) = |G(j\omega)|\,\sin\left(\omega t + \angle G(j\omega)\right)$$
%
% **결론** — 정상상태 사인응답의 크기비와 위상차는 그냥 $G(s)$ 에
% $s = j\omega$ 를 넣은 값입니다. 외울 것도 없습니다.
%% 2-1. 앞 주차와 이어 보기
% 같은 이야기가 계속 반복되고 있습니다.
%
% - **계단**의 정상상태 $\rightarrow$ $G(0)$ 을 본다 (5주차 `dcgain`)
% - **사인**의 정상상태 $\rightarrow$ $G(j\omega)$ 를 본다 (오늘)
%
% 둘 다 "입력의 극점 자리에 $s$ 를 넣는다" 는 같은 규칙입니다.
% 계단의 극점은 $s = 0$, 사인의 극점은 $s = \pm j\omega$ 이기 때문입니다.
%% 3. 크기와 위상을 어떻게 재는가
% 실험으로 잰다면 두 가지 방법이 있습니다.
%
% - **눈으로** — 진폭을 자로 재고, 꼭짓점이 얼마나 늦는지 본다.
%   직관적이지만 잡음이 있으면 부정확하다
% - **계산으로** — 신호에 $e^{-j\omega t}$ 를 곱해 적분한다.
%   푸리에 계수를 구하는 것과 같고, 잡음에 강해 실무에서 이 방법을 쓴다
%
% **반드시 지킬 것 하나** — 과도응답이 사라진 뒤에 재야 합니다.
% 처음 몇 주기는 $G$ 의 극점에서 오는 항이 섞여 있어 값이 틀립니다.
%
% 아래는 여러 주파수에서 실제로 재서 `bode` 곡선 위에 얹어 본 결과입니다.
%
% ![직접 잰 값(동그라미)이 bode 곡선 위에 정확히 놓인다](w09_measure.png)
%
% **그림 파일** `w09_measure.png` — `make_figures.m` 의 `fig_sine_measure`
%   · 다시 만들려면 `make_figures('w09_measure')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_sine_measure`
% **직접 해 보려면** — `W09_01_sine_to_bode.m` 을 실행하면 `freq_scan` 이
% 주파수마다 사인을 넣어 재는 과정을 표로 찍어 줍니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위 그림 파란 곡선 | `bode` 가 그린 크기 곡선 | MATLAB 이 **식으로** 계산한 것 |
% | 위 그림 빨간 동그라미 | 사인을 넣어 **직접 잰** 값 | `lsim` 으로 시뮬레이션해서 자로 잰 것 |
