%
% **만드는 곳** — `make_figures.m` 의 `fig_hpf`
% **직접 바꿔 보려면** — 함수 안의 차단주파수 $0.5$ Hz 를 $2$ 로 올리면
% 사건까지 함께 깎여 나갑니다
%
% 그림 해석 — **저역통과 그림과 좌우가 반대라는 점을 보십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 곡선의 방향 | 왼쪽이 낮고 오른쪽이 평평 | **저역통과와 정확히 반대** |
% | 왼쪽 위 빨간 세로 점선 | 차단주파수 $0.5$ Hz | 이 아래를 깎는다 |
% | 왼쪽 위 초록 동그라미 | 알고 싶은 사건 $5$ Hz, 이득 $0$ dB | 그대로 통과 |
% | 왼쪽 위 빨간 글씨 | 느린 치우침은 막힌다 | 저주파가 걸러지는 것 |
% | 왼쪽 아래 위상 | $0$ 이 아니라 **$+$** 쪽 | 고역통과는 위상을 **앞세운다** |
% | 왼쪽 아래 차단주파수에서의 값 | $+45^\circ$ | 저역통과의 $-45^\circ$ 와 부호만 반대 |
% | 오른쪽 위 빨간 점선 | 영점이 서서히 흘러가는 것 (드리프트) | 센서가 시간이 지나며 치우치는 현상 |
% | 오른쪽 위 파란 신호 | $t=1.5{\sim}2.5$ s 에 진동이 얹혀 있다 | **알고 싶은 사건이 치우침에 묻혀 있다** |
% | 오른쪽 아래 파란 곡선 | 치우침이 사라지고 진동만 남았다 | 고역통과가 한 일 |
% | 오른쪽 아래 초록 점선 | 알고 싶던 사건 | 파란 곡선과 잘 맞는다 |
% | 오른쪽 아래 $t<0.5$ s 구간 | 파란 곡선이 $1.2$ 에서 내려온다 | 필터가 자리를 잡는 데 걸리는 시간 |
%
% 실무 용도가 분명합니다 — **가속도계나 자이로의 드리프트 제거**,
% 진동 신호에서 사건 검출, 심전도의 기저선 제거 등입니다.
% 저역통과가 "잡음 제거" 라면 고역통과는 "치우침 제거" 입니다.
%
% 읽을 것
%
% - 원래 신호에는 서서히 올라가는 치우침이 있어 **사건이 묻혀 있다**
% - 고역통과를 지나면 치우침이 사라지고 사건만 남는다
% - 위상이 **$+$** 쪽이다. 저역통과가 늦추는 것과 반대로 **앞세운다**
%
% 위상을 앞세운다는 것이 어디서 본 이야기 같다면 맞습니다.
% **미분기가 하는 일이 이것이고, 7주차의 PD 와 11주차의 Lead 가 같은 계열입니다.**
%
% $$\frac{s}{s+\omega_0} \quad\text{와}\quad
%   \frac{K_d\,s}{s/N + 1} \quad\text{는 같은 모양이다}$$
%% 7-8. 네 가지 필터를 한눈에
% 저역통과·고역통과에 두 가지를 더하면 기본형이 넷입니다.
%
% | 이름 | 전달함수 | 통과 대역 | 용도 |
% |---|---|---|---|
% | 저역통과 | $\frac{\omega_0}{s+\omega_0}$ | 느린 것 | 측정 잡음 제거 |
% | 고역통과 | $\frac{s}{s+\omega_0}$ | 빠른 것 | 영점 흐름 제거 |
% | 대역통과 | $\frac{(\omega_0/Q)s}{s^2+(\omega_0/Q)s+\omega_0^2}$ | 특정 대역만 | 특정 진동만 보기 |
% | 대역저지 | $\frac{s^2+\omega_0^2}{s^2+(\omega_0/Q)s+\omega_0^2}$ | 특정 대역만 뺀 나머지 | 전원 잡음($60$ Hz) 제거 |
%
% ![같은 신호를 네 필터에 통과시켜 본 것](w09_filters.png)
%
% **그림 파일** `w09_filters.png` — `make_figures.m` 의 `fig_filter_family`
%   · 다시 만들려면 `make_figures('w09_filters')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_filter_family`
% **직접 바꿔 보려면** — 함수 안의 입력 성분 $0.5$, $5$, $30$ Hz 를
% 바꾸면 네 칸이 함께 달라집니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 파란 곡선 | 저역통과 ($2$ Hz) | 왼쪽만 평평 |
% | 왼쪽 위 빨간 곡선 | 고역통과 ($2$ Hz) | 오른쪽만 평평. **파란 것과 거울상** |
% | 왼쪽 위 노란 곡선 | 대역통과 ($5$ Hz) | 가운데만 솟은 산 모양 |
% | 왼쪽 위 보라 곡선 | 대역저지 ($5$ Hz) | 가운데만 파인 골짜기 모양 |
% | 네 곡선의 관계 | 산과 골, 왼쪽과 오른쪽 | **네 가지가 전부**다. 다섯 번째는 없다 |
% | 오른쪽 위 신호 | $0.5 + 5 + 30$ Hz 를 섞은 것 | 네 칸 모두 이 신호를 쓴다 |
% | 왼쪽 아래 파란 곡선 | 크고 느린 물결만 남았다 | 저역통과가 $0.5$ Hz 만 남긴 것 |
% | 왼쪽 아래 빨간 곡선 | 잔물결만 남았다 | 고역통과가 $5$ 와 $30$ Hz 를 남긴 것 |
% | 두 곡선을 **더하면** 원 신호 | 저역 $+$ 고역 $=$ 전체 | 이것이 두 필터가 짝인 이유 |
% | 오른쪽 아래 파란 곡선 | 중간 빠르기 물결만 | 대역통과가 $5$ Hz 만 남긴 것 |
% | 오른쪽 아래 빨간 곡선 | 굵은 물결 $+$ 아주 잔 물결 | 대역저지가 $5$ Hz 만 뺀 것 |
%
% 필터는 **더하기와 빼기**로 만들어집니다.
% 대역통과 $=$ 저역통과 $\times$ 고역통과, 대역저지 $=$ 전체 $-$ 대역통과입니다.
%
% 입력은 $0.5$ Hz + $5$ Hz + $30$ Hz 세 성분이 섞인 신호입니다.
% 각 필터가 그중 무엇을 남기는지 시간축에서 바로 보입니다.
%% 7-9. 이 과목의 플랜트도 사실 필터다
% 여기까지 오면 뒤집어 볼 수 있습니다.
% **우리가 제어하려는 대상 자체가 이미 저역통과 필터입니다.**
%
% ![학기 내내 쓴 플랜트도 저역통과다](w09_plant_lpf.png)
%
% **그림 파일** `w09_plant_lpf.png` — `make_figures.m` 의 `fig_plant_is_lpf`
%   · 다시 만들려면 `make_figures('w09_plant_lpf')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_plant_is_lpf`
% **직접 확인해 보려면** — 명령창에 `bandwidth(plant_msd())` 와
% `bandwidth(plant_dcmotor('speed'))` 를 쳐 보십시오
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 파란 곡선 | 질량-스프링-댐퍼 | $\omega \approx 1$ 에 봉우리가 있는 2차 저역통과 |
% | 왼쪽 위 빨간 곡선 | DC 모터 (속도) | 봉우리 없이 완만하게 내려간다 |
% | 두 곡선의 왼쪽 끝 | 둘 다 평평 | 느린 지령은 잘 따라간다 |
% | 두 곡선의 오른쪽 끝 | 둘 다 급하게 떨어진다 | **빠른 지령은 못 따라간다** |
% | 검은 가로 점선 | $-3$ dB | 대역폭을 읽는 선 |
% | 오른쪽 위 회색 신호 | 느린 성분 $+$ 빠른 성분 | 모터에 넣을 입력 |
% | 오른쪽 위 초록 굵은 곡선 | 느린 성분만 | 참고선 |
% | 왼쪽 아래 파란 곡선 | 모터의 실제 출력 | **잔물결이 거의 사라졌다** |
% | 왼쪽 아래 초록 점선 | 느린 성분 | 파란 곡선과 잘 맞는다 |
% | 파란 곡선에 아주 작게 남은 잔물결 | 완전히 없어지진 않았다 | 필터가 무한히 가파르지 않기 때문 |
% | 오른쪽 아래 왼쪽 막대 | MSD 대역폭 $1.54$ rad/s | |
% | 오른쪽 아래 오른쪽 막대 | DC 모터 대역폭 $1.92$ rad/s | 모터가 조금 더 빠르다 |
%
% **아무도 필터를 넣지 않았는데 필터처럼 동작합니다.**
% 물리적인 관성과 마찰 자체가 저역통과 필터이기 때문입니다.
% 그래서 대역폭은 "이 시스템이 따라갈 수 있는 한계" 라고 읽으면 됩니다.
%
% 물리적으로 당연합니다.
%
% - 질량은 관성이 있어 빨리 흔들리지 않는다
% - 코일은 인덕턴스가 있어 전류가 급히 바뀌지 않는다
% - 열은 천천히 퍼진다
%
% 그래서 **빠른 지령은 아무리 넣어도 따라오지 못하고**, 그 한계를 숫자로 적은 것이 대역폭입니다.
%
% 다만 주의할 것이 하나 있습니다. 질량-스프링-댐퍼의 크기 곡선에는 **봉우리**가 있습니다
% (감쇠비가 $0.1$ 이라서). 저역통과이긴 하지만 **차단주파수 근처를 오히려 키웁니다.**
% 6절에서 본 공진입니다. 필터로 쓸 생각이라면 감쇠비를 $0.707$ 이상으로 잡아야 합니다.
Gm = plant_msd();
Gd = plant_dcmotor('speed');
fprintf('=== 이 과목의 플랜트를 필터로 보면 ===\n');
fprintf('    시스템                대역폭[rad s^-1]   대역폭[Hz]   봉우리\n');
fprintf('   ------------------  -----------------  -----------  --------\n');
for c_f = {{'질량-스프링-댐퍼', Gm}, {'DC 모터 (속도)', Gd}}
    nm_f = c_f{1}{1}; G_f = c_f{1}{2};
    b_f  = bandwidth(G_f);
    w_f  = logspace(-2, 2, 2000);
    pk   = max(abs(squeeze(freqresp(G_f, w_f))))/abs(dcgain(G_f));
    if pk > 1.05, pkStr = sprintf('%.2f 배', pk); else, pkStr = '없음'; end
    fprintf('   %-18s  %17.3f  %11.3f  %8s\n', nm_f, b_f, b_f/(2*pi), pkStr);
end
fprintf('\n');
fprintf('  읽는 법\n');
fprintf('    대역폭보다 훨씬 빠른 지령은 아무리 넣어도 못 따라옵니다.\n');
fprintf('    반대로 대역폭 안쪽의 잡음은 그대로 출력에 나옵니다.\n');
fprintf('    그래서 대역폭을 넓히면 빨라지지만 잡음에 약해집니다.\n');
fprintf('    11주차에서 이 맞바꿈을 설계에 그대로 씁니다 (Lead 는 넓히고 Lag 는 좁힌다).\n\n');
