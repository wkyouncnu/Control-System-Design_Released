% | 위 그림 $\omega = 1$ 근처의 봉우리 | 약 $+15$ dB | 이 주파수에서 크기가 커진다 (공진) |
% | 위 그림 $\omega > 2$ 구간 | 오른쪽 아래로 곧게 떨어진다 | 빠른 신호는 못 따라간다 |
% | 위 그림 $\omega < 0.3$ 구간 | $0$ dB 로 평평 | 느린 신호는 그대로 통과 |
% | 아래 그림 왼쪽 끝 | 위상 $0^\circ$ | 느린 신호는 안 늦는다 |
% | 아래 그림 $\omega = 1$ | 위상 $-90^\circ$ | 정확히 사분의 일 주기 늦는다 |
% | 아래 그림 오른쪽 끝 | 위상 $-180^\circ$ | 반 주기 늦는다. **부호가 뒤집힌 셈** |
% | 아래 그림이 $\omega=1$ 근처에서 급하게 꺾이는 것 | 위상이 빠르게 변한다 | 감쇠비가 작다는 뜻 |
