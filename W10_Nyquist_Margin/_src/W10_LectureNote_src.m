% 앞의 세 줄은 공식과 실측이 소수점 셋째 자리까지 같습니다.
% 마지막 줄 $\zeta = 0.707$ 에서는 공식이 $1.0$ 을 주고 실측도 $1.0$ 입니다.
% **봉우리가 없으니 최대값이 저주파의 $1$ 그 자체**인 것입니다.
%% 5-1-2. 대역폭을 $\omega_n$ 과 $\zeta$ 로 쓰면
% 5-1절에서 대역폭을 `bandwidth` 로 재었습니다.
% 2차 표준형에서는 **공식으로도** 쓸 수 있습니다. 같은 방법으로 유도합니다.
%
% **1단계** 정의대로 식을 세웁니다. $M(u) = 1/\sqrt{2}$ 가 되는 $u$ 를 찾습니다.
%
% $$\frac{1}{\sqrt{(1-u^2)^2 + (2\zeta u)^2}} = \frac{1}{\sqrt{2}}$$
%
% **2단계** 양변을 뒤집고 제곱합니다.
%
% $$(1-u^2)^2 + 4\zeta^2u^2 = 2$$
%
% **3단계** $x = u^2$ 로 두면 $x$ 의 2차 방정식이 됩니다.
%
% $$x^2 - 2x + 4\zeta^2 x + 1 - 2 = 0 \quad\Rightarrow\quad x^2 + (4\zeta^2 - 2)x - 1 = 0$$
%
% **4단계** 근의 공식을 쓰고 **양수인 근**만 고릅니다.
%
% $$x = (1 - 2\zeta^2) + \sqrt{4\zeta^4 - 4\zeta^2 + 2}$$
%
% **5단계** $u = \sqrt{x}$, $\omega_{BW} = u\,\omega_n$ 이므로
%
% $$\omega_{BW} = \omega_n\sqrt{1 - 2\zeta^2 + \sqrt{4\zeta^4 - 4\zeta^2 + 2}}$$
%
% **이 식에서 읽을 두 가지**
%
% - $\omega_n$ 이 앞에 곱으로 나와 있습니다 → **대역폭은 $\omega_n$ 에 비례**합니다
% - 제곱근 안은 $\zeta$ 만의 함수이고 $\zeta$ 가 커지면 작아집니다 →
%   **$\zeta$ 가 커지면 대역폭은 줄어듭니다**
%
% **시간영역과의 연결** — 상승시간은 대역폭에 반비례합니다 ($t_r \approx 1.8/\omega_{BW}$).
% 정착시간과 첨두시간도 마찬가지입니다. 2차 표준형의 식을 그대로 보면
%
% $$t_s \approx \frac{4}{\zeta\omega_n}, \qquad T_p = \frac{\pi}{\omega_n\sqrt{1-\zeta^2}}$$
%
% 셋 다 분모에 $\omega_n$ 이 있습니다. 그리고 $\omega_{BW}$ 도 $\omega_n$ 에 비례합니다.
% **그래서 셋 다 대역폭에 반비례합니다.**
% 거꾸로 읽으면 — **상승시간을 반으로 줄이려면 대역폭을 두 배로 넓혀야 합니다.**
%
% ![대역폭 공식과 시간영역 사양 세 가지](w10_bw_zeta.png)
%
% **그림 파일** `w10_bw_zeta.png` — `make_figures.m` 의 `fig_w10_bw_zeta`
%   · 다시 만들려면 `make_figures('w10_bw_zeta')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w10_bw_zeta`
% **직접 확인해 보려면** — `W10_05_ol_to_cl.m` 의 **4절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 곡선 | 5단계의 공식 | $\omega_n = 1$ 로 두고 그린 것 |
% | 왼쪽 동그라미 | `bandwidth` 로 잰 실측값 | 곡선 위에 정확히 얹힌다 |
% | 왼쪽 곡선이 내려가는 것 | $\zeta$ 가 커지면 대역폭이 줄어든다 | 공식의 제곱근 안이 줄기 때문 |
% | 왼쪽 $\zeta = 0.1$ | 대역폭 약 $1.54\,\omega_n$ | $\omega_n$ 보다 넓다 |
% | 왼쪽 $\zeta = 0.9$ | 대역폭 약 $0.62\,\omega_n$ | $\omega_n$ 보다 좁다 |
% | 왼쪽 $\zeta = 0.707$ 부근 | 대역폭 $\approx \omega_n$ | **외워 두면 편한 자리** |
% | 오른쪽 세 직선 | $t_r$ · $T_p$ · $t_s$ | 양쪽 축이 모두 로그 |
% | 오른쪽 직선의 기울기 | 모두 $-1$ | 로그-로그에서 기울기 $-1$ = **반비례** |
% | 세 직선이 평행한 것 | 셋의 비율이 일정하다 | 하나를 알면 나머지를 안다 |
% | 가로축을 두 배로 옮길 때 | 세로축이 반으로 | **대역폭 두 배 = 시간 절반** |
%
% 공식과 실측을 대조합니다.
zb  = [0.1; 0.3; 0.5; 0.707; 0.9];
bw_formula  = sqrt(1 - 2*zb.^2 + sqrt(4*zb.^4 - 4*zb.^2 + 2));   % wn = 1
bw_measured = zeros(5,1);
for i = 1:5
    bw_measured(i) = bandwidth(tf(1, [1, 2*zb(i), 1]));
end
table(zb, bw_formula, bw_measured)
