%% 1. 불안정의 조건
% 단위 피드백 폐루프는 이렇습니다.
%
% $$T(s) = \frac{L(s)}{1 + L(s)}$$
%
% 분모가 $0$ 이 되는 $s$ 가 폐루프 극점이므로
%
% $$1 + L(s) = 0 \qquad \Rightarrow \qquad L(s) = -1$$
%
% $s = j\omega$ 로 놓고 읽으면 이렇습니다.
%
% $$|L(j\omega)| = 1 \quad\text{이면서}\quad \angle L(j\omega) = -180^\circ$$
%
% **왜 이것이 위험한가 — 이유가 두 가지입니다**
%
% **이유 1. 폐루프 이득이 무한대가 됩니다.**
%
% $T$ 의 분모를 그대로 보십시오.
%
% $$T(j\omega) = \frac{L(j\omega)}{1 + L(j\omega)}$$
%
% $L(j\omega) = -1$ 을 대입하면 분모가 이렇게 됩니다.
%
% $$1 + L(j\omega) = 1 + (-1) = 0$$
%
% 즉 $T$ 는 $\frac{-1}{0}$ 입니다. **0 으로 나누는 것**이므로
%
% $$|T(j\omega)| \rightarrow \infty$$
%
% 이것이 무슨 뜻인가 — $T$ 는 "지령 $1$ 을 넣으면 출력이 얼마냐" 를 재는 값입니다.
% 그 값이 무한대라면 **지령을 아주 조금만 넣어도 출력이 무한히 커진다**는 말이고,
% 거꾸로 읽으면 **입력이 없어도 그 주파수의 출력이 저절로 난다**는 말입니다.
% 그것이 바로 불안정입니다.
%
% **이유 2. $-1$ 은 두 군데에서 옵니다. 그리고 그 둘이 곱해집니다.**
%
% - 위상이 $-180^\circ$ 라는 것은 한 바퀴 돌아온 신호가 **뒤집혀 왔다**는 뜻,
%   곧 $-1$ 을 곱한 것입니다
% - 되먹임의 합산점은 **빼기**입니다. 거기서 $-1$ 을 한 번 더 곱합니다
% - 둘을 곱하면 $(-1)\times(-1) = +1$ 입니다
%
% 그러므로 돌아온 신호가 **원래 신호와 똑같은 부호로 더해집니다.**
% 거기에 크기까지 $1$ 이면 줄지도 늘지도 않고 **계속 돕니다.**
% 크기가 $1$ 보다 크면 돌 때마다 커집니다.
%
% ![-1 점에서 폐루프 이득이 치솟는 이유와 -1 이 두 군데서 오는 이유](w10_why_unstable.png)
%
% **그림 파일** `w10_why_unstable.png` — `make_figures.m` 의 `fig_w10_why_unstable`
%   · 다시 만들려면 `make_figures('w10_why_unstable')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w10_why_unstable`
% **직접 확인해 보려면** — `W10_04_gm_pm_build.m` 의 **1절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 가로축 | 실수축을 지나갈 때의 $L(j\omega)$ 값 | $-1$ 에 가까워지는 과정을 본다 |
% | 왼쪽 세로축 | 폐루프 이득 $T$ 의 크기 | $T = L/(1+L)$ 의 절댓값 |
% | 왼쪽 빨간 세로 점선 | $L = -1$ | 분모가 $0$ 이 되는 자리 |
% | 왼쪽 파란 곡선이 점선에서 치솟는 것 | 폐루프 이득이 무한대로 간다 | **0 으로 나눈 결과** |
% | 왼쪽 곡선의 오른쪽 끝 ($L \approx 0$) | 폐루프 이득도 거의 $0$ | $L$ 이 작으면 폐루프도 작다 |
% | 왼쪽 곡선의 왼쪽 끝 ($L = -2.4$) | 폐루프 이득 약 $1.7$ | $-1$ 에서 멀어지면 다시 얌전해진다 |
% | 오른쪽 검은 굵은 곡선 ① | 들어간 신호 $e$ | 출발점 |
% | 오른쪽 주황 곡선 ② | 위상 $-180^\circ$ 를 지난 결과 | 검은 곡선이 **뒤집혔다** ($-1$ 배) |
% | 오른쪽 초록 점선 ③ | 합산점의 빼기까지 거친 결과 | 다시 뒤집혀 **검은 곡선과 겹친다** |
% | 초록 점선이 검은 곡선과 겹치는 것 | $(-1)\times(-1) = +1$ | **같은 부호로 더해진다.** 이것이 진동의 씨앗 |
%
% 이 두 조건을 동시에 만족하는 주파수가 있으면 그 주파수로 진동합니다.
%
% 왼쪽 그림의 치솟음을 **숫자 세 개로** 확인해 봅니다.
L_vals = [-0.9; -0.99; -1.001];     % -1 에 점점 가까이 가는 L 값
T_vals = L_vals ./ (1 + L_vals);    % 폐루프 이득 T = L/(1+L)
table(L_vals, T_vals)
%%
% $-1$ 에 가까워질수록 폐루프 이득이 커집니다.
% $L = -1.001$ 에서는 부호까지 뒤집힌 $1000$ 배가 나옵니다.
% **$-1$ 을 지나는 순간 무언가 극적인 일이 일어난다는 것**을 이 세 숫자가 보여 줍니다.
%% 1-1. 숫자로 확인
% 강의자료 6장의 표준 예제로 확인합니다.
%
% $$L(s) = \frac{K}{s\,(s+1)^2}$$
G = 1/(s*(s+1)^2);
K = [0.5 1 2 3]';
max_real = zeros(size(K));            % 폐루프 극점 실수부의 최댓값
for i = 1:numel(K)
    max_real(i) = max(real(pole(feedback(K(i)*G, 1))));
end
stable = max_real < 0;                % 전부 좌반면이면 안정
table(K, max_real, stable)
%%
% 실수부 최댓값이 $0$ 을 넘는 순간 불안정해집니다.
% 이 시스템은 $K = 2$ 가 안정 한계이고, **5주차에서 라우스 표로 구했던
% 임계이득과 같은 값**입니다.
%% 2. 나이퀴스트 선도
% 보드 선도는 크기와 위상을 **따로** 그렸습니다.
% 나이퀴스트 선도는 둘을 **한 평면에** 그립니다.
%
% $\omega$ 를 훑으며 복소수 $L(j\omega)$ 를 복소평면에 찍는 것뿐입니다.
% 그러면 "$-1$ 이 되는가" 를 눈으로 볼 수 있습니다.
%
% 보드 선도와 나이퀴스트 선도는 **같은 정보를 다르게 그린 것**입니다.
%
% | | 보드 선도 | 나이퀴스트 선도 |
% |---|---|---|
% | 그림 개수 | 두 장 (크기, 위상) | **한 장** |
% | 가로축 | 주파수 | 실수부 |
% | 크기는 어디에 | 세로축 | **원점에서의 거리** |
% | 위상은 어디에 | 아래 그림의 세로축 | **원점에서 본 각도** |
% | 주파수는 어디에 | 가로축 | 곡선을 따라간 **위치** (축에 안 보인다) |
% | 잘 보이는 것 | 주파수별 특성 | **$-1$ 점과의 거리** |
%
% 그래서 "크기 $1$, 위상 $-180^\circ$" 라는 두 조건이
% 나이퀴스트 선도에서는 **점 하나**($-1$)가 됩니다. 이것이 오늘 이 그림을 쓰는 이유입니다.
%% 2-0. `nyquist` — 오늘의 새 명령
% - **원리** — $\omega$ 를 $-\infty$ 에서 $+\infty$ 까지 훑으며 복소수
%   $L(j\omega)$ 를 복소평면에 찍는다
% - **입력** — **개루프** 전달함수 $L$. `margin` 과 같습니다
% - **출력** — 받지 않으면 그림. `[re, im] = nyquist(L, w)` 로 값도 받을 수 있다
%
% 주의 네 가지
%
% - **폐루프를 넣으면 안 됩니다.** $-1$ 점 판정은 개루프에 대한 것입니다
% - 그림에 `-1` 자리를 표시해 주지 않습니다. `hold on` 하고 직접 찍으십시오
% - $\omega$ 가 음수인 쪽까지 그리므로 **곡선이 실축 기준으로 대칭**입니다.
%   두 겹으로 보이는 것이 정상입니다
% - **원점에 극점(적분기)이 있으면 곡선이 무한대로 날아가** 그림이 깨집니다.
%   그때는 `common/` 의 `nyquist1` 을 쓰십시오. $j\omega$ 축을 살짝 우회해 그려 줍니다
%
% 값을 받아 쓰는 예 — $-1$ 점까지의 **최단 거리**를 재 봅니다.
% 이 거리가 곧 "얼마나 아슬아슬한가" 입니다.
s = tf('s');
G_ex = 1/(s*(s+1)^2);
w_ex = logspace(-1, 1, 2000);
[re_ex, im_ex] = nyquist(0.5*G_ex, w_ex);
re_ex = squeeze(re_ex);  im_ex = squeeze(im_ex);
distance = min(hypot(re_ex + 1, im_ex))   % 궤적과 -1 점의 최단 거리
%%
% 이 거리가 **작을수록 불안정에 가깝습니다.**
% 5절에서 배울 감도 최대값은 이 거리의 역수입니다.
peak_sensitivity = 1/distance
