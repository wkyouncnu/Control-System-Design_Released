%% 2-0-1. 그런데 왜 $\omega$ 를 음수까지 훑는가 — 나이퀴스트 경로
% 앞 절의 주의에서 "곡선이 실축 기준으로 대칭이라 두 겹으로 보인다" 고 했습니다.
% 그것이 왜 그런지, 그리고 애초에 왜 그렇게 그리는지 짚고 갑니다.
% **이 절을 건너뛰면 다음 절의 판정법이 마술처럼 보입니다.**
%
% 우리가 알고 싶은 것은 **폐루프 극점이 우반면에 있는가**입니다.
% 폐루프 극점은 $1 + L(s) = 0$ 의 근이므로, 결국
% **"$1+L(s)$ 가 우반면에서 $0$ 이 되는 곳이 있는가"** 를 묻는 것입니다.
%
% 복소해석에는 이런 질문에 답하는 도구가 있습니다.
% **어떤 닫힌 길을 따라 함수값이 원점을 몇 바퀴 도는지 세면,
% 그 길 안에 영점과 극점이 각각 몇 개 있는지 알 수 있습니다.**
% 이것이 **편각원리**입니다.
%
% 그래서 **우반면 전체를 감싸는 닫힌 길**을 만듭니다. 그 길이 두 부분입니다.
%
% - **허수축** — $s = j\omega$ 로 $\omega$ 를 $-\infty$ 에서 $+\infty$ 까지
% - **무한대 반원** — 오른쪽을 크게 돌아 출발점으로 되돌아온다
%
% 이 닫힌 길을 **나이퀴스트 경로**라고 합니다.
%
% ![우반면을 감싸는 닫힌 길을 L 로 옮긴 것이 나이퀴스트 선도다](w10_contour.png)
%
% **그림 파일** `w10_contour.png` — `make_figures.m` 의 `fig_w10_contour`
