% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림의 빨간 별 | $-1$ 점 | **오늘 하루 종일 볼 자리** |
% | 왼쪽 파란 곡선 ($K=0.5$) | 별의 **오른쪽**을 지나간다 | 별에서 떨어져 있다 $\to$ 여유가 있다 |
