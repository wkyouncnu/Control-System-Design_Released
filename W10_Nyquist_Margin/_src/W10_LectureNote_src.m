%% 7. 오늘의 정리
% - 불안정의 조건은 $L(j\omega) = -1$. **여유란 그 점에서 얼마나 떨어졌는가**다
% - 나이퀴스트 선도는 크기와 위상을 한 평면에 그린 것이다
% - 나이퀴스트 판정 $Z = N + P$. 개루프가 안정하면 $-1$ 을 감지 않아야 한다
% - **이득여유는 $-180^\circ$ 인 곳에서, 위상여유는 $0$ dB 인 곳에서** 읽는다
% - 실무 기준은 GM $6$ dB 이상, PM $30^\circ \sim 60^\circ$
% - 위상여유는 **견딜 수 있는 시간지연**으로 바꿔 읽을 수 있다
% - 시간영역 사양과 주파수영역 사양은 서로 번역된다 ($\zeta \approx PM/100$)
% - $S + T = 1$ 은 피할 수 없다. 주파수를 나눠 쓴다
%
% 그리고 **이득 $K$ 를 손에 쥐었을 때** 오늘 노트가 답해 주는 것
%
% - $K$ 를 키우면 **크기 선도만 통째로 올라가고 위상 선도는 꼼짝도 않는다**
%   ($20\log_{10}|KG| = 20\log_{10}K + 20\log_{10}|G|$, $\angle(KG) = \angle G$)
% - 그래서 $0$ dB 교차주파수 $\omega_c$ 가 오른쪽으로 밀리고,
%   따라오는 폐루프 대역폭 $\omega_{BW}$ 도 같이 커진다 ($\omega_c \le \omega_{BW} \le 2\omega_c$)
% - **반응속도를 올리려면 결국 손대야 할 것은 대역폭(또는 교차주파수) 하나다**
%   ($t_r \approx 1.8/\omega_{BW}$)
% - 대가가 있다. **위상여유가 깎이고 오버슈트가 커진다.** 공짜는 없다
% - 그래서 설계는 "빠르게" 가 아니라 **"사양을 만족하는 가장 느린 것"** 을 고르는 일이다
% - 어림식($\zeta \approx PM/100$)은 **방향을 보는 데** 쓰고,
%   최종 확인은 반드시 `stepinfo` 로 한다 (6-3절에서 $K=1.2$ 가 그 예다)
