%% 5-2. 근본적인 맞바꿈 — 감도함수
% 두 전달함수를 함께 봅니다. 그런데 그 전에 **잡음이 어디로 들어오는지**를
% 그림에서 확인해야 합니다. 외란과 들어오는 자리가 다릅니다.
%
% ![측정 잡음 n 은 출력 쪽 되먹임 경로로 들어온다](loop_noise.png)
%
% **그림 파일** `loop_noise.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_noise')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('noise', ...)` 로 부릅니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 잡음 $n$ 이 꽂히는 자리 | **출력을 잰 뒤**, 되먹임 경로 | 외란($d$)과 **자리가 다르다** |
% | 외란 $d$ 는 어디였나 | 플랜트 **입력** 쪽 (1주차 6절) | 그래서 전달함수도 다르게 나온다 |
% | 제어기가 실제로 보는 값 | $r - (y + n)$ | 잡음이 섞인 값을 참값으로 믿는다 |
% | 그래서 생기는 일 | 제어기가 잡음을 **없애려고 움직인다** | 7주차 미분항 문제의 뿌리 |
%
% 이제 두 전달함수를 유도합니다. 신호를 따라가면 됩니다.
%
% $$e = r - (y + n), \qquad y = L\,e$$
%
% 둘째를 첫째에 넣고 $y$ 를 한쪽으로 모읍니다.
%
% $$y = L\,(r - y - n)
%   \;\Rightarrow\; (1+L)\,y = L\,r - L\,n
%   \;\Rightarrow\; y = \frac{L}{1+L}\,r - \frac{L}{1+L}\,n$$
%
% 그리고 오차는 (1주차 · 5주차와 같은 방법으로)
%
% $$e = \frac{1}{1+L}\,r$$
%
% 여기 나온 두 덩어리에 이름을 붙인 것이 전부입니다.
%
% $$S(s) = \frac{1}{1+L}, \qquad T(s) = \frac{L}{1+L}$$
%
% | 이름 | 식 | 무엇을 재는가 |
% |---|---|---|
% | **감도** $S$ | $\frac{1}{1+L}$ | 외란과 오차가 **얼마나 남는가**. 작을수록 좋다 |
% | **상보감도** $T$ | $\frac{L}{1+L}$ | 지령을 **얼마나 잘 따라가는가**, 동시에 **잡음을 얼마나 통과시키는가** |
%
% $T$ 의 이름에 "상보" 가 붙은 이유는 한 줄이면 나옵니다.
% 두 분수의 **분모가 같으므로 그냥 더하면** 됩니다.
%
% $$S + T = \frac{1}{1+L} + \frac{L}{1+L} = \frac{1 + L}{1+L} = 1$$
%
% $$S(j\omega) + T(j\omega) = 1 \qquad \text{(모든 주파수에서)}$$
%
% **이것이 제어의 근본적인 맞바꿈입니다.** 둘 다 작게 만들 수는 없습니다.
% $S$ 를 $0.01$ 로 만들면 그 주파수에서 $T$ 는 자동으로 $0.99$ 가 됩니다.
% 우리가 고를 수 있는 것은 **어느 주파수에서 어느 쪽을 작게 할 것인가**뿐입니다.
%
% 실무의 해법은 **주파수를 나눠 쓰는 것**입니다.
%
% - 저주파에서 $S$ 를 작게 $\rightarrow$ 외란 억제, 정상상태 오차 감소
% - 고주파에서 $T$ 를 작게 $\rightarrow$ 측정 잡음 억제
% - 교차주파수 근처는 어쩔 수 없다. 그래서 **교차주파수를 어디에 둘 것인가**가 설계다
%
% 이득을 키우면 저주파의 $|S|$ 는 좋아지는데 교차주파수 근처의 봉우리가
% 솟습니다. 그 봉우리가 위상여유와 정확히 반대로 움직입니다.
%
% ![감도의 봉우리와 위상여유는 같은 이야기다](w10_sensitivity.png)
%
% **그림 파일** `w10_sensitivity.png` — `make_figures.m` 의 `fig_w10_sensitivity`
%   · 다시 만들려면 `make_figures('w10_sensitivity')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w10_sensitivity`
% **직접 바꿔 보려면** — 함수 안의 `Ks = [0.3 0.8 1.6]` 을 바꿔 실행
%
% 그림 해석
%
