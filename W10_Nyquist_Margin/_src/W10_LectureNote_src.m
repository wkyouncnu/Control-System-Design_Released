% 실제 현장에서 모델은 전달함수로 오지 않습니다. **블록선도로 옵니다.**
% 비선형 블록이 섞여 있고 서브시스템이 여러 겹입니다.
%
% ![선형화의 대상은 이런 폐루프다](loop_closed.png)
%
% **그림 파일** `loop_closed.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_closed')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('closed', ...)` 로 부릅니다
% **직접 해 보려면** — `W10_03_run_simulink.m` 이 `W10_Margin_Check.slx` 에서
% 이 루프를 잘라 개루프를 뽑습니다
%
% 그림 해석 — **오늘은 "어디를 자를 것인가" 를 정하는 그림입니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 되먹임 선 | 출력이 앞으로 돌아온다 | 이 선을 **잘라야** 개루프가 된다 |
% | 왼쪽 원 (합산점) | $r$ 과 되먹임이 만나는 곳 | 자르는 자리를 여기 근처로 잡는다 |
% | 가운데 상자들 | 제어기와 플랜트 | 실제 모델에서는 서브시스템 여러 겹이다 |
% | 상자 사이의 선 | 신호 | `linio` 로 이 선 위에 **입력점과 출력점**을 찍는다 |
% | 오른쪽 $y$ | 출력 | 여기까지가 개루프 $L$ 이다 |
%
% `margin` 은 **개루프** 를 받습니다. 그래서 Simulink 모델에서도
% 반드시 루프를 끊어 $L$ 을 만든 뒤에 여유를 재야 합니다.
% 폐루프를 넣으면 엉뚱한 값이 나옵니다.
%
% 이때 쓰는 것이 **선형화**입니다. 절차는 두 줄입니다.
%
% - `linio` 로 **어디를 자를 것인가**를 지정한다 (루프를 끊어야 개루프가 된다)
% - `linearize` 로 그 두 점 사이의 전달함수를 얻는다
%
% `linio` — **자를 자리를 표시하는 명령**
%
% - **하는 일** — 모델의 어느 블록 어느 포트를 입력/출력으로 볼지 정한다
% - **입력** — `linio('모델/블록이름', 포트번호, 종류)`.
%   종류는 `'openinput'`(여기서 끊고 넣는다), `'openoutput'`(여기서 끊고 본다) 등
% - **출력** — 선형화 지점 객체. 여러 개를 배열로 묶어 `linearize` 에 준다
%
% `linearize` — **실제로 선형화하는 명령**
%
% - **하는 일** — 지정한 두 점 사이를 수치적으로 미분해 상태공간 모델을 만든다
% - **입력** — `linearize('모델이름', io)`
% - **출력** — `ss` 객체. 그대로 `margin`, `bode` 에 넣으면 된다
%
% 주의
%
% - 자르는 종류를 `'input'`/`'output'`(끊지 않음)으로 주면 **폐루프**가 나옵니다.
%   개루프를 원하면 반드시 `open` 이 붙은 것을 쓰십시오
% - 모델이 **평형점에 있어야** 제대로 된 선형화가 나옵니다
%% 6-1. 함정 — `linearize` 는 기본적으로 시간지연을 근사한다
% 4-1절에서 위상여유를 시간지연으로 바꿔 읽었습니다.
% 그런데 Simulink 모델에 `Transport Delay` 블록을 넣고 그대로 `linearize` 하면
% **지연이 결과에 반영되지 않습니다.**
%
% 기본 설정이 지연을 유리수 함수로 근사(파데 근사)하는데,
% 차수가 $0$ 이면 아예 무시해 버리기 때문입니다.
%
% 실제로 이 과목을 만들 때 겪은 일입니다 —
% 지연을 $0$ 초에서 $1$ 초까지 바꿔 가며 `linearize` 를 불렀는데
% **위상여유가 $44.06^\circ$ 로 꼼짝도 안 했습니다.**
%
% `linearizeOptions` — **그 설정을 바꾸는 명령**
%
% - **하는 일** — 선형화 방식을 정하는 옵션 묶음을 만든다
% - **입력** — 이름-값 쌍. 오늘 쓰는 것은 `'UseExactDelayModel'`
% - **출력** — 옵션 객체. `linearize(모델, io, opt)` 처럼 세 번째 인자로 준다
%
% 쓰는 법은 한 줄입니다.
%
%   `opt = linearizeOptions('UseExactDelayModel', 'on');`
%
% 이렇게 하면 지연을 근사하지 않고 **그대로** 다룹니다.
% 그러면 위상여유가 지연에 따라 제대로 깎입니다.
% $\tau = 1$ 초에서 $44.06^\circ \rightarrow 19.78^\circ$ 로,
% 이론값 $44.06 - 180\cdot 1 \cdot 0.424/\pi = 19.78$ 과 정확히 맞습니다.
%
% **교훈** — 도구가 조용히 근사하고 있을 수 있습니다.
% 결과가 "너무 안 변하면" 옵션을 의심하십시오.
%
% 3주차에서 손으로 한 야코비안 선형화를 도구가 대신 해 주는 것입니다.
%
% 실습 스크립트에서 확인할 것
%
% - `W10_01_nyquist_margin.m` — 나이퀴스트, 여유, 개루프가 불안정한 경우
% - `W10_02_pm_to_time.m` — 시간영역과의 번역표, 감도함수
% - `W10_03_run_simulink.m` — `W10_Margin_Check.slx` 를 선형화해 여유를 뽑고,
%   **시간지연을 키우며 위상여유가 깎이는 것**을 확인
%
% 마지막 스크립트의 결과를 미리 보면 이렇습니다.
% 지연이 $1.81$ 초를 넘으면 발산하는데, 그 값이 정확히 $PM/\omega_{cp}$ 입니다.
%% 6-2. `margin` 과 `allmargin` — 여유를 숫자로 받는 법
% `margin` 도 출력을 받느냐 안 받느냐로 하는 일이 갈립니다.
%
% | 호출 형태 | 무엇이 나오는가 |
% |---|---|
% | `margin(L)` | 보드 선도에 여유를 표시한 **그림** |
% | `[Gm, Pm] = margin(L)` | 이득여유(**배수**)와 위상여유(도) |
% | `[Gm, Pm, Wcg, Wcp] = margin(L)` | 위 둘 + 각각의 주파수 |
% | `allmargin(L)` | 여유 **전부**를 구조체로. 지연여유까지 |
%
% **가장 흔한 실수** — `Gm` 은 dB 가 아니라 **배수**입니다.
% 보드 선도에 적힌 dB 값과 맞추려면 `mag2db(Gm)` 를 해야 합니다.
%
% `allmargin` 이 돌려주는 것
%
% - `GainMargin`, `GMFrequency` — 이득여유와 그 주파수
% - `PhaseMargin`, `PMFrequency` — 위상여유와 그 주파수
% - `DelayMargin`, `DMFrequency` — **얼마나 지연되어도 버티는가** (초)
% - `Stable` — 폐루프가 안정이면 1
%
% 마지막 두 개가 실무에서 특히 유용합니다.
% 통신 지연이나 센서 처리 시간이 있는 시스템에서 바로 쓸 수 있는 숫자입니다.
s = tf('s');
Lm = 1/(s*(s+1)^2);

[Gm_, Pm_, Wcg_, Wcp_] = margin(Lm);
fprintf('이득여유 : %.3f 배 = %.2f dB   (w = %.3f rad/s)\n', Gm_, mag2db(Gm_), Wcg_);
fprintf('위상여유 : %.2f 도             (w = %.3f rad/s)\n', Pm_, Wcp_);

am = allmargin(Lm);
fprintf('\n지연여유 : %.4f 초\n', am.DelayMargin);
fprintf('  -> 루프에 %.0f ms 이상 지연이 생기면 불안정해집니다.\n', am.DelayMargin*1000);
fprintf('폐루프 안정 여부 : %d (1 이면 안정)\n', am.Stable);
fprintf('\n확인 : 위상여유 %.2f 도를 교차주파수 %.3f rad/s 로 나누면\n', Pm_, Wcp_);
fprintf('       %.4f 초로 지연여유와 같습니다.\n', deg2rad(Pm_)/Wcp_);
