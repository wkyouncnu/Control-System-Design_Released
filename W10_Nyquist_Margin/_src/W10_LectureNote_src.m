% **만드는 곳** — `make_figures.m` 의 `fig_w10_contour`
% **직접 확인해 보려면** — `W10_01_nyquist_margin.m` 의 **2절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 세로 직선 | 허수축 $s = j\omega$ | $\omega$ 를 $-\infty$ 에서 $+\infty$ 로 훑는 구간 |
% | 왼쪽 오른쪽 반원 | 반지름이 무한대인 반원 | 길을 닫기 위한 것. **여기서 $L \to 0$** 이라 그림에서는 원점 한 점이 된다 |
% | 두 구간이 이어져 닫힌 것 | 닫힌 길 | 편각원리를 쓰려면 **닫혀 있어야** 한다 |
% | 왼쪽 빨간 $\times$ ($s=1$) | 경로 **안쪽**의 개루프 극점 | 이것이 $P = 1$ 이다 |
% | 왼쪽 회색 $\times$ ($s=-3$) | 경로 **바깥**의 극점 | 좌반면이므로 세지 않는다 |
% | 오른쪽 그림 | 왼쪽 길을 $L$ 로 옮긴 결과 | **이것이 나이퀴스트 선도다** |
% | 오른쪽 곡선이 닫혀 있는 것 | 왼쪽 길이 닫혀 있었기 때문 | 열려 보이면 그린 범위가 모자란 것이다 |
% | 오른쪽 곡선이 실축 대칭인 것 | $L(-j\omega) = \overline{L(j\omega)}$ | 계수가 실수이므로 **항상** 그렇다 |
