% 읽을 것 세 가지입니다.
%
% - **식으로** 와 **직접잰값** 이 세 줄 모두 일치합니다. 마지막 줄이
%   3차인데도 맞습니다. **유도에 차수가 들어가지 않았으므로 당연합니다**
% - 세 줄 모두 PM 이 $90^\circ$ 보다 작고, 그래서 `식으로` 열이
%   $0.707$ 보다 큽니다. 즉 $\omega_c$ 에서 폐루프가 아직 $-3$ dB 위입니다.
%   그 결과 `비율` 열이 전부 $1$ 보다 큽니다
% - PM 이 가장 작은 줄에서 `식으로` 가 가장 크고 `비율` 도 가장 큽니다.
%   **$-1$ 점에 가까울수록 두 주파수가 벌어집니다**
%
% 왜 중요한가 — 사양서는 $\omega_{BW}$ 로 옵니다. 설계는 $\omega_c$ 로
% 합니다. 이 절의 식이 **둘 사이의 번역기**입니다. 사양이
% "$\omega_{BW} \ge 60$ rad/s" 이면 비율 $1.5$ 로 나눠
% "$\omega_c \ge 40$ rad/s 를 맞추자" 로 번역하고, 보드 선도에서 이득을
% 올려 $\omega_c$ 를 그 자리로 옮기면 됩니다 ($5$절의 $K$ 이야기).
% $11$주차 $3$-$3$-$1$절에서 이 번역을 설계 절차로 정리하고,
% $3$-$4$절에서 위상여유까지 함께 맞추는 법을 다룹니다.
%% 5-1-4. 세 화살표로 한 장에 정리
% 지금까지 주파수영역에서 읽은 값 세 개가 모두 시간영역으로 번역되었습니다.
% **공통점이 하나 있습니다. 전부 $\zeta$ 를 거쳐 갑니다.**
%
% | 주파수영역에서 읽는 값 | 중간 다리 | 시간영역 결과 |
% |---|---|---|
% | 위상여유 $\Phi_M$ 이 커지면 | $\zeta$ 가 커지고 | 오버슈트가 줄어든다 |
% | 대역폭 $\omega_{BW}$ 가 커지면 | 시간상수가 작아지고 | $t_s$ · $t_r$ · $T_p$ 가 줄어든다 |
% | 공진봉우리 $M_r$ 이 작아지면 | $\zeta$ 가 커지고 | 오버슈트가 줄어든다 |
%
% **$\zeta$ 하나가 두 세계를 잇는 다리입니다.** 그래서 주파수영역에서
% 설계해도 시간영역 사양을 맞출 수 있습니다. 오늘 수업의 가장 큰 그림입니다.
%
% ![주파수영역 값 세 개가 모두 감쇠비를 거쳐 시간영역으로](w10_arrows.png)
%
% **그림 파일** `w10_arrows.png` — `make_figures.m` 의 `fig_w10_arrows`
%   · 다시 만들려면 `make_figures('w10_arrows')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w10_arrows`
% **직접 확인해 보려면** — `W10_05_ol_to_cl.m` 의 **6절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 세 줄의 왼쪽 칸 | 주파수영역에서 읽는 값 | 오늘 `margin` · `bandwidth` 로 잰 것 |
% | 세 줄의 가운데 칸 | $\zeta$ 또는 시간상수 | **모든 줄이 여기를 지난다** |
% | 세 줄의 오른쪽 칸 | 시간영역 사양 | 4주차에서 배운 것 |
% | 첫째 줄 | 위상여유 경로 | 5-1-3절에서 유도했다 |
% | 둘째 줄 | 대역폭 경로 | 5-1-2절에서 유도했다 |
% | 셋째 줄 | 공진봉우리 경로 | 5-1-1절에서 유도했다 |
% | 회색 줄 | 대역폭이 개루프 교차주파수에 비례 | 4-3절의 어림 |
% | 맨 아래 빨간 줄 | 세 경로의 공통점 | **$\zeta$ 가 두 세계를 잇는 다리** |
% | 화살표 방향이 모두 왼쪽에서 오른쪽인 것 | 읽는 순서 | 주파수에서 재고 시간으로 해석한다 |
%
% 세 경로를 숫자 하나로 꿰어 봅니다. $\zeta$ 를 정하면 나머지가 전부 결정됩니다.
zA = 0.5;                                              % 감쇠비 하나만 정한다
u_A  = sqrt(sqrt(1 + 4*zA^4) - 2*zA^2);
PM_A = atan2(2*zA, u_A) * 180/pi                       % ① 위상여유 [도]
bw_A = sqrt(1 - 2*zA^2 + sqrt(4*zA^4 - 4*zA^2 + 2))    % ② 대역폭 (wn = 1)
Mr_A = 1/(2*zA*sqrt(1 - zA^2))                         % ③ 공진봉우리
OS_A = 100*exp(-pi*zA/sqrt(1 - zA^2))                  % 시간영역 오버슈트 [%]
%%
% $\zeta = 0.5$ 하나에서 네 숫자가 전부 나왔습니다.
% 거꾸로도 됩니다 — 측정으로 $PM$ 을 알면 $\zeta$ 를 알고,
% $\zeta$ 를 알면 오버슈트와 대역폭을 **재지 않고도** 짐작할 수 있습니다.
%% 5-1-5. 개루프를 빠르게 하면 폐루프도 빨라진다
% 4-3절에서 $\omega_c \le \omega_{BW} \le 2\omega_c$ 를 보았습니다.
% 이 어림의 **설계적 의미**는 이것입니다.
%
% **개루프 교차주파수 $\omega_c$ 를 오른쪽으로 밀면 폐루프 대역폭도
% 함께 오른쪽으로 가고, 그러면 시간응답이 빨라집니다.**
%
% 그리고 $\omega_c$ 를 오른쪽으로 미는 방법은 3-2절에서 이미 보았습니다.
% **이득을 키우면 크기 곡선이 통째로 올라가므로 $0$ dB 교차점이
% 오른쪽으로 옮겨 갑니다.** 세 절의 결과가 여기서 하나로 이어집니다.
%
% **$K$ 를 키우면 $\Rightarrow$ $\omega_c$ 커짐 $\Rightarrow$ $\omega_{BW}$ 커짐
% $\Rightarrow$ $t_r$, $t_s$, $T_p$ 줄어듦 (= 응답이 빨라짐)**
%
% 그러므로 **반응속도를 올리고 싶으면 손대야 할 것은 대역폭(또는 교차주파수)
% 하나입니다.** 9주차 5-5절에서 보드 선도로 확인한 그 평행이동이,
% 여기서 "폐루프가 얼마나 빨라지는가" 라는 숫자로 바뀝니다.
%
% **단, 공짜가 아닙니다.** 이득을 키우면 위상여유가 깎입니다 (3-3절).
% 그래서 빠르게 하려는 만큼 오버슈트가 커집니다. 이 맞바꿈이 설계의 본질입니다.
%
% 먼저 **$\zeta$ 를 고정하고 $\omega_n$ 만 키우는** 가장 깨끗한 예로
% "빠르기" 와 "대역폭" 이 같이 움직이는 것을 확인합니다.
% ($\zeta$ 를 고정했으므로 오버슈트는 세 경우 모두 똑같습니다.)
%
% ![감쇠비를 고정하고 고유진동수만 키우면 응답과 대역폭이 함께 빨라진다](w10_wn_speed.png)
%
% **그림 파일** `w10_wn_speed.png` — `make_figures.m` 의 `fig_w10_wn_speed`
%   · 다시 만들려면 `make_figures('w10_wn_speed')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w10_wn_speed`
% **직접 확인해 보려면** — `W10_05_ol_to_cl.m` 의 **7절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 세 곡선 | $\omega_n = 1,\ 3.16,\ 10$ 의 계단응답 | $\zeta = 0.2$ 로 고정 |
% | 세 곡선의 오버슈트 | 모두 똑같다 (약 $53\%$) | **오버슈트는 $\zeta$ 만 정한다** |
% | 세 곡선의 빠르기 | $\omega_n$ 이 클수록 빠르다 | 시간축이 $\omega_n$ 배로 압축된다 |
% | 왼쪽 파란 곡선 | 가장 느리다 | $\omega_n = 1$ |
% | 왼쪽 노란 곡선 | 가장 빠르다 | $\omega_n = 10$. 열 배 빠르다 |
% | 오른쪽 세 곡선 | 같은 세 경우의 폐루프 크기 | 모양이 똑같고 좌우로만 이동 |
% | 오른쪽 네모 표식 | 각 곡선이 $-3$ dB 를 지나는 점 | 대역폭 $\omega_{BW}$ |
% | 세 네모의 가로 위치 | 왼쪽 그림과 같은 순서 | **빠른 쪽이 대역폭도 넓다** |
% | 네모 사이의 간격 | $\omega_n$ 비율과 같다 | $\omega_{BW} \propto \omega_n$ (5-1-2절) |
% | 세 곡선의 봉우리 높이 | 모두 같다 | $M_r$ 도 $\zeta$ 만 정한다 |
%
% 숫자로 확인합니다. 교수자 강의자료의 예제를 그대로 씁니다.
zeta_w = 0.2;
wn_w   = [1; sqrt(10); 10];
bw_w   = zeros(3,1);  tr_w = zeros(3,1);  os_w = zeros(3,1);
for i = 1:3
    w  = wn_w(i);
    Tw = tf(w^2, [1, 2*zeta_w*w, w^2]);        % 2차 표준형 폐루프
    bw_w(i) = bandwidth(Tw);
    info    = stepinfo(Tw);
    tr_w(i) = info.RiseTime;
    os_w(i) = info.Overshoot;
end
table(wn_w, bw_w, tr_w, os_w)
%%
% - `bw_w` 가 `wn_w` 와 **같은 비율**로 늘어납니다 — $\omega_{BW} \propto \omega_n$
% - `tr_w` 는 **반대로 같은 비율로 줄어듭니다** — $t_r \propto 1/\omega_{BW}$
% - `os_w` 는 **세 줄이 전부 같습니다** — 오버슈트는 $\zeta$ 만 정하기 때문
%
% 마지막 줄이 중요합니다. **빠르기와 출렁임은 서로 다른 다이얼**입니다.
% $\omega_n$ 은 빠르기, $\zeta$ 는 출렁임을 담당합니다.
%% 5-1-6. 대역폭은 넓을수록 좋은가 — 맞바꿈
% 5-1-5절만 보면 "대역폭을 최대한 넓혀라" 로 읽힙니다. **아닙니다.**
% 대역폭을 정할 때 서로 반대로 당기는 요구가 셋 있습니다.
%
% **① 지령을 따라가려면 넓어야 합니다.**
% 대역폭은 "이 주파수까지는 따라간다" 는 경계입니다.
% 지령에 들어 있는 주파수 성분이 대역폭 밖에 있으면 그 성분은 못 따라갑니다.
% **계단응답의 상승시간을 반으로 줄이려면 대역폭을 약 두 배로 넓혀야 합니다**
% ($t_r \approx 1.8/\omega_{BW}$).
%
% **② 고주파 잡음을 막으려면 좁아야 합니다.**
% 센서 잡음은 대개 고주파입니다. 4-2절의 두 번째 근사를 떠올리십시오 —
% 고주파에서 $T \approx L$ 이므로, 대역폭 안에 있는 잡음은 **그대로 통과**합니다.
% 대역폭이 넓으면 그만큼 많은 잡음을 출력으로 들여보냅니다.
%
% **③ 부품 값이 올라갑니다.**
% 대역폭이 넓다는 것은 **빠른 센서 · 빠른 구동기 · 높은 샘플링**을 쓴다는 뜻입니다.
% $\omega_{BW}$ 를 열 배로 늘리려면 센서 대역도 열 배, 샘플링 주기도 열 배입니다.
% **부품 값은 대역폭과 함께 올라갑니다.** 설계서에 반드시 적히는 제약입니다.
%
% | 요구 | 방향 | 근거 |
% |---|---|---|
% | 지령 추종 · 빠른 응답 | **넓게** | $t_r \approx 1.8/\omega_{BW}$ |
% | 고주파 잡음 차단 | **좁게** | 고주파에서 $T \approx L$ |
% | 모델 오차에 대한 강건성 | **좁게** | 고주파에서 모델이 틀리기 쉽다 |
% | 부품 비용 · 샘플링 속도 | **좁게** | 빠른 부품은 비싸다 |
%
% **그래서 "충분히 빠르면서 필요 이상으로 넓지 않게" 가 정답입니다.**
% 사양에서 요구하는 상승시간으로 $\omega_{BW}$ 의 **하한**을 정하고,
% 잡음과 비용으로 **상한**을 정한 뒤 그 사이에서 고릅니다.
%
% 이 맞바꿈을 수식으로 보는 것이 다음 절입니다.
% 감도함수 $S$ 와 폐루프 $T$ 가 **더해서 항상 $1$** 이라는 사실이
