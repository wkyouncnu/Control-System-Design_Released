% | 오른쪽 그림 가로 방향 | 봉우리에 닿는 **시각**은 셋 다 다르다 | $\omega_n$ 은 **빠르기**만 바꾼다 |
%% 4-1-1. 이 공식이 어디서 오는가 (유도)
% 외울 필요는 없지만 **한 번은 따라가 보십시오.** 세 줄이면 됩니다.
%
% **1단계 — 계단응답을 적는다**
%
% 2차 표준형에 계단을 넣고 역라플라스 변환하면 이렇게 됩니다
% (부족감쇠 $0 < \zeta < 1$ 인 경우).
%
% $$y(t) = 1 - \frac{e^{-\zeta\omega_n t}}{\sqrt{1-\zeta^2}}\,
%          \sin\left(\omega_d t + \phi\right), \qquad
%   \omega_d = \omega_n\sqrt{1-\zeta^2}$$
%
% 여기서 $\phi = \arccos\zeta$ 입니다.
% 눈여겨볼 것은 **$e^{-\zeta\omega_n t}$ 가 점점 작아지는 봉투** 라는 점입니다.
% 진동이 그 봉투 안에서 잦아듭니다.
%
% **2단계 — 언제 가장 높은가**
%
% $y(t)$ 를 미분해서 $0$ 이 되는 첫 시각을 찾으면
%
% $$\frac{dy}{dt} = 0 \qquad \Rightarrow \qquad
%   t = T_p = \frac{\pi}{\omega_d}$$
%
% 즉 **첨두시간은 진동 반주기**입니다. 한 번 올라갔다가 꼭대기에 닿는 시각입니다.
%
% **3단계 — 그때 값이 얼마인가**
%
% $t = T_p$ 를 1단계 식에 넣으면 $\sin$ 항이 정리되어
%
% $$y(T_p) = 1 + e^{-\zeta\pi/\sqrt{1-\zeta^2}}$$
%
% 가 됩니다. 최종값이 $1$ 이므로 넘어선 몫은 뒤의 지수항뿐입니다.
%
% $$\%OS = \frac{y(T_p) - 1}{1}\times 100
%        = 100\,e^{-\zeta\pi/\sqrt{1-\zeta^2}}$$
%
% **왜 $\omega_n$ 이 사라졌는가**
%
% $\omega_n$ 은 지수의 어깨에 $\zeta\omega_n t$ 로 들어 있는데,
% $t = T_p = \pi/(\omega_n\sqrt{1-\zeta^2})$ 를 넣는 순간 $\omega_n$ 이 약분됩니다.
% **빠르기는 바뀌어도 모양은 안 바뀐다** 는 뜻입니다.
%
% 숫자로 확인해 봅니다.
fprintf('=== 유도한 공식이 맞는지 확인 ===\n');
fprintf('  zeta   %%OS(공식)   %%OS(실측)   Tp(공식)   Tp(실측)\n');
fprintf('  ----  ----------  ----------  ---------  ---------\n');
for z = [0.2 0.4 0.6 0.8]
    for w = 2
        Gx  = w^2/(s^2 + 2*z*w*s + w^2);
        ix  = stepinfo(Gx);
        os_f = 100*exp(-z*pi/sqrt(1-z^2));
        Tp_f = pi/(w*sqrt(1-z^2));
        fprintf('  %4.1f  %10.2f  %10.2f  %9.3f  %9.3f\n', ...
                z, os_f, ix.Overshoot, Tp_f, ix.PeakTime);
    end
end
fprintf('  --> 공식과 실측이 거의 같습니다\n\n');
% 봉투와 응답을 함께 그려 본다
z = 0.3; w = 2;
Gx = w^2/(s^2 + 2*z*w*s + w^2);
tx = (0:0.01:10)';
yx = step(Gx, tx);
env = exp(-z*w*tx)/sqrt(1-z^2);
plot(tx, yx, 'LineWidth', 2.5); hold on;
plot(tx, 1 + env, 'r--', 'LineWidth', 1.5);
plot(tx, 1 - env, 'r--', 'LineWidth', 1.5, 'HandleVisibility','off');
yline(1, 'k:'); grid on;
Tp = pi/(w*sqrt(1-z^2));
plot(Tp, 1 + exp(-z*pi/sqrt(1-z^2)), 'o', 'MarkerSize', 10, ...
     'MarkerFaceColor', 'm', 'MarkerEdgeColor', 'k');
xlabel('시간 [s]'); ylabel('출력');
legend('계단응답', '봉투 1 \pm e^{-\zeta\omega_n t}/\sqrt{1-\zeta^2}', ...
       '최종값', '첨두점 (공식으로 예측한 위치)', 'Location','northeast');
title('진동은 지수 봉투 안에서 잦아든다');
%% 4-2. 공식 둘 — 정착시간은 실수부만으로 정해진다
% $$t_s \approx \frac{4}{\zeta\omega_n}$$
%
% 분모 $\zeta\omega_n$ 이 바로 **극점 실수부의 크기**입니다.
%
% - 응답의 포락선이 $e^{-\zeta\omega_n t}$ 로 줄어든다
% - 이것이 $2\%$ 까지 줄어드는 시간이 $t_s$ 다
%
% 즉 정착시간 사양은 "극점이 얼마나 왼쪽에 있어야 하는가"를 정합니다.
%
% **주의** — 이 식은 포락선만 보고 만든 **근사식**입니다.
% 실제 정착시간은 이보다 짧게 나오는 경우가 많은데, 안전한 쪽으로 틀리므로
% 설계에 쓰기 좋습니다.
%
% 이번에는 반대로 **$\zeta$ 를 고정하고 실수부만** 바꿔 봅니다.
%
% ![정착시간은 극점의 실수부 하나로 정해진다](w04_ts_envelope.png)
%
% **그림 파일** `w04_ts_envelope.png` — `make_figures.m` 의 `fig_w04_ts_envelope`
%   · 다시 만들려면 `make_figures('w04_ts_envelope')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w04_ts_envelope`
% **직접 바꿔 보려면** — `W04_01_first_second_order.m` 의 **3절**에서
% $\omega_n$ 을 바꾸면 `stepinfo` 의 `SettlingTime` 이 따라 움직입니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 회색 띠 | 목표값의 $\pm 2\%$ ($0.98 \sim 1.02$) | 정착의 기준이 되는 띠 |
% | 왼쪽 점선 두 줄 (색마다 한 쌍) | $1 \pm e^{-\zeta\omega_n t}/\sqrt{1-\zeta^2}$ | **포락선.** 진동이 이 안에 갇혀 있다 |
% | 점선이 회색 띠에 들어가는 순간 | 그 색 곡선의 $t_s$ | 공식 $t_s \approx 4/|\text{실수부}|$ 가 여기서 나온다 |
% | 초록 곡선 (실수부 $-2.0$) | $t_s \approx 2.0$ s | 가장 빨리 끝난다 |
% | 빨간 곡선 (실수부 $-1.0$) | $t_s \approx 4.0$ s | 정확히 두 배 |
% | 파란 곡선 (실수부 $-0.5$) | $t_s \approx 8.0$ s | 또 두 배. **실수부에 반비례**한다 |
% | 세 곡선의 봉우리 높이 | 셋 다 같은 $25.4\%$ | $\zeta$ 를 $0.4$ 로 고정했으니 당연하다 |
% | 오른쪽 그림 세로 점선 세 개 | $-0.5$, $-1.0$, $-2.0$ | 각 색의 실수부 |
% | 오른쪽 그림 $\times$ 의 높이 | 초록이 가장 높다 ($\pm 4.58$) | 허수부는 제각각인데도 $t_s$ 는 실수부만 따른다 |
% | 오른쪽 그림 전체 | 점선이 **왼쪽**일수록 $t_s$ 가 짧다 | 빠르게 하려면 극점을 왼쪽으로 밀어야 한다 |
%
% 4-1 절과 이 절을 합치면 오늘의 두 문장이 완성됩니다.
%
% - **각도가 오버슈트를 정한다** ($\zeta = \cos\theta$)
% - **실수부가 정착시간을 정한다** ($t_s \approx 4/|\sigma|$)
%% 4-3. 두 공식을 함수로
% 이 과목에서는 `spec2pole` 함수로 만들어 두었습니다.
% 6, 7, 13주차에서 계속 씁니다.
%
% - **입력** — 허용 오버슈트 $[\%]$, 허용 정착시간 $[\mathrm{s}]$
% - **출력** — 필요한 $\zeta$ 최솟값, 필요한 $\omega_n$ 최솟값, 목표 극점
%
% 아래에서 요구를 넣고 확인해 봅니다.
P_OS = 10;  ts = 2;
[zeta_min, wn_min, s_target] = spec2pole(P_OS, ts);
fprintf('요구 : 오버슈트 %.0f %% 이하, 정착시간 %.1f s 이하\n', P_OS, ts);
fprintf('필요 : zeta >= %.4f,  wn >= %.4f rad/s\n', zeta_min, wn_min);
fprintf('목표 극점 : %.3f +- %.3fj  (실축과 %.1f 도)\n', ...
        real(s_target), imag(s_target), rad2deg(acos(zeta_min)));
info_t = stepinfo(wn_min^2/(s^2+2*zeta_min*wn_min*s+wn_min^2));
fprintf('확인 : 실제 오버슈트 %.2f %%, 실제 정착시간 %.2f s\n', ...
        info_t.Overshoot, info_t.SettlingTime);
