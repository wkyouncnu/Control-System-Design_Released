%% 7. Simulink 로 확인하기
% 모델 `W04_SecondOrder_Sweep.slx` 는 표준 2차 시스템을 **적분기 두 개**로
% 구현한 것입니다. 전달함수 블록을 쓰지 않은 이유가 있습니다.
%
% $$\ddot{y} = \omega_n^2 (r - y) - 2\zeta\omega_n \dot{y}$$
%
% 이 식을 그대로 블록으로 옮기면, **감쇠 경로의 게인 $2\zeta\omega_n$** 이
% $\zeta$ 가 들어가는 유일한 자리가 됩니다. 눈으로 보입니다.
%
% 확인할 것
%
% - 그 게인을 $0$ 으로 하면 $\zeta = 0$ 이 되어 영원히 진동한다
% - 즉 **감쇠란 속도를 되먹이는 일**이다
% - 이것이 7주차 미분제어 D 의 원리와 정확히 같다
%
% ![적분기 두 개로 펼치면 zeta 가 어디 있는지 보인다](w04_sim_blocks.png)
%
% **그림 파일** `w04_sim_blocks.png` — `common/dg_second_order.m` 의 `dg_second_order`
%   · 다시 만들려면 `make_figures('w04_sim_blocks')`
%
% **만드는 곳** — `common/dg_second_order.m` (`make_figures('w04_sim_blocks')`)
% **직접 확인해 보려면** — `W04_SecondOrder_Sweep.slx` 를 열면 **이 그림과
% 똑같은 블록 배치**가 그대로 있습니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 가운데 $1/s$ 상자 두 개 | 적분기 | 2차 시스템이니 적분기가 **둘**이다. 상태도 둘이다 |
% | 첫 적분기 왼쪽 신호 이름 | $d^2y/dt^2$ | 가속도. 여기가 운동방정식의 왼쪽이다 |
% | 두 적분기 사이 신호 이름 | $dy/dt$ | 속도. **되먹임을 여기서 따 간다** |
% | 마지막 신호 | $y$ | 위치 |
% | 왼쪽 주황 상자 | $\omega_n^2$ | 오차를 얼마나 세게 밀 것인가 |
% | 아래 초록 상자 | $2\zeta\omega_n$ | **$\zeta$ 가 들어가는 유일한 자리** |
% | 초록 상자로 들어오는 선의 출발점 | 두 적분기 **사이** | 즉 속도를 되먹인다 |
% | 초록 상자에서 나온 선이 도착하는 곳 | 두 번째 합산점의 $-$ | 속도에 비례해서 **뺀다** = 브레이크 |
% | 맨 아래 되먹임 선 | $y$ 를 맨 앞 합산점으로 | 위치 되먹임. 이건 1주차부터 있던 것 |
%
% **초록 상자 하나가 감쇠의 전부입니다.** 이 게인을 $0$ 으로 두면 브레이크가
% 없어져 영원히 진동합니다. 7주차에서 배울 미분제어 $D$ 가 정확히 이 자리에
