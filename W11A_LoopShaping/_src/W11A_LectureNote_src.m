% | 오른쪽 위 | 오차가 $\pm 0.05$ 안 | 설계 1단계에는 충분하다 |
% | 왼쪽 아래 | $\zeta = 0.707$ 에서 끊긴다 | 공명첨두가 그 위에서는 **없다** |
% | 오른쪽 아래 | PM 30/45/60 도의 오버슈트 | 사양 번역을 눈으로 |
%
% 오른쪽 아래의 세 점은 외워 둘 만합니다.
%
