%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 세로축 | $|L| = |PC|$ 를 dB 로 | 오늘 그리는 것은 **개루프** 크기다 |
% | 파란 띠 (왼쪽) | $|L|$ 이 크다 | 지령을 잘 따라가고 외란을 눌러 준다 |
% | 초록 띠 (가운데) | 0 dB 선을 지나간다 | **안정성이 결정되는 곳.** PM, GM 이 여기서 나온다 |
% | 빨간 띠 (오른쪽) | $|L|$ 이 작다 | 센서 잡음과 모르는 동특성을 피한다 |
% | 노란 동그라미 | $|L| = 0$ dB 인 점 | **교차주파수** $\omega_c$. 세 띠의 경계이자 속도의 척도 |
% | 가운데 띠의 기울기 | $-20$ dB/decade | 완만하게 지나가야 위상이 덜 깎인다 (3-2절) |
%
% 이 그림 한 장에 오늘 배울 것이 다 들어 있습니다. 왼쪽을 올리고 오른쪽을 내리고
% 가운데를 눕히는 것, 그것이 루프 성형입니다. 그런데 **왼쪽을 올리면 오른쪽도
% 같이 올라가려 하고**, 가운데를 급하게 꺾으면 위상여유가 사라집니다.
% 그 맞바꿈이 오늘의 주제입니다.
%
% 오늘의 계단
%
% - **1절** 루프이득 $L$ 과 두 식 $S$, $T$ — 그리고 $S+T=1$
% - **2절** 모터 예제 — 손으로 전부 되는 루프 하나
% - **3절** 네 숫자 : $\omega_c$, GM, PM, $\omega_b$ 와 서로의 관계
% - **4절** 주파수 띠 세 개 — 요구사항을 나눠 싣는다
% - **5절** 왜 되먹임인가 — 외란이 답한다
% - **6절** 공짜가 아니다 — 센서 잡음이라는 대가
%% 0-1. 가장 작은 예 — 샤워기를 얼마나 세게 돌리는가
% 1주차의 샤워기로 돌아갑니다. 물이 차면 손잡이를 온수 쪽으로 돌립니다.
% 여기서 **"얼마나 세게 돌리는가"** 가 바로 루프이득입니다.
%
% - 조금만 돌린다 ($|L|$ 작다) — 온도가 천천히 맞는다. 누가 옆에서 물을 틀면
%   (외란) 그대로 당한다
% - 많이 돌린다 ($|L|$ 크다) — 금방 맞는다. 외란도 금방 잡아낸다
% - 너무 많이 돌린다 — 뜨겁다 차갑다를 왕복한다. **발산한다**
%
% 그런데 중요한 것이 하나 더 있습니다. **빠르게 변하는 것에는 세게 반응하면
% 안 된다**는 것입니다. 수도관이 잠깐 덜컥거린 것(잡음)에 손잡이를 확 돌리면
% 오히려 온도가 엉망이 됩니다.
%
% 즉 **"천천히 변하는 것에는 세게, 빨리 변하는 것에는 약하게"** 반응해야 합니다.
% 이것이 바로 저주파 이득은 크게, 고주파 이득은 작게 라는 말입니다.
% 오늘 배우는 모든 것이 이 한 문장의 수학적 표현입니다.
%
% 숫자가 하나뿐인 예로 확인합니다. 루프이득이 $L = 100/s$ 라고 해 봅시다.
% 적분기 하나뿐인 가장 단순한 루프입니다.
L0 = 100/s;
T0 = feedback(L0, 1);             % 폐루프 (지령 -> 출력)
S0 = 1 - T0;                      % 오차가 남는 비율
w0 = [0.1 1 10 100 1000]';
tbl0 = table(w0, ...
    20*log10(squeeze(abs(freqresp(L0, w0)))), ...
    20*log10(squeeze(abs(freqresp(S0, w0)))), ...
    20*log10(squeeze(abs(freqresp(T0, w0)))), ...
    'VariableNames', {'w_rad_s', 'L_dB', 'S_dB', 'T_dB'})
%%
% 표를 읽는 법입니다.
%
% - $\omega = 0.1$ 에서 $|L| = 60$ dB (1000 배) 입니다. 이때 $|S| = -60$ dB,
%   즉 오차가 $1/1000$ 로 줄어듭니다. **루프이득이 크면 오차가 작다**
% - $\omega = 100$ 에서 $|L| = 0$ dB (딱 1배) 입니다. 여기가 교차주파수입니다
% - $\omega = 1000$ 에서 $|L| = -20$ dB 입니다. $|T| \approx -20$ dB,
%   즉 이 빠른 지령은 $1/10$ 밖에 못 따라갑니다. **루프이득이 작으면 못 따라간다**
%
% 왜 중요한가 — 표의 세 열이 완전히 맞물려 움직입니다. $L$ 을 정하면 $S$ 와 $T$ 가
% 따라 정해집니다. 그러니 **$L$ 의 모양만 설계하면 된다**는 것이 오늘의 전략입니다.
%% 1. 루프이득 $L$ — 한 바퀴 돌아오는 길
% 왜 필요한가 — 위에서 $L$, $S$, $T$ 라는 기호를 썼습니다. 세 개가 각각
% 무엇인지, 어디서 나온 것인지 정확히 정의하고 넘어가야 합니다.
%
% 1주차와 10주차에서 쓴 블록선도를 다시 봅니다.
%
% ![제어기가 있는 단위 되먹임 루프](loop_controller.png)
%
% **그림 파일** `loop_controller.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_controller')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 $r$ | 지령 (내가 원하는 값) | 모터라면 "분당 1000 회전" |
% | 원 안의 $+$, $-$ | $r$ 은 더하고 $y$ 는 뺀다 | 여기서 **오차** $e = r - y$ 가 생긴다 |
% | 첫 상자 $C(s)$ | 제어기 (내가 설계하는 것) | 출력은 **제어입력** $u = Ce$ |
% | 둘째 상자 $P(s)$ | 플랜트 (주어진 것, 못 바꾼다) | 출력은 $y = Pu$ |
% | 아래 선 | $y$ 를 합산점으로 되돌린다 | 상자가 없다 $\to$ **단위** 되먹임 ($H=1$) |
% | $C$ 와 $P$ 가 **직렬** | 신호가 차례로 지난다 | 그래서 $L = PC$ 로 **곱**이 된다 |
%
% 이 그림에서 신호를 따라가며 식을 세웁니다. 4-8-0 절의 네 단계 그대로입니다.
%
% $$e = r - y, \qquad u = C e, \qquad y = P u$$
%
% 뒤에서부터 대입합니다.
%
% $$y = P u = P C e = P C (r - y)$$
%
% $y$ 가 양변에 있으므로 한쪽으로 모읍니다. **$(1 + PC)$ 가 생기는 자리가 바로
% 여기입니다.**
%
% $$y + P C y = P C r \quad \Longrightarrow \quad (1 + P C)\, y = P C\, r$$
%
% 나눕니다.
%
% $$\frac{y}{r} = \frac{P C}{1 + P C}$$
%
% 여기서 분모에 반복해서 나오는 $PC$ 에 이름을 붙입니다. 이것이 **루프이득**입니다.
%
% $$L(s) \;=\; P(s)\,C(s)$$
%
% 이름의 뜻 — 합산점에서 출발해 $C$ 와 $P$ 를 지나 되먹임 선을 타고 **제자리로
% 돌아올 때까지 신호에 곱해지는 양**입니다. 한 바퀴(loop) 도는 동안의 이득입니다.
%
% | 이름 | 무엇인가 | 어디에 |
% |---|---|---|
% | 전방경로 | $r$ 에서 $y$ 까지 **한 번** 가는 길 | 분자 |
% | 루프이득 $L$ | 한 바퀴 돌아 **제자리로** 오는 길 | 분모 |
%
% 10주차에서 나이퀴스트 선도를 그린 것도, 보드 선도에서 여유를 읽은 것도
% 전부 이 $L(j\omega)$ 였습니다. 같은 것에 이제 이름을 붙인 것입니다.
%
% 왜 중요한가 — 설계에서 내가 만지는 것은 $C$ 하나뿐인데, 성능은 전부 $L = PC$ 로
% 결정됩니다. 그래서 "$C$ 를 어떻게 할까" 가 아니라 **"$L$ 을 어떤 모양으로
% 만들까"** 를 먼저 정하는 것이 순서가 맞습니다.
%% 1-1. 두 개의 이름 — 감도함수 $S$ 와 상보감도함수 $T$
% 왜 필요한가 — $y/r$ 하나만으로는 설계를 못 합니다. 오차는 얼마나 남는지,
% 외란은 얼마나 들어오는지도 알아야 합니다. 그 답이 같은 블록선도에서 두 개 더
% 나옵니다.
%
% **첫째, 오차는 얼마나 남는가.** 위의 유도에서 $e$ 를 구해 봅니다.
%
% $$e = r - y = r - P C e \quad \Longrightarrow \quad (1 + PC)\, e = r$$
%
% $$\frac{e}{r} = \frac{1}{1 + PC} = \frac{1}{1+L} \;\equiv\; S(s)$$
%
% 이것을 **감도함수**(sensitivity function) $S$ 라고 부릅니다.
%
% **둘째, 출력은 얼마나 따라가는가.** 방금 유도한 것입니다.
%
% $$\frac{y}{r} = \frac{PC}{1+PC} = \frac{L}{1+L} \;\equiv\; T(s)$$
%
% 이것을 **상보감도함수**(complementary sensitivity function) $T$ 라고 부릅니다.
% "상보" 는 $S$ 를 보완해서 1 을 만든다는 뜻입니다. 바로 다음 절에서 확인합니다.
%
% 기호를 정리해 둡니다. 오늘 내내 쓰는 네 개입니다.
%
% | 기호 | 이름 | 식 | 뜻 | 단위 |
% |---|---|---|---|---|
% | $P$ | 플랜트 | 주어진다 | 못 바꾸는 대상 | 시스템마다 다르다 |
% | $C$ | 제어기 | 내가 만든다 | 설계 변수 | 시스템마다 다르다 |
% | $L$ | 루프이득 | $PC$ | 한 바퀴 도는 동안의 이득 | 무차원 |
% | $S$ | 감도함수 | $\frac{1}{1+L}$ | 오차가 **남는** 비율 | 무차원 |
% | $T$ | 상보감도함수 | $\frac{L}{1+L}$ | 지령을 **따라가는** 비율 | 무차원 |
%
% $S$ 와 $T$ 는 둘 다 **무차원**입니다. 비율이기 때문입니다. 그래서 dB 로 그려서
% 0 dB 선과 비교하는 것이 의미가 있습니다. $|S| = -40$ dB 는 "오차가 1 % 로
% 줄었다" 는 뜻이고, $|T| = 0$ dB 는 "지령을 100 % 따라간다" 는 뜻입니다.
%
% 왜 "감도" 라는 이름인가 — 1주차 8절에서 모델오차에 대한 민감도를 구했을 때
% 똑같은 $\frac{1}{1+KG}$ 가 나왔습니다. 플랜트가 10 % 틀렸을 때 폐루프 성능이
% 몇 % 변하는가 — 그 비율이 $S$ 입니다. 외란이 들어오는 비율과 모델오차에
% 민감한 정도가 **같은 식**이라는 것이 되먹임 이론의 출발점입니다.
%% 1-2. $S + T = 1$ — 오늘 가장 중요한 한 줄
% 왜 필요한가 — 설계자는 보통 이렇게 바랍니다. "오차도 작고($|S|$ 작고)
% 추종도 잘 되게($|T|$ 크게) 해 주세요." 그런데 그것은 **원하는 것이 아니라
% 자동으로 따라오는 것**입니다. 더 중요한 것은 **둘을 동시에 작게 만들 수 없다**는
% 사실입니다. 그 이유가 이 한 줄에 있습니다.
%
% 유도는 두 줄입니다. 분모가 같으니 그냥 더합니다.
%
% $$S + T = \frac{1}{1+L} + \frac{L}{1+L} = \frac{1 + L}{1 + L} = 1$$
%
% **모든 주파수에서, 어떤 $P$ 와 $C$ 에 대해서도** 성립합니다. 설계로 깰 수
% 없습니다. 분모가 같은 두 분수를 더한 것이니 당연한데, 결과는 전혀 당연하지
% 않습니다.
%
% 손으로 한 번 확인합니다. 위의 $L = 100/s$ 에 $\omega = 100$ 을 넣습니다.
%
% $$L(j100) = \frac{100}{j100} = -j$$
%
% $$S = \frac{1}{1-j} = \frac{1+j}{2}, \qquad T = \frac{-j}{1-j} = \frac{-j(1+j)}{2} = \frac{1-j}{2}$$
%
% $$S + T = \frac{1+j}{2} + \frac{1-j}{2} = \frac{2}{2} = 1$$
%
% 허수부가 서로 지워지고 실수부만 남아 **정확히 1** 이 됩니다.
%
% MATLAB 으로 네 주파수에서 검산합니다.
wchk = [0.1 1 10 100]';
Schk = squeeze(freqresp(S0, wchk));
Tchk = squeeze(freqresp(T0, wchk));
table(wchk, Schk, Tchk, Schk + Tchk, ...
    'VariableNames', {'w_rad_s', 'S', 'T', 'S_plus_T'})
%%
% 마지막 열이 전부 정확히 $1 + 0i$ 입니다. 반올림 오차조차 없습니다.
%
% ![한쪽을 작게 하면 다른 쪽은 1 에 가까워진다](w11a_s_plus_t.png)
%
% **그림 파일** `w11a_s_plus_t.png` — `make_figures.m` 의 `fig_w11a_s_plus_t`
%   · 다시 만들려면 `make_figures('w11a_s_plus_t')`
%
% **직접 확인해 보려면** — `W11A_01_L_S_T.m` 의 **2절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림의 파란 선 | 저주파에서 $-60$ dB 아래 | $|S|$ 작다 $\to$ 오차가 거의 없다 |
% | 왼쪽 그림의 주황 선 | 저주파에서 0 dB | $|T| = 1$ $\to$ 지령을 100 % 따라간다 |
% | 두 선이 **교차하는 점** | 둘 다 $-3$ dB 근처 | 여기가 $\omega_c$ 근처다 (3-1절) |
% | 고주파 | 파란 선 0 dB, 주황 선 급강하 | 오차가 100 %, 추종은 0 % |
% | 오른쪽 그림 | 빨간 선 위에 딱 붙어 있다 | $|S+T| = 0$ dB, 즉 **정확히 1** |
%
% 이 제약을 어떻게 사는가 — **주파수마다 다른 것을 요구하면 됩니다.**
%
% - 저주파에서는 $|S|$ 를 작게 (오차와 외란을 잡겠다). 그러면 $|T| \approx 1$ 이
%   되는데, 저주파 지령은 어차피 따라가고 싶은 것이니 **문제가 아니라 덕입니다**
% - 고주파에서는 $|T|$ 를 작게 (잡음을 막겠다). 그러면 $|S| \approx 1$ 이
%   되는데, 고주파 지령은 어차피 따라갈 생각이 없으니 **괜찮습니다**
% - 중간주파수에서는 둘 다 1 근처입니다. 여기는 포기하는 대신 **안정성**을 챕니다
%
% 왜 중요한가 — 4절의 "주파수 띠 세 개" 가 바로 이 결론입니다.
% 그리고 11B 주차에서 설계할 때, 사양을 모든 주파수에서 동시에 만족시키려 하지
% 않고 **띠별로 나눠 배정**하는 이유도 이것입니다.
%% 1-3. $|L|$ 이 크면, 작으면 — 근사식 두 개
% 왜 필요한가 — $S$ 와 $T$ 를 매번 계산하기는 번거롭습니다. 그런데 극단적인
% 두 경우에는 암산으로 됩니다. 설계할 때 실제로 쓰는 것은 이 두 근사식입니다.
%
% **첫째, $|L| \gg 1$ (저주파) 일 때.** 분모의 1 을 무시합니다.
%
% $$S = \frac{1}{1+L} \approx \frac{1}{L}, \qquad T = \frac{L}{1+L} \approx \frac{L}{L} = 1$$
%
% dB 로 쓰면 더 쓰기 좋습니다. $|S|_{dB} \approx -|L|_{dB}$ 입니다.
% **보드 선도의 $|L|$ 곡선을 0 dB 선 기준으로 뒤집으면 그게 $|S|$ 입니다.**
%
% **둘째, $|L| \ll 1$ (고주파) 일 때.** 분모의 $L$ 을 무시합니다.
%
% $$S = \frac{1}{1+L} \approx 1, \qquad T = \frac{L}{1+L} \approx L$$
%
% dB 로 $|T|_{dB} \approx |L|_{dB}$ 입니다. **고주파에서는 $|T|$ 가 $|L|$ 과
% 그냥 같습니다.**
%
% 정리하면 이렇습니다. 이 표가 오늘의 핵심 도구입니다.
%
% | 주파수 영역 | $|L|$ | $|S|$ | $|T|$ | 읽는 법 |
% |---|---|---|---|---|
% | 저주파 | $\gg 1$ (크다) | $\approx 1/|L|$ (작다) | $\approx 1$ | $|L|$ 을 뒤집으면 $|S|$ |
% | $\omega = \omega_c$ | $= 1$ (0 dB) | $\approx 1$ 근처 | $\approx 1$ 근처 | 여기서 안정성이 결정된다 |
% | 고주파 | $\ll 1$ (작다) | $\approx 1$ | $\approx |L|$ (작다) | $|L|$ 이 그대로 $|T|$ |
%
% 근사가 실제로 맞는지 수치로 확인합니다. $L = 100/s$ 에서 $\omega = 1$ (저주파,
% $|L| = 40$ dB) 과 $\omega = 10^4$ (고주파, $|L| = -40$ dB) 를 봅니다.
wlo = 1;  whi = 1e4;
LdB_lo = 20*log10(abs(freqresp(L0, wlo)));
LdB_hi = 20*log10(abs(freqresp(L0, whi)));
cmp = table( ...
    {'저주파 w=1'; '고주파 w=1e4'}, ...
    [LdB_lo; LdB_hi], ...
    [20*log10(abs(freqresp(S0, wlo))); 20*log10(abs(freqresp(T0, whi)))], ...
    [-LdB_lo; LdB_hi], ...
    'VariableNames', {'영역', 'L_dB', '실제_dB', '근사_dB'})
%%
% 저주파에서 $|S|$ 는 $-40.0$ dB 이고 근사식 $-|L|_{dB}$ 도 $-40.0$ dB 입니다.
% 고주파에서 $|T|$ 는 $-40.0$ dB 이고 근사식 $|L|_{dB}$ 도 같습니다.
% 소수 첫째 자리까지 맞습니다.
%
% 왜 중요한가 — 설계할 때 "저주파 외란을 40 dB 줄이고 싶다" 는 요구가 오면,
% $|S| \le -40$ dB 를 풀 필요 없이 그냥 **$|L| \ge 40$ dB** 로 바꿔 읽으면
% 됩니다. 사양이 $L$ 에 대한 조건으로 번역되는 것, 이것이 루프 성형의 실용적
% 가치입니다.
%% 2. 모터 예제 — 손으로 전부 되는 루프 하나
% 왜 필요한가 — 지금까지는 $L = 100/s$ 라는 가짜 루프를 썼습니다. 이제 실제
% 플랜트에 실제 제어기를 달아 봅니다. 그런데 놀랍게도 **그 결과가 똑같이
% $100/s$** 가 됩니다. 담당교수 강의자료의 모터 예제를 그대로 가져온 것입니다.
%
% 플랜트는 DC 모터 속도 전달함수입니다.
%
% $$P(s) = \frac{0.1}{0.5 s + 2}$$
Pm = 0.1/(0.5*s + 2);
table([dcgain(Pm); pole(Pm)], 'VariableNames', {'플랜트_DC이득과_극점'})
%%
% 플랜트의 DC 이득은 $0.1/2 = 0.05$ 이고 극점은 $-2/0.5 = -4$ 입니다.
% 둘 다 암산으로 나옵니다.
%
% **제어기를 달기 전에 안 달아 본다.** 담당교수 강의자료가 여기서 시작합니다.
% 가장 단순한 제어기, 즉 $C = 1$ (아무것도 안 하는 비례제어기) 을 놓고 목표
% 속도 1 을 줘 봅니다.
C1 = 1;
L1 = Pm*C1;
T1 = L1/(1 + L1);
table(dcgain(L1), dcgain(T1), 1 - dcgain(T1), 20*log10(dcgain(T1)), ...
    'VariableNames', {'L_0', 'T_0', '정상상태오차', 'T_0_dB'})
%%
% 목표가 1 인데 **출력이 $0.0476$ 밖에 안 나옵니다.** 오차가 $95.2\,\%$ 입니다.
% 쓸 수 없는 제어기입니다.
%
% 왜 이렇게 되는지는 1-3 절의 근사식으로 바로 설명됩니다. $s = 0$ 에서
%
% $$|L(0)| = |P(0)| \cdot 1 = 0.05 \;\ll\; 1$$
%
% 이므로 $|S| \approx 1$ 입니다. $S$ 가 1 이라는 것은 **오차가 하나도 줄지
% 않는다**는 뜻입니다. 실제로 $T(0) = L/(1+L) = 0.05/1.05 = 0.0476$ 이고,
% 이것을 dB 로 읽으면 $-26.4$ dB 입니다. 담당교수 강의자료는 이 값을
% `mag2db` 로 읽어 "저주파 이득이 모자란다" 는 것을 한눈에 보여 줍니다.
%
% 처방은 하나뿐입니다. **저주파에서 $|L|$ 을 키운다.** 가장 확실한 방법은
% $s = 0$ 에서 이득이 무한대가 되는 것, 즉 **적분기**를 넣는 것입니다.
% 그것이 PI 제어기입니다. 11B 주차에서 설계하는 방법을 배웁니다. 오늘은
% 주어진 것으로 봅니다.
%
% $$C(s) = \frac{500 s + 2000}{s} = \frac{500(s+4)}{s}$$
Cm = (500*s + 2000)/s;
Lm = Pm*Cm;
%%
% 이제 $L$ 을 손으로 곱해 봅니다. **여기서 재미있는 일이 일어납니다.**
%
% $$L = PC = \frac{0.1}{0.5 s + 2} \cdot \frac{500 s + 2000}{s}$$
%
% 분자와 분모를 각각 인수분해합니다.
%
% $$500 s + 2000 = 500 (s + 4), \qquad 0.5 s + 2 = 0.5 (s + 4)$$
%
% $(s+4)$ 가 **위아래에 똑같이 있습니다.** 약분됩니다.
%
% $$L = \frac{0.1 \cdot 500 (s+4)}{0.5 (s+4) \cdot s} = \frac{50}{0.5\, s} = \frac{100}{s}$$
%
% 즉 **제어기의 영점이 플랜트의 극점을 정확히 지웁니다.** 남는 것은 적분기
% 하나뿐입니다. 0-1 절에서 쓴 $L = 100/s$ 가 바로 이것이었습니다.
Lm_min = minreal(Lm);
Lm_min
%%
% `minreal` 이 약분을 수행해 $100/s$ 를 확인해 줍니다.
%
% - **원리** — 분자와 분모에 공통으로 있는 인수를 찾아 지웁니다
% - **입력** — 전달함수. 둘째 인수로 허용오차를 줄 수 있습니다
% - **출력** — 약분된 전달함수
% - **주의** — 실제 시스템에서 극점과 영점이 **정확히** 같은 일은 없습니다.
%   모터의 시정수가 조금 틀리면 약분이 안 되고 $L$ 에 아주 느린 극영점 쌍이
%   남습니다. 설계용 계산에는 쓰되 **실물이 그렇다고 믿으면 안 됩니다**
% - **예제** — 위의 `minreal(Lm)` 이 그 예입니다
%
% 왜 중요한가 — 이 약분 덕분에 오늘 쓰는 모든 숫자를 **손으로 검산할 수
% 있습니다.** 그래서 이 예제를 골랐습니다. 5-3 절에서 Simulink 결과와 대조할 때
% 그 가치가 드러납니다.
%% 2-1. 손으로 $|S(j\omega)|$ 를 쓴다
% 왜 필요한가 — $L = 100/s$ 이므로 $S$ 와 $T$ 도 1차식입니다. 공식을 손으로
% 완전히 써 둘 수 있습니다. 5절에서 이 식에 숫자를 넣어 외란 감쇠량을 계산합니다.
%
% $$S = \frac{1}{1+L} = \frac{1}{1 + \frac{100}{s}} = \frac{s}{s + 100}$$
%
% $$T = \frac{L}{1+L} = \frac{\frac{100}{s}}{1 + \frac{100}{s}} = \frac{100}{s + 100}$$
%
% 분수 안의 분수를 정리하는 자리를 한 줄 더 보입니다. 위아래에 $s$ 를 곱한 것입니다.
%
% $$\frac{1}{1 + \frac{100}{s}} = \frac{1 \cdot s}{\left(1 + \frac{100}{s}\right) s} = \frac{s}{s + 100}$$
%
% $S$ 는 **고역통과**(미분기 모양), $T$ 는 **저역통과**입니다. 둘의 꺾이는
% 주파수는 똑같이 $100$ rad/s 입니다.
%
% 주파수응답의 크기를 씁니다. $s = j\omega$ 를 넣습니다.
%
% $$|S(j\omega)| = \left|\frac{j\omega}{j\omega + 100}\right| = \frac{\omega}{\sqrt{\omega^2 + 100^2}}$$
%
% $$|T(j\omega)| = \frac{100}{\sqrt{\omega^2 + 100^2}}$$
%
% 두 식을 제곱해서 더하면 1 이 됩니다. $|S|^2 + |T|^2 = 1$ 입니다.
% (주의 — 이것은 $S+T=1$ 과 **다른** 식이고, $L$ 이 순허수일 때만 성립하는
% 우연입니다. 일반적으로 성립하는 것은 $S+T=1$ 뿐입니다.)
Sm = 1/(1 + Lm_min);
Tm = Lm_min/(1 + Lm_min);
wv = [1 10 100 1000]';
hand_S = wv./sqrt(wv.^2 + 100^2);
