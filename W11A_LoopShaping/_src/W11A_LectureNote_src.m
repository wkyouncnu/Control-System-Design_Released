%% 3-4. 위상여유와 감쇠비 — 공식은 없지만 규칙은 있다
% 왜 필요한가 — 사양은 보통 시간영역으로 옵니다. "오버슈트 20 % 이하".
% 그런데 설계는 주파수영역에서 합니다. 둘을 잇는 다리가 **PM 과 $\zeta$ 의
% 관계**입니다.
%
% 먼저 분명히 해 둘 것 — **PM 과 $\zeta$ 사이에 닫힌 형태의 공식은 없습니다.**
% $\omega_c$ 식을 PM 정의에 넣으면 이런 식이 나옵니다.
%
% $$\text{PM} = 90^\circ - \arctan\frac{\sqrt{\sqrt{1+4\zeta^4} - 2\zeta^2}}{2\zeta}$$
%
% 이 식을 $\zeta$ 에 대해 뒤집을 수가 없습니다. 그래서 **어림셈**을 씁니다.
% 그런데 다행히 이 관계가 거의 직선입니다.
%
% $$\zeta \;\approx\; \frac{\text{PM}}{100}$$
%
% PM 을 도(degree) 로 넣습니다. PM 50 도면 $\zeta \approx 0.5$, PM 70 도면
% $\zeta \approx 0.7$ 입니다. 외우기 쉽습니다.
%
% 얼마나 맞는지 직접 재 봅니다.
rule1 = pm_mea/100;
err1  = rule1 - zv;
table(zv, pm_mea, rule1, err1, ...
    'VariableNames', {'zeta_실제', 'PM_deg', 'PM_나누기_100', '오차'})
