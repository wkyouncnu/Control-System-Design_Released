% 오차가 전 구간에서 $\pm 0.06$ 안입니다. **설계 1단계의 값을 정하는 데는
% 충분합니다.** 정확한 값은 설계 후 `stepinfo` 로 재면 됩니다.
%
% 참고 — 문헌에는 중간 구간용으로 $\zeta \approx 0.01\,(\text{PM} - 4^\circ)$ 라는
% 보정식도 나옵니다. PM 15 도에서 55 도 사이에서 더 맞다고 되어 있지만,
% 위 표의 2차 표준루프에서는 $\text{PM}/100$ 이 더 맞습니다. 루프의 형태에 따라
% 달라지므로 **어느 쪽이든 어림셈이라는 것을 잊지 않는 것**이 중요합니다.
%
% 어림셈이 통하는 조건도 적어 둡니다.
%
% - 최소위상 시스템 (우반평면 영점이 없다)
% - **지배 극점 쌍**이 뚜렷하다 (다른 극점이 훨씬 멀리 있다)
% - $\omega_c$ 근처에서 $|L|$ 이 $-20$ dB/decade 로 완만하다
%
% 조건을 벗어나면 PM 은 넉넉한데 응답이 이상한 일이 생깁니다. 그래서
% **주파수영역에서 설계하고 시간영역에서 확인하는** 두 단계가 항상 필요합니다.
%
% 어긋나는 방식이 구체적으로 세 가지 있습니다. 세 루프 모두 PM 은 $40 \sim 52$ 도로
% 비슷하게 좋아 보입니다. 어림셈으로 얻은 $\zeta$ 에 4주차의 오버슈트 공식을
% 넣어 **예측**을 만들고, 실제 계단응답의 **실측**과 맞대 본 것입니다.
%
% | 루프 $L$ | PM | 예측 %OS | 실측 %OS | 무엇이 어긋났나 |
% |---|---|---|---|---|
% | $\frac{100}{s(s+10)}$ | 51.8 도 | 14.9 % | 16.3 % | 어긋나지 않았다 (비교 기준) |
% | $\frac{40(s+2)}{s^2(s+10)}$ | 41.7 도 | 23.7 % | 37.2 % | **폐루프 영점**이 오버슈트를 1.6 배로 키웠다 |
% | $\frac{5(s+1)}{s(s^2+0.4s+100)}$ | 48.3 도 | 17.7 % | 0.0 % | **숨은 공진** ($\zeta = 0.017$) 이 끝없이 흔들린다 |
%
% 셋째 줄이 가장 위험합니다. 오버슈트가 0 이라서 계단응답만 짧게 보면 완벽해
% 보이는데, 폐루프 극점 중 감쇠비가 $0.017$ 인 것이 하나 있어서 $40$ 초가 지나도
% 잔물결이 남습니다. **PM 은 교차주파수 한 점만 보는 숫자**이므로, 교차주파수에서
% 멀리 떨어진 공진은 PM 에 전혀 나타나지 않습니다.
%
% 확인하는 방법은 두 가지입니다.
%
% - `damp(T)` 로 폐루프 극점의 감쇠비를 **전부** 본다. 가장 작은 값이 기준이다
% - 계단응답을 **충분히 길게** 본다 (위 셋째 루프는 $40$ 초가 필요하다)
%
% 실습은 `W11A_03_pm_zeta.m` 의 **3절**입니다. 세 응답을 나란히 그려 줍니다.
%% 3-4-1. 사양을 번역하는 사슬 — 오버슈트에서 PM 까지
% 왜 필요한가 — 이제 조각이 다 모였습니다. 시간 사양을 주파수 목표로 바꾸는
% 전체 사슬을 한 번에 이어 봅니다. 11B 주차에서 매번 쓰는 절차입니다.
%
% 사슬은 네 칸입니다.
%
% | 단계 | 쓰는 식 | 근거 |
% |---|---|---|
% | 오버슈트 $\to \zeta$ | $\zeta = \frac{-\ln(\%OS/100)}{\sqrt{\pi^2 + \ln^2(\%OS/100)}}$ | 4주차 |
% | $\zeta \to$ PM | $\text{PM} \approx 100\,\zeta$ | 3-4절 |
% | 정착시간 $\to \omega_n$ | $\omega_n \approx \frac{4}{\zeta\, t_s}$ | 4주차 (2 % 기준) |
% | $\omega_n \to \omega_c$ | $\omega_c = \omega_n\sqrt{\sqrt{1+4\zeta^4} - 2\zeta^2}$ | 3-3-1절 |
%
% 예제로 "오버슈트 10 % 이하, 정착시간 0.5 초 이하" 를 번역합니다.
OS_req = 10;  ts_req = 0.5;
lnOS  = log(OS_req/100);
z_req = -lnOS/sqrt(pi^2 + lnOS^2);
PM_req = 100*z_req;
wn_req = 4/(z_req*ts_req);
wc_req = wn_req*sqrt(sqrt(1 + 4*z_req^4) - 2*z_req^2);
wb_req = wn_req*sqrt(1 - 2*z_req^2 + sqrt(2 - 4*z_req^2 + 4*z_req^4));
table(z_req, PM_req, wn_req, wc_req, wb_req, ...
    'VariableNames', {'zeta', 'PM_deg', 'wn', 'wc_목표', 'wb_예상'})
%%
% 결과를 설계 목표로 쓰면 이렇게 읽습니다.
%
% - **위상여유 59 도 이상** 확보할 것
% - **교차주파수 11 rad/s 이상** 으로 밀 것
%
% 번역이 맞는지 거꾸로 확인합니다. 이 $\zeta$, $\omega_n$ 으로 2차 루프를 만들어
% 실제 오버슈트와 정착시간을 재 봅니다.
Lreq = wn_req^2/(s*(s + 2*z_req*wn_req));
si = stepinfo(feedback(Lreq, 1));
[~, pm_chk, ~, wc_chk] = margin(Lreq);
table(si.Overshoot, si.SettlingTime, pm_chk, wc_chk, ...
    'VariableNames', {'실제_OS_퍼센트', '실제_ts_초', '실제_PM_deg', '실제_wc'})
