% 읽는 법
%
% - $\zeta$ 가 $0.6$ 까지는 식과 실측이 소수 넷째 자리까지 같습니다
% - $\zeta = 0.707$ 은 **경계**입니다. 식은 $\omega_r = 0.0174$ 라는 아주 작은
%   값을 주고 실측은 0 을 줍니다. 봉우리가 막 사라지는 지점이라 그렇습니다
% - $\zeta = 0.8$ 은 빈칸(`NaN`)입니다. 봉우리가 없으니 $M_r$ 은 그냥 1 (0 dB) 입니다
%
% **공식에는 유효 구간이 붙어 있습니다.** 구간을 적어 두지 않은 공식을
% 그대로 계산해서 숫자가 나왔다고 믿는 것이 가장 흔한 실수입니다.
%
% 실용적 기준 — **$M_r \le 2$ (6 dB) 이하로 유지**합니다. 이것은 $\zeta \ge 0.26$,
% 즉 PM 26 도 이상에 해당합니다. $M_r$ 이 크면 그 주파수의 외란이나 잡음이
% **증폭되어** 나옵니다.
%
% 세 가지 날카로움 지표를 한 표에 모아 둡니다. 전부 같은 것을 다르게 본 것입니다.
%
% | 지표 | 어디서 보는가 | 좋은 값 | 서로의 관계 |
% |---|---|---|---|
% | 오버슈트 %OS | 시간영역 계단응답 | $\le 20$ % | $\zeta$ 가 결정 |
% | 공명첨두 $M_r$ | 폐루프 $|T|$ 의 봉우리 | $\le 2$ (6 dB) | $\zeta$ 가 결정 |
% | 위상여유 PM | 개루프 $L$ 의 $\omega_c$ | $\ge 45$ 도 | $\zeta \approx$ PM/100 |
%% 4. 주파수 띠 세 개 — 요구사항을 나눠 싣는다
% 왜 필요한가 — 1-2 절에서 $S + T = 1$ 때문에 모든 것을 동시에 가질 수 없다는
% 것을 봤습니다. 해법은 **주파수마다 다른 것을 요구하는 것**이었습니다.
% 이제 그것을 구체적인 설계 지침으로 정리합니다. 담당교수 강의자료의
% 세 영역 구분을 그대로 따릅니다.
%
% 0 절의 그림을 다시 봅니다. 그 세 띠가 이것입니다.
%
% | 띠 | 주파수 범위 | 요구사항 | $|L|$ 을 어떻게 | 담당 보상기 (11B) |
% |---|---|---|---|---|
% | **저주파** | $\omega \ll \omega_c$ | 지령 추종, 정상상태오차, 외란 억제 | **크게** (높은 이득) | PI, Lag, 적분기 |
% | **중간** | $\omega \approx \omega_c$ | 상대안정성 (PM, GM), 강인성 | **완만하게** ($-20$ dB/dec) | Lead, PD |
% | **고주파** | $\omega \gg \omega_c$ | 센서 잡음 차단, 모르는 동특성 회피 | **작게** (빠르게 감쇠) | 저역통과 필터 |
%
% 각 띠를 하나씩 봅니다.
%
% **저주파 띠 — $|L|$ 을 크게.** 1-3 절에서 $|S| \approx 1/|L|$ 이었습니다.
% 저주파 외란을 40 dB 줄이려면 그 주파수에서 $|L| \ge 40$ dB 가 필요합니다.
% 정상상태오차도 같은 이야기입니다. $s \to 0$ 에서 $|L| \to \infty$ 면
% ($=$ 적분기가 있으면) 계단 오차가 0 이 됩니다 (5주차).
%
% **중간 띠 — 완만하게.** 3-2 절에서 기울기가 PM 을 결정한다고 했습니다.
% 저주파에서 올린 이득을 고주파로 내려야 하는데, **그 내려오는 길이
% $\omega_c$ 를 지나갈 때만 완만하면** 됩니다. 저주파에서 아무리 급하게
% 올려 놓았어도 괜찮습니다.
%
% **고주파 띠 — 작게.** 1-3 절에서 $|T| \approx |L|$ 이었습니다.
% 6절에서 보겠지만 센서 잡음은 $T$ 를 타고 들어옵니다. 그러니 고주파에서
% $|L|$ 을 떨어뜨리는 것이 곧 잡음 차단입니다. 그리고 모델에 없는 고주파
% 동특성 (모터 축의 비틀림 진동 같은 것) 이 있어도 $|L|$ 이 작으면
% 불안정해지지 않습니다.
%
% 모터 루프가 이 지침을 만족하는지 확인합니다.
chk_w = [1 10 100 1000 1e4]';
chk = table(chk_w, ...
    20*log10(squeeze(abs(freqresp(Lm_min, chk_w)))), ...
    20*log10(squeeze(abs(freqresp(Sm, chk_w)))), ...
    20*log10(squeeze(abs(freqresp(Tm, chk_w)))), ...
    'VariableNames', {'w_rad_s', 'L_dB', 'S_dB', 'T_dB'})
%%
% 읽으면 이렇습니다.
%
% - $\omega = 1$ : $|L| = 40$ dB 로 충분히 크다. 저주파 외란을 $1/100$ 로 줄인다
% - $\omega = 100$ : 0 dB 통과. 기울기가 $-20$ dB/dec 이므로 PM 90 도
% - $\omega = 10^4$ : $|T| = -40$ dB. 이 주파수 잡음은 $1/100$ 만 들어온다
%
% 세 띠 모두 합격입니다. 좋은 루프입니다.
%
% 왜 중요한가 — 11B 주차의 종합 설계에서 사양 다섯 개를 다섯 단계로 나눠
% 맞추는데, **그 나눔의 기준이 바로 이 세 띠**입니다. 어떤 사양이 어느 띠의
% 문제인지 알아보는 것이 설계의 첫걸음입니다.
%% 5. 왜 되먹임인가 — 외란이 답한다
% 왜 필요한가 — 1주차에서 "되먹임을 하면 좋다" 고 배웠습니다. 그런데 **왜**
% 좋은지 가장 선명하게 답하는 것이 외란입니다. 그리고 그 답은 주파수영역에서만
% 제대로 보입니다.
%
% 먼저 외란이 **어디로 들어오는가** 를 구분해야 합니다. 들어오는 자리가 다르면
% 전달함수가 달라집니다.
%
% ![외란이 플랜트 입력에 들어가는 폐루프](loop_disturbance.png)
%
% **그림 파일** `loop_disturbance.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_disturbance')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | $C$ 와 $P$ 사이의 원 | $u$ 와 $d$ 가 **여기서 만난다** | 플랜트가 받는 것은 $u + d$ |
% | 그 원의 부호 | 둘 다 $+$ | 외란이 제어입력에 **더해진다** |
% | 합산점 뒤 신호 | $u + d$ | 유도의 출발점 |
% | $d$ 의 물리적 정체 | 모터라면 부하 토크, 바람, 마찰 | 내가 모르는 입력 |
%
% 이 자리에 들어오는 것을 **입력외란**(input disturbance) $d_i$ 라고 합니다.
% 출력 쪽에 바로 더해지는 것은 **출력외란**(output disturbance) $d_o$ 입니다.
% 둘을 나눠서 봅니다.
%% 5-1. 출력외란 — 전달함수가 바로 $S$ 다
% 출력에 직접 더해지는 경우입니다. 센서가 보는 값이 $y = (\text{플랜트 출력}) + d_o$
% 인 상황입니다. 측정 오프셋이나 외부에서 밀리는 힘이 이에 해당합니다.
%
% 신호를 따라갑니다. 지령은 0 으로 둡니다 ($r = 0$, 외란만 보기 위해).
%
% $$y = P u + d_o, \qquad u = C e, \qquad e = -y$$
%
% 대입합니다.
%
% $$y = P C (-y) + d_o$$
%
% $y$ 를 한쪽으로 모읍니다.
%
% $$(1 + PC)\, y = d_o \quad \Longrightarrow \quad \frac{y}{d_o} = \frac{1}{1+L} = S$$
%
% **출력외란에 대한 전달함수가 감도함수 $S$ 그 자체입니다.** 그래서 $S$ 를
% 작게 만드는 것이 곧 외란 억제입니다. 1-2 절에서 $|S|$ 를 저주파에서 작게
% 하라고 한 이유가 이것입니다.
%
% 개루프와 비교하면 차이가 분명합니다. 되먹임이 없으면 $e = r$ 이므로
% $u = Cr$ 이고, $y = PCr + d_o$ 입니다. 즉
%
% $$\left.\frac{y}{d_o}\right|_{\text{개루프}} = 1$$
%
% **외란이 그대로 출력에 나옵니다.** 제어기를 어떻게 설계해도 1 입니다.
%
% | 구조 | $y/d_o$ | 저주파에서 | 설계로 바꿀 수 있는가 |
% |---|---|---|---|
% | 개루프 | $1$ | $1$ (그대로) | **못 바꾼다** |
% | 폐루프 | $S = \frac{1}{1+L}$ | $\approx 1/|L|$ (작다) | $|L|$ 을 올리면 작아진다 |
%
% 담당교수 강의자료의 표현을 옮기면 "$L(s)$ 가 크면 $1/L(s)$ 가 작은 수가 되므로
% 외란이 잘 억제된다" 그리고 "고주파 영역의 외란은 억제할 수 없다" 입니다.
% 후자는 고주파에서 $|L| < 1$ 이므로 $|S| \approx 1$ 이 되기 때문입니다.
%% 5-2. 입력외란 — 개루프는 손쓸 방법이 아예 없다
% 왜 필요한가 — 출력외란은 개루프에서 $1$ 이라 좀 추상적입니다. 입력외란이
% 되먹임의 가치를 훨씬 선명하게 보여 줍니다. 그리고 실제 시스템의 외란은 대부분
% 입력 쪽에 있습니다 (부하 토크, 바람, 마찰).
%
% 위 그림의 구조입니다. 플랜트가 받는 것은 $u + d_i$ 입니다. $r = 0$ 으로 둡니다.
%
% $$y = P(u + d_i), \qquad u = C e = -C y$$
%
% 대입합니다.
%
% $$y = P(-Cy + d_i) = -PC y + P d_i$$
%
% $y$ 를 모읍니다.
%
% $$(1 + PC)\, y = P\, d_i \quad \Longrightarrow \quad \frac{y}{d_i} = \frac{P}{1 + L} = P\,S$$
%
% 개루프는 어떤가요. 되먹임이 없으니 $u$ 는 $y$ 와 무관합니다. $r=0$ 이면 $u=0$ 이고
%
% $$\left.\frac{y}{d_i}\right|_{\text{개루프}} = P$$
%
% **두 식을 나란히 놓고 보십시오.**
%
% $$\left.\frac{y}{d_i}\right|_{\text{개루프}} = P \qquad \text{vs} \qquad \left.\frac{y}{d_i}\right|_{\text{폐루프}} = \frac{P}{1+L}$$
%
% 차이는 **분모의 $1 + L$ 뿐**입니다. 그런데 이것이 결정적입니다.
%
% - 개루프에는 $C$ 가 **아예 나타나지 않습니다.** 제어기를 아무리 잘 설계해도
%   $y/d_i = P$ 입니다. 담당교수 강의자료의 표현 그대로 **"제어기를 얼마나 잘
%   설계하든 $d_i$ 가 $y$ 에 미치는 영향을 줄일 수 없다"**
% - 폐루프에서는 $|L|$ 을 올리는 만큼 그대로 나누어집니다
%
% **이것이 "왜 되먹임인가" 에 대한 가장 정직한 답입니다.** 되먹임이 아니면
% 입력외란에 대해 할 수 있는 일이 없습니다.
%
% 수치로 확인합니다. 모터 루프에서 네 주파수의 외란을 비교합니다.
wd = [0.1 2 2*pi 100]';
open_dB   = 20*log10(squeeze(abs(freqresp(Pm, wd))));
closed_dB = 20*log10(squeeze(abs(freqresp(Pm*Sm, wd))));
table(wd, open_dB, closed_dB, open_dB - closed_dB, ...
    'VariableNames', {'w_rad_s', '개루프_dB', '폐루프_dB', '되먹임이_번_dB'})
%%
% 마지막 열이 되먹임의 이득입니다.
%
% - $\omega = 0.1$ : **60 dB** (1000 배) 좋아진다. $|L(0.1)| = 60$ dB 와 같다
% - $\omega = 2$ : 34 dB
% - $\omega = 2\pi$ : 24 dB
% - $\omega = 100$ : **3 dB 뿐이다.** 여기가 $\omega_c$ 이므로 $|L| = 1$,
%   즉 $|1+L| \approx \sqrt{2}$ 밖에 안 된다
%
% **되먹임이 버는 양이 정확히 $|1 + L|$ 입니다.** $\omega_c$ 를 넘으면
% 되먹임은 아무것도 해 주지 않습니다. 이것이 4절에서 "고주파 외란은 억제할 수
% 없다" 고 한 것의 수치적 근거입니다.
%
% ![외란 — 개루프와 폐루프의 결정적 차이](w11a_dist.png)
%
% **그림 파일** `w11a_dist.png` — `make_figures.m` 의 `fig_w11a_dist`
%   · 다시 만들려면 `make_figures('w11a_dist')`
%
% **직접 확인해 보려면** — `W11A_04_disturbance_noise.m` 의 **1절**과 **2절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 회색 선 | 0 dB 에 붙어 있다 | 개루프 출력외란 : 그대로 나온다 |
% | 왼쪽 위 파란 선 | 저주파에서 급강하 | 폐루프 : $|S|$ 만큼 줄어든다 |
% | 오른쪽 위 회색 선 | $|P|$ 모양 | 개루프 입력외란. **$C$ 가 없다** |
% | 오른쪽 위 두 선의 간격 | 저주파에서 벌어진다 | 그 간격이 $|1+L|$ |
% | 왼쪽 아래 | 회색은 수평, 주황은 0 으로 복귀 | 계단 외란 : 되먹임만이 되돌린다 |
% | 오른쪽 아래 | 진폭이 확연히 다르다 | $2\pi$ rad/s 정현 외란 |
%% 5-3. 손계산 $-24.05$ dB 를 Simulink 와 대조한다
% 왜 필요한가 — 담당교수 강의자료의 Simulink 예제에 외란 감쇠량이
% $-24.0541$ dB 로 적혀 있습니다. 그 숫자가 어디서 나온 것인지 손으로 확인하고,
% 직접 시뮬레이션해서 맞춰 보겠습니다. **같은 답을 세 가지 방법으로 구하는**
% 연습입니다.
%
% 강의자료의 외란은 $\omega = 2\pi$ rad/s (즉 1 Hz) 정현파이고 출력 쪽에
% 들어갑니다. 그러니 5-1 절의 $y/d_o = S$ 를 쓰면 됩니다.
%
% **방법 1 — 손계산.** 2-1 절의 식에 $\omega = 2\pi$ 를 넣습니다.
%
% $$|S(j2\pi)| = \frac{2\pi}{\sqrt{(2\pi)^2 + 100^2}} = \frac{6.2832}{\sqrt{39.478 + 10000}} = \frac{6.2832}{100.197}$$
%
% $$= 0.062708 \quad \Longrightarrow \quad 20\log_{10}(0.062708) = -24.05 \;\text{dB}$$
w_d = 2*pi;
hand = w_d/sqrt(w_d^2 + 100^2);
%%
% **방법 2** — `freqresp` 로 재기.
mat = abs(freqresp(Sm, w_d));
%%
% **방법 3 — 시간영역 시뮬레이션.** 정현 외란을 넣고 정상상태 진폭을 잽니다.
td = (0:1e-4:6)';
yd = lsim(Sm, sin(w_d*td), td);
amp = max(yd(td > 4));                       % 과도응답이 끝난 뒤의 진폭
table([hand; mat; amp], 20*log10([hand; mat; amp]), ...
    'RowNames', {'손계산', 'freqresp', 'lsim_진폭'}, ...
    'VariableNames', {'크기', 'dB'})
%%
% 세 방법 모두 $-24.05$ dB 입니다. 강의자료의 `DB = -24.0541` 과 같습니다.
%
% 방법마다 덤으로 주는 것이 다릅니다.
%
% | 방법 | 덤으로 알게 되는 것 | 한계 |
% |---|---|---|
% | 손계산 | $\omega$ 가 커지면 어떻게 변하는지 **식으로** 안다 | 루프가 복잡하면 못 한다 |
% | `freqresp` | 모든 주파수를 한 번에 | 왜 그 값인지는 안 알려 준다 |
% | `lsim` | **과도응답**까지 보인다. 비선형도 가능 | 정상상태를 기다려야 한다 |
%
% 왜 중요한가 — 주파수영역의 숫자가 시간영역의 눈에 보이는 진폭과 정확히
% 맞아떨어진다는 것을 한 번 확인해 두면, 앞으로 보드 선도를 **믿고** 설계할 수
% 있습니다. `W11A_05_run_simulink.m` 에서 같은 것을 Simulink 모델로 한 번 더
% 확인합니다.
%% 5-4. 더 줄이려면 — PI 의 꺾이는 자리를 옮긴다
% 왜 필요한가 — 지금까지는 주어진 제어기를 **분석**했습니다. 이제 처음으로
% **설계**를 해 봅니다. 1 Hz 외란이 $-24.05$ dB 로 줄었는데, 이것이 부족하다고
% 하면 무엇을 어떻게 바꿔야 하는가. 이 한 번의 선택이 루프 성형의 전부입니다.
%
% 답은 5-1 절에 이미 있습니다. $y/d_o = S \approx 1/|L|$ 이므로
% **그 주파수에서 $|L|$ 을 더 올리면** 됩니다. 문제는 "어떻게 올리는가" 입니다.
% 아무 데나 올리면 교차주파수가 따라 올라가 버리고, 그러면 잡음과 포화가
% 문제가 됩니다. **저주파만 올려야** 합니다.
%
% 그래서 PI 제어기를 담당교수 강의자료의 표기로 다시 씁니다. 지금까지 쓴
% $(500s+2000)/s$ 와 **완전히 같은 식**인데, 설계에 쓰기 편한 모양입니다.
%
% $$C(s) = K\,\frac{T_i s + 1}{T_i s}, \qquad K_i = \frac{K}{T_i}$$
%
% 두 표기가 같다는 것을 손으로 확인합니다. $K = 500$, $1/T_i = 4$ 를 넣으면
%
% $$500 \cdot \frac{\frac{s}{4} + 1}{\frac{s}{4}} = 500 \cdot \frac{s+4}{s} = \frac{500s + 2000}{s}$$
%
% 이 모양에서 각 기호가 보드 선도의 무엇인지가 중요합니다.
%
% | 기호 | 보드 선도에서 | 무엇을 정하는가 |
% |---|---|---|
% | $K$ | 고주파쪽 **평평한 이득** | 교차주파수 $\omega_c$ |
% | $1/T_i$ | **꺾이는 자리** (코너 주파수) | 이 왼쪽이 $-20$ dB/dec 로 올라간다 |
% | $K_i = K/T_i$ | $\omega \to 0$ 에서의 기울기 높이 | 저주파 이득의 크기 |
%
% 즉 **$1/T_i$ 를 오른쪽으로 옮기면 저주파 이득이 통째로 올라갑니다.**
% $K$ 는 그대로이므로 고주파는 건드리지 않습니다. 네 가지로 재 봅니다.
K_pi = 500;
invTi = [4 10 20 40]';
pm_pi = zeros(4,1); wc_pi = zeros(4,1); wb_pi = zeros(4,1);
Sd_pi = zeros(4,1); os_pi = zeros(4,1);
for k = 1:4
    Ti = 1/invTi(k);
    Ck = K_pi*(Ti*s + 1)/(Ti*s);
    Lk = minreal(Pm*Ck);
    [~, pm_pi(k), ~, wc_pi(k)] = margin(Lk);
    Tk = Lk/(1 + Lk);
    wb_pi(k) = bandwidth(Tk);
    Sd_pi(k) = 20*log10(abs(freqresp(1/(1 + Lk), 2*pi)));
    os_pi(k) = stepinfo(Tk).Overshoot;
end
table(invTi, K_pi./(1./invTi), pm_pi, wc_pi, wb_pi, Sd_pi, os_pi, ...
    'VariableNames', {'꺾이는자리', 'Ki', 'PM_deg', 'wc', 'wb', '외란_1Hz_dB', 'OS_퍼센트'})
%%
% 읽는 법 — **세 열만 보면 됩니다.**
%
% - 꺾이는 자리를 4 에서 20 으로 옮기면 1 Hz 외란이 $-24.05$ 에서 $-32.90$ dB 로
%   **$8.85$ dB 더 줄어듭니다.** 외란이 추가로 $2.8$ 배 작아진 것입니다
% - 교차주파수는 $100$ 에서 $101.8$ 로 거의 그대로입니다.
%   **저주파만 들어올렸기 때문입니다. 이것이 루프 성형입니다**
% - 대가는 PM 이 $90$ 도에서 $81$ 도로 9 도 줄고, 오버슈트가 0 에서 $8.8\,\%$ 로
%   생기는 것입니다. 꺾이는 자리를 40 까지 밀면 $-38.67$ dB 까지 가지만
%   오버슈트가 $15.6\,\%$ 가 됩니다
%
% 왜 PM 이 줄어드는가 — PI 의 위상은 항상 **음수**입니다. $0$ 에서 $-90$ 도
% 사이이고, 꺾이는 자리에서 $-45$ 도입니다. 꺾이는 자리를 오른쪽으로 옮기면
% 그 음의 위상이 $\omega_c$ 쪽으로 다가옵니다. **PI 는 저주파 이득을 사고
% 위상여유를 지불합니다.** 그래서 실무 지침은
%
% $$\frac{1}{T_i} \;\approx\; \frac{\omega_c}{10}$$
%
% 입니다. 한 데케이드 떨어뜨리면 $\omega_c$ 에서의 위상 손실이 $6$ 도 이내로
% 남습니다. 위 표에서 $\omega_c = 100$ 이므로 $1/T_i = 10$ 이 그 지침에
% 해당하고, 실제로 PM 이 $86.6$ 도로 $3.4$ 도만 깎였습니다.
%
% 왜 중요한가 — 이것이 11B 주차에서 `controlSystemDesigner` 로 **마우스로**
% 하게 될 일입니다. 영점을 끌어 옮기면 이 표가 실시간으로 바뀝니다.
% 오늘은 그 표를 손으로 한 번 만들어 본 것입니다.
% 실습은 `W11A_04_disturbance_noise.m` 의 **1-1 절**입니다.
%% 6. 공짜가 아니다 — 센서 잡음이라는 대가
% 왜 필요한가 — 5절까지 보면 "$|L|$ 을 크게 하면 다 좋다" 로 읽힙니다.
% 그런데 그러지 않는 이유가 있습니다. 되먹임을 하려면 **측정을 해야 하고**,
% 측정에는 잡음이 섞입니다. 그 잡음이 되먹임 선을 타고 루프 안으로 들어옵니다.
%
% ![측정 잡음이 있는 폐루프](loop_noise.png)
%
% **그림 파일** `loop_noise.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_noise')`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 되먹임 선 위의 원 | $y$ 와 $n$ 이 **여기서 만난다** | 제어기가 보는 것은 $y + n$ |
% | $n$ 의 물리적 정체 | 엔코더 양자화, 전기 노이즈, 진동 | 보통 **고주파**다 |
% | 합산점으로 가는 신호 | $y + n$ | 제어기는 참값과 잡음을 구별 못 한다 |
% | 앞의 원과 비교 | 외란은 $P$ 앞, 잡음은 $P$ 뒤 | 그래서 전달함수가 다르다 |
%
% 신호를 따라갑니다. $r = 0$ 으로 둡니다.
%
% $$e = -(y + n), \qquad u = Ce, \qquad y = Pu$$
%
% 대입합니다.
%
% $$y = P C \cdot (-(y+n)) = -PC y - PC n$$
%
% $y$ 를 모읍니다.
%
% $$(1 + PC)\, y = -PC\, n \quad \Longrightarrow \quad \frac{y}{n} = -\frac{L}{1+L} = -T$$
%
% **잡음에 대한 전달함수가 $-T$ 입니다.** 부호만 다를 뿐 지령 추종 전달함수와
% 똑같습니다. 이것이 되먹임 제어의 근본적인 맞바꿈입니다.
%
% | 신호 | 전달함수 | 저주파에서 | 고주파에서 |
% |---|---|---|---|
% | 지령 $r \to y$ | $T$ | $\approx 1$ (좋다) | $\approx 0$ |
% | 잡음 $n \to y$ | $-T$ | $\approx -1$ (**나쁘다**) | $\approx 0$ |
%
% **지령을 잘 따라가게 만들면 잡음도 똑같이 잘 따라갑니다.** 같은 $T$ 이니
% 피할 방법이 없습니다. 다행히 센서 잡음은 대개 고주파라서, 고주파에서
% $|T|$ 를 떨어뜨리면 (= $|L|$ 을 떨어뜨리면) 막을 수 있습니다.
% 4절에서 고주파 띠의 요구사항이 "잡음 차단" 이었던 이유입니다.
%
% ![되먹임의 대가 — 잡음은 T 를 타고 들어온다](w11a_noise.png)
%
% **그림 파일** `w11a_noise.png` — `make_figures.m` 의 `fig_w11a_noise`
%   · 다시 만들려면 `make_figures('w11a_noise')`
%
% **직접 확인해 보려면** — `W11A_04_disturbance_noise.m` 의 **3절**
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 | 저주파에서 $|T| = 0$ dB | 저주파 잡음은 100 % 통과한다 |
% | 가운데 | 출력이 잘게 떨린다 | 잡음에 $-T$ 가 곱해져 나온 것 |
% | 오른쪽 두 곡선 | 대역폭 좁은 쪽이 매끈하다 | 잡음은 줄지만 **느려진다** |
%
% 오른쪽 그림이 핵심입니다. 잡음을 줄이려고 대역폭을 좁히면 응답이 느려집니다.
% **빠르게 하면서 잡음도 적게 하는 방법은 없습니다.**
%
% 얼마나 남는지 숫자로 셀 수도 있습니다. 샘플 간격 $T_s$ 로 만든 백색잡음은
% $0$ 부터 $\pi/T_s$ 까지 **고르게** 퍼져 있고, $-T$ 는 대역폭까지만
% 통과시킵니다. 그래서 출력 분산은 통과한 띠만큼만 남습니다.
%
% $$\sigma_y^2 = \frac{\sigma_n^2 \, T_s}{2\pi} \int_{-\pi/T_s}^{\pi/T_s} |T(j\omega)|^2 \, d\omega$$
%
% 실습 3절이 이 적분을 `trapz` 로 계산해 실측 표준편차와 대조합니다.
% $T_s = 10^{-4}$, $\sigma_n = 0.02$, 대역폭 $100$ rad/s 에서 식은 $0.001413$,
% 실측은 $0.001408$ 로 $0.4\,\%$ 차이입니다. **입력의 $7\,\%$ 만 남은 것**입니다.
%
% - **[주의] 표준편차를 재려면 기록이 충분히 길어야 합니다.** 대역폭이
%   $100$ rad/s 이면 독립된 표본이 초당 $30$ 개 남짓입니다. $0.5$ 초짜리
%   기록으로는 표준편차가 $30\,\%$ 넘게 틀어집니다. 그래서 실습은 그림용으로
%   $0.5$ 초, 숫자 확인용으로 $20$ 초를 따로 씁니다
% - 틀어진 값을 보고 "식이 틀렸나" 를 의심하기 쉽지만, **통계량은 표본 수가
%   모자라면 틀리는 것이 정상**입니다. 적분이나 보간을 고칠 문제가 아닙니다
%% 6-1. 오차 예산 — 세 항을 한 식에 모은다
% 왜 필요한가 — 지금까지 지령, 외란, 잡음을 따로 봤습니다. 실제로는 세 개가
% 동시에 들어옵니다. 중첩원리(선형시스템)로 더하면 됩니다.
%
% 각 전달함수를 모으면 이렇습니다.
%
% $$y = T\, r \;+\; S\, d_o \;+\; P S\, d_i \;-\; T\, n$$
%
% 네 항이 각각 무엇인지 왼쪽부터 짚습니다.
%
% - $T\,r$ — **따라가고 싶은 것.** 이 항만 크게 만들고 싶다
% - $S\,d_o$ — 출력외란이 남긴 것
% - $P S\, d_i$ — 입력외란이 남긴 것
% - $-T\,n$ — 센서 잡음이 들어온 것. 부호가 음수다
%
% 이것을 **오차 예산**(error budget) 이라고 부릅니다. 네 항이 각각 어느 주파수
% 띠에서 문제가 되는지 정리합니다.
%
% | 항 | 전달함수 | 신호의 주파수 | 설계 목표 | 어느 띠 |
% |---|---|---|---|---|
% | 지령 $r$ | $T$ | 보통 저주파 | $|T| \approx 1$ | 저주파 |
% | 출력외란 $d_o$ | $S$ | 보통 저주파 | $|S|$ 작게 | 저주파 |
% | 입력외란 $d_i$ | $PS$ | 보통 저주파 | $|S|$ 작게 | 저주파 |
% | 센서잡음 $n$ | $-T$ | 보통 **고주파** | $|T|$ 작게 | 고주파 |
%
% **네 항 중 셋이 저주파에서 $|L|$ 을 크게 하라고 하고, 하나가 고주파에서
% 작게 하라고 합니다.** 요구가 서로 다른 주파수에 있어서 둘 다 만족시킬 수
% 있습니다. 이것이 루프 성형이 가능한 근본적인 이유입니다.
%
% 모터 루프로 세 항의 크기를 한 번 재 봅니다. 저주파 외란 $d_o$ 와
% 고주파 잡음 $n$ 이 동시에 들어오는 경우입니다.
tb = (0:1e-4:1)';
rng(0);
r_sig = ones(size(tb));                      % 계단 지령
d_sig = 0.3*sin(2*pi*tb);                    % 1 Hz 출력외란
n_sig = 0.02*randn(size(tb));                % 고주파 센서 잡음
y_r = lsim(Tm,  r_sig, tb);
y_d = lsim(Sm,  d_sig, tb);
y_n = lsim(-Tm, n_sig, tb);
table([max(abs(r_sig)); max(abs(d_sig)); max(abs(n_sig))], ...
      [max(abs(y_r)); max(abs(y_d(tb>0.5))); max(abs(y_n(tb>0.5)))], ...
    'RowNames', {'지령_r', '외란_d', '잡음_n'}, ...
    'VariableNames', {'입력_진폭', '출력_기여'})
%%
% 지령은 1 이 그대로 1 로 나오고 (좋다), 외란 0.3 은 0.019 로 줄고 (좋다),
% 잡음 0.02 는 0.019 가 거의 그대로 나옵니다 (어쩔 수 없다).
%
% 잡음 기여가 줄지 않는 이유 — `randn` 잡음은 모든 주파수에 퍼져 있고,
% 그중 **저주파 성분은 $|T| = 1$ 로 100 % 통과**합니다. 센서 잡음을 줄이는
% 진짜 방법은 제어기가 아니라 **더 좋은 센서**입니다. 제어 설계로 막을 수 있는
% 것은 고주파 성분뿐입니다.
%
% 왜 중요한가 — 11B 주차 종합 설계의 5단계에서 저역통과 필터를 붙이는 이유가
% 이것입니다. 그리고 그 필터가 위상여유를 깎아서 다시 조정해야 하는 것까지,
% 전부 이 절의 맞바꿈에서 나옵니다.
%% 7. 오늘의 정리
% 오늘 배운 것을 한 장으로 압축합니다. **이 표만 외워도 됩니다.**
%
% | 기호 | 식 | 저주파에서 | 고주파에서 | 설계 목표 |
% |---|---|---|---|---|
% | $L$ | $PC$ | 크게 | 작게 | 모양을 내가 정한다 |
% | $S$ | $\frac{1}{1+L}$ | $\approx 1/|L|$ | $\approx 1$ | 저주파에서 작게 |
% | $T$ | $\frac{L}{1+L}$ | $\approx 1$ | $\approx |L|$ | 고주파에서 작게 |
%
% 그리고 **$S + T = 1$** — 둘을 동시에 작게 만들 수 없다. 그래서 주파수를
% 나눠서 쓴다.
%
% 네 숫자를 읽는 자리를 다시 확인합니다.
%
% | 숫자 | 어디서 | 기준선 | 명령 |
% |---|---|---|---|
% | $\omega_c$ | 개루프 $|L|$ | 0 dB | `margin` |
% | GM | 개루프 $|L|$ | 위상 $-180$ 도인 곳 | `margin` |
% | PM | 개루프 위상 | $\omega_c$ 에서 $-180$ 도까지 | `margin` |
% | $\omega_b$ | **폐루프** $|T|$ | $-3$ dB | `bandwidth` |
%
% 서로의 관계 세 개입니다. 전부 어림셈이지만 실무에서 그대로 씁니다.
%
% | 관계 | 식 | 쓰는 곳 |
% |---|---|---|
% | PM 과 감쇠비 | $\zeta \approx \text{PM}/100$ | 오버슈트 사양을 PM 으로 번역 |
% | $\omega_c$ 와 대역폭 | $\omega_b \approx 1.5\,\omega_c$ | 대역폭 사양을 $\omega_c$ 로 번역 |
% | 기울기와 PM | $-20$ dB/dec $\to$ PM 90 도, $-40$ $\to$ 0 도 | 보드 선도를 보고 PM 짐작 |
%
% 네 개의 신호가 출력에 어떻게 기여하는가 — 오차 예산입니다.
%
% $$y = T\,r + S\,d_o + P S\,d_i - T\,n$$
%
% 그리고 **왜 되먹임인가** 에 대한 답.
%
% | 외란 | 개루프 | 폐루프 | 결론 |
% |---|---|---|---|
% | 출력외란 $d_o$ | $1$ | $S$ | 개루프는 그대로 당한다 |
% | 입력외란 $d_i$ | $P$ ($C$ 가 **없다**) | $PS$ | 개루프는 **설계로 어쩔 수 없다** |
%
% 마지막으로 **대가**. 되먹임은 센서 잡음을 $-T$ 로 끌어들입니다. 지령 추종과
% 같은 전달함수이므로 피할 수 없고, 고주파에서 $|L|$ 을 떨어뜨려 막습니다.
%% 8. 다음 시간 예고 — 그 모양을 어떻게 만드는가
% 오늘은 **어떤 모양이 좋은 모양인지** 배웠습니다. 다음 시간(11B)에는
% **그 모양을 실제로 만드는 도구**를 배웁니다.
%
% | 도구 | 하는 일 | 오늘의 어느 띠 |
% |---|---|---|
% | 이득 $K$ | 곡선 전체를 위아래로 평행이동 | 전 구간 |
% | PD, Lead | $\omega_c$ 근처의 위상을 올린다 | 중간 띠 |
% | PI, Lag | 저주파 이득을 올린다 | 저주파 띠 |
% | 저역통과 필터 | 고주파를 떨어뜨린다 | 고주파 띠 |
%
% 그리고 이 모든 것을 **마우스로 끌어서** 하는 도구를 씁니다.
% `controlSystemDesigner` 앱입니다. 7주차에 근궤적으로 한 번 만난 그 앱을,
% 이번에는 보드 선도 쪽에서 씁니다.
%
% 다음 시간에 답할 질문들입니다.
%
% - 저주파 이득을 올리면 왜 위상여유가 사라지는가, 그리고 어떻게 되살리는가
% - PD 와 Lead 는 둘 다 위상을 올리는데 왜 Lead 를 쓰는가
% - 앱에서 동그라미와 x 를 끌면 무엇이 변하고 무엇이 안 변하는가
% - 사양 다섯 개를 어떻게 다섯 단계로 나눠 맞추는가
% - 공칭 모델로 다 맞춰 놓고 실제 시스템에서 확인하면 무엇이 달라지는가
%
% 오늘 배운 표 하나 ($L$, $S$, $T$ 와 세 띠) 를 머리에 넣어 두면 다음 시간은
% 그 표를 손으로 실현하는 작업이 됩니다.
