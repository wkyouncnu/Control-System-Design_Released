fprintf('  roots(poly(A))    : %s\n', mat2str(round(sort(roots(poly(A_ex))).', 4)));
fprintf('  전달함수의 극점   : %s\n', ...
        mat2str(round(sort(pole(tf(ss(A_ex,[0;1],[1 0],0)))).', 4)));
fprintf('  --> 넷이 같습니다. **고유값 = 극점** 이 이렇게 확인됩니다.\n\n');
fprintf('=== 반대로도 됩니다 (13주차에서 씁니다) ===\n');
