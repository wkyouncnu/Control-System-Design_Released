% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 초록 영역 | 실수부 $<0$ | 그 모드는 **사라진다** |
% | 왼쪽 빨간 영역 | 실수부 $>0$ | 그 모드는 **커진다** |
% | ① 과 ② 의 거리 차이 | 원점에서 멀수록 빠르다 | 왼쪽으로 갈수록 빨리 사라진다 |
