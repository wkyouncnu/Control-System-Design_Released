%% 1. 상태방정식의 해
% 3주차에서 두 줄을 배웠습니다.
%
% $$\dot{x} = Ax + Bu, \qquad y = Cx + Du$$
%
% 이 미분방정식의 해는 이렇게 생겼습니다.
%
% $$x(t) = e^{At}\,x(0) + \int_0^t e^{A(t-\tau)}\,B\,u(\tau)\,d\tau$$
%
% 복잡해 보이지만 어렵지 않습니다. 두 조각으로 읽으면 됩니다.
%
% - **앞의 항** — 초기조건이 스스로 흘러가는 것. 입력과 무관하다
% - **뒤의 항** — 입력이 만든 것. 초기조건과 무관하다
%
% 선형 시스템이라 두 효과가 그냥 **더해집니다.** 이것을 중첩이라 합니다.
%
% 그리고 $e^{At}$ 를 **상태천이행렬**이라 부릅니다.
% 이름이 거창하지만 하는 일은 하나입니다 —
% **지금 상태를 넣으면 $t$ 초 뒤 상태를 돌려준다.**
%% 2. 행렬 지수함수 $e^{At}$ 는 무엇인가
% 정의는 스칼라 지수함수의 급수를 그대로 흉내 낸 것입니다.
%
% $$e^{At} = I + At + \frac{(At)^2}{2!} + \frac{(At)^3}{3!} + \cdots$$
%
% MATLAB 에서는 `expm(A*t)` 한 줄입니다.
%
% **중요한 주의** — `exp(A)` 와 `expm(A)` 는 완전히 다릅니다.
%
% - `exp(A)` — 행렬의 **각 원소**에 지수함수를 씌운다. 우리가 원하는 것이 아니다
% - `expm(A)` — 행렬 지수함수. 이것이 맞다
%
% 학생들이 가장 많이 틀리는 지점입니다. 반드시 `m` 을 붙이십시오.
A0 = [0 1; -2 -3];
fprintf('exp(A)  = %s   <- 틀린 것\n', mat2str(round(exp(A0), 4)));
fprintf('expm(A) = %s   <- 맞는 것\n', mat2str(round(expm(A0), 4)));
%% 2-1. 상태천이행렬의 성질 세 가지
% 외울 것은 셋뿐이고, 전부 스칼라 지수함수에서 그대로 옮겨 온 것입니다.
%
% $$e^{A\cdot 0} = I \qquad\qquad (e^{At})^{-1} = e^{-At}$$
%
% $$e^{A(t_1+t_2)} = e^{At_1}\,e^{At_2}$$
%
% 각각의 뜻
%
% - **첫째** — $0$ 초 뒤의 상태는 지금 상태. 당연합니다
% - **둘째** — 시간을 거꾸로 돌릴 수 있다. 선형 시스템이라 가능합니다
% - **셋째** — $2$ 초 흐른 것은 $1$ 초 흐르고 또 $1$ 초 흐른 것과 같다
%
% 셋째가 "천이" 라는 이름의 근거입니다.
% 상태가 시간을 따라 **한 자리에서 다음 자리로 옮겨 가는** 것입니다.
%
% **주의** — $e^{At}e^{Bt} = e^{(A+B)t}$ 는 **일반적으로 틀립니다.**
% $AB = BA$ 일 때만 성립합니다. 행렬은 곱셈 순서가 중요하기 때문입니다.
%% 2-2. $e^{At}$ 가 실제로 하는 일
% 식만 보면 감이 안 옵니다. 그림으로 확인하겠습니다.
%
% $x(t) = e^{At}x(0)$ 에서 $e^{At}$ 는 **초기 상태를 받아 $t$ 초 뒤의 상태로 보내는 사상**입니다.
% 시각 $t$ 를 하나 정하면 $e^{At}$ 는 $2\times 2$ 행렬 하나가 되고,
% 그 행렬을 $x(0)$ 에 곱하면 그 순간의 상태가 나옵니다.
%
% ![상태천이행렬이 상태를 시간에 따라 옮긴다](w12_transition.png)
%
% **그림 파일** `w12_transition.png` — `make_figures.m` 의 `fig_w12_transition`
%   · 다시 만들려면 `make_figures('w12_transition')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w12_transition`
% **직접 확인해 보려면** — `W12_01_state_response.m` 의 **1-1절**이
% `expm(A*t)` 로 구한 상태와 `lsim` 결과가 같은지 대조합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 회색 화살표 | 각 점에서의 $\dot{x} = Ax$ 방향 | 상태가 다음 순간 향할 방향 |
% | 왼쪽 빨간 원 | 서로 다른 초기 상태 $x(0)$ | 출발점 네 개 |
% | 왼쪽 파란 곡선 | $e^{At}x(0)$ 를 $t$ 에 대해 그린 것 | 상태 궤적 |
% | 왼쪽 검은 별 | 원점 | 이 시스템의 평형점 |
% | 모든 궤적이 원점으로 수렴 | 두 고유값이 모두 음수 | **점근 안정** |
% | 왼쪽 점선 두 개 | 고유벡터 방향 | 궤적이 결국 정렬되는 축 |
% | 오른쪽 두 곡선 | 같은 궤적의 $x_1(t)$, $x_2(t)$ | 왼쪽 궤적을 시간축으로 편 것 |
% | 오른쪽 세로 점선 | $t = 0,\,0.5,\,1.5$ | 그 시각의 $e^{At}x(0)$ 값 |
% | $t = 0$ 에서 두 점이 $x(0)$ 와 일치 | $e^{A\cdot 0} = I$ | 2-1 절의 첫째 성질 |
%
% 왼쪽과 오른쪽은 **같은 궤적의 두 표현**입니다.
% 왼쪽은 시간을 감추고 자취만, 오른쪽은 시간축을 펴서 값을 보여 줍니다.
%% 3. 고유값과 고유벡터가 왜 나오는가
% $e^{At}$ 를 급수로 계산하는 것은 사람이 할 일이 아닙니다.
% 그런데 $A$ 가 **대각행렬**이면 이야기가 달라집니다.
%
% $$A = \left[\begin{array}{cc}\lambda_1 & 0\\ 0 & \lambda_2\end{array}\right]
%   \qquad\Rightarrow\qquad
%   e^{At} = \left[\begin{array}{cc}e^{\lambda_1 t} & 0\\
%                                   0 & e^{\lambda_2 t}\end{array}\right]$$
%
% 각 원소에 지수함수를 씌우면 끝입니다. **스칼라 문제 두 개로 쪼개진** 것입니다.
%
% 그래서 이런 생각을 합니다 — **좌표를 바꿔서 $A$ 를 대각행렬로 만들 수 없을까?**
%
% 그것이 정확히 고유값 분해입니다.
%
% $$A = V\,\Lambda\,V^{-1} \qquad\Rightarrow\qquad e^{At} = V\,e^{\Lambda t}\,V^{-1}$$
%
% - $\Lambda$ — 고유값을 대각선에 놓은 행렬
% - $V$ — 고유벡터를 열로 세운 행렬
%
% **고유벡터는 좌표축입니다.** 그 축에서 보면 시스템이 스칼라 문제로 쪼개집니다.
%% 3-0. 오른쪽 식이 왜 성립하는가 — 급수에 그대로 넣으면 된다
% $e^{At} = V e^{\Lambda t} V^{-1}$ 를 받아 적지 말고 **급수 정의에 넣어** 봅니다.
% 두 걸음이면 끝납니다.
%
% **첫째 걸음 — $A$ 의 거듭제곱이 어떻게 되는가.**
% $A = V\Lambda V^{-1}$ 를 두 번 곱해 봅니다.
%
% $$A^2 = \left(V\Lambda V^{-1}\right)\left(V\Lambda V^{-1}\right)
%       = V\Lambda \left(V^{-1}V\right) \Lambda V^{-1}
%       = V\Lambda^2 V^{-1}$$
%
% **가운데의 $V^{-1}V$ 가 단위행렬이 되어 지워지는 것**이 핵심입니다.
% 같은 일이 몇 번을 곱해도 반복되므로
%
% $$A^k = V\,\Lambda^k\,V^{-1} \qquad (k = 0, 1, 2, \ldots)$$
%
% **둘째 걸음 — 급수에 넣는다.** 2절의 정의는 이것이었습니다.
%
% $$e^{At} = I + At + \frac{(At)^2}{2!} + \frac{(At)^3}{3!} + \cdots$$
%
% 각 항에 위 결과를 넣습니다. $I = V I V^{-1}$ 로 써 두면 모양이 같아집니다.
%
% $$e^{At} = V I V^{-1} + V\Lambda V^{-1}t + V\frac{\Lambda^2}{2!}V^{-1}t^2 + \cdots$$
%
% **모든 항의 앞뒤에 $V$ 와 $V^{-1}$ 이 똑같이 붙어 있으므로 밖으로 묶어냅니다.**
%
% $$e^{At} = V\left(I + \Lambda t + \frac{(\Lambda t)^2}{2!} + \cdots\right)V^{-1}
%          = V\,e^{\Lambda t}\,V^{-1}$$
%
% 그리고 $\Lambda$ 는 대각행렬이므로 $e^{\Lambda t}$ 는 **대각선에 지수함수만 놓으면** 됩니다.
%
% $$e^{\Lambda t} = \left[\begin{array}{cc}
%   e^{\lambda_1 t} & 0 \\ 0 & e^{\lambda_2 t}\end{array}\right]$$
%
% **이제 왜 고유값만 보면 안정성을 알 수 있는지도 보입니다.**
% $e^{At}$ 안에 들어 있는 시간 함수가 $e^{\lambda_i t}$ 뿐이기 때문입니다.
% 어느 하나라도 $\mathrm{Re}(\lambda_i) > 0$ 이면 그 항이 커지고, 전체가 발산합니다.
%
% 아래에서 세 가지를 대조합니다 — `expm`, 급수 직접 계산, 그리고 고유분해.
Ad = [0 1; -2 -3];
[Vd, Dd] = eig(Ad);
td = 0.4;
E_expm  = expm(Ad*td);
E_eigen = real(Vd * diag(exp(diag(Dd)*td)) / Vd);
E_ser   = eye(2);  Tk = eye(2);
for kk = 1:25
    Tk = Tk * (Ad*td) / kk;
    E_ser = E_ser + Tk;
end
fprintf('=== e^{At} 를 세 방법으로 (t = %.1f) ===\n', td);
fprintf('  expm      : %s\n', mat2str(round(E_expm(:).', 6)));
fprintf('  급수 25항  : %s\n', mat2str(round(E_ser(:).', 6)));
fprintf('  고유분해   : %s\n', mat2str(round(E_eigen(:).', 6)));
fprintf('  최대 차이  : expm-급수 %.2e,  expm-고유분해 %.2e\n', ...
        max(abs(E_expm(:)-E_ser(:))), max(abs(E_expm(:)-E_eigen(:))));
fprintf('  --> 세 방법이 같은 답을 줍니다. 정의·급수·분해가 모두 같은 것입니다.\n\n');
