%% 4. 모드 — 고유값 하나가 만드는 응답 조각
% 위 식을 풀어 쓰면 이렇게 됩니다.
%
% $$x(t) = c_1\,e^{\lambda_1 t}\,v_1 + c_2\,e^{\lambda_2 t}\,v_2 + \cdots$$
%
% 각 항을 **모드**(mode)라고 부릅니다. 읽는 법은 이렇습니다.
%
% - $e^{\lambda_i t}$ — **얼마나 빨리** 사그라드는가 (또는 커지는가)
% - $v_i$ — **어느 방향으로** 그 일이 일어나는가
% - $c_i$ — 초기조건에 그 모드가 **얼마나 섞여 있는가**
%
% 계수는 좌표변환 한 줄로 나옵니다.
%
% $$c = V^{-1}x(0)$$
