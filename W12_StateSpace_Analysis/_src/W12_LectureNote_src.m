%% 6. 유사변환 — 좌표를 바꿔도 시스템은 같다
% 상태를 $z = T^{-1}x$ 로 바꿔 보겠습니다. 그러면
%
% $$\dot{z} = T^{-1}A T\,z + T^{-1}B\,u, \qquad y = C T\,z + D u$$
%
% 즉 $(A,B,C,D)$ 가 $(T^{-1}AT,\; T^{-1}B,\; CT,\; D)$ 로 바뀝니다.
% **행렬은 완전히 달라 보이는데 시스템은 그대로입니다.**
%
% 무엇이 안 바뀌는가
%
% - **고유값** — 특성다항식 $\left|T^{-1}AT - \lambda I\right|$ 가
%   $\left|A - \lambda I\right|$ 와 같기 때문
% - **전달함수** — 입출력 관계는 좌표와 무관하다
% - **가제어성·가관측성** — 오늘 배울 두 판정도 안 바뀐다
%
% 무엇이 바뀌는가
%
% - $A, B, C$ 의 **숫자들**
% - 상태 $x$ 의 **물리적 의미**
%
% 그래서 **상태공간 표현은 하나가 아닙니다.** 무한히 많습니다.
% 3주차에서 만든 것은 그중 하나(가제어 표준형에 가까운 것)일 뿐입니다.
%
% 실무에서는 목적에 맞는 좌표를 골라 씁니다.
% 대각화하면 모드가 보이고, 가제어 표준형으로 바꾸면 13주차 극배치가 쉬워집니다.
%
% 가장 유용한 좌표는 $T = V$ (고유벡터를 열로 쌓은 행렬)입니다.
% 이때 $V^{-1}AV = \Lambda$ 가 대각행렬이 되어 상태방정식이
%
% $$\dot{z}_i = \lambda_i z_i \qquad (i = 1, 2)$$
%
% 처럼 **서로 얽히지 않은 1차 방정식 두 개**로 갈라집니다.
% 각 $z_i$ 는 $z_i(0)e^{\lambda_i t}$ 로 혼자 움직입니다.
%
% ![좌표를 바꾸면 모드가 분리된다](w12_similarity.png)
%
% **그림 파일** `w12_similarity.png` — `make_figures.m` 의 `fig_w12_similarity`
%   · 다시 만들려면 `make_figures('w12_similarity')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w12_similarity`
% **직접 확인해 보려면** — `W12_01_state_response.m` 의 **3-1절**이
% `[V,D] = eig(A)` 로 대각화하고 고유값이 보존되는지 확인합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 두 곡선 | 원좌표계의 $x_1$, $x_2$ | 지수함수 두 개가 **더해진** 모양 |
% | 왼쪽 $x_2$ 가 아래로 꺾였다 돌아오는 것 | 두 모드의 부호가 반대 | 단일 지수함수로는 설명 안 됨 |
% | 오른쪽 두 곡선 | 모드 좌표 $z = V^{-1}x$ | 각각 **순수 지수함수 하나** |
% | 오른쪽 검은 점선 | 해석해 $z_i(0)e^{\lambda_i t}$ | 계산값과 정확히 겹침 |
% | $z_2$ 가 $z_1$ 보다 빨리 사라지는 것 | $\lambda_2 = -2 < \lambda_1 = -1$ | 빠른 모드가 먼저 소멸 |
% | 두 그림의 감쇠 속도가 같은 것 | 고유값은 좌표에 무관 | **유사변환 불변량** |
%
% 좌표를 바꿔도 **고유값은 그대로**입니다.
% 바뀐 것은 상태를 어떤 축으로 쪼개 보느냐 뿐입니다.
[Gm, pm] = plant_msd();
sys1 = ss(pm.A, pm.B, pm.C, pm.D);
T = [1 1; 0 2];
sys2 = ss(T\pm.A*T, T\pm.B, pm.C*T, pm.D);
fprintf('원래 A   : %s,  고유값 %s\n', mat2str(round(pm.A,3)), ...
        mat2str(round(eig(pm.A).', 3)));
fprintf('바꾼 A   : %s,  고유값 %s\n', mat2str(round(sys2.A,3)), ...
        mat2str(round(eig(sys2.A).', 3)));
fprintf('두 전달함수의 극점 차이 : %.2e\n', ...
        max(abs(sort(pole(tf(sys1))) - sort(pole(tf(sys2))))));
%% 7. 가제어성 — 입력으로 모든 상태를 움직일 수 있는가
% 이제 오늘의 두 번째 큰 주제입니다.
%
% 13주차에서 우리는 **고유값을 원하는 자리로 옮기려고** 합니다.
% 그런데 옮길 수 없는 경우가 있습니다. 입력이 그 상태를 못 미는 경우입니다.
%
% 정의는 이렇습니다.
%
% - 어떤 초기 상태에서 출발하든, **유한한 시간 안에** 원하는 상태로
%   데려갈 수 있는 입력이 존재하면 그 시스템은 **가제어**하다
%
% 판정은 행렬 하나의 계수를 보면 끝납니다.
%
% $$\mathcal{C} = \left[\begin{array}{cccc}
%   B & AB & A^2B & \cdots \end{array}\right],
%   \qquad \mathrm{rank}(\mathcal{C}) = n \;\Rightarrow\; \text{가제어}$$
%% 7-1. 왜 그 행렬인가 — 직관
% 각 열이 무엇을 뜻하는지 보면 자연스럽습니다.
%
% | 열 | 의미 |
% |---|---|
% | $B$ | 입력이 **지금 당장** 미는 방향 |
% | $AB$ | 그 밀린 것이 **다음 순간** 흘러가는 방향 |
% | $A^2B$ | 또 그다음 방향 |
%
% 즉 **입력 하나로 만들어 낼 수 있는 방향을 전부 모은 것**입니다.
% 그 방향들이 $n$ 차원 공간을 다 덮으면(계수 $n$) 어디든 갈 수 있습니다.
%
% 열이 $n$ 개까지만인 이유는 케일리-해밀턴 정리 때문입니다.
% $A^n$ 부터는 앞의 것들의 조합으로 표현되어 **새 방향이 안 나옵니다.**
%
% 상태가 둘뿐이면 이것을 그림으로 볼 수 있습니다.
%
% ![B 와 AB 가 평면을 덮는가](w12_reach.png)
%
% **그림 파일** `w12_reach.png` — `make_figures.m` 의 `fig_w12_reach`
%   · 다시 만들려면 `make_figures('w12_reach')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w12_reach`
% **직접 확인해 보려면** — `W12_02_ctrb_obsv.m` 의 **1절**이
% 같은 두 경우의 계수를 계산합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 빨간 화살표 | $B$ | 입력이 **지금 당장** 미는 방향 |
% | 파란 화살표 | $AB$ | 그 밀린 것이 **다음 순간** 흘러가는 방향 |
% | 연한 파란 곡선들 | 입력을 아무렇게나 넣어 본 궤적 | 원점에서 출발해 실제로 도달한 곳 |
% | 왼쪽 : 두 화살표가 **어긋나** 있는 것 | 두 방향이 독립이다 | 둘을 조합하면 평면 전체를 만든다 |
% | 왼쪽 : 곡선이 평면을 채우는 것 | 어디든 갈 수 있다 | **가제어**. 계수 $2$ |
% | 오른쪽 : 두 화살표가 **한 직선 위**인 것 | $AB$ 가 $B$ 의 배수다 | 새 방향이 안 나온다 |
% | 오른쪽 : 곡선이 직선에 갇힌 것 | 입력을 어떻게 넣어도 그 선을 못 벗어난다 | **가제어 아님**. 계수 $1$ |
%
% 오른쪽 그림이 "가제어가 아니다" 의 정확한 뜻입니다.
% 상태가 **안 움직이는 것이 아니라, 정해진 방향으로만 움직이는 것**입니다.
% 그 직선 밖으로는 아무리 큰 입력을 넣어도 나갈 수 없습니다.
%% 7-2. `ctrb` — 오늘의 새 명령
% 명령 정리
%
% - **하는 일** — 가제어성 행렬 $[B\;\;AB\;\;\cdots]$ 를 만들어 준다
% - **입력** — `ctrb(A, B)` 또는 `ctrb(sys)`
% - **출력** — $n \times (n\cdot m)$ 행렬. 판정은 `rank` 로 따로 한다
%
% 주의 두 가지
%
% - `ctrb` 는 **판정을 안 해 줍니다.** 반드시 `rank` 를 씌워야 합니다
% - 차수가 높으면 $A^{n-1}B$ 가 아주 커져 **수치적으로 위험**하다.
%   $n$ 이 $10$ 을 넘으면 `ctrbf` 나 `minreal` 을 쓰는 편이 낫다
%
% 예제 — 대각행렬이라 두 상태가 서로 무관한 시스템에서
Ac = [-1 0; 0 -2];
for B = {[1;1], [1;0]}
    r = rank(ctrb(Ac, B{1}));
    fprintf('B = %-8s : ctrb = %-14s rank = %d -> %s\n', ...
            mat2str(B{1}.'), mat2str(ctrb(Ac, B{1})), r, ...
            string(r == 2).replace("true","가제어").replace("false","가제어 아님"));
end
%% 8. 가제어가 아니면 실제로 무슨 일이 생기는가
% 판정만 하면 와닿지 않으니 직접 돌려 봅니다.
% 같은 계단 입력을 넣고 상태 두 개를 모두 그린 것입니다.
%
% ![입력이 못 미는 상태는 꿈쩍도 하지 않는다](w12_ctrb.png)
%
% **그림 파일** `w12_ctrb.png` — `make_figures.m` 의 `fig_ctrb`
%   · 다시 만들려면 `make_figures('w12_ctrb')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_ctrb`
% **직접 바꿔 보려면** — `W12_02_ctrb_obsv.m` 의 **2절**에서 `A` 의
% 비대각 원소를 $0$ 이 아닌 값으로 바꿔 보십시오. 가제어가 됩니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 제목 | $B = [1;1]$, rank $= 2$ | 가제어 |
% | 왼쪽 파란 곡선 | $x_1$ 이 $1$ 로 올라간다 | 입력이 밀었다 |
% | 왼쪽 빨간 곡선 | $x_2$ 가 $0.5$ 로 올라간다 | 이쪽도 밀었다 |
% | 두 상태가 **다른 값**에 수렴하는 것 | 고유값이 $-1$ 과 $-2$ 로 다르다 | 정상값 $= 1/|\lambda|$ |
% | 오른쪽 제목 | $B = [1;0]$, rank $= 1$ | 가제어 아님 |
% | 오른쪽 파란 곡선 | $x_1$ 은 똑같이 움직인다 | 여기는 문제없다 |
% | 오른쪽 빨간 곡선 | $x_2$ 가 **$0$ 에 딱 붙어 있다** | 입력이 아무리 세도 안 움직인다 |
% | 그 직선이 정말 평평한 것 | 기울기가 $0$ | 이 상태는 **손댈 방법이 없다** |
%
% 여기서 배울 것 — **가제어가 아니면 그 상태의 고유값은 영원히 그 자리입니다.**
% 13주차의 `place` 는 이런 시스템에서 오류를 냅니다.
% 그 고유값이 우반면에 있다면 **그 시스템은 안정화가 불가능**합니다.
%% 9. 진자는 가제어인가
% 12~14주차의 주인공은 **거꾸로 선 진자**입니다.
% 3주차에서 만든 그 진자를 $\theta_0 = 180^\circ$ 에서 선형화한 것입니다.
%
% 상태는 둘입니다 — 각도와 각속도. 입력은 하나 — 축에 거는 토크.
%
% 토크 하나로 각도와 각속도를 **둘 다** 원하는 대로 만들 수 있는가?
[sysUp, pUp] = plant_pendulum(pi);
fprintf('=== 거꾸로 선 진자 ===\n');
fprintf('  A = %s\n', mat2str(round(pUp.A, 3)));
fprintf('  B = %s\n', mat2str(round(pUp.B, 3)));
fprintf('  고유값 : %s   <- 하나가 양수. 개루프 불안정\n', ...
        mat2str(round(eig(pUp.A).', 3)));
fprintf('  ctrb   = %s\n', mat2str(round(ctrb(pUp.A, pUp.B), 3)));
fprintf('  rank   = %d / 2  ->  가제어\n', rank(ctrb(pUp.A, pUp.B)));
%% 9-1. 왜 가제어인가 — 손으로 확인
% 진자의 $A$ 와 $B$ 는 이렇게 생겼습니다.
%
% $$A = \left[\begin{array}{cc} 0 & 1\\ \frac{mgl}{J} & -\frac{b}{J}\end{array}\right],
%   \qquad B = \left[\begin{array}{c} 0\\ \frac{1}{J}\end{array}\right]$$
%
% 가제어성 행렬을 만들면
%
% $$\mathcal{C} = \left[\begin{array}{cc} B & AB \end{array}\right]
%   = \left[\begin{array}{cc} 0 & \frac{1}{J}\\
%     \frac{1}{J} & -\frac{b}{J^2}\end{array}\right]$$
%
% 행렬식이 $-1/J^2$ 이고 $J \ne 0$ 이므로 **항상 가제어**입니다.
%
% 물리적으로 읽으면 — 토크는 각속도를 직접 밉니다($B$ 의 둘째 성분).
% 그리고 각속도가 변하면 각도가 따라 변합니다($A$ 의 첫째 줄 $[0\;\;1]$).
% 그래서 **토크 하나로 둘 다 조종할 수 있습니다.**
%
% 13주차를 진행할 수 있다는 뜻입니다.
%% 10. 가관측성 — 출력만 보고 상태를 알 수 있는가
% 이제 반대편입니다.
%
% 14주차에서 우리는 **못 재는 상태를 만들어 내려고** 합니다.
% 그런데 만들어 낼 수 없는 경우가 있습니다. 출력에 그 정보가 안 나오는 경우입니다.
%
% 정의는 가제어성과 짝을 이룹니다.
%
% - 유한한 시간 동안 $y(t)$ 와 $u(t)$ 를 지켜본 것만으로
%   초기 상태 $x(0)$ 를 알아낼 수 있으면 **가관측**하다
%
% 판정 행렬도 짝입니다.
%
% $$\mathcal{O} = \left[\begin{array}{c} C \\ CA \\ CA^2 \\ \vdots\end{array}\right],
%   \qquad \mathrm{rank}(\mathcal{O}) = n \;\Rightarrow\; \text{가관측}$$
%
% 직관 — $C$ 는 지금 보이는 것, $CA$ 는 그 변화율에 담긴 정보,
% $CA^2$ 는 또 그 변화율입니다. **출력과 그 미분들을 다 모으면
% 상태를 복원할 수 있는가**를 묻는 것입니다.
%% 10-1. `obsv` — 오늘의 새 명령
% 명령 정리
%
% - **하는 일** — 가관측성 행렬을 세로로 쌓아 만들어 준다
% - **입력** — `obsv(A, C)` 또는 `obsv(sys)`
% - **출력** — $(n\cdot p) \times n$ 행렬. 판정은 `rank` 로 따로
%
% 주의
%
% - `ctrb` 는 **가로로**, `obsv` 는 **세로로** 쌓습니다. 혼동하지 마십시오
% - 역시 판정을 안 해 주므로 `rank` 를 씌워야 합니다
%
% 쌍대성 — 두 판정은 사실 같은 문제입니다.
%
% $$\mathrm{rank}\,\mathcal{O}(A, C) = \mathrm{rank}\,\mathcal{C}(A^{T}, C^{T})$$
%
% 즉 **$(A, C)$ 의 가관측성은 $(A^{T}, C^{T})$ 의 가제어성과 같습니다.**
% 14주차에서 관측기 이득을 `place(A', C', p)'` 로 구하는 이유가 바로 이것입니다.
%% 11. 가관측이 아니면 무슨 일이 생기는가
% 초기조건을 서로 다르게 주고 출력이 구별되는지 봅니다.
%
% ![구별이 안 되면 추정도 안 된다](w12_obsv.png)
%
% **그림 파일** `w12_obsv.png` — `make_figures.m` 의 `fig_obsv`
%   · 다시 만들려면 `make_figures('w12_obsv')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_obsv`
% **직접 바꿔 보려면** — `W12_02_ctrb_obsv.m` 의 **3절**에서 `C` 를 바꿔 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 제목 | $C = [1\;\;1]$, rank $= 2$ | 가관측 |
% | 왼쪽 파란 곡선 | $x(0) = [1;0]$ 일 때의 출력, $y(0) = 1$ | |
% | 왼쪽 빨간 곡선 | $x(0) = [1;1]$ 일 때의 출력, $y(0) = 2$ | **출발점이 다르다** |
% | 두 곡선이 구별되는 것 | 출력만 봐도 어느 쪽인지 안다 | 그래서 $x(0)$ 를 복원할 수 있다 |
% | 오른쪽 제목 | $C = [1\;\;0]$, rank $= 1$ | 가관측 아님 |
% | 오른쪽 두 곡선 | **완전히 포개져 있다** | $x_2$ 가 $0$ 이든 $1$ 이든 출력이 같다 |
% | 둘 다 $y(0) = 1$ 인 것 | $C$ 가 $x_1$ 만 보니까 | $x_2$ 의 정보가 출력에 **아예 안 실린다** |
% | 오른쪽 곡선이 $e^{-t}$ 하나인 것 | $x_2$ 의 모드가 안 보인다 | 그 모드는 출력에서 사라졌다 |
%
% 여기서 배울 것 — **출력이 같으면 안쪽이 달라도 알 방법이 없습니다.**
% 14주차의 관측기는 이런 상태를 추정할 수 없습니다.
% 그 상태가 불안정하다면 **모르는 채로 발산하는 것을 지켜봐야** 합니다.
%% 12. 진자에서 무엇을 재야 하는가
% 센서를 하나만 달 수 있다면 무엇을 측정해야 하는가?
%
% 상태는 각도와 각속도 둘입니다. 후보는 셋입니다.
%
% - 각도계만 — $C = [1\;\;0]$
% - 자이로만 — $C = [0\;\;1]$
% - 둘 다 — $C = I$
%
% 하나씩 판정해 봅니다.
Cs = { '각도만  C = [1 0]',  [1 0]
       '각속도만 C = [0 1]', [0 1]
       '둘 다   C = eye(2)', eye(2) };
fprintf('=== 센서 선택별 가관측성 ===\n');
for k = 1:3
    r = rank(obsv(pUp.A, Cs{k,2}));
    fprintf('  %-20s rank = %d / 2  ->  %s\n', Cs{k,1}, r, ...
            string(r == 2).replace("true","가관측").replace("false","가관측 아님"));
end
%%
% 셋 다 가관측입니다. **각도 하나만 재도 됩니다.**
%
% 왜 그런가 — $A$ 의 첫 줄이 $[0\;\;1]$ 이라 각도의 미분이 각속도입니다.
% 각도를 계속 지켜보고 있으면 그 **기울기**에서 각속도를 알 수 있습니다.
% 그래서 각도계 하나로 두 상태를 다 복원할 수 있습니다.
%
% 실무적으로 중요한 결론입니다 — **센서를 하나만 달아도 됩니다.**
% 각속도계를 추가로 다는 것은 잡음이 적은 추정을 얻기 위한 선택이지,
% 필수가 아닙니다. 14주차에서 각도계 하나로 관측기를 만듭니다.
%% 12-1. 상쇄가 일어나면 무엇이 사라지는가
% 가제어·가관측이 깨지는 가장 흔한 원인이 **극점과 영점의 상쇄**입니다.
%
% 7주차에서 "불안정한 극점을 상쇄하면 절대 안 된다" 고 했습니다.
% 그 이유가 오늘 정확히 나옵니다.
%
% 상쇄가 일어나면 그 모드는 **전달함수에서 사라집니다.**
% 그런데 상태공간에는 그대로 남아 있습니다. 없어진 것이 아닙니다.
%
% - 상쇄된 모드가 **안정**하면 — 안 보여도 스스로 죽으니 괜찮다
% - 상쇄된 모드가 **불안정**하면 — 안 보이는 채로 발산한다. **재앙이다**
