%% 3-1. 오늘의 새 명령 세 개 — `eig`, `expm`, `poly`
% `eig` — **고유값과 고유벡터**
%
% - **하는 일** — $Av = \lambda v$ 를 만족하는 $\lambda$ 와 $v$ 를 구한다
% - **입력** — 정사각행렬 $A$
% - **출력** — `eig(A)` 는 고유값 벡터. `[V, D] = eig(A)` 는 고유벡터 행렬 $V$ 와
%   고유값을 대각선에 놓은 $D$
%
% 주의
%
% - 출력을 **하나만 받으면 고유값만** 나옵니다. 벡터가 필요하면 두 개로 받으십시오
% - $V$ 의 **열**이 고유벡터입니다. 행이 아닙니다
% - 고유벡터는 길이가 정해져 있지 않습니다. MATLAB 은 길이를 $1$ 로 맞춰 줍니다.
%   그래서 부호가 교과서와 반대로 나올 수 있는데 **틀린 것이 아닙니다**
%
% `expm` — **행렬 지수함수** (2절에서 봤습니다)
%
% - `exp` 와 혼동하지 마십시오. 반드시 `m` 을 붙입니다
%
% `poly` — **특성다항식의 계수**
%
% - **하는 일** — 행렬을 주면 $\left|sI - A\right|$ 의 계수를,
%   근의 목록을 주면 그 근을 갖는 다항식의 계수를 돌려준다
% - **입력** — 행렬 $A$ 또는 근 벡터
% - **출력** — 계수 벡터. $s$ 의 **높은 차수부터**
%
% 왜 유용한가 — "**고유값 $=$ 전달함수의 극점**" 을 손으로 확인할 때 씁니다.
% `roots(poly(A))` 와 `eig(A)` 가 같은 답을 줍니다.
%
% 주의
%
% - `poly` 와 `roots` 는 **서로 반대**입니다. `roots(poly(A))` 는 제자리로 돌아옵니다
% - 차수가 높으면 계수를 거쳐 가는 동안 오차가 커집니다.
%   실무에서는 `eig` 를 직접 쓰고, `poly` 는 **확인용**으로만 씁니다
% - 13주차에서 `poly([-8 -10 -12])` 처럼 **원하는 극점으로 특성다항식을 만들 때**
%   다시 씁니다
A_ex = [0 1; -2 -3];
