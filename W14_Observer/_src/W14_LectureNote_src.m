%% 1. 관측기 — 같은 모델을 함께 돌린다
% 실제 플랜트가
%
% $$\dot{x} = Ax + Bu, \qquad y = Cx$$
%
% 라면, 컴퓨터 안에서도 똑같이 돌립니다.
%
% $$\dot{\hat{x}} = A\hat{x} + Bu$$
%
% 입력 $u$ 는 우리가 만든 것이니 당연히 압니다.
%
% **그런데 이것만으로는 안 됩니다.** 초기값이 다르면 영영 어긋난 채로 갑니다.
% 이것을 **열린 관측기**라 하고, 실무에서 쓰면 안 되는 것입니다.
%
% 그래서 한 항을 더합니다.
%
% $$\dot{\hat{x}} = A\hat{x} + Bu + L\,(y - C\hat{x})$$
%
% 마지막 항을 읽어 보십시오.
%
% - $y$ — 실제로 **잰** 출력
% - $C\hat{x}$ — 내가 **예상한** 출력
% - 그 차이가 나면 그만큼 추정을 고친다
%
% **오차를 보고 고친다** — 1주차부터 해 온 그것입니다.
% 다만 이번에는 제어가 아니라 **추정**에 씁니다.
%% 2. 추정오차의 방정식 — 두 줄이면 나옵니다
% 추정오차를 $e = x - \hat{x}$ 로 두고 두 식을 뺍니다.
%
% $$\dot{e} = (Ax + Bu) - \left(A\hat{x} + Bu + L(Cx - C\hat{x})\right)$$
%
% $$\dot{e} = A(x - \hat{x}) - LC(x - \hat{x}) = (A - LC)\,e$$
%
% **입력 $u$ 가 사라졌습니다.** 이것이 결정적입니다.
%
% - 무슨 입력을 넣든 추정오차는 **스스로** 줄어든다
% - 지령을 바꿔도, 외란이 들어와도 관측기는 제 할 일을 한다
%
% 조건은 하나 — $A - LC$ 의 고유값이 전부 좌반면에 있어야 합니다.
% 그리고 그 고유값을 우리가 정할 수 있는지가 **가관측성**입니다 (12주차).
%
% 말로만 하면 잘 안 믿깁니다. 숫자로 확인하겠습니다.
%
% ![추정오차는 초기값에도 입력에도 흔들리지 않는다](w14_error_dyn.png)
%
% **그림 파일** `w14_error_dyn.png` — `make_figures.m` 의 `fig_w14_error_dyn`
%   · 다시 만들려면 `make_figures('w14_error_dyn')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w14_error_dyn`
% **직접 확인해 보려면** — `W14_01_observer.m` 의 **3절**이
% 초기 추정오차를 바꿔 가며 같은 확인을 합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 세 곡선 | 서로 다른 초기 추정오차 $e(0)$ | 출발점이 달라도 |
% | 셋 다 $0$ 으로 수렴 | $e^{(A-LC)t}$ 가 감쇠한다 | **관측기가 스스로 따라잡는다** |
% | 수렴 속도가 셋 다 같은 것 | 속도를 정하는 것은 $A-LC$ 의 고유값 | 초기값과 무관하다 |
% | 오른쪽 네 곡선 | 같은 $e(0)$ 에 **입력만 다르게** | $u=0$, 계단, 저주파 정현, 고주파 정현 |
% | 네 곡선이 완전히 겹치는 것 | 오차 방정식에 $u$ 가 없다 | **이 절의 결론** |
%
% 오른쪽 그림이 왜 중요한가 — 관측기는 제어기가 무엇을 하든 **상관없이**
% 제 할 일을 합니다. 이 성질이 7절의 **분리원리**를 가능하게 합니다.
%% 3. 전치 트릭 — 왜 `place(A', C', p)'` 인가
% 13주차의 `place` 는 $A - BK$ 를 다뤘는데 지금은 $A - LC$ 라 모양이 다릅니다.
%
% 그런데 전치해도 고유값은 안 변합니다.
%
% $$\mathrm{eig}(A - LC) = \mathrm{eig}\left((A - LC)^{T}\right)
%   = \mathrm{eig}\left(A^{T} - C^{T}L^{T}\right)$$
%
% 오른쪽을 보십시오. $A^{T}$ 를 $A$ 로, $C^{T}$ 를 $B$ 로, $L^{T}$ 를 $K$ 로
% 놓으면 **13주차와 완전히 같은 문제**입니다.
%
% 그래서
%
% $$L = \mathrm{place}(A^{T},\; C^{T},\; p_{obs})^{T}$$
%
% **전치를 두 번 하는 것이 전부입니다.**
%
% 이렇게 두 문제가 짝을 이루는 것을 **쌍대성**이라 부릅니다.
%
% | 13주차 (제어) | 14주차 (추정) |
% |---|---|
% | $A - BK$ | $A - LC$ |
% | 가제어성 `rank(ctrb(A,B))` | 가관측성 `rank(obsv(A,C))` |
% | `place(A, B, p)` | `place(A', C', p)'` |
% | 대가 : 제어입력이 커진다 | 대가 : 잡음이 증폭된다 |
%
% **마지막 줄까지 대칭입니다.** 6절에서 확인합니다.
%
% 이 표를 그림으로 보면 대응이 더 분명합니다.
%
% ![13주차와 14주차는 전치 관계](w14_duality.png)
%
% **그림 파일** `w14_duality.png` — `make_figures.m` 의 `fig_w14_duality`
%   · 다시 만들려면 `make_figures('w14_duality')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w14_duality`
% **직접 확인해 보려면** — `W14_01_observer.m` 의 **2절**이
% 전치를 한 단계씩 나누어 보여 줍니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 열 | 13주차에서 푼 문제 | 극점을 옮기는 일 |
% | 오른쪽 초록 열 | 14주차에서 푸는 문제 | 상태를 알아내는 일 |
% | 가로 화살표 다섯 개 | 전치로 짝지어진 항목 | **한 줄씩 정확히 대응한다** |
% | 둘째 줄 $A-BK$ 와 $A-LC$ | 닫는 행렬의 모양 | $B \leftrightarrow C^{T}$, $K \leftrightarrow L^{T}$ |
% | 셋째 줄 가제어와 가관측 | 12주차의 두 판정 | 각각이 각 문제의 입장권 |
% | 다섯째 줄 | 치르는 대가 | 대칭이 **여기까지** 이어진다 |
%
% 이것이 오늘 새로 배울 것이 적은 이유입니다.
% 문제가 새로운 것이 아니라, **지난주 문제를 전치해 놓은 것**입니다.
[Gp, p] = plant_dcmotor('position');
A = p.A; B = p.B; C = p.C; D = p.D;
p_obs = [-30 -34 -38];
L = place(A', C', p_obs)';
fprintf('C = %s  ->  각도만 잰다\n', mat2str(C));
fprintf('rank(obsv) = %d / %d  ->  가관측\n', rank(obsv(A,C)), size(A,1));
fprintf('L = %s  (열벡터)\n', mat2str(round(L.', 2)));
fprintf('eig(A - L*C) = %s\n', mat2str(round(sort(eig(A-L*C)).', 3)));
%% 4. 관측기가 정말 따라잡는가
% 실제 플랜트는 초기값이 있고, 관측기는 **아무것도 모르니 $0$ 에서 출발**합니다.
% 그런데도 따라잡습니다.
%
% ![관측기는 0 에서 출발해도 따라잡는다](w14_converge.png)
%
% **그림 파일** `w14_converge.png` — `make_figures.m` 의 `fig_obs_converge`
%   · 다시 만들려면 `make_figures('w14_converge')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_obs_converge`
% **직접 해 보려면** — `W14_01_observer.m` 의 **3절**, 또는
% `W14_03_run_simulink.m` 이 Simulink 로 같은 실험을 합니다
%
% 그림 해석 — **위 두 칸이 상태, 아래 두 칸이 그 오차입니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
