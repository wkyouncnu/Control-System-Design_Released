%
% 관측기는 State-Space 블록 하나로 구현했습니다.
%
% $$\dot{\hat{x}} = (A - LC)\hat{x} + \left[\begin{array}{cc}B & L\end{array}\right]
%   \left[\begin{array}{c}u\\ y\end{array}\right]$$
%
% 괄호를 풀면 $\dot{\hat{x}} = A\hat{x} + Bu + L(y - C\hat{x})$ 와 같습니다.
%
% 이 모델에는 오늘 처음 보는 블록이 하나 있습니다.
%
% `Demux` — 묶여 있는 신호를 다시 갈라내는 블록
%
% - 하는 일 — 여러 개가 묶인 신호선 하나를 받아 **여러 출력 포트로 나눈다**.
%   1주차에서 쓴 `Mux` 의 정반대다
% - `Number of outputs` — 몇 갈래로 나눌지. 숫자 하나를 적으면 균등하게 나누고,
%   `[1 3]` 처럼 벡터를 적으면 **첫 갈래는 1 개, 둘째 갈래는 3 개**로 나눈다
% - 왜 필요한가 — 이 모델의 실제 플랜트는 $C$ 를
%   $\left[\begin{array}{c}C\\ I\end{array}\right]$ 로 두어
%   **측정값 $y$ 와 진짜 상태 $x$ 를 한 선에 함께** 내보낸다.
%   그런데 둘의 쓰임이 완전히 다르다
% - $y$ — 관측기에 넣어 준다. **관측기가 볼 수 있는 유일한 것**
% - $x$ — 그래프에만 쓴다. 우리가 채점하려고 몰래 보는 값이고,
%   **관측기 쪽으로는 절대 가지 않는다**
% - 그래서 `Demux` 의 출력 개수를 `[1 size(A,1)]` 로 두었다.
%   첫 포트가 $y$ 한 개, 둘째 포트가 상태 전부다.
%   **이 갈라짐이 오늘 실험의 공정성을 보장합니다**
%
% `W14_03_run_simulink.m` 을 실행하면 다음을 확인합니다.
%
% | 관측기 극의 배수 | $|L|$ | 각도 오차 $2\%$ 도달 | 추정 각속도의 진동 |
% |---|---|---|---|
% | $1$ 배 | $484$ | $0.508$ s | $0.34$ |
% | $2$ 배 | $5574$ | $0.200$ s | $1.41$ |
