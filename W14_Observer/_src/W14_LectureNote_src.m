%% 8. 왜 분리되는가 — 좌표를 바꿔 보면
% 증명은 좌표변환 한 번이면 끝납니다.
%
% 상태를 $[x;\;\hat{x}]$ 대신 **$[x;\;e]$** 로 잡습니다. 여기서 $e = x - \hat{x}$ 입니다.
%
% $$\dot{x} = Ax + Bu = Ax - BK\hat{x} = Ax - BK(x - e) = (A-BK)x + BKe$$
%
% $$\dot{e} = (A - LC)\,e$$
%
% 행렬로 쓰면
%
% $$\left[\begin{array}{c}\dot{x}\\ \dot{e}\end{array}\right] =
%   \left[\begin{array}{cc} A-BK & BK\\ 0 & A-LC\end{array}\right]
%   \left[\begin{array}{c}x\\ e\end{array}\right]$$
%
% **왼쪽 아래가 $0$ 입니다.** 이런 행렬을 블록 상삼각이라 하고,
% 그 고유값은 **대각 블록의 고유값을 합친 것**입니다.
%
% 물리적으로 읽으면 이렇습니다.
%
% - 추정오차 $e$ 는 제어와 무관하게 스스로 줄어든다 (아랫줄에 $x$ 가 없다)
% - 그 $e$ 가 위로 새어 들어가 $x$ 를 흔들지만, $e$ 가 죽으면 그 영향도 사라진다
%
% 즉 **오차는 제어를 신경 안 쓰고, 제어는 오차가 죽기를 기다리면 됩니다.**
%% 9. 관측기 기반 제어기의 정체
% 관측기와 제어기를 합치면 결국 **$y$ 를 받아 $u$ 를 내놓는 전달함수 하나**입니다.
%
% $$D(s) : \quad \dot{\hat{x}} = (A - BK - LC)\hat{x} + Ly, \qquad u = -K\hat{x}$$
%% 9-0. $A - BK - LC$ 는 어디서 나왔는가 — 대입 한 번
% 세 글자가 한꺼번에 붙어 있어 복잡해 보이지만 **대입 한 번**이면 나옵니다.
%
% 우리가 가진 것은 두 줄뿐입니다.
%
% | 어디서 나왔나 | 식 |
% |---|---|
% | 관측기 (1절) | $\dot{\hat{x}} = A\hat{x} + Bu + L\left(y - C\hat{x}\right)$ |
% | 제어기 (7절) | $u = -K\hat{x}$ |
%
% **둘째를 첫째에 넣습니다.** $u$ 자리에 $-K\hat{x}$ 를 그대로 씁니다.
%
% $$\dot{\hat{x}} = A\hat{x} + B\left(-K\hat{x}\right) + L y - LC\hat{x}$$
%
% $\hat{x}$ 가 붙은 항이 셋입니다. 묶어냅니다.
%
% $$\dot{\hat{x}} = \left(A - BK - LC\right)\hat{x} + L\,y$$
%
% **세 글자가 각각 어디서 왔는지 보십시오.**
%
% | 항 | 어디서 | 하는 일 |
% |---|---|---|
% | $A$ | 플랜트 모델 | 컴퓨터 안에서 같은 모델을 돌린다 |
% | $-BK$ | **제어기**를 넣어서 | 내가 넣는 입력을 관측기도 알고 있다 |
% | $-LC$ | **관측기**의 보정항 | 잰 값과 예상값의 차이로 고친다 |
%
% 그리고 입력은 $y$ 하나, 출력은 $u$ 하나입니다.
% 즉 이 두 줄은 **$y \to u$ 인 상태공간 모델**이고,
% 3주차의 공식으로 전달함수를 만들 수 있습니다.
%
% $$D(s) = -K\left(sI - A + BK + LC\right)^{-1} L$$
%
% 앞의 $-K$ 는 출력식 $u = -K\hat{x}$ 의 $C$ 자리이고,
% 뒤의 $L$ 은 입력식의 $B$ 자리입니다. $D$ 항은 없습니다.
%
% 이것의 보드 선도를 그려 보면 재미있는 사실이 나옵니다 —
% **중간 주파수에서 위상을 올립니다.**
%
% 7주차와 11주차의 **Lead 보상기**가 하던 그 일입니다.
%
% 즉 상태공간이라는 전혀 다른 길로 왔는데, 결과물은 **우리가 이미 아는 물건**입니다.
% 10강 slide 75~77 의 결론이 이것입니다.
%
% 이 사실이 주는 안도감이 있습니다. 상태공간은 새로운 마법이 아니라,
% **같은 것을 다른 언어로 적는 방법**입니다.
%
% ![관측기 기반 제어기](loop_observer.png)
%
% **그림 파일** `loop_observer.png` — `common/dg_loop.m` 의 `dg_loop`
%   · 다시 만들려면 `make_figures('loop_observer')`
%
% **만드는 곳** — `common/dg_loop.m` 을 `dg_loop('observer', ...)` 로 부릅니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 위쪽 플랜트 | 실제 시스템 | 여기서 나오는 것은 $y$ 하나뿐 |
% | 아래쪽 관측기 상자 | 컴퓨터 안에서 도는 모델 | 실제 상태와 **선으로 안 이어져 있다** |
% | 관측기로 들어가는 선 | $u$ 와 $y$ 둘뿐 | **우리가 아는 것만 쓴다** |
% | 관측기에서 나오는 $\hat{x}$ | 추정 상태 | 이것을 $K$ 에 넣는다 |
% | $-K$ 상자 | 13주차에 만든 것 | 그대로 쓴다. 분리원리 덕분이다 |
% | 루프 전체 | $y \to \hat{x} \to u \to$ 플랜트 | 결국 $y$ 를 받아 $u$ 를 내는 제어기 |
