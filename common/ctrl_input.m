function [u, t, umax] = ctrl_input(C, G, t)
%CTRL_INPUT  단위 계단 지령을 넣었을 때 제어기가 내보내는 신호 u(t)
%
%   [u, t, umax] = ctrl_input(C, G)
%   [u, t, umax] = ctrl_input(C, G, t)
%
%   왜 필요한가
%     설계를 끝내고 step(T) 로 출력만 확인하면 절반만 본 것입니다.
%     구동기(모터, 밸브, 추진기)가 실제로 낼 수 있는 힘에는 한계가 있어서
%     제어입력 u(t) 가 그 한계를 넘으면 설계는 종이 위에서만 맞습니다.
%
%   원리
%     지령 r 에서 제어입력 u 까지의 전달함수는
%
%         U(s)        C(s)
%         ---- = --------------
%         R(s)    1 + C(s)G(s)
%
%     입니다. 계단 지령이면 R(s) = 1/s 이므로 U(s) 를 직접 만들어
%     역라플라스 변환하면 u(t) 가 나옵니다.
%
%   입력
%     C - 제어기 전달함수 (이득까지 포함한 것)
%     G - 플랜트 전달함수
%     t - 시간 벡터 (생략하면 자동)
%
%   출력
%     u    - 제어입력 (열벡터)
%     t    - 시간 벡터 (열벡터)
%     umax - max |u(t)| , t > 0 구간
%
%   주의 : PD 제어기의 미분 킥
%     이상적인 PD 제어기 C = K(s+z) 에 계단 지령을 넣으면 u(t) 안에
%     t = 0 에서 임펄스(무한대 스파이크)가 생깁니다. 계단은 순간적으로
%     튀는 신호인데 미분기가 그 기울기를 그대로 증폭하기 때문입니다.
%     이 함수는 그 임펄스를 빼고 t > 0 의 연속 부분만 돌려줍니다.
%     실제 장치에서는 이 임펄스가 문제가 되므로 유사미분을 씁니다.
%     (7주차 Lead 보상기 절 참고)
%
%   예제
%     s = tf('s');  G = 1/(s*(s+2));
%     [u, t, umax] = ctrl_input(5*(s+3), G);
%     plot(t, u); fprintf('max|u| = %.2f\n', umax);
%
%   제어시스템설계 | 충남대학교 자율운항시스템공학과

if nargin < 3 || isempty(t)
    t = linspace(0, 10, 2001)';
end
t = t(:);

% 1. 지령 -> 제어입력 전달함수를 만들고 계단 입력을 곱한다
s  = tf('s');
Ur = minreal(C / (1 + C*G), 1e-6);      % U(s)/R(s)
U  = minreal(Ur / s, 1e-6);             % U(s)  (계단 지령)

% 2. 임펄스 성분(직결항)을 분리한다
[n, d] = tfdata(U, 'v');
n = n(:).'; d = d(:).';
if numel(n) > numel(d)
    error(['ctrl_input:부적절 - 제어기가 너무 이상적이어서 제어입력을 ' ...
           '계산할 수 없습니다. 유사미분 형태로 바꾸십시오.']);
end
[~, rem] = deconv([zeros(1, numel(d)-numel(n)) n], d);

% 3. 연속 부분을 역라플라스 변환 (계단 지령이므로 U(s) 의 임펄스응답)
u = impulse(tf(rem, d), t);
u = u(:);

umax = max(abs(u));
end
