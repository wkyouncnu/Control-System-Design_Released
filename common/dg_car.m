function dg_car(ttl)
%DG_CAR  자동차 운전으로 본 피드백 (강의자료 2_Concept 4쪽)
%
%   dg_car()
%   dg_car('제목')
%
%   왜 이 그림인가
%     블록선도를 처음 보면 기호가 낯설어 무슨 말인지 안 들어옵니다.
%     그런데 **누구나 이미 피드백 제어기를 해 본 적이 있습니다.** 운전입니다.
%
%       운전자는 가고 싶은 방향과 실제 가는 방향의 차이를 **눈으로 보고**,
%       그 차이를 줄이도록 핸들을 돌린다.
%
%     이 문장을 그대로 블록으로 옮기면 폐루프 블록선도가 됩니다.
%     기호만 바꾸면 `dg_loop('closed')` 와 같은 그림입니다.
%
%   대응
%     원하는 방향  <->  목표값 r
%     눈으로 본 차이 <->  오차 e
%     운전자        <->  제어기 C(s)
%     핸들 각도     <->  제어입력 u
%     자동차        <->  플랜트 G(s)
%     실제 방향     <->  출력 y
%
%   출처
%     강의자료/2024년/02_Concept.pptx  4쪽 "Feedback concept in car driving"
%
%   See also DG_LOOP
%
%   제어시스템설계 | 충남대학교 자율운항시스템공학과

if nargin < 1 || isempty(ttl), ttl = '운전자가 곧 피드백 제어기다'; end

% 라벨이 블록에 겹치지 않도록 두 가지를 함께 합니다.
%   (1) 화살표를 넉넉히 길게 잡는다
%   (2) **그림 창을 넓게 잡는다** — dg_arrow 의 글자 크기는 11 pt 로 고정이라,
%       그림이 작게 뽑히면 글자가 상대적으로 커져 블록을 덮는다.
dg_new(15.5, 4.8, ttl);
set(gcf, 'Position', [80 80 1180 380]);

e  = dg_sum(2.9, 2.8, '+-');
dr = dg_block(6.0, 2.8, 2.0, 1.0, '운전자',   [0.88 0.93 1.00]);
wh = dg_block(9.3, 2.8, 1.8, 1.0, '핸들',     [1.00 0.95 0.85]);
ca = dg_block(12.5, 2.8, 1.8, 1.0, '자동차',  [0.93 0.93 0.93]);

dg_arrow([0.6 2.8], e.L, '원하는 방향');
dg_arrow(e.R, dr.L, '차이');
dg_arrow(dr.R, wh.L, '');
dg_arrow(wh.R, ca.L, '핸들 각도');
dg_arrow(ca.R, [15.0 2.8], '실제 방향');
dg_arrow([14.2 2.8], [14.2 1.0], '');
dg_arrow([14.2 1.0], [2.9 1.0], '눈으로 본다', 'dash');
dg_arrow([2.9 1.0], e.B, '');

text(7.8, 4.35, '차이를 보고 그만큼 고친다 — 이것이 피드백의 전부다', ...
     'HorizontalAlignment','center', 'FontSize', 10, 'Color', [0.45 0.45 0.45]);
text(7.8, 0.35, '기호만 바꾸면 r, e, C(s), u, G(s), y 인 폐루프 블록선도가 된다', ...
     'HorizontalAlignment','center', 'FontSize', 10, 'Color', [0.45 0.45 0.45]);
end
