%% 1. 전달함수의 정의
%
%  전달함수는 "입력을 넣으면 출력이 얼마나 나오는가"를 s 영역에서 나타낸 비율입니다.
%
%      G(s) = Y(s) / U(s)        (단, 모든 초기조건이 0)
%
%  왜 초기조건이 0 이어야 하는가:
%      전달함수는 시스템 자체의 성질만 담고 싶기 때문입니다.
%      초기조건은 시스템의 성질이 아니라 "지금 어떤 상태에 있는가"이므로
%      전달함수에서는 배제합니다.
%
%  왜 굳이 s 영역으로 가는가:
%      시간영역에서 입력과 출력의 관계는 미분방정식입니다. 풀기 번거롭고,
%      시스템 여러 개를 연결하면 감당이 안 됩니다.
%      s 영역에서는 이 관계가 단순한 곱셈이 됩니다.
%
%          Y(s) = G(s) * U(s)
%
%      곱셈이니까 직렬 연결은 그냥 곱하면 되고, 병렬은 더하면 됩니다.
%      이것이 라플라스 변환을 배우는 실용적인 이유의 전부입니다.

%% 2. 전달함수를 만드는 세 가지 방법
%
%  예제로 이 시스템을 씁니다.
%
%      G(s) = 2*(s+1) / (s^2 + 3*s + 2) = 2*(s+1) / ((s+1)*(s+2))

% --- 방법 1 : 계수 벡터로 만들기 ---
%     분자와 분모의 계수를 s 의 높은 차수부터 나열합니다.
%     분자 2*(s+1) = 2s + 2  -> [2 2]
%     분모 s^2 + 3s + 2      -> [1 3 2]
G1 = tf([2 2], [1 3 2]);

% --- 방법 2 : s 를 변수처럼 쓰기 (이 과목의 기본 방식) ---
%     s = tf('s') 로 선언해 두면 수식을 종이에 쓰듯 그대로 입력할 수 있습니다.
%     식이 복잡할수록 이 방법이 압도적으로 편하고 실수도 적습니다.
s  = tf('s');
G2 = 2*(s+1) / (s^2 + 3*s + 2);

% --- 방법 3 : 영점, 극점, 이득으로 만들기 ---
%     zpk(영점벡터, 극점벡터, 이득)
%     인수분해된 형태를 이미 알고 있을 때 가장 직관적입니다.
G3 = zpk(-1, [-1 -2], 2);

fprintf('=== 세 가지 방법으로 만든 전달함수 ===\n');
G1
G2
G3

%% 2-1. 정말 같은 것인가 확인
%
%  겉보기 표현은 달라도 같은 시스템입니다. 두 가지로 확인합니다.
%    (1) 계단응답의 최대 차이가 0 에 가까운가
%    (2) 극점과 영점이 같은가

t = 0:0.01:10;
y1 = step(G1, t);
y2 = step(G2, t);
y3 = step(G3, t);

fprintf('\n=== 세 표현이 같은지 확인 ===\n');
fprintf('  G1 과 G2 의 응답 최대 차이 : %.3e\n', max(abs(y1-y2)));
fprintf('  G1 과 G3 의 응답 최대 차이 : %.3e\n', max(abs(y1-y3)));
fprintf('  --> 표현 방법이 다를 뿐 같은 시스템입니다.\n');
fprintf('      상황에 맞게 편한 방법을 쓰면 됩니다.\n\n');

%% 2-2. 셋 중 무엇을 쓸까
%
%  결론: 이 과목에서는 방법 2 (s 연산자) 를 기본으로 씁니다.
%
%  이유는 단순합니다. 종이에 쓴 식을 그대로 옮겨 적을 수 있어서
%  실수가 가장 적기 때문입니다. 계수를 하나씩 세다 보면 꼭 틀립니다.
%
%  방법 1 은 남의 코드를 읽을 때 알아볼 정도면 되고,
%  방법 3 은 극점과 영점을 이미 알고 있을 때 편합니다.

%% 3. 극점과 영점이란 무엇인가
%
%  전달함수를 분수로 보면
%
%      G(s) = N(s) / D(s)
%
%  극점(pole)  : 분모를 0 으로 만드는 s. 즉 G(s) 가 무한대가 되는 지점.
%  영점(zero)  : 분자를 0 으로 만드는 s. 즉 G(s) 가 0 이 되는 지점.
%
%  분모를 0 으로 놓은 식 D(s) = 0 을 특성방정식(characteristic equation)이라고 하고,
%  그 근이 곧 극점입니다.
%
%  왜 특성방정식이라 부르는가:
%      이 방정식이 시스템의 "성격"을 결정하기 때문입니다.
%      빠른지 느린지, 진동하는지 아닌지, 안정한지 불안정한지가
%      전부 극점 위치에서 나옵니다. 입력이 무엇이든 상관없습니다.
%
%  이제 그 이유를 봅시다.

G = 4 / (s^2 + 2*s + 4);          % 예제 시스템

fprintf('=== 극점과 영점 ===\n');
fprintf('  전달함수 G(s) = 4/(s^2+2s+4)\n');

pl = pole(G);
fprintf('  극점 : ');
fprintf('%+.3f%+.3fj   ', [real(pl).'; imag(pl).']);
fprintf('\n');

zr = zero(G);
if isempty(zr)
    fprintf('  영점 : 없음 (분자가 상수 4 라서 0 이 되는 s 가 존재하지 않습니다)\n\n');
else
    fprintf('  영점 : ');
    fprintf('%+.3f%+.3fj   ', [real(zr).'; imag(zr).']);
    fprintf('\n\n');
end

fprintf('  damp 명령으로 극점을 해석하면:\n');
damp(G)

%% 4. 극점 위치가 응답 모양을 결정한다
%
%  이번 절이 2주차의 핵심입니다.
%
%  극점이 p 일 때 응답에는 exp(p*t) 라는 항이 나타납니다.
%  이것을 모드(mode)라고 부릅니다. 따라서 극점 위치를 보면 응답 모양을 알 수 있습니다.
%
%      p 가 음의 실수         -> exp(-|p|t)          지수적으로 감소
%      p 가 양의 실수         -> exp(+|p|t)          지수적으로 발산 (불안정)
%      p = a +- j*w (a<0)     -> exp(at)*cos(wt)     진동하며 감소
%      p = a +- j*w (a>0)     -> exp(at)*cos(wt)     진동하며 발산 (불안정)
%      p = +- j*w  (a=0)      -> cos(wt)             영원히 같은 크기로 진동
%
%  정리하면 이렇습니다.
%      실수부 = 얼마나 빨리 사라지는가 (왼쪽일수록 빨리 사라짐)
%      허수부 = 얼마나 빨리 흔들리는가 (위아래로 멀수록 빨리 흔들림)
%      실수부가 하나라도 0 보다 크면 -> 불안정
%
%  아래에서 다섯 가지 경우를 직접 그려 봅니다.

cases = {
    '음의 실근 두 개 (진동 없음)',        1/((s+0.5)*(s+2))
    '복소근, 실수부 음수 (감쇠 진동)',    1/(s^2 + 0.6*s + 4)
    '순허수근 (지속 진동)',               1/(s^2 + 4)
    '복소근, 실수부 양수 (발산 진동)',    1/(s^2 - 0.6*s + 4)
    '양의 실근 (지수 발산)',              1/((s-0.5)*(s+2))
};

t2 = 0:0.01:15;

figure('Name','극점 위치와 응답 모양');
tiledlayout(numel(cases(:,1)), 2, 'TileSpacing','compact');

for i = 1:size(cases,1)
    Gi = cases{i,2};

    % 왼쪽 : 극점 위치
    nexttile
    pl = pole(Gi);
    plot(real(pl), imag(pl), 'x', 'MarkerSize', 12, 'LineWidth', 3); hold on;
    xline(0, 'k-', 'LineWidth', 1.5);      % 허수축 (안정 경계)
    yline(0, 'k:', 'LineWidth', 0.5);
    grid on; xlim([-2.5 1.5]); ylim([-3 3]);
    ylabel('Imag');
    if i == 1, title('극점 위치 (x 표시)'); end
    if i == size(cases,1), xlabel('Real'); end

    % 오른쪽 : 임펄스 응답 (자연응답)
    nexttile
    plot(t2, impulse(Gi, t2), 'LineWidth', 2); grid on;
    ylabel('y(t)');
    if i == 1, title('임펄스 응답'); end
    if i == size(cases,1), xlabel('Time [s]'); end
    text(0.02, 0.9, cases{i,1}, 'Units','normalized', 'FontSize', 9);
end

fprintf('=== 다섯 가지 극점 배치 ===\n');
for i = 1:size(cases,1)
    pl = pole(cases{i,2});
    fprintf('  %-32s 극점 = %s\n', cases{i,1}, ...
            strjoin(arrayfun(@(z) sprintf('%+.2f%+.2fj', real(z), imag(z)), ...
                    pl.', 'UniformOutput', false), ', '));
end
fprintf('  --> 허수축(실수부 0)을 기준으로 왼쪽이면 안정, 오른쪽이면 불안정입니다.\n');
fprintf('      이 하나의 문장이 5주차 안정도 판별의 전부입니다.\n\n');

%% 5. 영점은 무슨 일을 하는가
%
%  간단히 말하면 이렇습니다.
%
%      극점은 응답의 "재료"를 정하고,
%      영점은 그 재료를 "얼마씩 섞을지"를 정합니다.
%
%  그래서 극점을 그대로 두고 영점만 바꾸면, 진동 주파수와 감쇠 속도는
%  똑같은데 초반 모양만 달라집니다. 아래에서 확인해 봅시다.

G_base = 4/(s^2 + 2*s + 4);        % 영점 없음

Gz1 = G_base * (s/2  + 1);          % 좌반면 영점 s = -2
Gz2 = G_base * (-s/2 + 1);          % 우반면 영점 s = +2  (비최소위상)

t3 = 0:0.01:8;

figure('Name','영점의 영향');
h1 = plot(t3, step(G_base, t3), 'LineWidth', 2); hold on;
h2 = plot(t3, step(Gz1,   t3), 'LineWidth', 2);
h3 = plot(t3, step(Gz2,   t3), 'LineWidth', 2);
yline(1, 'k--'); grid on;
xlabel('Time [s]'); ylabel('y(t)');
title('극점은 그대로, 영점만 바꿨을 때');
legend([h1 h2 h3], {'영점 없음', '좌반면 영점 (s = -2)', '우반면 영점 (s = +2)'}, ...
       'Location','southeast');

fprintf('=== 영점의 영향 ===\n');
fprintf('  왼쪽(음수) 영점 : 초반이 빨라지고 오버슈트가 커집니다.\n');
fprintf('  오른쪽(양수) 영점 : 처음에 반대 방향으로 갔다가 돌아옵니다.\n');
fprintf('\n');
fprintf('  오른쪽 영점이 만드는 이 "처음엔 반대로" 현상은 실제로 있습니다.\n');
fprintf('  비행기 고도를 올리려고 조종간을 당기면 순간적으로 고도가 살짝\n');
fprintf('  내려갔다가 올라갑니다. 꼬리날개가 먼저 아래로 눌리기 때문입니다.\n');
fprintf('  이런 시스템은 제어하기 까다롭습니다. 목표로 가라고 했는데 처음엔\n');
fprintf('  반대로 가니 제어기가 헷갈리기 때문입니다.\n\n');

%% 6. 이번 실습의 정리
%
%  1) 전달함수는 초기조건 0 에서의 출력/입력 비이며, s 영역에서 곱셈으로
%     시스템을 다룰 수 있게 해 줍니다.
%
%  2) MATLAB 에서 만드는 법은 tf(계수), s 연산자, zpk 세 가지가 있고
%     모두 같은 결과를 줍니다. 이 과목에서는 s 연산자 방식을 기본으로 씁니다.
%
%  3) 극점 = 특성방정식의 근 = 응답에 나타나는 모드 exp(p*t) 의 지수.
%       실수부는 감쇠 속도, 허수부는 진동 주파수를 결정합니다.
%       실수부가 하나라도 양수면 불안정합니다.
%
%  4) 영점은 모드의 혼합 비율을 바꿉니다. 특히 우반면 영점은 응답을 잠깐
%     반대로 보내는 고약한 성질이 있습니다.
%
%  다음 실습 : W02_02_msd_derivation.m
%              물리 법칙에서 출발해 전달함수를 직접 유도하고,
%              댐퍼 값을 바꾸면 극점이 어떻게 움직이는지 추적합니다.
