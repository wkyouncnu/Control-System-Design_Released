%
% 왜 그런가 — $(s+z)G(s)$ 를 풀어 쓰면 $sG(s) + zG(s)$ 입니다.
% 앞항이 **미분**입니다. $z$ 가 작을수록 미분 성분의 비중이 커져 초반이 가팔라집니다.
