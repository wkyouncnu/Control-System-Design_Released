%% 7. 극점과 영점
% 전달함수를 $G(s) = \frac{N(s)}{D(s)}$ 로 보면
%
% - **극점** (pole) — 분모를 $0$ 으로 만드는 $s$. $G(s)$ 가 무한대가 되는 지점
% - **영점** (zero) — 분자를 $0$ 으로 만드는 $s$. $G(s)$ 가 $0$ 이 되는 지점
%
% 분모를 $0$ 으로 놓은 식 $D(s)=0$ 을 **특성방정식**이라 하고 그 근이 극점입니다.
%
% "특성"이라는 이름이 붙은 이유가 있습니다. 시스템이 빠른지 느린지, 진동하는지
% 아닌지, 안정한지 불안정한지가 **전부 이 방정식의 근에서 결정**되기 때문입니다.
% 입력이 무엇이든 상관없습니다. 시스템 자체의 성격입니다.
%% 8. 왜 극점이 응답을 결정하는가
% 이유는 의외로 단순합니다. **부분분수 전개**를 해 보면 바로 보입니다.
%
% 극점이 $p_1$, $p_2$ 인 시스템의 응답을 라플라스 영역에서 쪼개면
%
% $$Y(s) = \frac{A}{s - p_1} + \frac{B}{s - p_2} + (\text{입력이 만든 항})$$
%
% 이 되고, 각 항을 시간 영역으로 되돌리면
%
% $$y(t) = A\,e^{p_1 t} + B\,e^{p_2 t} + \ldots$$
%
% 입니다. 즉 **극점 하나가 지수함수 항 하나**를 만듭니다.
% 이것을 **모드**라고 부릅니다.
%
% 그러면 극점 위치를 보고 응답을 읽을 수 있습니다.
% 극점을 $p = \sigma + j\omega$ 라고 쓰면
%
% $$e^{pt} = e^{\sigma t}\,e^{j\omega t}
%          = e^{\sigma t}\;\times\;(\cos\omega t + j\sin\omega t)$$
%
% 앞의 $e^{\sigma t}$ 가 **크기**를 맡고, 뒤의 $\cos$, $\sin$ 이 **흔들림**을 맡습니다.
%
% 이므로 두 부분이 각각 다른 일을 합니다.
%
% - **실수부 $\sigma$** — 크기를 정한다. 음수면 줄어들고 양수면 커진다
% - **허수부 $\omega$** — 흔들리는 빠르기를 정한다
% - 실수부가 하나라도 $0$ 보다 크면 그 항이 커지므로 **전체가 발산**한다
%
% 말로 하면 어렵습니다. 그림으로 봅니다.
% ![극점 위치와 응답 모양](polemap.png)
%
% **그림 파일** `polemap.png` — `common/dg_polemap.m` 의 `dg_polemap`
%   · 다시 만들려면 `make_figures('polemap')`
%
% **만드는 곳** — `common/dg_polemap.m` (`make_figures('polemap')`)
%
% 그림 해석 — **왼쪽의 번호와 오른쪽의 번호를 짝지어 보십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림의 분홍 영역 | 오른쪽 절반 | **여기 있으면 발산**한다 |
% | 왼쪽 세로축(허수부) | 얼마나 빨리 진동하는가 | $0$ 이면 안 진동한다 |
% | 왼쪽 가로축(실수부) | 얼마나 빨리 사라지는가 | 왼쪽일수록 빠르다 |
% | 극점 1 ($-0.5$, 실수) | 오른쪽 1번 : 느리게 사라짐 | 원점에 가까우니 느리다 |
% | 극점 2 ($-2$, 실수) | 오른쪽 2번 : 빠르게 사라짐 | 왼쪽으로 갔더니 빨라졌다 |
% | 극점 3 ($-0.5 \pm 2j$) | 오른쪽 3번 : 느리게 진동하며 사라짐 | 허수부가 생기니 **진동이 생겼다** |
% | 극점 4 ($-2 \pm 2j$) | 오른쪽 4번 : 빠르게 감쇠 | 왼쪽으로 가니 빨리 감쇠한다 |
% | 극점 5 ($0 \pm 2j$, 허수축 위) | 오른쪽 5번 : 계속 진동 | **줄지도 늘지도 않는다.** 안정 경계 |
% | 극점 6 (우반면) | 오른쪽 6번 : 진동하며 발산 | 화면 밖으로 나간다 |
%
% 이 그림 한 장이 앞으로 열두 주 동안 쓸 지도입니다.
% **왼쪽으로 갈수록 빠르고, 위아래로 갈수록 흔들리고, 오른쪽은 금지 구역**입니다.
%% 7-1. 극점을 옮기면 응답이 어떻게 변하는가
% 극점의 **실수부와 허수부를 따로** 움직여 보면 각각이 무엇을 정하는지 분명해집니다.
