%% 12. 전달함수의 한계
% 질문 하나를 던져 봅니다.
%
% **"물체를 $0.5\,\mathrm{m}$ 당겨 놓고 힘을 전혀 주지 않은 채 놓았다. 어떻게 되는가?"**
%
% 전달함수로 답해 보면 입력 $F=0$ 이므로 $X(s) = G(s)\cdot 0 = 0$ 입니다.
% 즉 **"아무 일도 안 일어난다"** 고 답합니다. 명백히 틀렸습니다.
%
% 이유는 3단계에서 초기조건을 $0$ 으로 두고 버렸기 때문입니다.
% 전달함수는 입력과 출력의 관계만 담을 뿐, **시스템 내부가 지금 어떤 상태인지는
% 담지 못합니다.**
%
% 못 담는 것이 초기조건만은 아닙니다. 한 장으로 정리하면 이렇습니다.
%
% ![전달함수가 못 다루는 것 세 가지](w02_tf_limits.png)
%
% **그림 파일** `w02_tf_limits.png` — `make_figures.m` 의 `fig_w02_tf_limits`
%   · 다시 만들려면 `make_figures('w02_tf_limits')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w02_tf_limits`
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 두 곡선 | 초기값 0.8 만큼 통째로 어긋난다 | 전달함수는 초기조건을 버렸다 |
% | 오른쪽 위 | 입력 3 과 1.2 의 결과가 다르다 | 포화를 모른다 |
% | 왼쪽 아래 | 각이 작을 때만 두 곡선이 겹친다 | 동작점 근처에서만 맞다 |
% | 오른쪽 아래 | 곡선 하나로 시스템이 요약된다 | 그래도 쓰는 이유 |
%
% | 한계 | 발생하는 현상 | 다루는 주차 |
% |---|---|---|
% | 초기조건을 $0$ 으로 본다 | 당겨 놓고 놓으면 아무 일도 없다고 답한다 | 3주차 상태공간 |
% | 비선형을 모른다 | 구동기가 포화해도 그대로 계산한다 | 6주차 · 11주차 |
% | 한 동작점에서만 맞다 | 크게 움직이면 어긋난다 | 3주차 선형화 |
%
% 그런데도 학기 내내 전달함수를 쓰는 이유는 오른쪽 아래 칸에 있습니다.
% **미분방정식을 풀지 않고 블록을 곱셈으로 이어 붙일 수 있기 때문**입니다.
% 설계는 거기서 합니다. 그리고 **검증은 반드시 Simulink 로** 합니다.
%
% 이 한계를 넘으려면 **세 번째 표현**이 필요합니다. 다음 절에서 소개합니다.
%% 12-1. 세 번째 표현 — 상태공간
% 오늘의 네 단계는 여기서 끝나지 않습니다. **한 칸이 더 있습니다.**
%
% $$\text{미분방정식} \rightarrow \text{라플라스} \rightarrow
%   \text{전달함수} \rightarrow \text{상태공간}$$
%
% 앞 절에서 본 한계의 원인은 하나였습니다 —
% **라플라스 변환할 때 초기조건을 $0$ 으로 두고 버렸다**는 것입니다.
%
% 그러면 **버리지 않는 길**로 가면 됩니다.
% 라플라스 변환을 아예 하지 않고, 미분방정식을 그대로 두는 것입니다.
%
% **아이디어 — 2계 미분방정식 하나를 1계 두 개로 쪼갠다**
%
% 컴퓨터는 1계 미분방정식만 풀 줄 압니다. 그래서 2계짜리를 1계 두 개로 나눕니다.
% 나누려면 **무엇을 계속 기억하고 있어야 하는지**를 정해야 합니다.
%
% 질량-스프링-댐퍼에서 다음 순간을 계산하려면 무엇을 알아야 하는가?
%
% - **위치만?** 부족합니다. 같은 자리라도 날아가는 중인지 멈춰 있는지 다릅니다
% - **위치와 속도?** 충분합니다. 이 둘과 앞으로 들어올 힘만 알면 미래가 정해집니다
%
% 그래서 이 둘을 **상태**(state)라고 부르고 이름을 붙입니다.
%
% $$x_1 = x \;(\text{위치}), \qquad x_2 = \dot{x} \;(\text{속도})$$
%
% 이제 각 상태의 미분을 **상태와 입력만으로** 적습니다.
%
% $$\dot{x}_1 = \dot{x} = x_2$$
%
% $$\dot{x}_2 = \ddot{x} = \frac{1}{m}\left(F - b\dot{x} - kx\right)
%              = -\frac{k}{m}x_1 - \frac{b}{m}x_2 + \frac{1}{m}F$$
%
% 둘째 줄은 오늘 2절에서 세운 운동방정식을 $\ddot{x}$ 에 대해 푼 것뿐입니다.
% **새로운 물리는 하나도 없습니다.** 같은 식을 다르게 적었을 뿐입니다.
%% 12-2. 행렬로 묶으면 두 줄이 됩니다
% 위 두 식의 계수만 뽑아 행렬로 적습니다.
%
% $$\left[\begin{array}{c}\dot{x}_1\\ \dot{x}_2\end{array}\right] =
%   \left[\begin{array}{cc} 0 & 1\\ -\frac{k}{m} & -\frac{b}{m}\end{array}\right]
%   \left[\begin{array}{c}x_1\\ x_2\end{array}\right] +
%   \left[\begin{array}{c}0\\ \frac{1}{m}\end{array}\right] F$$
%
% 우리가 재는 것이 위치라면
%
% $$x = \left[\begin{array}{cc}1 & 0\end{array}\right]
%       \left[\begin{array}{c}x_1\\ x_2\end{array}\right] + 0\cdot F$$
%
% 이 두 줄을 기호로 쓴 것이 **상태공간 표현**입니다.
%
% $$\dot{x} = Ax + Bu, \qquad y = Cx + Du$$
%
% 네 행렬의 뜻만 지금 알아 두면 됩니다.
%
% | 행렬 | 크기 | 담고 있는 정보 |
% |---|---|---|
% | $A$ | $2\times 2$ | 아무도 안 건드려도 시스템이 저 혼자 어떻게 움직이는가 |
% | $B$ | $2\times 1$ | 입력이 어느 상태를 얼마나 밀어 주는가 |
% | $C$ | $1\times 2$ | 여러 상태 중 우리가 실제로 볼 수 있는 것은 무엇인가 |
% | $D$ | $1\times 1$ | 입력이 출력에 곧바로 튀어나오는 몫 (대개 $0$) |
%
% **왜 이것이 초기조건 문제를 푸는가** — 상태 $x_1, x_2$ 가 식 안에 그대로
% 살아 있습니다. 시작할 때 $x_1(0) = 0.5$ 라고 넣어 주면 됩니다.
% 전달함수에는 그 값을 넣을 자리가 아예 없었습니다.
%
% **오늘은 여기까지입니다.** 상태를 고르는 요령, 표현이 여러 개인 이유,
% 상태공간으로만 할 수 있는 일은 **3주차 4~6절**에서 제대로 다룹니다.
% 오늘은 "세 번째 표현이 있고, 그것이 초기조건을 담는다" 만 알면 됩니다.
%% 12-3. `ss` — 오늘의 마지막 새 명령
% - **하는 일** — 네 행렬 $A, B, C, D$ 로 상태공간 모델을 만든다
% - **입력** — `ss(A, B, C, D)`. 행렬 네 개
% - **출력** — 상태공간 객체. `tf` 로 만든 것과 거의 똑같이 쓸 수 있다
%
% 함께 알아 둘 것
%
% - `tf(sys)` — 상태공간을 전달함수로 바꾼다
% - `ss(G)` — 전달함수를 상태공간으로 바꾼다
% - `initial(sys, x0, t)` — **초기조건에서 출발한 응답**. `tf` 에는 없는 기능
%
% 주의
%
% - $A$ 는 정사각행렬이어야 하고, $B$ 의 행 수가 $A$ 와 같아야 한다
% - $C$ 의 열 수도 $A$ 와 같아야 한다. 크기가 안 맞으면 바로 오류가 난다
% - `initial` 의 $x_0$ 는 **열벡터**로 준다
%
% 이제 손으로 만든 행렬이 정말 같은 시스템인지 확인해 봅니다.
A_hand = [0 1; -k/m, -b/m];
B_hand = [0; 1/m];
C_hand = [1 0];
D_hand = 0;
sys_ss = ss(A_hand, B_hand, C_hand, D_hand);

fprintf('=== 손으로 만든 상태공간 ===\n');
fprintf('  m = %.1f, b = %.1f, k = %.1f\n', m, b, k);
disp('A ='); disp(A_hand);
disp('B ='); disp(B_hand);
fprintf('C = %s ,  D = %g\n\n', mat2str(C_hand), D_hand);

fprintf('=== 전달함수로 되돌리면 ===\n');
tf(sys_ss)
fprintf('  오늘 4단계에서 구한 G(s) 의 극점 : %s\n', ...
        mat2str(round(sort(pole(G)).', 4)));
fprintf('  상태공간에서 되돌린 것의 극점    : %s\n', ...
        mat2str(round(sort(pole(tf(sys_ss))).', 4)));
fprintf('  --> 같은 시스템입니다. 표현만 다릅니다.\n');
%% 12-4. 이제 아까 그 질문에 답할 수 있습니다
% **"물체를 $0.5\,\mathrm{m}$ 당겨 놓고 힘 없이 놓았다. 어떻게 되는가?"**
%
% 상태공간에는 초기조건을 넣을 자리가 있으므로 `initial` 로 바로 답합니다.
% 물리적으로 기대하는 답은 **진동하며 제자리로 돌아온다** 입니다.
t5 = 0:0.01:40;
plot(t5, initial(sys_ss, [0.5;0], t5), 'LineWidth',2); hold on
plot(t5, zeros(size(t5)), 'k--', 'LineWidth',2)
yline(0,'k:'); grid on
xlabel('시간 [s]'); ylabel('변위 x [m]')
title('0.5 m 당겨 놓고 놓았을 때 (F = 0)')
legend('상태공간이 주는 답','전달함수가 주는 답 (항상 0)','Location','northeast')
%%
% 파란 곡선이 우리가 기대한 답입니다. 검은 점선이 전달함수의 답이고요.
%
% **이것으로 오늘의 사슬이 완성되었습니다.**
%
% | 표현 | 유도 방법 | 용도 | 초기조건 |
% |---|---|---|---|
% | 미분방정식 | 자유물체도에서 | 물리를 그대로 담는다 | 담긴다 |
% | 전달함수 | 라플라스 변환 | **설계.** 블록을 곱셈으로 잇는다 | 못 담는다 |
% | 상태공간 | 1계 두 개로 쪼개기 | **해석과 현대제어** (12~14주차) | 담긴다 |
%
% 다음 절에서 이 셋을 Simulink 에 나란히 놓고 **정말 같은지** 확인합니다.
%% 13. Simulink 로 확인하기 — 세 표현을 나란히
% 모델 `W02_MSD_ThreeWays.slx` 에는 **오늘 배운 세 표현이 그대로 하나씩**
% 들어 있습니다. 위에서 아래로 세 갈래입니다.
%
% | 경로 | 구성 방식 | 해당 절 |
% |---|---|---|
% | **A** | `Integrator` 블록 두 개 | 2~3절 미분방정식 |
% | **B** | `Transfer Fcn` 블록 | 5절 전달함수 |
% | **C** | `State-Space` 블록 | 12-2절 상태공간 |
%
% 셋을 같은 입력으로 동시에 구동하고 Scope 한 화면에 겹쳐 봅니다.
%% 13-1. 처음 보는 블록 세 가지
% 모델을 열기 전에 블록 이름을 짚고 갑니다. **처음 보는 것이 셋 있습니다.**
%
% | 블록 | 라이브러리 | 기능 | 대응하는 개념 |
% |---|---|---|---|
% | `Integrator` | Continuous | 들어온 신호를 **시간에 대해 적분**한다. 기호가 $1/s$ 다 | $\ddot{x} \to \dot{x} \to x$ 로 내려가는 계단 |
% | `Transfer Fcn` | Continuous | 분자·분모 계수를 넣으면 그 전달함수로 동작한다 | 5절의 $G(s) = 1/(ms^2+bs+k)$ |
% | `State-Space` | Continuous | 행렬 $A,B,C,D$ 를 넣으면 그 상태공간으로 동작한다 | 12-2절의 네 행렬 |
% | `Mux` | Signal Routing | 신호 여러 개를 **한 다발로 묶는다.** 계산은 안 한다 | 세 경로를 Scope 하나에 넣으려고 |
%
% `Integrator` 를 두 개 쓰는 이유
%
% - 운동방정식을 $\ddot{x} = (F - b\dot{x} - kx)/m$ 로 정리한다
% - 왼쪽 끝에서 $\ddot{x}$ 를 만들고 적분하면 $\dot{x}$
% - 한 번 더 적분하면 $x$
% - 그 $x$ 와 $\dot{x}$ 를 다시 앞으로 되먹여 $kx$ 와 $b\dot{x}$ 를 만든다
%
% **즉 블록선도가 곧 미분방정식입니다.** 되먹임 선 두 개가 스프링과 댐퍼입니다.
%
% `Integrator` 와 `Transfer Fcn` 의 결정적 차이
%
% - `Integrator` 를 더블클릭하면 `Initial condition` 칸이 **있다**
% - `Transfer Fcn` 을 더블클릭하면 그 칸이 **없다**
% - `State-Space` 에는 `Initial conditions` 칸이 **있다**
%
% 12절에서 말로 설명한 한계가 **블록 다이얼로그에 그대로 있습니다.**
% 모델을 열면 직접 확인해 보십시오.
%% 13-2. 두 가지 실험
% `W02_03_run_simulink.m` 이 실험을 두 번 합니다.
%
% **실험 1 — 초기조건 $0$, 계단 입력**
%
% 세 응답이 **완전히 겹칩니다** (차이가 $10^{-6}$ 수준).
% 계산 방식은 전혀 다른데 답이 같은 이유는 셋 다 결국 같은 미분방정식이기 때문입니다.
%
% **실험 2 — 초기조건 $0.5\,\mathrm{m}$**
%
% **경로 B 만 반응하지 못합니다.** 넣을 칸이 없으니 당연합니다.
% A 와 C 는 진동하며 제자리로 돌아옵니다.
%
% 이 두 실험이 오늘 배운 것을 한 번에 확인해 줍니다 —
% **세 표현은 같은 것이지만, 담는 정보는 다르다.**
%
% 모델은 모델을 열고 `Ctrl+T` 를 눌러도 실행됩니다. Scope 가 자동으로 열립니다.
%% 13-3. 오늘 나온 명령을 여러 가지로 써 본다
% 같은 시스템을 세 가지 표현으로 오갈 수 있다는 것이 오늘의 요지였습니다.
% 그 왕복을 명령으로 어떻게 하는지 한자리에 모았습니다.
%
% | 호출 형태 | 무엇이 나오는가 | 언제 쓰는가 |
% |---|---|---|
% | `zpk(z, p, k)` | 영점·극점·이득으로 만든 전달함수 | 극영점을 직접 지정할 때 |
% | `[z,p,k] = zpkdata(G,'v')` | 영점·극점·이득을 **벡터로** 꺼낸다 | 값을 계산에 쓸 때 |
% | `[num,den] = tfdata(G,'v')` | 분자·분모 계수를 벡터로 | 계수가 필요할 때 |
% | `[A,B,C,D] = ssdata(sys)` | 네 행렬을 꺼낸다 | 상태공간으로 계산할 때 |
% | `ss(G)` | 전달함수를 상태공간으로 | 초기조건을 주고 싶을 때 |
% | `tf(sysSS)` | 상태공간을 전달함수로 | 극점·영점을 보고 싶을 때 |
% | `minreal(G)` | 극영점 상쇄를 정리한 최소실현 | 차수가 부풀었을 때 |
% | `impulse(G,t)` | 임펄스응답 | 계단응답의 **미분**과 같다 |
% | `initial(sysSS, x0, t)` | 입력 없이 초기조건만으로의 응답 | 전달함수로는 못 하는 일 |
%
% 두 번째 칸의 `'v'` 는 "벡터로 달라" 는 뜻입니다.
% 빼면 셀 배열로 나와 다루기 번거롭습니다.
s = tf('s');

% (1) 같은 시스템을 세 방식으로 만들고 대조한다
Ga = tf(4, [1 0.8 4]);
Gb = zpk([], roots([1 0.8 4]).', 4);
Gc = 4/(s^2 + 0.8*s + 4);
fprintf('tf 대 s 연산자 : %.2e,   tf 대 zpk : %.2e\n', ...
        norm(Ga-Gc, inf), norm(tf(Gb)-Gc, inf));

% (2) 값을 꺼내는 세 가지 명령
[zz, pp_, kk] = zpkdata(Gc, 'v');
[nn, dd]      = tfdata(Gc, 'v');
fprintf('zpkdata : 영점 %s, 극점 %s, 이득 %.4g\n', ...
        mat2str(round(zz.',3)), mat2str(round(pp_.',3)), kk);
fprintf('tfdata  : 분자 %s, 분모 %s\n', mat2str(nn), mat2str(dd));

% (3) 극영점 상쇄가 있으면 minreal 이 정리해 준다
Gcancel = (s+2)/((s+1)*(s+2));
fprintf('상쇄 전 극점 %s -> minreal 뒤 %s\n', ...
        mat2str(round(pole(Gcancel).',3)), ...
        mat2str(round(pole(minreal(Gcancel, 1e-6)).',3)));

% (4) 임펄스응답은 계단응답의 미분이다
tt = (0:0.001:15)';
ys = step(Gc, tt);  yi = impulse(Gc, tt);
fprintf('impulse 와 계단응답의 수치미분 차이 : %.3e (미분 오차)\n', ...
        max(abs(yi(2:end) - diff(ys)/0.001)));

% (5) 전달함수로는 못 하고 상태공간으로만 되는 일
Gss = ss([0 1; -4 -0.8], [0; 4], [1 0], 0);   % 물리 상태 : 위치와 속도
y_ini = initial(Gss, [0.5; 0], tt);
fprintf('초기 위치 0.5 에서 놓았을 때 : 시작 %.3f -> 끝 %.4f\n', ...
        y_ini(1), y_ini(end));
%% 14. 오늘의 정리
% - 모델링은 **물리법칙 → 미분방정식 → 라플라스 변환 → 전달함수** 네 단계다.
%   어떤 시스템이든 절차는 같고 바뀌는 것은 1단계의 물리 법칙뿐이다
% - 2차 시스템은 $\omega_n$ 과 $\zeta$ 두 숫자로 요약된다
% - 극점은 특성방정식의 근이고, 응답에 나타나는 모드 $e^{pt}$ 의 지수다
% - 극점이 전부 좌반면에 있으면 안정, 우반면에 하나라도 있으면 불안정
% - 영점은 모드가 섞이는 비율을 바꾼다. 오른쪽 영점은 응답을 잠깐 반대로 보낸다
% - **전달함수는 초기조건을 담지 못한다.** 그 한계를 넘는 것이 상태공간이다
% - 상태공간은 2계 미분방정식을 **1계 두 개로 쪼갠 것**이다.
%   $\dot{x}=Ax+Bu$, $y=Cx+Du$ 두 줄이고, 상태가 식 안에 살아 있어
%   초기조건을 그대로 넣을 수 있다
% - **같은 시스템의 세 표현** — 미분방정식 · 전달함수 · 상태공간.
%   Simulink 의 세 경로가 그것을 눈으로 확인해 준다
%% 다음 주 예고
% 3주차에서는 두 가지를 합니다.
%
% - **블록선도** — 시스템 여러 개가 직렬 · 병렬 · 되먹임으로 얽혀 있을 때
%   전체 전달함수를 구하는 규칙
% - **선형화** — 이번 학기 전반부에서 가장 중요한 개념
%
% 세상의 거의 모든 시스템은 사실 **비선형**입니다. 우리가 지금까지 쓴 선형 이론을
% 어떻게 적용할 수 있는가? 그 답이 선형화입니다.
%
% 진자를 예로 들어, 같은 시스템인데도 어느 지점 근처에서 선형화하느냐에 따라
% 안정한 모델이 나오기도 하고 불안정한 모델이 나오기도 하는 것을 직접 확인합니다.
