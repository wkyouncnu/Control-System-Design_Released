%% 9. 댐퍼를 세게 하면 극점은 어디로 가는가
% 극점은 특성방정식 $ms^2+bs+k=0$ 의 근이므로 근의 공식을 쓰면
%
% $$s = \frac{-b \pm \sqrt{b^2-4mk}}{2m}$$
%
% 판별식의 부호에 따라 세 가지로 갈립니다.
%
% - $b^2 < 4mk$ 즉 $\zeta<1$ — 복소근 → **부족감쇠**, 진동하며 수렴
% - $b^2 = 4mk$ 즉 $\zeta=1$ — 중근 → **임계감쇠**, 진동 없이 가장 빠르게
% - $b^2 > 4mk$ 즉 $\zeta>1$ — 서로 다른 실근 → **과감쇠**, 진동 없지만 느리게
%
% $b$ 를 $0$ 부터 키우면서 극점이 그리는 자취를 따라가 봅니다.
% 두 극점은 허수축에서 출발해 반지름 $\omega_n$ 인 원을 따라 왼쪽으로 이동하다가,
% $s = -\omega_n$ 에서 만난 뒤 실축을 따라 좌우로 갈라집니다.
%
% ![댐퍼를 키우면 극점이 실축으로 모인다](w02_damper_sweep.png)
%
% **그림 파일** `w02_damper_sweep.png` — `make_figures.m` 의 `fig_damper_sweep`
%   · 다시 만들려면 `make_figures('w02_damper_sweep')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_damper_sweep`
% **직접 바꿔 보려면** — `W02_02_msd_derivation.m` 의 **3절**에서
% `b` 목록을 바꿔 실행
%
% 그림 해석 — **왼쪽 $\times$ 와 오른쪽 곡선을 색으로 짝지으십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 회색 점선 원 | 반지름 $1$ | $\omega_n = 1$ 이 고정이라 극점이 이 원 위에 있다 |
% | 왼쪽 파란 $\times$ ($b=0.2$) | $-0.1 \pm 1.0j$, 허수축에 바짝 | 감쇠가 거의 없다 |
% | 왼쪽 빨간 $\times$ ($b=1.0$) | $-0.5 \pm 0.87j$ | 원 위를 미끄러져 내려왔다 |
% | 왼쪽 노란 $\times$ ($b=2.0$) | 실축 위 $-1$ 에 **하나로 겹친다** | **임계감쇠.** 원과 실축이 만나는 자리 |
% | 왼쪽 보라 $\times$ ($b=3.0$) | 실축 위 $-0.38$ 과 $-2.6$ 으로 갈라짐 | 원을 벗어나 좌우로 흩어진다 |
% | 왼쪽 전체 | 극점이 **원을 따라 미끄러지다 실축에서 갈라진다** | 댐퍼가 하는 일의 전부 |
% | 오른쪽 파란 곡선 | 첫 봉우리 $1.73$, 오래 진동한다 | 왼쪽 파란 $\times$ 와 짝 |
% | 오른쪽 노란 곡선 | 오버슈트 없이 가장 빨리 도달 | **임계감쇠가 가장 좋은 자리** |
% | 오른쪽 보라 곡선 | 오버슈트는 없지만 **더 느리다** | 과감쇠. 댐퍼가 너무 세면 오히려 느려진다 |
%
% **댐퍼를 키운다고 계속 좋아지지 않습니다.** $b = 2$ 가 최고이고
% 그보다 키우면 오히려 느려집니다. 4주차에서 이것을 $\zeta = 1$ 로 다시 만납니다.
b_sweep = linspace(0,4,400);
pp = zeros(2,numel(b_sweep));
for i=1:numel(b_sweep), pp(:,i) = roots([m b_sweep(i) k]); end
plot(real(pp(1,:)), imag(pp(1,:)), '.', 'MarkerSize',8); hold on
plot(real(pp(2,:)), imag(pp(2,:)), '.', 'MarkerSize',8)
for bm = [0.2 1.0 2.0 3.0]
    pm = roots([m bm k]);
    plot(real(pm), imag(pm), 'kx', 'MarkerSize',12, 'LineWidth',2)
    text(real(pm(1))+0.05, imag(pm(1))+0.08, sprintf('b=%.1f',bm), 'FontSize',9)
end
xline(0,'k-','LineWidth',1.5); grid on; axis equal
xlim([-4 0.5]); ylim([-1.5 1.5]); xlabel('Real'); ylabel('Imag')
title('b 를 0 에서 4 까지 키울 때 극점이 움직이는 길')
