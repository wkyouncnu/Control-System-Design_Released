% |---|---|---|
% | 왼쪽 위 세 쌍의 $\times$ | 같은 높이, 다른 가로 위치 | 허수부 고정, 실수부만 바꿈 |
% | 오른쪽 위 세 곡선 | 진동하는 **주기가 모두 같다** | 진동수는 허수부가 정한다 |
