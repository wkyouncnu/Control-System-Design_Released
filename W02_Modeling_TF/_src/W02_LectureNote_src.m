%% 10. 감쇠 상태별 응답
% 위 그림의 대표 지점들이 실제로 어떤 응답을 만드는지 봅니다.
%
% 눈여겨볼 점은 **임계감쇠 $\zeta=1$ 이 "진동 없이 가장 빠른" 지점**이라는 것입니다.
% 감쇠를 더 키우면 진동은 여전히 없지만 오히려 느려집니다.
% 극점 하나가 원점 쪽으로 되돌아오면서 그 느린 극점이 응답을 지배하기 때문입니다.
%
% 극점 위치와 응답을 **나란히** 놓고 보면 대응이 한눈에 들어옵니다.
%
% ![극점이 어디 있는지와 응답이 어떻게 생겼는지](w02_damping.png)
%
% **그림 파일** `w02_damping.png` — `make_figures.m` 의 `fig_w02_damping`
%   · 다시 만들려면 `make_figures('w02_damping')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w02_damping`
% **직접 바꿔 보려면** — 이 절 아래 코드에서 `bi` 목록에 값을 더해 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 점선 원 | 다섯 극점이 모두 원 위에 | $\omega_n$ 이 같고 $\zeta$ 만 다르다 |
% | 원이 허수축과 만나는 곳 | $\zeta = 0$ | 오른쪽에서 영원히 진동한다 |
% | 원이 실축과 만나는 곳 | $\zeta = 1$ | 진동 없이 가장 빠른 자리 |
% | 실축 위 두 점 ($\zeta=2$) | 극점이 갈라졌다 | 느린 쪽이 응답을 지배해 오히려 느리다 |
% | 오른쪽 $\zeta=0.3$ 곡선 | 가장 크게 넘어간다 | 각이 넓을수록 오버슈트가 크다 |
%
% 왼쪽 그림에서 점선 원의 반지름이 $\omega_n$ 입니다. **다섯 경우가 모두 같은 원 위에**
% 있습니다. $\zeta$ 만 다르므로 각도만 다릅니다.
%
% - $\zeta = 0$ — 극점이 허수축 위. 영원히 흔들린다
% - $\zeta = 0.3$ — 각이 넓다. 많이 넘어간다
% - $\zeta = 0.707$ — 각이 $45^\circ$. 오버슈트 약 $4.3\%$
% - $\zeta = 1$ — 두 극점이 실축에서 만난다. 진동이 없는 가장 빠른 지점
% - $\zeta = 2$ — 실극점 둘로 갈라진다. 느린 쪽이 응답을 지배해 오히려 느려진다
t3 = 0:0.01:30;
for bi = [0.2 1.0 2.0 3.0]
    plot(t3, step(1/(m*s^2+bi*s+k), t3), 'LineWidth',2); hold on
end
yline(1/k,'k--','LineWidth',1.5); grid on
xlabel('시간 [s]'); ylabel('변위 x [m]'); title('댐퍼 값에 따른 계단응답')
legend('b=0.2 (부족감쇠)','b=1.0 (부족감쇠)', ...
       'b=2.0 (임계감쇠)','b=3.0 (과감쇠)','Location','southeast')
%% 11. 영점은 무슨 일을 하는가
% 간단히 말하면 이렇습니다.
%
% - **극점**은 응답의 재료를 정한다
% - **영점**은 그 재료를 얼마씩 섞을지를 정한다
%
% 그래서 극점을 그대로 두고 영점만 바꾸면, 진동 주파수와 감쇠 속도는 똑같은데
% 초반 모양만 달라집니다.
%
% 아래 그림에서 **오른쪽 영점** $s=+2$ 인 경우를 특히 눈여겨보십시오.
% 응답이 처음에 **반대 방향으로 갔다가** 돌아옵니다.
%
% 이건 실제로 있는 현상입니다. 비행기 고도를 올리려고 조종간을 당기면 순간적으로
% 고도가 살짝 내려갔다가 올라갑니다. 꼬리날개가 먼저 아래로 눌리기 때문입니다.
%
% 이런 시스템은 제어하기 까다롭습니다. 올라가라고 했는데 내려가니 제어기가
% "더 세게 당겨야 하나?" 하고 혼동하기 때문입니다.
%
% ![영점이 원점에 가까울수록 오버슈트가 커진다](w02_zero_effect.png)
%
% **그림 파일** `w02_zero_effect.png` — `make_figures.m` 의 `fig_zero_effect`
%   · 다시 만들려면 `make_figures('w02_zero_effect')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_zero_effect`
% **직접 바꿔 보려면** — 영점을 $+2$ 처럼 **우반면**에 두어 보십시오.
% 응답이 처음에 반대로 가는 것을 볼 수 있습니다 (역응답)
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 검은 굵은 점선 | 영점이 없을 때 | 기준. 첫 봉우리 $1.37$ |
% | 노란 곡선 (영점 $-10$) | 검은 점선과 **거의 포개진다** | 영점이 멀면 없는 것과 같다 |
% | 빨간 곡선 (영점 $-2$) | 첫 봉우리 $1.42$ | 조금 커졌다 |
