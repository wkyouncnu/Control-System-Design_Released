%
% 위 두 칸 — 허수부를 고정하고 실수부만 왼쪽으로 옮기면
% **진동 주기는 그대로인데 봉투가 빨리 줄어듭니다.**
%
% 아래 두 칸 — 실수부를 고정하고 허수부만 올리면
% **사그라드는 속도는 그대로인데 더 촘촘히 흔들립니다.**
%
% 이것이 2차 응답을 읽는 전부입니다.
%
% $$y(t) \propto e^{-\sigma t}\cos(\omega_d t + \phi)
%   \qquad \sigma = \text{실수부}, \quad \omega_d = \text{허수부}$$
%
%% 8-0. 같은 것을 나란히 다시
% 위 그림을 좌우로 짝지어 보면 이렇게 됩니다.
