%%
zeta = -real(r(1))/abs(r(1))            % 감쇠비 1 = 임계감쇠
%% 4-2-1. 이탈점에서는 반드시 직각으로 떠난다
% 앞 절에서 궤적이 $-2$ 에서 갈라진다는 것은 구했습니다.
% 그런데 **어느 방향으로** 갈라지는지는 아직 말하지 않았습니다.
% 비스듬히 떠날 수도 있는 것 아닙니까.
%
% **아닙니다. 두 가지가 만난 이탈점에서는 언제나 $\pm 90^\circ$, 즉 직각입니다.**
% 이것도 유도됩니다.
%
% 이탈점 $\sigma_b$ 근처에서 $K(\sigma) = -1/L(\sigma)$ 를 테일러 전개합니다.
% 이탈점은 정의상 $K'(\sigma_b) = 0$ 인 자리이므로 **1차 항이 없습니다.**
% 그래서 2차 항이 첫 항이 됩니다. 근을 $s = \sigma_b + \delta$ 라 두면
%
% $$K = K_b + \frac{1}{2}K''(\sigma_b)\,\delta^2$$
%
% $\delta$ 에 대해 풀면
%
% $$\delta^2 = \frac{2(K - K_b)}{K''(\sigma_b)}$$
%
% 이탈점은 $K(\sigma)$ 의 **봉우리**이므로 $K''(\sigma_b) < 0$ 입니다.
% 그리고 궤적을 따라가려면 $K > K_b$ 여야 합니다. 그러므로 오른쪽은 **음수**입니다.
%
% $$\delta^2 < 0 \qquad \Rightarrow \qquad \delta = \pm j\sqrt{\frac{2(K-K_b)}{\left| K'' \right|}}$$
%
% $\delta$ 가 **순허수**입니다. 실축에서 위아래로, 곧 직각으로 떠납니다.
%
% **몇 가지 더 알 수 있습니다**
%
% - $\delta$ 가 $\sqrt{K - K_b}$ 에 비례한다 → 이탈점 바로 위에서는 이득을
%   조금만 키워도 극점이 **훅 벌어진다.** 10-3절에서 다시 만날 이야기다
% - 가지 $q$ 개가 만나면 첫 항이 $\delta^q$ 가 되어 떠나는 각이
%   $180^\circ/q$ 씩 갈라진다. $q=2$ 면 $90^\circ$ 와 $270^\circ$ 다
%
% 숫자로 확인합니다. 극점이 셋인 $L(s) = 1/((s+1)(s+3)(s+10))$ 으로
% (궤적이 전체적으로는 수직이 아닌 경우를 골랐습니다.)
L_b = 1/((s+1)*(s+3)*(s+10));

sigma = linspace(-2.999, -1.001, 200001);
K_sigma = -(sigma+1).*(sigma+3).*(sigma+10);
[K_b, i_b] = max(K_sigma);

sigma_b = sigma(i_b)
