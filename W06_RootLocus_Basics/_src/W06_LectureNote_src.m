% 외울 것은 **각도 $= 180^\circ/(n-m)$** 하나입니다.
% $n-m$ 이 $1$ 이면 $180^\circ$(왼쪽), $2$ 면 $90^\circ$(수직), $3$ 이면 $60^\circ$,
% $4$ 면 $45^\circ$ — 점점 눕습니다.
