% 빨간 점선이 공식으로 구한 점근선이고, 파란 곡선이 실제 궤적입니다.
%
% ![n-m 이 클수록 점근선이 오른쪽으로 눕는다](w06_asymptote.png)
%
% **그림 파일** `w06_asymptote.png` — `make_figures.m` 의 `fig_asymptote`
%   · 다시 만들려면 `make_figures('w06_asymptote')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_asymptote`
% **직접 바꿔 보려면** — `W06_01_rlocus_rules.m` 의 **4절**에서 극점을
