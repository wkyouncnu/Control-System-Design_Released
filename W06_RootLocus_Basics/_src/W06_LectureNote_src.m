% **두 사양을 모두 만족합니다.** CTMS 가 고른 값과 같습니다.
%
% **4단계 — 반드시 계단응답으로 확인한다**
%
% 이 시스템은 극점이 넷이라 **2차 근사가 정확하지 않습니다.**
% 그래서 사양 영역만 보고 끝내면 안 되고, 응답을 직접 그려 확인해야 합니다.
T_ctms = feedback(350*H_ctms, 1);

pole(T_ctms)'          % 지배극점 두 개가 사양 영역 안에 있는지 본다
%%
