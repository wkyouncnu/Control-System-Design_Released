%
% **2단계 — 궤적과 사양 영역을 겹쳐 그린다**
H_ctms = (s + 7)/(s*(s + 5)*(s + 15)*(s + 20));

figure
rlocus(H_ctms)
sgrid(0.7, 1.8)             % 사양 영역을 겹쳐 그린다
axis([-22 3 -15 15])
title('궤적이 사양 영역을 지나는가')
