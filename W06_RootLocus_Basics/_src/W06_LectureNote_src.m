% **이 예제가 주는 교훈 세 가지**
%
% - 사양은 시간영역의 말이지만, 근궤적에서는 **$s$ 평면의 영역**이 된다
% - 궤적이 그 영역을 지나면 비례제어로 끝난다. 지나지 않으면 **제어기가 필요하다** (7주차)
% - 극점이 셋 이상이면 2차 공식은 어림이다. **마지막 판정은 언제나 계단응답**이다
%% 10-3. 궤적으로 강건성을 본다 — 이득이 10 % 틀리면 극점이 어디까지 가나
% **왜 필요한가** — 지금까지는 $K$ 를 하나 골라 검증하고 끝냈습니다.
% 그런데 그 $K$ 가 현장에서 **정확히 구현되는 일은 없습니다.**
%
% - 저항의 공차가 $5\%$ 다
% - 모터 토크 상수가 온도에 따라 변한다
% - 전원이 $24$ V 가 아니라 $22$ V 다
%
% 셋 다 결과는 하나입니다 — **루프이득이 설계값과 다르다.**
% 그러면 극점은 내가 계산한 자리에 없습니다. 그러면 어디에 있습니까.
%
% **무엇인가 — 답은 이미 그려져 있습니다**
%
% 근궤적은 바로 "$K$ 가 바뀔 때 극점이 지나가는 길" 입니다.
% 그러므로 $K$ 가 $0.9K^*$ 와 $1.1K^*$ 사이일 때 극점이 있을 수 있는 자리는
% **궤적 위의 짧은 토막**입니다. 새로 그릴 것이 없습니다.
%
% - 토막이 짧다 → 이득이 좀 틀려도 응답이 거의 안 변한다
% - 토막이 길다 → 예민하다. 부품을 정밀하게 골라야 한다
%% 10-3-1. 토막의 길이를 미분으로 구한다
% 궤적을 그리지 않고 **토막의 길이를 바로 계산**할 수도 있습니다.
% 특성방정식을 $D(s,K)=0$ 이라 쓰고 양변을 전미분합니다.
% $K$ 가 조금 바뀌면 근 $p$ 도 조금 바뀌지만, 둘을 함께 움직여도
% 식은 계속 $0$ 이어야 하므로
%
% $$dD = \frac{\partial D}{\partial s}\,dp + \frac{\partial D}{\partial K}\,dK = 0$$
%
% $dp$ 에 대해 풀면
%
% $$\frac{dp}{dK} = -\frac{\partial D/\partial K}{\partial D/\partial s}$$
%
% $K$ 는 $D$ 안에서 늘 $+K$ 형태로 한 번만 나오므로 $\partial D/\partial K = 1$ 이고,
% 결국 **분모만 계산하면 됩니다.**
%
% $$\left| \Delta p \right| \approx \frac{\left| \Delta K \right|}{\left| D'(p) \right|}, \qquad D'(s) = \frac{dD}{ds}$$
%
% 이 식이 말하는 것 — $D'(p)$ 가 작은 곳, 즉 **근이 서로 가까운 곳에서
% 극점이 가장 많이 움직입니다.** 이탈점(4-2절)이 바로 두 근이 만나는 곳이므로,
% 이탈점 근처에서 이득 민감도가 가장 큽니다.
%
% 10-1절의 $G = 1/((s+1)(s+2))$, $K^*=8$ 로 확인해 봅니다.
% $D(s) = s^2+3s+2+K$ 이므로 $D'(s) = 2s+3$ 입니다.
p_star = -1.5 + 1i*sqrt(10 - 1.5^2);      % K = 8 일 때의 극점
dp_dK  = -1/(2*p_star + 3)                % 미분으로 구한 민감도
%%
dp_pred = 0.8*dp_dK                       % K 를 8 -> 8.8 로 (dK = +0.8)

p_new = pole(feedback(8.8*G_ex, 1));      % 실제로 다시 풀어 본 것
dp_true = p_new(1) - p_star
%%
% 예측 $0.144j$, 실제 $0.140j$ — **미분 한 번으로 맞혔습니다.**
% (차이는 $\Delta K$ 가 무한소가 아니라서 남는 2차 항입니다.)
%
% 그리고 예측값이 **순허수**인 것을 보십시오.
% 이 플랜트에서 이득 오차는 극점을 **위아래로만** 움직이고
% 좌우로는 못 움직입니다. 그러므로 $t_s$ 는 강건하고 $\%OS$ 만 변합니다.
% 10-1절 표의 "실수부가 셋 다 $-1.5$" 가 바로 이 이야기입니다.
K_rob = [7.2 8 8.8]';
OS = zeros(3,1);   ts = OS;   Re = OS;

for i = 1:3
    T = feedback(K_rob(i)*G_ex, 1);
    OS(i) = stepinfo(T).Overshoot;
    ts(i) = stepinfo(T).SettlingTime;
    p = pole(T);
    Re(i) = real(p(1));
end

table(K_rob, Re, OS, ts)
%% 10-3-2. 임계 이득에 가까울수록 같은 10 % 가 위험해진다
% 4-3절의 $L(s) = 1/(s(s+1)(s+3))$ 는 임계 이득이 $K_{cr} = 12$ 였습니다.
% 같은 $\pm 10\%$ 를 **$K^*=4$ 근처**와 **$K^*=10$ 근처**에서 각각 봅니다.
Kbit  = linspace(3.6, 4.4, 40);           % K* = 4 의 +-10 %
Kbit2 = linspace(9.0, 11.0, 40);          % K* = 10 의 +-10 %
Kall  = linspace(0.01, 14, 400);          % 전체 궤적

P  = zeros(3, 400);   Q1 = zeros(3, 40);   Q2 = zeros(3, 40);
for i = 1:400, P(:,i)  = pole(feedback(Kall(i)*L3,  1)); end
for i = 1:40,  Q1(:,i) = pole(feedback(Kbit(i)*L3,  1)); end
for i = 1:40,  Q2(:,i) = pole(feedback(Kbit2(i)*L3, 1)); end

figure                                    % rlocus 차트 위에 그리면 오류가 난다
plot(real(P)',  imag(P)',  'b.', 'MarkerSize', 4); hold on; grid on
plot(real(Q1)', imag(Q1)', 'r.', 'MarkerSize', 14)
plot(real(Q2)', imag(Q2)', 'm.', 'MarkerSize', 14)
xline(0, 'k-')
xlabel('실수부'); ylabel('허수부'); axis([-4 1 -2.5 2.5])
title('파란 점 : 전체 궤적    빨간 점 : K = 3.6 \sim 4.4    자홍 점 : K = 9 \sim 11')
%%
% 숫자로 봅니다. $K_{cr}=12$ 이므로 $K_{cr}/K^*$ 가 **이득여유**입니다
% (이 이름은 10주차에서 제대로 배웁니다).
K_two = [3.6 4 4.4 9 10 11]';
Re = zeros(6,1);   ts = Re;   OS = Re;   GM = 12./K_two;

for i = 1:6
    T = feedback(K_two(i)*L3, 1);
    p = pole(T);
    [~, j] = max(real(p));                % 허수축에 가장 가까운 극점
    Re(i) = real(p(j));
    ts(i) = stepinfo(T).SettlingTime;
    OS(i) = stepinfo(T).Overshoot;
end

table(K_two, GM, Re, ts, OS)
