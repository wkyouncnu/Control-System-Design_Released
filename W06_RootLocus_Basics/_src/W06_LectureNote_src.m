% | 비교 | $K^*=4$ 근처 | $K^*=10$ 근처 |
% |---|---|---|
% | 실수부 | $-0.284 \rightarrow -0.249$ | $-0.085 \rightarrow -0.027$ |
% | 실수부가 몇 배로 | $0.88$ 배 | $0.32$ 배 |
% | 정착시간 | $13.8 \rightarrow 15.3$ s | $45 \rightarrow 142$ s |
% | 이득여유 | $3.0$ | $1.2$ |
%
% **토막의 길이는 두 경우가 비슷합니다** ($0.11$ 대 $0.15$).
% 그런데 결과는 전혀 다릅니다. 이유는 **남은 거리**입니다.
%
% - $K^*=4$ 에서는 허수축까지 $0.27$ 이 남아 있는데 토막이 실수부를 $0.035$ 만 먹는다 → $13\%$
% - $K^*=10$ 에서는 남은 거리가 $0.055$ 뿐인데 토막이 $0.058$ 을 먹는다 → **$100\%$ 를 넘는다**
%
% 즉 임계 이득 가까이에서는 **이득 오차 $10\%$ 가 안정 여유를 전부 써 버립니다.**
% 궤적이 허수축에 거의 평행하게 올라가기 때문입니다.
%
% **설계 지침으로 정리하면**
%
% - 고른 $K^*$ 가 임계 이득의 **절반을 넘지 않게** 둔다 (이득여유 $2$ 이상)
% - 사양을 딱 맞추는 $K$ 가 아니라 **여유를 두고 만족하는 $K$** 를 고른다
% - 확인은 언제나 같은 방식 — 궤적 위에 $\pm 10\%$ 토막을 찍어 보면 된다
%
% 이 "여유" 를 각도와 이득 두 가지 숫자로 정식화한 것이 10주차의
% **이득여유 · 위상여유**입니다. 오늘은 궤적 위의 토막으로 먼저 눈에 익힙니다.
%% 11. 오늘의 정리
% - 근궤적은 $1+KL(s)=0$ 의 근이 $K$ 에 따라 움직이는 자취다.
%   그 식은 폐루프 전달함수의 **분모**이므로 새로운 이론이 아니다
% - **각도 조건** $\angle L(s) = \pm 180^\circ(2q+1)$ 이 그 점이 궤적 위인지 정하고,
%   **크기 조건**이 그때의 $K$ 를 정한다. 나머지 규칙은 전부 여기서 나온다
% - 실축 위에서는 **오른쪽에 있는 극·영의 개수가 홀수인 구간**이 궤적이다
% - 실축을 떠나는 **이탈점**은 $K(\sigma) = -1/L(\sigma)$ 의 봉우리다.
%   봉우리라서 1차 항이 없으므로, 두 가지는 거기서 **반드시 직각으로** 떠나고
%   벌어지는 거리는 $\sqrt{K-K_b}$ 에 비례한다 (4-2-1절)
% - 허수축 교차는 특성방정식에 $s = j\omega$ 를 넣어 실수부·허수부를 각각 $0$ 으로 두면 나온다.
%   그 $K$ 가 **임계 이득**이고 5주차 라우스 표의 답과 같다
% - `rlocus(L)` 로 그린다. $L$ 은 개루프, $K$ 는 빼고 넣는다
% - 궤적은 개루프 극점에서 출발해 영점에서 끝난다. 남는 가지는 무한대로
% - $n-m$ 이 클수록 오른쪽으로 휘어 불안정해지기 쉽다
% - **극을 추가하면 오른쪽으로, 영을 추가하면 왼쪽으로** 궤적이 움직인다
% - `sgrid` 로 사양 영역을 겹치고 `rlocfind` 로 이득을 읽는다
% - `rlocus` 의 이득 눈금은 성기다. 정확한 값은 따로 계산할 것
% - `rlocus` 그림 위에 `legend` 를 부르면 오류가 난다
% - **궤적이 사양 영역을 지나지 않으면 비례제어로는 불가능하다**
% - 근궤적은 포화를 모른다. 제어입력을 반드시 확인할 것
% - 궤적은 **강건성 도구**이기도 하다. $K$ 를 $\pm 10\%$ 흔들어 토막을 찍으면
%   부품 공차가 응답을 얼마나 바꾸는지 그 자리에서 보인다.
%   토막의 길이는 $\left| \Delta K \right| / \left| D'(p) \right|$ 로 계산할 수도 있다
% - 임계 이득에 가까운 $K$ 는 사양을 만족해도 **쓰면 안 된다.**
