% | 오른쪽 아래 ($n-m=4$) | 점근선이 $45^\circ$ | 더 눕는다 |
% | 왼쪽 아래·오른쪽 아래의 궤적 | 결국 **허수축을 넘어간다** | $K$ 를 키우면 불안정해진다 |
