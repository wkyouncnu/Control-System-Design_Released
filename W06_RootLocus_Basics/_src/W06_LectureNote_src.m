%
% **극점의 실수부는 셋 다 $-1.5$ 로 같습니다.** 이 플랜트에서 $K$ 는 허수부만
% 키우므로, 정착시간은 거의 그대로이고 진동만 심해집니다.
t = 0:0.005:5;
figure                      % 앞 절의 근궤적 차트 위에 그리면 오류가 난다 (새 창을 연다)
plot(t, step(feedback(3*G_ex,1),  t), 'LineWidth', 2); hold on; grid on
plot(t, step(feedback(8*G_ex,1),  t), 'LineWidth', 2)
plot(t, step(feedback(38*G_ex,1), t), 'LineWidth', 2)
yline(1, 'k--')
