%% 9. 설계가 실패하는 경우 — 궤적이 영역을 지나지 않는다
% 실습에서 이런 문제를 풀어 봅니다.
%
% - 오버슈트 $20\%$ 이하, 정착시간 $2$ 초 이하
%
% `spec2pole` 이 준 목표 극점은 $-2.0 \pm 3.9j$ 입니다.
% 그런데 `rlocfind` 로 찾으면 $-0.29 \pm 3.64j$ 가 나옵니다. 전혀 다른 곳입니다.
%
% **원인** — 궤적이 목표점 근처를 지나지 않기 때문입니다.
%
% 이 시스템의 궤적을 보면
%
% - 원점 극점과 $s=-2$ 극점이 서로 다가와 만난 뒤
% - 복소수가 되어 **위로 곧장 올라간다**
% - 올라가는 동안 실수부가 거의 변하지 않는다
%
% 즉 아무리 $K$ 를 키워도 극점을 **왼쪽으로 보낼 수가 없습니다.**
% 정착시간은 실수부가 정하므로 이 사양은 비례제어로 **불가능**합니다.
%
% **근궤적은 $K$ 로 정해지는 정해진 길입니다.**
% 그 길이 사양 영역을 지나지 않으면 방법이 없습니다.
% 그때는 **길 자체를 바꿔야** 하고, 그것이 극이나 영을 추가하는 일입니다.
% 7주차의 주제가 바로 이것입니다.
%
% ![궤적이 세로 직선이면 정착시간을 못 바꾼다](w06_design_fail.png)
%
% **그림 파일** `w06_design_fail.png` — `make_figures.m` 의 `fig_design_fail`
%   · 다시 만들려면 `make_figures('w06_design_fail')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_design_fail`
% **직접 확인해 보려면** — `W06_02_design_by_rlocus.m` 의 **5절**이
% 같은 결론을 `stepinfo` 로 확인합니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 그림 $\times$ 두 개 | $0$ 과 $-2$ | 개루프 극점. 원점 극점이 있으니 타입 1 |
% | 왼쪽 실축의 선분 | $-2$ 와 $0$ 사이 | 두 극점이 서로 다가온다 |
% | 왼쪽 $-1$ 에서 갈라지는 세로선 | 만난 뒤 위아래로 곧게 | **실수부가 $-1$ 에 붙박여 있다** |
% | 세로선이 정말 수직인 것 | 왼쪽으로도 오른쪽으로도 안 휜다 | $n-m=2$ 이므로 점근선이 $90^\circ$ |
% | 왼쪽 회색 점선 부채꼴·원 | 사양 영역 | 이 안으로 들어가야 하는데 |
% | 궤적이 원 안으로 못 들어가는 것 | 세로선이 원을 스치듯 지난다 | **$K$ 로는 도달할 수 없는 자리** |
% | 오른쪽 그림 빨간 점선 | 요구 정착시간 $3$ s | 목표선 |
% | 오른쪽 파란 곡선 | $K$ 를 $0$ 에서 $20$ 까지 키운 실제 정착시간 | 거의 $3.5{\sim}4$ s 에서 오르내린다 |
% | 파란 곡선이 빨간 선 **아래로 안 내려가는 것** | $K$ 를 아무리 키워도 안 된다 | 사양을 만족하는 $K$ 가 **존재하지 않는다** |
% | 파란 곡선의 톱니 모양 | $\pm 2\%$ 띠에 걸치는 봉우리가 하나씩 바뀌는 자리 | 계산상의 불연속. 추세만 보면 된다 |
