%% 3. 궤적은 어디서 출발해 어디로 가는가
% 규칙은 식에서 바로 나옵니다. 외울 것이 없습니다.
%
% $$1 + KL(s) = 0 \;\Longrightarrow\; L(s) = -\frac{1}{K}$$
%
% - $K \to 0$ 이면 $L(s) \to \infty$ — 즉 $L$ 의 **극점**
% - $K \to \infty$ 이면 $L(s) \to 0$ — 즉 $L$ 의 **영점**
%
% 따라서
%
% - **규칙 1** — 궤적은 개루프 극점에서 **출발**한다
% - **규칙 2** — 궤적은 개루프 영점에서 **끝난다**
% - 영점이 부족하면 남는 가지는 **무한대로** 뻗어 나간다
%
% 영점이 있을 때와 없을 때를 나란히 놓으면 규칙 2 가 바로 보입니다.
%
% ![영점이 있으면 그리로 빨려 들어간다](w06_start_end.png)
%
% **그림 파일** `w06_start_end.png` — `make_figures.m` 의 `fig_w06_start_end`
%   · 다시 만들려면 `make_figures('w06_start_end')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w06_start_end`
% **직접 바꿔 보려면** — `W06_01_rlocus_rules.m` 의 **2절**에서 영점 위치를
% $-2$ 대신 $-0.5$ 나 $-4$ 로 옮겨 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 두 그림의 빨간 $\times$ | 개루프 극점 | **$K=0$ 일 때 폐루프 극점 $=$ 개루프 극점.** 출발점이다 |
% | 왼쪽 그림 $\times$ 위치 | $-1$ 과 $-3$ | 두 개니까 가지도 두 개 |
% | 왼쪽 그림 실축 위 파란 선 | $-3$ 과 $-1$ **사이**만 이어져 있다 | 두 극점이 서로 다가온다 |
% | 왼쪽 그림 $-2$ 에서 갈라져 올라가는 세로선 | 만난 뒤 복소수가 된다 | 영점이 없으니 **갈 곳이 없다** |
% | 왼쪽 세로선이 위아래로 계속 뻗는 것 | 무한대로 간다 | 규칙 : 남는 가지는 무한대로 |
% | 오른쪽 그림 초록 $\circ$ | 개루프 영점 $-2$ | **$K=\infty$ 일 때의 도착점** |
% | 오른쪽 그림 $-1$ 과 $-2$ 사이 선분 | 한 가지가 영점으로 들어간다 | 규칙 2 그대로 |
% | 오른쪽 그림 $-5$ 에서 왼쪽으로 뻗는 선 | 나머지 한 가지 | 짝이 없으니 무한대로 |
% | 오른쪽 그림에 **세로로 뻗는 가지가 없는 것** | 복소수가 안 된다 | **영점 하나가 궤적 모양을 통째로 바꿨다** |
%
% 오른쪽 그림이 7주차 PD 제어의 원리입니다. 영점을 하나 놓아 궤적을
% 실축 쪽으로 눌러 앉히는 것입니다.
%% 3-1. 실축 위의 궤적 — 손작도에서 가장 먼저 하는 일
% 근궤적을 손으로 그릴 때 **제일 먼저 칠하는 것이 실축**입니다.
% 규칙은 한 줄이고, 1-2절의 각도 조건에서 바로 나옵니다.
%
% **실축 위의 어떤 점에서, 그 점의 오른쪽에 있는 극점과 영점의 개수를 세십시오.
% 홀수이면 그 점은 궤적 위에 있고, 짝수(0 포함)이면 아닙니다.**
%
% 왜 그런지 보겠습니다. 실축 위의 시험점 $\sigma$ 를 잡으면
%
% - $\sigma$ 의 **오른쪽**에 있는 실수 극·영 $\to$ 그 벡터는 왼쪽을 향하므로 각이 $180^\circ$
% - $\sigma$ 의 **왼쪽**에 있는 실수 극·영 $\to$ 벡터가 오른쪽을 향하므로 각이 $0^\circ$
% - **복소수 극·영** $\to$ 반드시 켤레쌍으로 있으므로 위아래 각이 상쇄되어 합이 $0^\circ$
%
% 그러므로 각의 총합은 (오른쪽 개수) $\times\,180^\circ$ 이고,
% 이것이 $180^\circ$ 의 **홀수배**가 되려면 오른쪽 개수가 홀수여야 합니다.
%
% ![오른쪽 개수가 홀수인 구간만 궤적이다](w06_real_axis.png)
%
% **그림 파일** `w06_real_axis.png` — `make_figures.m` 의 `fig_w06_real_axis`
%   · 다시 만들려면 `make_figures('w06_real_axis')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w06_real_axis`
% **직접 확인해 보려면** — 아래 코드에서 극점과 영점 목록을 바꿔 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 빨간 $\times$ 세 개 | 극점 $-1$, $-3$, $-5$ | 세 개니까 가지도 세 개 |
% | 왼쪽 초록 $\circ$ | 영점 $-2$ | 한 가지가 여기로 들어간다 |
% | 각 구간 위의 숫자 | 그 구간에서 **오른쪽에 있는 극·영의 개수** | 손으로 세면 되는 값 |
% | $-1$ 오른쪽 구간 (숫자 $0$) | 짝수 | 궤적이 아니다 |
% | $-2 \sim -1$ 구간 (숫자 $1$) | 홀수 | **굵게 칠했다.** 궤적이다 |
% | $-3 \sim -2$ 구간 (숫자 $2$) | 짝수 | 궤적이 아니다 |
% | $-5 \sim -3$ 구간 (숫자 $3$) | 홀수 | **굵게 칠했다.** 궤적이다 |
% | $-5$ 왼쪽 구간 (숫자 $4$) | 짝수 | 궤적이 아니다 |
% | 굵은 구간이 하나 걸러 나타나는 것 | 극·영을 하나 지날 때마다 홀짝이 뒤집힌다 | **번갈아 칠하면 된다** |
% | 오른쪽 그림의 실축 부분 | 왼쪽 굵은 구간과 정확히 같다 | 손으로 센 결과를 MATLAB 이 확인해 준다 |
%
% 아래 코드는 이 세기를 그대로 옮긴 것입니다.
pz   = [-1 -3 -5 -2]';                  % 극점 셋 + 영점 하나
test = [-6; -4; -2.5; -1.5; -0.5];      % 구간마다 시험점 하나

count_right = zeros(size(test));        % 시험점 오른쪽에 있는 극·영의 개수
for i = 1:numel(test)
    count_right(i) = sum(pz > test(i));
end
on_locus = mod(count_right, 2) == 1;    % 홀수이면 궤적 위

table(test, count_right, on_locus)
%% 3-2. 가지는 왜 $n$ 개이고, 왜 실축에 대칭인가
% 앞 절에서 궤적의 출발점과 도착점을 정했습니다.
% 그러면 **가지가 몇 개**이고 **전체 모양이 어떤 제약을 받는지**도
% 같은 식 하나에서 나옵니다. 여기가 규칙 3 의 근거입니다.
%
% **1단계 — 특성방정식을 다항식으로 적는다**
%
% 개루프를 분자와 분모로 쓰면 $L(s) = \frac{N(s)}{D(s)}$ 이고,
% $N$ 의 차수가 $m$, $D$ 의 차수가 $n$ 입니다.
% 실제 시스템은 $n \ge m$ 입니다 (분모 차수가 더 높다 $=$ 진짜 시스템).
%
% $$1 + K\frac{N(s)}{D(s)} = 0$$
%
% 양변에 $D(s)$ 를 곱하면 **분수가 사라지고 다항식 하나**가 됩니다.
%
% $$D(s) + K\,N(s) = 0$$
%
% **2단계 — 차수를 센다 (규칙 3)**
%
% $K$ 가 유한한 값이면 $K N(s)$ 의 차수는 $m$ 이고, $n \ge m$ 이므로
% 합의 최고차항은 $D(s)$ 의 $s^n$ 입니다. **$K$ 가 아무리 커도 차수는 $n$ 입니다.**
%
% 대수학의 기본정리에 따라 $n$ 차 방정식의 근은 언제나 $n$ 개입니다.
% $K$ 를 $0$ 에서 $\infty$ 까지 바꾸는 동안 근의 **개수가 변할 수 없으므로**
%
% $$(\text{가지 개수}) = n = (\text{개루프 극점 개수})$$
%
% **3단계 — 왜 끊기지 않는 곡선인가**
%
% 다항식의 근은 계수의 **연속함수**입니다. $K$ 를 조금 바꾸면 계수 $K N(s)$ 가
% 조금 바뀌고, 따라서 근도 조금만 움직입니다. 그래서 궤적은 점이 튀지 않고
% 이어진 곡선이 됩니다. `rlocus` 가 선으로 그릴 수 있는 이유입니다.
%
% **4단계 — 왜 실축에 대칭인가**
%
% $D(s)$ 와 $N(s)$ 의 계수는 전부 **실수**입니다. 물리 계수(질량, 저항, 이득)에서
% 왔기 때문입니다. 실계수 다항식에 복소수 근 $s_1 = \sigma + j\omega$ 가 있으면,
% 그 켤레 $\bar{s}_1 = \sigma - j\omega$ 도 반드시 근입니다.
%
% $$D(s_1) + K N(s_1) = 0
%   \;\Longrightarrow\;
%   \overline{D(s_1) + K N(s_1)} = D(\bar{s}_1) + K N(\bar{s}_1) = 0$$
%
% (계수가 실수이므로 켤레를 씌우면 $s$ 에만 켤레가 걸립니다.)
% 그러므로 **근은 실수이거나 켤레쌍**이고, 궤적은 언제나 실축에 대칭입니다.
%
% 손으로 그릴 때 **위쪽 절반만 그리면 되는** 이유가 이것입니다.
%
% **5단계 — 무한대로 가는 가지가 $n-m$ 개인 이유**
%
% $K \to \infty$ 를 보려면 식을 $K$ 로 나눕니다.
%
% $$\frac{D(s)}{K} + N(s) = 0$$
%
% $K\to\infty$ 이면 첫 항이 사라져 $N(s) = 0$, 즉 **영점** $m$ 개가 남습니다.
% 나머지 $n - m$ 개의 근은 이 극한으로 설명되지 않는데, 그 근들은
% $\left|s\right| \to \infty$ 로 달아나기 때문입니다.
% 실제로 $\left|s\right|$ 가 크면 $D(s)/K \approx s^n/K$ 이므로,
% 이 항이 사라지지 않으려면 $\left|s\right|^n$ 이 $K$ 와 함께 커져야 합니다.
%
% $$\left|s\right| \sim K^{1/(n-m)} \rightarrow \infty$$
%
% 그래서 **$n-m$ 개의 가지가 무한대로 뻗습니다** (규칙 4). 그 방향이 다음 절의 점근선입니다.
%
% 숫자로 확인합니다. $K$ 를 세 가지로 바꾸어 폐루프 극점을 직접 구해 봅니다.
L_br = 1/(s*(s+1)*(s+3));      % 극점 3 개, 영점 0 개

pole(feedback(0.1*L_br, 1))'   % K = 0.1
pole(feedback(1*L_br,   1))'   % K = 1
pole(feedback(10*L_br,  1))'   % K = 10
%%
% 세 줄 모두 **극점이 3 개**이고, 복소수가 나오면 반드시 **켤레쌍**입니다.
% 가지가 $n=3$ 개이고 궤적이 실축에 대칭이라는 것이 이것입니다.
%% 4. 가지 개수와 점근선
% - **규칙 3** — 가지 개수 $=$ 개루프 극점 개수
% - **규칙 4** — 무한대로 가는 가지 개수 $= n - m$ (극점 수 $-$ 영점 수)
% - **규칙 5** — 점근선 각도
%
% $$\theta = \frac{(2q+1)\cdot 180^\circ}{n-m}, \qquad q = 0,1,2,\ldots$$
%
% - **규칙 6** — 점근선이 실축과 만나는 점
%
% $$\sigma = \frac{\sum(\text{극점}) - \sum(\text{영점})}{n-m}$$
%
% 이 두 공식도 **외울 것이 아니라 1-2절의 각도 조건에서 나옵니다.**
% 다음 절에서 유도합니다.
%% 4-0. 점근선 각도는 각도 조건을 멀리서 본 것이다
% 궤적이 무한대로 뻗어 나갈 때, 즉 $|s|$ 가 아주 클 때를 생각합니다.
%
% **아주 멀리서 보면 극점과 영점이 전부 한 점(원점)에 뭉쳐 보입니다.**
% 지구에서 보면 서울과 부산이 다른 곳이지만 달에서 보면 한 점인 것과 같습니다.
%
% 그러면 개루프는 이렇게 보입니다.
%
% $$L(s) = \frac{(s-z_1)\cdots(s-z_m)}{(s-p_1)\cdots(s-p_n)}
%   \;\approx\; \frac{s^m}{s^n} = \frac{1}{s^{\,n-m}} \qquad (|s| \gg 1)$$
%
% 이제 **1-2절의 각도 조건**을 이 식에 그대로 씁니다.
% $s = |s|\,e^{j\theta}$ 라 하면 $\frac{1}{s^{n-m}}$ 의 각은 $-(n-m)\theta$ 이므로
%
% $$\angle L(s) = -(n-m)\,\theta = \pm 180^\circ (2q+1)$$
%
% 양변을 $-(n-m)$ 으로 나누면 **규칙 5 가 그대로 나옵니다.**
%
% $$\theta = \frac{(2q+1)\cdot 180^\circ}{n-m}$$
%
% $q$ 에 $0, 1, 2, \ldots$ 를 넣으면 서로 다른 각이 $n-m$ 개 나오고,
% 그 개수가 곧 **무한대로 가는 가지의 개수**입니다 (규칙 4).
%
% | $n-m$ | 각도 | 궤적이 가는 방향 |
% |---|---|---|
% | $1$ | $180^\circ$ | 왼쪽으로만. **절대 불안정해지지 않는다** |
% | $2$ | $\pm 90^\circ$ | 수직으로 올라간다 |
% | $3$ | $60^\circ,\ 180^\circ,\ 300^\circ$ | 두 가지가 **오른쪽으로 휜다** |
% | $4$ | $45^\circ,\ 135^\circ,\ 225^\circ,\ 315^\circ$ | 더 심하게 휜다 |
%
% **$n-m$ 이 클수록 각이 작아져 오른쪽으로 눕습니다.** 그래서 불안정해지기 쉽습니다.
%% 4-0-1. 점근선 중심은 한 항 더 남긴 것이다
% 위에서는 $s^m/s^n$ 만 남기고 나머지를 다 버렸습니다.
% **한 항만 더 남기면 점근선이 실축과 만나는 자리까지 나옵니다.**
%
% 다항식을 전개하면 둘째 항의 계수가 근의 합입니다 (근과 계수의 관계).
%
% $$(s-p_1)\cdots(s-p_n) = s^n - \left(\sum p_j\right)s^{n-1} + \cdots$$
%
% 분자도 같은 꼴이므로
%
% $$L(s) \approx \frac{s^m - \left(\sum z_i\right)s^{m-1}}
%                      {s^n - \left(\sum p_j\right)s^{n-1}}
%   = \frac{1}{s^{\,n-m}}\cdot
%     \frac{1 - \left(\sum z_i\right)/s}{1 - \left(\sum p_j\right)/s}$$
%
% $1/s$ 가 아주 작으므로 $\frac{1}{1-x} \approx 1+x$ 를 쓰면
%
% $$L(s) \approx \frac{1}{s^{\,n-m}}
%   \left(1 + \frac{\sum p_j - \sum z_i}{s}\right)$$
%
% 한편 점근선이 $s = \sigma$ 를 중심으로 뻗는다면 그 모양은 이렇습니다.
%
% $$\frac{1}{(s-\sigma)^{\,n-m}}
%   = \frac{1}{s^{\,n-m}}\left(1 - \frac{\sigma}{s}\right)^{-(n-m)}
%   \approx \frac{1}{s^{\,n-m}}\left(1 + \frac{(n-m)\,\sigma}{s}\right)$$
%
% **두 식의 $1/s$ 계수를 맞추면** 규칙 6 이 나옵니다.
%
% $$(n-m)\,\sigma = \sum p_j - \sum z_i
%   \qquad\Rightarrow\qquad
%   \sigma = \frac{\sum(\text{극점}) - \sum(\text{영점})}{n-m}$$
%
% **읽는 법** — 점근선의 중심은 극점과 영점의 **무게중심** 같은 것입니다.
% 극점이 왼쪽에 많을수록 중심이 왼쪽으로 가고, 영점을 왼쪽에 놓으면
% (빼기이므로) 중심이 오른쪽으로 밀립니다.
%
% 아래에서 손계산과 MATLAB 을 대조합니다.
La = 1/(s*(s+1)*(s+3));
p  = pole(La);
z  = zero(La);

n_minus_m = numel(p) - numel(z)                       % 무한대로 가는 가지 수
%%
sigma = (sum(p) - sum(z))/n_minus_m                   % 점근선 중심 (규칙 6)
theta = (2*(0:n_minus_m-1) + 1)*180/n_minus_m         % 점근선 각도 [도] (규칙 5)
