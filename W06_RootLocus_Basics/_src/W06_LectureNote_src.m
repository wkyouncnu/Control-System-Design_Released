% 4-1 절 그림의 빨간 점선과 대조해 보십시오. 같은 자리, 같은 각도입니다.
%
% 정리하면 이렇습니다.
%
% **$n-m$ 이 클수록 궤적이 오른쪽으로 휘어 불안정해지기 쉽다**
