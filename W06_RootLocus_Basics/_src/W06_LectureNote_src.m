% |---|---|---|
% | 오버슈트 $< 5\%$ | $\%OS = 100e^{-\zeta\pi/\sqrt{1-\zeta^2}}$ | $\zeta > 0.7$ |
% | 상승시간 $< 1$ s | $t_r \approx 1.8/\omega_n$ | $\omega_n > 1.8$ rad/s |
