%% 4-2. 이탈점 — 궤적은 어디서 실축을 떠나는가
% 0-1절의 그림에서 두 극점이 $-2$ 에서 만나 위아래로 갈라졌습니다.
% **왜 하필 $-2$ 인가**에 답합니다.
%
% 특성방정식을 $K$ 에 대해 풀면 이렇습니다.
%
% $$K = -\frac{1}{L(s)}$$
%
% 이 식을 **실축 위에서만** 그려 보십시오. $K(\sigma)$ 라는 보통의 함수가 됩니다.
% 실축 위의 두 가지가 서로 다가오다 만나는 자리는
% **그 함수가 봉우리(최댓값)를 이루는 곳**입니다.
% 그보다 $K$ 를 더 키우면 실축 위에는 해가 없으므로 근이 복소수가 됩니다.
%
% 따라서 조건은 미분이 $0$ 인 곳입니다.
%
% $$\frac{dK}{d\sigma} = 0$$
%
% 예제로 확인합니다. $L(s) = \frac{1}{(s+1)(s+3)}$ 이면
%
% $$K(\sigma) = -(\sigma+1)(\sigma+3) = -(\sigma^2 + 4\sigma + 3)$$
%
% $$\frac{dK}{d\sigma} = -(2\sigma + 4) = 0 \quad\Rightarrow\quad \sigma = -2$$
%
% 그리고 그때의 이득은 $K = -(-1)(1) = 1$ 입니다.
%
% ![K가 최대가 되는 자리에서 궤적이 갈라진다](w06_breakaway.png)
%
% **그림 파일** `w06_breakaway.png` — `make_figures.m` 의 `fig_w06_breakaway`
%   · 다시 만들려면 `make_figures('w06_breakaway')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w06_breakaway`
% **직접 확인해 보려면** — 아래 코드에서 극점 위치를 $-1$, $-4$ 로 바꾸면
% 이탈점이 $-2.5$ 로 옮겨 갑니다
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 파란 곡선 | 실축 위의 각 점을 지나는 데 필요한 $K$ | $K(\sigma) = -(\sigma+1)(\sigma+3)$ |
% | 곡선의 양 끝 ($\sigma = -1, -3$) | $K = 0$ | 극점 자리. **출발점의 이득이 0** 이라는 규칙 1 |
% | 곡선의 봉우리 | $\sigma = -2$ 에서 $K = 1$ | 실축 위에서 갈 수 있는 **가장 큰 이득** |
% | 봉우리 오른쪽·왼쪽이 낮은 것 | 같은 $K$ 에 실축 해가 둘 | 두 가지가 마주 보고 다가온다 |
% | $K > 1$ 인 가로선이 곡선과 안 만나는 것 | 실축에 해가 없다 | **그래서 복소수가 된다** |
% | 오른쪽 그림의 빨간 $\circ$ | 같은 자리 $-2$ | 왼쪽 봉우리와 정확히 일치 |
% | 오른쪽 세로선이 $-2$ 에서 시작하는 것 | 이탈점에서 위아래로 갈라진다 | 손계산이 그림을 맞혔다 |
%
% **이탈점은 중근이 생기는 자리**이기도 합니다.
% $K=1$ 에서 특성방정식은 $s^2+4s+4 = (s+2)^2$ 이 되어 근이 $-2$ 로 겹칩니다.
% 4주차의 말로 하면 **임계감쇠**($\zeta=1$)가 되는 이득입니다.
sig = linspace(-2.999, -1.001, 4001);
Ksig = -(sig+1).*(sig+3);
[Kbrk, ib] = max(Ksig);
fprintf('=== 이탈점 ===\n');
fprintf('  수치로 찾은 이탈점 : sigma = %.4f, K = %.4f\n', sig(ib), Kbrk);
fprintf('  손계산             : sigma = -2, K = 1\n');
r_brk = roots([1 4 3+Kbrk]);
fprintf('  그 K 의 폐루프 극점 : %s  (중근)\n', mat2str(round(r_brk.', 4)));
fprintf('  그때의 감쇠비       : %.4f  (임계감쇠)\n\n', ...
        -real(r_brk(1))/abs(r_brk(1)));
%% 4-3. 허수축을 넘는 자리 — 임계 이득을 손으로 구한다
% 5주차에서 라우스 표로 구했던 **임계 이득**을 근궤적에서도 구할 수 있습니다.
% 방법이 더 간단합니다.
%
% 궤적이 허수축을 지나는 순간의 근은 $s = j\omega$ 입니다.
% 그러므로 특성방정식에 $s = j\omega$ 를 **대입해 버리면** 됩니다.
% 복소수 방정식 하나는 실수 방정식 두 개와 같으므로,
% 미지수 $K$ 와 $\omega$ 두 개를 정확히 구할 수 있습니다.
%
% 예제 $L(s) = \frac{1}{s(s+1)(s+3)}$ 로 해 봅니다. 특성방정식은
%
% $$s^3 + 4s^2 + 3s + K = 0$$
%
% $s = j\omega$ 를 넣으면 $s^2 = -\omega^2$, $s^3 = -j\omega^3$ 이므로
%
% $$-j\omega^3 - 4\omega^2 + 3j\omega + K = 0$$
%
% 실수부와 허수부를 따로 $0$ 으로 둡니다.
%
% | 부분 | 식 | 결과 |
% |---|---|---|
% | 허수부 | $-\omega^3 + 3\omega = 0$ | $\omega(3 - \omega^2) = 0 \to \omega = \sqrt{3} = 1.732$ |
% | 실수부 | $K - 4\omega^2 = 0$ | $K = 4 \times 3 = 12$ |
%
% $\omega = 0$ 도 해이지만 그것은 $K=0$ 인 원점 극점이므로 버립니다.
%
% ![임계 이득에서는 진폭이 일정한 진동이 나온다](w06_jw_cross.png)
%
% **그림 파일** `w06_jw_cross.png` — `make_figures.m` 의 `fig_w06_jw_cross`
%   · 다시 만들려면 `make_figures('w06_jw_cross')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w06_jw_cross`
% **직접 확인해 보려면** — 아래 코드에서 $K$ 값을 바꿔 가며 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 빨간 $\times$ 세 개 | 극점 $0$, $-1$, $-3$ | 원점 극점이 있으므로 타입 1 |
% | 왼쪽 궤적이 오른쪽으로 휘는 것 | $n-m=3$ 이라 점근선이 $\pm 60^\circ$ | 4절의 규칙 그대로 |
% | 왼쪽 빨간 $\circ$ 두 개 | $\pm 1.732j$ | **손계산이 맞힌 그 자리** |
% | 그 점의 이득 $K=12$ | 임계 이득 | 5주차 라우스 표의 답과 같다 |
% | 오른쪽 초록 곡선 ($K=4$) | 진동하다 $1$ 에 정착 | 궤적이 아직 좌반면 |
% | 오른쪽 노란 곡선 ($K=12$) | **진폭이 줄지도 커지지도 않는다** | 근이 정확히 허수축 위 |
% | 노란 곡선의 주기 $3.63$ s | $2\pi/\omega = 2\pi/1.732$ | **손계산한 $\omega$ 를 눈으로 확인** |
% | 오른쪽 빨간 곡선 ($K=16$) | 진폭이 점점 커진다 | 근이 우반면으로 넘어갔다 |
%
% 노란 곡선의 주기를 자로 재면 $\omega$ 가 나옵니다.
% **손계산 · 근궤적 · 시간응답 세 가지가 같은 숫자를 가리키는 것**을 확인하십시오.
w_hand = sqrt(3);  K_hand = 4*w_hand^2;
L3 = 1/(s*(s+1)*(s+3));
fprintf('=== 허수축 교차 ===\n');
fprintf('  손계산 : K = %.4f, omega = %.4f, 주기 = %.4f s\n', ...
        K_hand, w_hand, 2*pi/w_hand);
fprintf('  그 K 의 폐루프 극점 : %s\n', ...
        mat2str(round(pole(feedback(K_hand*L3,1)).', 4)));
fprintf('  실수부가 0 이면 정확히 허수축 위입니다.\n');
fprintf('  K = 11.5 일 때 극점 : %s (안정)\n', ...
        mat2str(round(pole(feedback(11.5*L3,1)).', 4)));
fprintf('  K = 12.5 일 때 극점 : %s (불안정)\n\n', ...
        mat2str(round(pole(feedback(12.5*L3,1)).', 4)));
%% 4-4. 손으로 그리는 다섯 단계 — 그리고 MATLAB 으로 검산
% 지금까지 나온 규칙을 실제로 그리는 순서로 세우면 다섯 단계입니다.
% **시험에서도 이 순서대로 하면 됩니다.**
%
% | 단계 | 하는 일 | 근거 |
% |---|---|---|
% | 1 | 극점에 $\times$, 영점에 $\circ$ 를 찍는다 | 규칙 1, 2 (출발점과 도착점) |
% | 2 | 실축에서 **오른쪽 개수가 홀수인 구간**을 칠한다 | 3-1절 |
% | 3 | $n-m$ 을 세고 **점근선**을 그린다 | 4절 |
% | 4 | 실축 구간 안에서 **이탈점**을 구한다 | 4-2절 |
% | 5 | $s=j\omega$ 를 대입해 **허수축 교차와 임계 이득**을 구한다 | 4-3절 |
%
% 그리고 마지막에 반드시 `rlocus` 로 검산합니다.
%
% **손작도의 목적은 그림을 예쁘게 그리는 것이 아닙니다.**
% MATLAB 이 그려 준 그림이 **말이 되는지 판단할 눈**을 얻는 것입니다.
% 플랜트를 잘못 입력했거나 부호를 틀렸을 때, 손작도 감각이 없으면
% 이상한 그림을 그대로 믿게 됩니다.
%
% 아래 코드가 다섯 단계를 한 번에 확인합니다.
Lchk = 1/(s*(s+1)*(s+3));
pz   = [pole(Lchk).' zero(Lchk).'];
nmk  = numel(pole(Lchk)) - numel(zero(Lchk));

fprintf('=== 다섯 단계 검산 ===\n');
fprintf('1) 극점 %s,  영점 %s\n', ...
        mat2str(round(pole(Lchk).',3)), mat2str(zero(Lchk).'));
fprintf('2) 실축 궤적 구간 : -1 ~ 0 과 -3 아래쪽 (오른쪽 개수가 홀수인 곳)\n');
fprintf('3) n-m = %d  ->  점근선 각도 %s 도,  중심 %.4f\n', nmk, ...
        mat2str((2*(0:nmk-1)+1)*180/nmk), sum(pole(Lchk))/nmk);
sig2 = linspace(-0.999, -0.001, 4001);
K2   = -1./real(arrayfun(@(x) evalfr(Lchk, x), sig2));
[Kb2, ib2] = max(K2);
fprintf('4) 이탈점 sigma = %.4f  (그때 K = %.4f)\n', sig2(ib2), Kb2);
fprintf('5) 허수축 교차 K = %.4f, omega = %.4f\n', 12, sqrt(3));
fprintf('   -> rlocus(Lchk) 를 그려 눈으로 대조하십시오.\n\n');
%% 5. 오늘의 핵심 — 극과 영을 추가하면
% 제어기를 설계한다는 것은 결국 **극이나 영을 추가하는 일**입니다.
%
% - **비례제어 P** — 아무것도 추가하지 않는다. $K$ 만 조절
% - **미분제어 D** — **영점**을 추가한다 → 궤적을 **왼쪽으로** 당긴다
% - **적분제어 I** — 원점에 **극점**을 추가한다 → 궤적을 **오른쪽으로** 밀어낸다
%
% 이유는 $n-m$ 이 바뀌기 때문입니다.
%
% - 극을 추가하면 $n$ 이 늘어 $n-m$ 이 커진다 → 점근선이 눕는다 → 불안정해지기 쉽다
% - 영을 추가하면 $m$ 이 늘어 $n-m$ 이 작아진다 → 점근선이 선다 → 안정해진다
%
% 표로 보면
%
% - $n-m = 1$ — 점근선 $180^\circ$. 왼쪽으로만 간다. 절대 불안정해지지 않는다
% - $n-m = 2$ — 점근선 $\pm 90^\circ$. 수직으로 올라간다
% - $n-m = 3$ — 점근선 $60^\circ, 180^\circ, 300^\circ$. 두 가지가 **오른쪽으로 휜다**
% - $n-m = 4$ — 더 심하게 휜다
%
% ![영점을 더하면 궤적이 왼쪽으로 당겨진다](w06_four_loci.png)
%
% **그림 파일** `w06_four_loci.png` — `make_figures.m` 의 `fig_four_loci`
%   · 다시 만들려면 `make_figures('w06_four_loci')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_four_loci`
% **직접 바꿔 보려면** — `W06_01_rlocus_rules.m` 의 **5절**에서 영점을
% $-2$ 대신 $-0.5$ 로 옮기면 당기는 힘이 더 세집니다
%
% 그림 해석 — **$L_b$ 와 $L_c$ 두 칸만 비교하면 됩니다**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 위 $L_a$ | 극점 $-1$, $-3$ 뿐 | 기준. 궤적이 $-2$ 에서 수직으로 올라간다 |
% | 오른쪽 위 $L_b$ | $L_a$ 에 **원점 극점을 추가** | 적분기를 넣은 것 |
% | $L_b$ 의 궤적 | $-0.45$ 근처에서 갈라져 **오른쪽으로 휘어** 허수축을 넘는다 | **극을 추가하면 오른쪽으로** |
% | $L_b$ 가 허수축을 넘는 것 | $L_a$ 에는 없던 일 | 극점 하나가 시스템을 불안정하게 만들 수 있다 |
% | 왼쪽 아래 $L_c$ | $L_b$ 에 **영점 $-2$ 를 추가** | PD 제어를 흉내 낸 것 |
% | $L_c$ 의 궤적 | 다시 거의 **수직**으로 섰다 | **영을 추가하면 왼쪽으로** |
% | $L_c$ 가 허수축을 안 넘는 것 | $L_b$ 의 문제가 사라졌다 | 영점 하나가 불안정을 고쳤다 |
% | $L_c$ 의 초록 $\circ$ | $-2$ 의 영점 | 한 가지가 여기로 들어간다 |
% | 오른쪽 아래 $L_d$ | 극점을 넷까지 늘림 | 궤적이 크게 벌어져 더 쉽게 넘어간다 |
%
% **$L_b$ 에서 $L_c$ 로 가는 것이 7주차의 PD 제어입니다.**
% 영점 하나를 적당한 자리에 놓아 궤적을 통째로 왼쪽으로 끌어옵니다.
Gb = 1/((s+1)*(s+2));
tiledlayout(2,2,'TileSpacing','compact')
cs = {'기준 n-m=2', Gb; '극 추가 n-m=3', Gb/(s+3);
      '극 두 개 n-m=4', Gb/((s+3)*(s+4)); '영 추가 n-m=1', Gb*(s+3)};
for i=1:4
    nexttile; rlocus(cs{i,2}); grid on; title(cs{i,1});
    xlim([-6 3]); ylim([-4 4]);
end
%% 5-1. 그래서 PD 제어가 좋은 것이다
% 위 그림에서 영점을 추가한 경우를 보십시오. 궤적이 통째로 **왼쪽**으로 옮겨갔습니다.
%
% 왼쪽이 좋은 이유는 이미 배웠습니다.
%
% - 왼쪽 $=$ 실수부가 크게 음수 $=$ 빨리 잦아든다 $=$ 정착시간이 짧다
% - 허수축에서 멀어졌으므로 불안정해질 걱정도 줄었다
%
% 즉 **영점 하나로 더 빠르고 더 안정한** 시스템을 만들 수 있습니다.
% 그 영점을 만드는 것이 미분제어입니다.
%
% $$C(s) = K_p + K_d s = K_d\left(s + \frac{K_p}{K_d}\right)$$
%
% 괄호 안의 $\left(s + K_p/K_d\right)$ 가 추가되는 영점이고,
% 그 위치는 $K_p/K_d$ 로 **우리가 정할 수 있습니다.**
% 7주차에서 이 위치를 어떻게 고르는지 배웁니다.
%
% 실제로 확인해 보면
%
% - P 제어 — $K = 120.4$ 에서 불안정해진다
% - PD 제어 (영점 $s=-3$) — $K = 5000$ 까지 키워도 안정하다
