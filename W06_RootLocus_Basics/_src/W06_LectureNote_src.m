xlim([-5 1]); ylim([-4 4]);
title('그 점들을 이은 것이 근궤적이다');
%%
% 왼쪽 그림의 점들이 오른쪽 선 위에 그대로 놓입니다.
% `rlocus` 는 그 점 찍기를 자동으로 해 주는 명령일 뿐입니다.
%
% 이 예에서 보이는 것
%
% - 이득이 $0$ 이면 극점은 개루프 극점 $-1$, $-3$ 에 있다 (**출발점**)
% - 이득을 키우면 둘이 서로 다가와 $-2$ 에서 만난다
% - 더 키우면 위아래로 갈라져 **세로로** 올라간다
% - 실수부가 $-2$ 에서 변하지 않으므로 **아무리 키워도 안정**하다
K = [0 1 4 16]';
pole1 = zeros(size(K));   pole2 = zeros(size(K));
for i = 1:numel(K)
    r = roots([1 4 3+K(i)]);       % 특성방정식 s^2 + 4s + (3+K) = 0
    pole1(i) = r(1);
    pole2(i) = r(2);
end

table(K, pole1, pole2)
