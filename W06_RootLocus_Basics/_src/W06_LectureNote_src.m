%% 4. 가지 개수와 점근선
% - **규칙 3** — 가지 개수 $=$ 개루프 극점 개수
% - **규칙 4** — 무한대로 가는 가지 개수 $= n - m$ (극점 수 $-$ 영점 수)
% - **규칙 5** — 점근선 각도
%
% $$\theta = \frac{(2q+1)\cdot 180^\circ}{n-m}, \qquad q = 0,1,2,\ldots$$
%
% - **규칙 6** — 점근선이 실축과 만나는 점
%
% $$\sigma = \frac{\sum(\text{극점}) - \sum(\text{영점})}{n-m}$$
%
% 이 두 공식도 **외울 것이 아니라 1-2절의 각도 조건에서 나옵니다.**
% 다음 절에서 유도합니다.
%% 4-0. 점근선 각도는 각도 조건을 멀리서 본 것이다
% 궤적이 무한대로 뻗어 나갈 때, 즉 $|s|$ 가 아주 클 때를 생각합니다.
%
% **아주 멀리서 보면 극점과 영점이 전부 한 점(원점)에 뭉쳐 보입니다.**
% 지구에서 보면 서울과 부산이 다른 곳이지만 달에서 보면 한 점인 것과 같습니다.
%
% 그러면 개루프는 이렇게 보입니다.
%
% $$L(s) = \frac{(s-z_1)\cdots(s-z_m)}{(s-p_1)\cdots(s-p_n)}
%   \;\approx\; \frac{s^m}{s^n} = \frac{1}{s^{\,n-m}} \qquad (|s| \gg 1)$$
%
% 이제 **1-2절의 각도 조건**을 이 식에 그대로 씁니다.
% $s = |s|\,e^{j\theta}$ 라 하면 $\frac{1}{s^{n-m}}$ 의 각은 $-(n-m)\theta$ 이므로
%
% $$\angle L(s) = -(n-m)\,\theta = \pm 180^\circ (2q+1)$$
%
% 양변을 $-(n-m)$ 으로 나누면 **규칙 5 가 그대로 나옵니다.**
%
% $$\theta = \frac{(2q+1)\cdot 180^\circ}{n-m}$$
%
% $q$ 에 $0, 1, 2, \ldots$ 를 넣으면 서로 다른 각이 $n-m$ 개 나오고,
% 그 개수가 곧 **무한대로 가는 가지의 개수**입니다 (규칙 4).
%
% | $n-m$ | 각도 | 궤적이 가는 방향 |
% |---|---|---|
% | $1$ | $180^\circ$ | 왼쪽으로만. **절대 불안정해지지 않는다** |
% | $2$ | $\pm 90^\circ$ | 수직으로 올라간다 |
% | $3$ | $60^\circ,\ 180^\circ,\ 300^\circ$ | 두 가지가 **오른쪽으로 휜다** |
% | $4$ | $45^\circ,\ 135^\circ,\ 225^\circ,\ 315^\circ$ | 더 심하게 휜다 |
%
% **$n-m$ 이 클수록 각이 작아져 오른쪽으로 눕습니다.** 그래서 불안정해지기 쉽습니다.
%% 4-0-1. 점근선 중심은 한 항 더 남긴 것이다
% 위에서는 $s^m/s^n$ 만 남기고 나머지를 다 버렸습니다.
% **한 항만 더 남기면 점근선이 실축과 만나는 자리까지 나옵니다.**
%
% 다항식을 전개하면 둘째 항의 계수가 근의 합입니다 (근과 계수의 관계).
%
% $$(s-p_1)\cdots(s-p_n) = s^n - \left(\sum p_j\right)s^{n-1} + \cdots$$
%
% 분자도 같은 꼴이므로
%
% $$L(s) \approx \frac{s^m - \left(\sum z_i\right)s^{m-1}}
%                      {s^n - \left(\sum p_j\right)s^{n-1}}
%   = \frac{1}{s^{\,n-m}}\cdot
%     \frac{1 - \left(\sum z_i\right)/s}{1 - \left(\sum p_j\right)/s}$$
%
% $1/s$ 가 아주 작으므로 $\frac{1}{1-x} \approx 1+x$ 를 쓰면
%
% $$L(s) \approx \frac{1}{s^{\,n-m}}
%   \left(1 + \frac{\sum p_j - \sum z_i}{s}\right)$$
%
% 한편 점근선이 $s = \sigma$ 를 중심으로 뻗는다면 그 모양은 이렇습니다.
%
% $$\frac{1}{(s-\sigma)^{\,n-m}}
%   = \frac{1}{s^{\,n-m}}\left(1 - \frac{\sigma}{s}\right)^{-(n-m)}
%   \approx \frac{1}{s^{\,n-m}}\left(1 + \frac{(n-m)\,\sigma}{s}\right)$$
%
% **두 식의 $1/s$ 계수를 맞추면** 규칙 6 이 나옵니다.
%
% $$(n-m)\,\sigma = \sum p_j - \sum z_i
%   \qquad\Rightarrow\qquad
%   \sigma = \frac{\sum(\text{극점}) - \sum(\text{영점})}{n-m}$$
%
% **읽는 법** — 점근선의 중심은 극점과 영점의 **무게중심** 같은 것입니다.
% 극점이 왼쪽에 많을수록 중심이 왼쪽으로 가고, 영점을 왼쪽에 놓으면
% (빼기이므로) 중심이 오른쪽으로 밀립니다.
%
% 아래에서 손계산과 MATLAB 을 대조합니다.
La = 1/(s*(s+1)*(s+3));
