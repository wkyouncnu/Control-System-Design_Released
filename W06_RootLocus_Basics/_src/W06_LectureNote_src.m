%% 1. 근궤적이란
% 폐루프 특성방정식은 이것입니다.
%
% $$1 + K L(s) = 0$$
%
% 여기서 $L(s)$ 는 개루프 전달함수에서 $K$ 를 뺀 나머지입니다.
% $K$ 를 $0$ 에서 무한대까지 바꾸면 이 방정식의 근이 움직이고,
% 그 자취를 **근궤적**이라 합니다.
%
% 5주차에서 `roots` 로 직접 만든 그 그림에 이름이 붙은 것입니다.
%
% 말로 하면 추상적이니, **점을 네 개만 찍어** 보겠습니다.
%
% ![궤적은 특정 K 의 극점을 무수히 이은 것](w06_what_is.png)
%
% **그림 파일** `w06_what_is.png` — `make_figures.m` 의 `fig_w06_what_is`
%   · 다시 만들려면 `make_figures('w06_what_is')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w06_what_is`
% **직접 바꿔 보려면** — `W06_01_rlocus_rules.m` 의 **1절**에서 `Ks` 목록을 바꿔 실행
%
% 그림 해석 — **왼쪽 $\times$ 와 오른쪽 곡선을 색으로 짝지어 읽으십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 왼쪽 회색 선 | 근궤적 | $K$ 를 $0$ 에서 $200$ 까지 촘촘히 훑어 찍은 것 |
% | 왼쪽 파란 $\times$ ($K=10$) | $-1.0 \pm 1.1j$, 허수축에서 조금 떨어져 있다 | 실수부가 크니 잘 감쇠한다 |
% | 오른쪽 파란 곡선 ($K=10$) | 오버슈트 없이 천천히 상승한다 | 그 극점 위치와 맞는 응답 |
% | 왼쪽 빨간 $\times$ ($K=40$) | $-0.58 \pm 2.65j$, 위로 올라갔다 | 허수부가 커지고 실수부는 오히려 오른쪽으로 왔다 |
% | 오른쪽 빨간 곡선 | 첫 봉우리 $1.48$ | 허수부가 커지니 오버슈트가 커진다 |
% | 왼쪽 노란 $\times$ ($K=90$) | $-1.0 \pm 4.0j$ | 더 위로 |
% | 오른쪽 노란 곡선 | 첫 봉우리 $1.80$, 오래 진동한다 | 각도가 커졌으니 오버슈트가 커진다 |
% | 왼쪽 보라 $\times$ ($K=150$) | **허수축 오른쪽**으로 넘어갔다 | 불안정 |
% | 오른쪽에 보라 곡선이 없는 것 | 그릴 수가 없다 | 발산하므로 계단응답이 존재하지 않는다 |
% | 네 $\times$ 의 실수부 | 넷 다 $-1.0$ 근처로 거의 같다 | **$K$ 로는 실수부를 못 바꾼다.** 9절의 복선 |
% | 왼쪽 실축의 $\times$ 들 ($-10$ 근처) | $K$ 가 커질수록 왼쪽으로 | 빠른 극점 하나는 응답에 거의 영향이 없다 |
%
% **왼쪽 그림 하나로 오른쪽 네 개를 전부 예측할 수 있습니다.**
% 이것이 근궤적을 쓰는 이유입니다.
%% 1-1. 이 식은 어디서 나왔는가
% $1 + KL(s) = 0$ 을 갑자기 받아들이지 말고 어디서 왔는지 확인합니다.
% 3주차에서 유도한 폐루프 전달함수에서 한 줄로 나옵니다.
%
% $$T(s) = \frac{K\,G(s)}{1 + K\,G(s)H(s)}$$
%
% **극점은 분모를 $0$ 으로 만드는 $s$** 였습니다 (2주차).
% 그러므로 폐루프 극점은 다음 식의 근입니다.
%
% $$1 + K\,G(s)H(s) = 0$$
%
% 여기서 $L(s) = G(s)H(s)$ 로 묶은 것이 **개루프 전달함수**입니다.
% 센서가 이상적이어서 $H = 1$ 이면 $L = G$ 가 됩니다.
%
% 즉 근궤적은 새로운 이론이 아니라 5주차에서 `roots` 로 하던 일에
% **이름을 붙인 것**입니다. 다만 5주차에서는 $K$ 를 하나씩 넣어 근을 구했고,
% 오늘은 그 근들이 그리는 **선 전체의 성질**을 봅니다.
%
% 확인해 봅니다. 두 방법이 같은 답을 주어야 합니다.
G1 = 1/((s+1)*(s+3));
Ktest = 5;
fprintf('=== 같은 답인지 확인 ===\n');
fprintf('feedback 으로 만든 폐루프 극점 : %s\n', ...
        mat2str(round(pole(feedback(Ktest*G1, 1)).', 4)));
fprintf('특성방정식 1+KL=0 의 근        : %s\n', ...
        mat2str(round(roots([1 4 3+Ktest]).', 4)));
%% 1-2. 어떤 점이 궤적 위에 있는지 확인하는 법 — 각도 조건
% **여기가 근궤적의 뿌리입니다.** 이 절만 이해하면 뒤의 규칙은 전부 따라 나옵니다.
%
% 특성방정식을 $L$ 에 대해 풀면 이렇습니다.
%
% $$1 + K L(s) = 0 \quad\Rightarrow\quad L(s) = -\frac{1}{K}$$
%
% $K$ 는 **양의 실수**입니다. 그러므로 $-1/K$ 도 **음의 실수**입니다.
% 어떤 복소수가 음의 실수가 되려면 두 가지가 동시에 성립해야 합니다.
%
% | 조건 | 식 | 무엇을 정하는가 |
% |---|---|---|
% | **각도 조건** | $\angle L(s) = \pm 180^\circ \times (2q+1)$ | 그 점이 궤적 위에 **있는가** |
% | **크기 조건** | $L(s)$ 의 크기가 $1/K$ 이다 | 있다면 그때의 $K$ 가 **얼마인가** |
%
% 순서가 중요합니다. **먼저 각도로 걸러 내고, 통과한 점에 대해서만 크기로 $K$ 를 구합니다.**
%
% 각도와 크기를 실제로 세는 법은 그림으로 보면 간단합니다.
% $L(s)$ 를 인수로 쓰면
%
% $$L(s) = \frac{(s+z_1)(s+z_2)\cdots}{(s+p_1)(s+p_2)\cdots}$$
%
% 이고, 각 인수 $(s + p_i)$ 는 **극점 $-p_i$ 에서 시험점 $s$ 로 향하는 벡터**입니다.
% 곱은 각을 더하고 나눗셈은 각을 빼므로
%
% $$\angle L(s) = \sum(\text{영점에서 온 각}) - \sum(\text{극점에서 온 각})$$
%
% $$K = \frac{1}{\left| L(s) \right|}
%     = \frac{\prod(\text{극점까지의 거리})}{\prod(\text{영점까지의 거리})}$$
%
% **자를 대고 재면 되는 일**입니다. 그림에서 확인합니다.
%
% ![시험점에서 각을 더해 180도인지 본다](w06_angle_cond.png)
%
% **그림 파일** `w06_angle_cond.png` — `make_figures.m` 의 `fig_w06_angle_cond`
%   · 다시 만들려면 `make_figures('w06_angle_cond')`
%
% **만드는 곳** — `make_figures.m` 의 `fig_w06_angle_cond`
% **직접 확인해 보려면** — 아래 코드에서 `s_test` 를 바꿔 가며 실행
%
% 그림 해석
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 두 그림의 빨간 $\times$ | 극점 $-1$ 과 $-3$ | 영점이 없으므로 뺄 것만 있다 |
% | 왼쪽 파란 화살표 | 극점 $-1$ 에서 시험점으로 | 이 화살표의 각이 $\theta_1 = 116.6^\circ$ |
% | 왼쪽 초록 화살표 | 극점 $-3$ 에서 시험점으로 | 이 화살표의 각이 $\theta_2 = 63.4^\circ$ |
% | 왼쪽 두 각의 합 | 정확히 $180^\circ$ | **각도 조건을 만족한다 $\to$ 궤적 위의 점** |
% | 왼쪽 아래 $K$ 값 | 두 화살표 길이의 곱 $= 5$ | 크기 조건이 준 이득 |
% | 오른쪽 시험점 $-0.5+2j$ | 조금만 옮겼을 뿐이다 | 눈으로는 궤적 위처럼 보인다 |
% | 오른쪽 두 각의 합 | $114.6^\circ$ | $180^\circ$ 가 아니다 $\to$ **궤적 위의 점이 아니다** |
% | 두 그림의 차이 | 시험점의 위치뿐 | 각도 조건이 **합격·불합격을 가른다** |
%
% 각도 조건이 통과한 점에서 크기 조건으로 구한 $K=5$ 가 정말 맞는지
% 폐루프 극점으로 확인합니다.
s_test = -2 + 2i;
th1 = rad2deg(angle(s_test - (-1)));
th2 = rad2deg(angle(s_test - (-3)));
K_from_mag = abs(s_test + 1) * abs(s_test + 3);

fprintf('=== 각도 조건과 크기 조건 ===\n');
fprintf('시험점 s = %s\n', num2str(s_test));
fprintf('  극점 -1 에서 온 각 : %.2f 도\n', th1);
fprintf('  극점 -3 에서 온 각 : %.2f 도\n', th2);
fprintf('  합                : %.2f 도  -> 180 도이면 궤적 위\n', th1 + th2);
fprintf('  크기 조건이 준 K   : %.4f\n', K_from_mag);
fprintf('  그 K 의 폐루프 극점 : %s\n', ...
        mat2str(round(roots([1 4 3+K_from_mag]).', 4)));
fprintf('  --> 시험점과 같으면 성공입니다.\n\n');
