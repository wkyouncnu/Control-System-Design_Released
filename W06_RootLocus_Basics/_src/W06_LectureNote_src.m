%% 4-3-1. 복소극점에서는 어느 방향으로 출발하는가 — 출발각
% 실축 위의 극점에서는 궤적이 실축을 따라 움직이므로 방향을 고민할 일이 없습니다.
% 그런데 **복소극점**에서는 궤적이 어느 쪽으로 떠나는지 알 수 없으면
% 스케치를 시작할 수조차 없습니다. 그 방향을 **출발각**이라 하고,
% 1-2절의 각도 조건에서 바로 구해집니다.
%
% **1단계 — 극점 바로 옆에 시험점을 둔다**
%
% 복소극점 $p_1$ 에서 아주 조금 떨어진 점 $s = p_1 + \epsilon\,e^{j\theta_d}$ 를 생각합니다.
% $\epsilon$ 이 아주 작으므로, **다른 극점과 영점에서 이 점을 바라본 각은
% $p_1$ 을 바라본 각과 사실상 같습니다.** 달라지는 것은 $p_1$ 자신에서 본 각뿐이고,
% 그것이 바로 우리가 구하려는 $\theta_d$ 입니다.
%
% **2단계 — 각도 조건을 적는다**
%
% 1-2절의 조건은 "영점까지의 각의 합에서 극점까지의 각의 합을 뺀 것이
% $180^\circ$ 의 홀수배" 였습니다. 극점 쪽 합을 $p_1$ 과 나머지로 나누어 적으면
%
% $$\sum_{i}\angle(p_1 - z_i) - \theta_d - \sum_{j \neq 1}\angle(p_1 - p_j) = \pm 180^\circ$$
%
% **3단계 — $\theta_d$ 에 대해 푼다**
%
% $$\theta_d = 180^\circ + \sum_{i}\angle(p_1 - z_i) - \sum_{j \neq 1}\angle(p_1 - p_j)$$
%
% 말로 옮기면 이렇습니다. **$180^\circ$ 에서 시작해, 영점에서 온 각은 더하고
% 다른 극점에서 온 각은 뺀다.** 영점이 도착점이므로 궤적을 끌어당기고,
% 다른 극점은 밀어낸다고 읽으면 부호를 외우지 않아도 됩니다.
%
% **예제로 손계산합니다.** $L(s) = \frac{1}{s\left(s^2+2s+5\right)}$ 이면
% 극점은 $0$, $-1 \pm 2j$ 이고 영점은 없습니다.
% $p_1 = -1+2j$ 에서 출발각을 구합니다.
%
% | 항 | 벡터 | 각 |
% |---|---|---|
% | 원점 극점에서 본 각 | $p_1 - 0 = -1+2j$ | $116.57^\circ$ |
% | 켤레 극점에서 본 각 | $p_1 - (-1-2j) = 4j$ | $90^\circ$ |
% | 영점 | 없음 | $0$ |
%
% $$\theta_d = 180^\circ + 0 - \left(116.57^\circ + 90^\circ\right) = -26.57^\circ$$
%
% **읽는 법** — 각이 음수이므로 궤적은 그 극점에서 **오른쪽 아래 방향**으로
% 떠납니다. 오른쪽으로 간다는 것은 이득을 키우면 불안정 쪽으로 간다는 뜻이고,
% 실제로 이 시스템은 4-3절의 방법으로 임계 이득을 구할 수 있는 시스템입니다.
%
% 손으로 구한 각을 **실제 궤적의 방향과 대조**합니다.
% 이득을 아주 조금 준 폐루프 극점이 개루프 극점에서 어느 방향으로
% 움직였는지 재면 됩니다.
p1     = -1 + 2i;              % 출발각을 구할 복소극점
others = [0, -1-2i];           % 나머지 극점 두 개 (영점은 없다)

theta_hand = 180 - sum(rad2deg(angle(p1 - others)))   % 손계산 : 180 에서 극점 각을 뺀다
%%
