%
% 그림 해석 — **왼쪽 위에서 오른쪽 아래로 순서대로 보십시오**
%
% | 관찰 위치 | 관찰 내용 | 해석 |
% |---|---|---|
% | 네 칸의 빨간 점선 | 공식으로 구한 점근선 | 손으로 계산한 것 |
% | 네 칸의 파란·초록 곡선 | `rlocus` 가 그린 실제 궤적 | MATLAB 이 계산한 것 |
% | 둘이 멀리서 **겹치는 것** | 점근선은 $K$ 가 클 때의 근사 | 가까이서는 다르지만 멀리서는 같다 |
% | 빨간 네모 | 점근선이 만나는 점 $\sigma$ | 규칙 6 의 공식으로 나온 자리 |
% | 왼쪽 위 ($n-m=1$) | 점근선이 $180^\circ$, 즉 **실축 왼쪽** | 가지 하나가 왼쪽으로만 간다. 절대 불안정해지지 않는다 |
% | 오른쪽 위 ($n-m=2$) | 점근선이 $90^\circ$, **수직** | 위아래로 곧게 올라간다. 실수부가 안 변한다 |
